//! Native port of the D-028 flat G2 orbifold scan hot paths
//! (`metaphysica.simulations.PM.geometry.orbifold_gauge_scan`): group closure
//! from generators and the stratum analysis (fixed loci, orbits, stabilisers,
//! crossings, codimension-7 points).
//!
//! Everything is exact integer / rational arithmetic with the same
//! `DEN = 12` translation convention as the Python reference, and the same
//! element and locus ordering, so records agree field for field. The one
//! float field, `exceptional`, is the exact rational converted once.
//! Python stays the reference path; this module is an accelerator selected
//! through `metaphysica._dispatch`.

pub mod iso;
pub mod locus;
pub mod num;
pub mod strata;

use iso::Iso;
use serde_json::{json, Value};
use strata::{Ctx, Res};

fn elems_from_rows(flat: &[i64]) -> Res<Vec<Iso>> {
    let w = num::N * num::N + num::N;
    if flat.len() % w != 0 {
        return Err(format!("flat element buffer length {} is not a multiple of {w}", flat.len()));
    }
    flat.chunks(w).map(Iso::from_row).collect()
}

/// Close the group generated by the flat generator rows; returns flat rows.
pub fn close_group_rows(gens: &[i64], limit: usize) -> Res<Vec<i64>> {
    let g = elems_from_rows(gens)?;
    Ok(iso::close_group(&g, limit)?.iter().flat_map(|e| e.to_row()).collect())
}

fn row_json(r: &strata::Row, crosses: &[usize]) -> Value {
    let b1 = if r.dim >= 1 { r.betti[1] } else { 0 };
    let mut v = json!({
        "kind": r.kind, "k": r.k, "label": r.label, "dim": r.dim,
        "orbit_size": r.orbit_size, "stabiliser_order": r.stabiliser_order,
        "free_normal": r.free_normal, "betti": r.betti, "b1": b1,
        "crosses_orbits": crosses,
    });
    if let Some(e) = &r.exceptional {
        v["exceptional"] = json!(e);
    }
    v
}

/// Orbit indices (sorted) of the other loci each representative meets.
fn crossing_rows(
    meets: &[Vec<Vec<locus::Locus>>],
    orbs: &[Vec<usize>],
    n_loci: usize,
) -> (usize, Vec<Vec<usize>>) {
    let mut orb_of = vec![0usize; n_loci];
    for (k, o) in orbs.iter().enumerate() {
        o.iter().for_each(|&i| orb_of[i] = k);
    }
    let total = meets.iter().flatten().filter(|m| !m.is_empty()).count();
    let rows = meets
        .iter()
        .map(|per_locus| {
            let hit: std::collections::BTreeSet<usize> = per_locus
                .iter()
                .enumerate()
                .filter(|(_, m)| !m.is_empty())
                .map(|(i, _)| orb_of[i])
                .collect();
            hit.into_iter().collect()
        })
        .collect();
    (total, rows)
}

/// Full D-028 stratum data of one group (flat element rows, in group order),
/// as JSON: `order, flat_betti, strata, n_loci, crossings, codim7`.
pub fn analyse_rows(flat: &[i64], threads: usize) -> Res<String> {
    let elems = elems_from_rows(flat)?;
    let ctx = Ctx::new(&elems)?;
    let loci = strata::unique_loci(&elems);
    let orbs = strata::orbits_of_loci(&ctx, &loci)?;
    let reps: Vec<usize> = orbs.iter().map(|o| o[0]).collect();
    let rows = orbs
        .iter()
        .map(|o| strata::stratum_row(&ctx, &loci.items[o[0]], o.len()))
        .collect::<Res<Vec<_>>>()?;
    let flat_b = strata::flat_betti(&elems)?;
    let meets = strata::rep_meets(&loci, &reps, threads);
    let (crossings, per_row) = crossing_rows(&meets, &orbs, loci.items.len());
    let pts = strata::point_loci(&loci, &meets, threads);
    let c7: Vec<Value> = strata::codim7_points(&ctx, &pts)
        .iter()
        .map(|&(o, s)| json!({"orbit_size": o, "stabiliser_order": s}))
        .collect();
    let strata_json: Vec<Value> = rows.iter().zip(&per_row).map(|(r, c)| row_json(r, c)).collect();
    let out = json!({
        "order": elems.len(), "flat_betti": flat_b, "strata": strata_json,
        "n_loci": loci.items.len(), "crossings": crossings, "codim7": c7,
    });
    serde_json::to_string(&out).map_err(|e| e.to_string())
}

