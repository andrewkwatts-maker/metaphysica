//! Affine isometries x -> M x + c/DEN of the torus in lattice coordinates,
//! and group closure from generators (same BFS order as the Python reference).

use super::num::{Rat, N};
use std::collections::HashMap;

/// Translation denominator: c is stored modulo DEN (thirds and sixths fit).
pub const DEN: i64 = 12;

#[derive(Clone, PartialEq, Eq, Hash, Debug)]
pub struct Iso {
    pub m: [[i64; N]; N],
    pub c: [i64; N],
}

impl Iso {
    pub fn identity() -> Iso {
        Iso { m: std::array::from_fn(|i| std::array::from_fn(|j| (i == j) as i64)), c: [0; N] }
    }

    /// Rebuild from a flat row [M row-major (49), c (7)].
    pub fn from_row(row: &[i64]) -> Result<Iso, String> {
        if row.len() != N * N + N {
            return Err(format!("element row has {} entries, expected {}", row.len(), N * N + N));
        }
        Ok(Iso {
            m: std::array::from_fn(|i| std::array::from_fn(|j| row[i * N + j])),
            c: std::array::from_fn(|i| row[N * N + i].rem_euclid(DEN)),
        })
    }

    pub fn to_row(&self) -> Vec<i64> {
        self.m.iter().flatten().chain(self.c.iter()).copied().collect()
    }
}

/// g after h.
pub fn compose(g: &Iso, h: &Iso) -> Iso {
    let m = std::array::from_fn(|i| {
        std::array::from_fn(|j| (0..N).map(|k| g.m[i][k] * h.m[k][j]).sum())
    });
    let c = std::array::from_fn(|i| {
        ((0..N).map(|k| g.m[i][k] * h.c[k]).sum::<i64>() + g.c[i]).rem_euclid(DEN)
    });
    Iso { m, c }
}

/// Integer inverse of a unimodular matrix (exact, via rationals).
pub fn int_inverse(m: &[[i64; N]; N]) -> Result<[[i64; N]; N], String> {
    let mut a: Vec<Vec<Rat>> = (0..N)
        .map(|i| (0..N).map(|j| Rat::int(m[i][j] as i128)).chain((0..N).map(|j| Rat::int((i == j) as i128))).collect())
        .collect();
    for c in 0..N {
        let p = (c..N).find(|&i| !a[i][c].is_zero()).ok_or("singular matrix")?;
        a.swap(c, p);
        let inv = Rat::int(1).div(a[c][c]);
        a[c].iter_mut().for_each(|x| *x = x.mul(inv));
        for i in (0..N).filter(|&i| i != c) {
            let f = a[i][c];
            let src = a[c].clone();
            for (x, y) in a[i].iter_mut().zip(src) {
                *x = x.sub(f.mul(y));
            }
        }
    }
    let mut out = [[0i64; N]; N];
    for i in 0..N {
        for j in 0..N {
            let x = a[i][N + j];
            if !x.is_int() {
                return Err("matrix inverse is not integral".into());
            }
            out[i][j] = x.n as i64;
        }
    }
    Ok(out)
}

/// Order of g (Python `element_order`), failing above `limit`.
pub fn element_order(g: &Iso, limit: usize) -> Result<usize, String> {
    let e = Iso::identity();
    let mut cur = g.clone();
    for n in 1..=limit {
        if cur == e {
            return Ok(n);
        }
        cur = compose(g, &cur);
    }
    Err(format!("element order exceeds {limit}"))
}

fn is_closed(elems: &[Iso]) -> bool {
    let keys: std::collections::HashSet<&Iso> = elems.iter().collect();
    elems.iter().all(|a| elems.iter().all(|b| keys.contains(&compose(a, b))))
}

const FULL_CHECK_MAX: usize = 128;

/// Group generated by `gens` modulo the lattice; Err if its order exceeds
/// `limit`. Element order is the BFS order of the Python `close_group`.
pub fn close_group(gens: &[Iso], limit: usize) -> Result<Vec<Iso>, String> {
    let mut elems = vec![Iso::identity()];
    let mut seen: HashMap<Iso, usize> = HashMap::from([(Iso::identity(), 0)]);
    let mut frontier = vec![0usize];
    while !frontier.is_empty() {
        let mut next = Vec::new();
        for &xi in &frontier {
            for g in gens {
                let y = compose(g, &elems[xi]);
                if !seen.contains_key(&y) {
                    seen.insert(y.clone(), elems.len());
                    next.push(elems.len());
                    elems.push(y);
                }
            }
        }
        if elems.len() > limit {
            return Err(format!("group order exceeds {limit} (no closure)"));
        }
        frontier = next;
    }
    if elems.len() <= FULL_CHECK_MAX && !is_closed(&elems) {
        return Err("generated set is not closed under products".into());
    }
    Ok(elems)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn rot3() -> Iso {
        // x0 -> x1 -> x2 -> x0 cyclic permutation of coordinates
        let mut g = Iso::identity();
        g.m = [[0; N]; N];
        for (j, i) in [(0, 1), (1, 2), (2, 0)] {
            g.m[i][j] = 1;
        }
        for k in 3..N {
            g.m[k][k] = 1;
        }
        g
    }

    #[test]
    fn closure_of_a_three_cycle_has_order_three() {
        let g = close_group(&[rot3()], 10).unwrap();
        assert_eq!(g.len(), 3);
    }

    #[test]
    fn closure_fails_early_above_the_limit() {
        let mut t = Iso::identity();
        t.c[0] = 1; // translation by 1/12: order 12
        assert!(close_group(&[t.clone()], 11).unwrap_err().contains("exceeds 11"));
        assert_eq!(close_group(&[t], 12).unwrap().len(), 12);
    }

    #[test]
    fn inverse_and_order() {
        let g = rot3();
        let inv = int_inverse(&g.m).unwrap();
        let prod = compose(&g, &Iso { m: inv, c: [0; N] });
        assert_eq!(prod, Iso::identity());
        assert_eq!(element_order(&g, 12).unwrap(), 3);
    }
}
