const repairPrompt = (c, defects) => [
  `Target: repair the defects a reviewer found in chain ${c.id} (${c.title}) of ${NAME}. One target.`,
  COMMON,
  `Files of this chain: ${[...new Set(c.steps.flatMap(s => s.files))].join(', ')}.`,
  'Open the evidence of each defect first, serious ones first. Fix it and add or correct its test, or show with evidence that it is not a defect and put it in `left` with the reason. Run only the test files you touch.',
  `Commit: git add -- <paths> && git commit -m "${NAME} review ${c.id}: <what>" -- <paths> (no attribution line).`,
  'Defects:',
  JSON.stringify(defects, null, 1),
].join('\n')

const exec = (label, ph, schema) => ({ label, phase: ph, schema, agentType: 'executor', model: 'fable' })

const runChain = ph => async c => {
  const records = []
  for (const s of c.steps) {
    const r = await agent(stepPrompt(c, s), exec(`${c.id}:${s.id}`, ph, STEP))
    records.push(r || { id: s.id, done: false, commits: [], files: [], notes: 'the agent returned nothing; rerun this step' })
    if (r && r.declined) break
  }
  log(`${c.id}: ${records.filter(r => r.done).length}/${c.steps.length} steps done, ${records.flatMap(r => r.commits || []).length} commits`)
  return { chain: c.id, records }
}

const reviewChain = async (ran, c) => {
  const commits = ran.records.flatMap(r => r.commits || [])
  if (!commits.length) return { ...ran, review: null }
  const review = await agent(reviewPrompt(c, ran.records), { label: `review:${c.id}`, phase: 'Review', schema: REVIEW })
  return { ...ran, review }
}

const repairChain = async (reviewed, c) => {
  const defects = (reviewed.review && reviewed.review.defects) || []
  if (!defects.length) return { ...reviewed, repaired: null }
  const repaired = await agent(repairPrompt(c, defects), exec(`repair:${c.id}`, 'Repair', REPAIRED))
  log(`${c.id}: ${defects.length} defects (${defects.filter(d => d.severity === 'serious').length} serious), ${repaired ? repaired.fixed : 0} fixed`)
  return { ...reviewed, repaired }
}

const wanted = SPRINT.chains.filter(c => !A.only || A.only.includes(c.id))
if (!wanted.length) return { error: 'args.only names no chain of this sprint' }
const canary = wanted.find(c => c.id === A.canary) || wanted[0]

phase('Canary')
const first = await runChain('Canary')(canary)
if (first.records.some(r => r.declined) || !first.records.some(r => (r.commits || []).length)) {
  return { error: 'the canary chain did no work; nothing else was started', canary: first }
}
const done = [await repairChain(await reviewChain(first, canary), canary)]

phase('Fix')
const rest = wanted.filter(c => c.id !== canary.id)
const out = (await pipeline(rest, runChain('Fix'), reviewChain, repairChain)).map((r, i) => r || { chain: rest[i].id, failed: true })

const all = [...done, ...out]
const steps = all.flatMap(r => r.records || [])
return {
  sprint: NAME,
  chains: all.map(r => ({
    chain: r.chain,
    failed: !!r.failed,
    steps: (r.records || []).map(s => ({ id: s.id, done: !!s.done, declined: !!s.declined, commits: s.commits, tests: s.tests, needs_other_lane: s.needs_other_lane, blocked: s.blocked, notes: s.notes })),
    defects: r.review ? r.review.defects : null,
    repaired: r.repaired ? { fixed: r.repaired.fixed, left: r.repaired.left, commits: r.repaired.commits } : null,
  })),
  totals: {
    chains: all.length,
    failed_chains: all.filter(r => r.failed).map(r => r.chain),
    steps: steps.length,
    done: steps.filter(s => s.done).length,
    commits: steps.flatMap(s => s.commits || []).length,
    needs_other_lane: steps.flatMap(s => s.needs_other_lane || []),
    blocked: steps.flatMap(s => s.blocked || []),
    defects_left: all.flatMap(r => (r.repaired && r.repaired.left) || []),
  },
}
