const PASS = {
  type: 'object',
  properties: {
    lane: { type: 'string' },
    declined: { type: 'boolean' },
    rows_added: { type: 'number' },
    rows_corrected: { type: 'number' },
    gaps_closed: { type: 'array', items: { type: 'string' } },
    gaps_open: { type: 'array', items: { type: 'string' } },
    ideas_total: { type: 'number' },
    notes: { type: 'string' },
  },
  required: ['lane', 'rows_added', 'gaps_closed', 'gaps_open'],
}
const CHECK = {
  type: 'object',
  properties: {
    lane: { type: 'string' },
    defects: {
      type: 'array',
      items: {
        type: 'object',
        properties: {
          row: { type: 'string' },
          where: { type: 'string' },
          what: { type: 'string' },
          fix: { type: 'string' },
        },
        required: ['row', 'what'],
      },
    },
    checked: { type: 'string' },
  },
  required: ['lane', 'defects', 'checked'],
}
const REPAIRED = {
  type: 'object',
  properties: {
    lane: { type: 'string' },
    fixed: { type: 'number' },
    left: { type: 'array', items: { type: 'string' } },
    notes: { type: 'string' },
  },
  required: ['lane', 'fixed', 'left'],
}

