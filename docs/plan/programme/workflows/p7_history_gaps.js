const repairPrompt = (lane, defects) => [
  `Target: repair docs/plan/programme/ideas/${lane}.md for the defects a checker found. One target, one file.`,
  COMMON,
  'Read docs/plan/programme/HISTORY_REVIEW.md (the row layout and the rules) and the rows named below.',
  'Open the source of each defect before you change a row. Correct the row; where the defect is itself wrong, leave the row and say why in `left`.',
  FILE_RULES,
  'Defects:',
  JSON.stringify(defects, null, 1),
].join('\n')

const opts = (label, ph, schema) => ({ label, phase: ph, schema, agentType: 'executor', model: 'opus' })

const secondPass = async lane => {
  const halves = []
  for (const half of ['first', 'second']) {
    const r = await agent(passPrompt(lane, half), opts(`p7gap:${lane}:${half}`, 'Second pass', PASS))
    halves.push(r || { lane, declined: false, rows_added: 0, gaps_closed: [], gaps_open: [`the ${half} half returned nothing; rerun this lane`] })
    if (r && r.declined) break
  }
  const declined = halves.some(h => h.declined)
  log(`${lane}: +${halves.reduce((n, h) => n + (h.rows_added || 0), 0)} rows, ${halves.flatMap(h => h.gaps_open).length} gap entries open${declined ? ', DECLINED' : ''}`)
  return { lane, halves, declined }
}

const check = async (passed, lane) => {
  if (passed.declined) return { ...passed, check: null }
  const c = await agent(checkPrompt(lane), opts(`p7gap:check:${lane}`, 'Check', CHECK))
  return { ...passed, check: c }
}

const repair = async (checked, lane) => {
  const defects = (checked.check && checked.check.defects) || []
  if (!defects.length) return { ...checked, repaired: null }
  const r = await agent(repairPrompt(lane, defects), opts(`p7gap:repair:${lane}`, 'Repair', REPAIRED))
  log(`${lane}: ${defects.length} defects, ${r ? r.fixed : 0} fixed`)
  return { ...checked, repaired: r }
}

const lanes = (args && args.lanes) || LANES
const out = (await pipeline(lanes, secondPass, check, repair)).map((r, i) => r || { lane: lanes[i], failed: true })
return {
  lanes: out.map(r => ({
    lane: r.lane,
    failed: !!r.failed,
    declined: !!r.declined,
    rows_added: (r.halves || []).reduce((n, h) => n + (h.rows_added || 0), 0),
    rows_corrected: (r.halves || []).reduce((n, h) => n + (h.rows_corrected || 0), 0),
    gaps_open: (r.halves || []).flatMap(h => h.gaps_open),
    defects: r.check ? r.check.defects.length : null,
    defects_left: r.repaired ? r.repaired.left : [],
    notes: (r.halves || []).map(h => h.notes).filter(Boolean).join(' / '),
  })),
}
