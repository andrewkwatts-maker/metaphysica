export const meta = {
  name: 'pm-p7-history-lanes',
  description: 'P7 history and ideas review: read-only lanes, one file per lane under docs/plan/programme/ideas',
  phases: [{ title: 'Lanes', detail: 'one executor per lane; each chain runs its lanes in order' }],
}

// args: { chains: [[lane, ...], ...] }  One agent runs per chain at a time, so the number of
// chains is the number of agent slots this run uses. Lane names are the rows of the Lanes table
// in docs/plan/programme/HISTORY_REVIEW.md.

const RESULT = {
  type: 'object',
  properties: {
    lane: { type: 'string' },
    file: { type: 'string' },
    ideas: { type: 'number' },
    timeline_rows: { type: 'number' },
    candidates_seen: { type: 'array', items: { type: 'string' } },
    gaps: { type: 'array', items: { type: 'string' } },
    notes: { type: 'string' },
  },
  required: ['lane', 'file', 'ideas', 'gaps'],
}

const lanePrompt = lane => [
  `Target: lane \`${lane}\` of the P7 history and ideas review. One target, one file.`,
  'Read docs/plan/programme/HISTORY_REVIEW.md first, all of it (about 120 lines). It gives your',
  'source (your row in the Lanes table), the method, the layout of your file, the owner\'s',
  'candidates to search for, and the rules.',
  `Write exactly one file: docs/plan/programme/ideas/${lane}.md (250 lines at most).`,
  'Everything else is read-only. Do not commit, push, build or run tests.',
  'Read narrowly: commit subjects first, then only the hunks that state a model, claim, removal,',
  'retraction, refutation or ruling. Pipe every git command through head or cut. Never open',
  'generated output (AutoGenerated/, built html) and never page a whole commit.',
  'Every row cites a commit hash or a file:line. Record, do not judge.',
  'Stop when the file is written and every matching subject is covered; list under Gaps what you',
  'did not open. Return the counts and the gaps.',
].join('\n')

const chains = (args && args.chains) || []
if (!chains.length) {
  return { error: 'pass args.chains, a list of lists of lane names' }
}

phase('Lanes')
const out = await parallel(chains.map(chain => async () => {
  const done = []
  for (const lane of chain) {
    const r = await agent(lanePrompt(lane), {
      label: `p7:${lane}`, phase: 'Lanes', schema: RESULT, agentType: 'executor', model: 'opus',
    })
    done.push(r || { lane, file: '', ideas: 0, gaps: ['the agent returned nothing; rerun this lane'] })
    log(`${lane}: ${r ? r.ideas + ' ideas, ' + r.gaps.length + ' gaps' : 'no result'}`)
  }
  return done
}))
return out.filter(Boolean).flat()
