const opts = (label, ph, schema) => ({ label, phase: ph, schema, agentType: 'executor', model: 'fable' })

const runChain = async c => {
  const records = []
  for (const s of c.steps) {
    const r = await agent(stepPrompt(c, s), opts(`r2:${c.id}:${s.id}`, c.id === 'E' ? 'Canary' : 'Fix', STEP))
    records.push(r || { id: s.id, done: false, commits: [], files: [], notes: 'the agent returned nothing; rerun this step' })
    if (r && r.declined) break
  }
  log(`${c.id}: ${records.filter(r => r.done).length}/${c.steps.length} steps done, ${records.flatMap(r => r.commits || []).length} commits`)
  return { chain: c.id, records }
}

const reviewChain = async (ran, c) => {
  const commits = ran.records.flatMap(r => r.commits || [])
  if (c.noReview || !commits.length) return { ...ran, review: null }
  const review = await agent(reviewPrompt(c, ran.records), opts(`r2:review:${c.id}`, 'Review', REVIEW))
  return { ...ran, review }
}

const repairChain = async (reviewed, c) => {
  const defects = (reviewed.review && reviewed.review.defects) || []
  if (!defects.length) return { ...reviewed, repaired: null }
  const repaired = await agent(repairPrompt(c, defects), opts(`r2:repair:${c.id}`, 'Repair', REPAIRED))
  log(`${c.id}: ${defects.length} defects (${defects.filter(d => d.severity === 'serious').length} serious), ${repaired ? repaired.fixed : 0} fixed`)
  return { ...reviewed, repaired }
}

const wanted = CHAINS.filter(c => !A.only || A.only.includes(c.id))
const canaryChain = wanted.find(c => c.id === 'E')
const done = []
if (canaryChain) {
  phase('Canary')
  const ran = await runChain(canaryChain)
  if (ran.records.some(r => r.declined) || !ran.records.some(r => (r.commits || []).length)) {
    return { error: 'the canary chain did no work; nothing else was started', canary: ran }
  }
  done.push(await repairChain(await reviewChain(ran, canaryChain), canaryChain))
}

phase('Fix')
const rest = wanted.filter(c => c.id !== 'E')
const out = (await pipeline(rest, runChain, reviewChain, repairChain)).map((r, i) => r || { chain: rest[i].id, failed: true })

return {
  chains: [...done, ...out].map(r => ({
    chain: r.chain,
    failed: !!r.failed,
    steps: (r.records || []).map(s => ({ id: s.id, done: !!s.done, declined: !!s.declined, commits: s.commits, tests: s.tests, needs_other_lane: s.needs_other_lane, blocked: s.blocked, notes: s.notes })),
    defects: r.review ? r.review.defects : null,
    repaired: r.repaired ? { fixed: r.repaired.fixed, left: r.repaired.left, commits: r.repaired.commits } : null,
  })),
}
