"""Run selections resumably with the existing worker, pool and cache.

Resume is the run cache's rule: a run is reused when its result exists for the
current engine fingerprint; a root from another fingerprint is a different
directory, so it is rerun (and left behind as stale).

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import threading
from pathlib import Path
from typing import Any, Callable, Dict, List, Mapping, Optional, Sequence, Union

from metaphysica.testground.configurations.lifecycle import Classifier
from metaphysica.testground.runner.cache import RunCache
from metaphysica.testground.runner.pool import PoolResult, PoolTask, run_pool
from metaphysica.testground.runner.worker import run_configuration
from metaphysica.testground.sweep.selections import configuration_for

__all__ = ["SHARED_STATE_THEORIES", "shares_state", "check_jobs", "run_selections"]

#: Theories whose runs share state (PM's build writes through the engine's
#: shared AutoGenerated junction); also honoured: a ``shared_state`` attribute.
SHARED_STATE_THEORIES = frozenset({"pm"})

Runner = Callable[..., Any]


def shares_state(theory: Any) -> bool:
    return bool(getattr(theory, "shared_state", False)) or \
        theory.id in SHARED_STATE_THEORIES


def check_jobs(theory: Any, jobs: int) -> None:
    """Refuse parallel runs for a theory whose runs would race on shared state."""
    if jobs < 1:
        raise ValueError("--jobs must be at least 1")
    if jobs > 1 and shares_state(theory):
        raise ValueError(
            "theory %r shares state between runs (its build writes through the "
            "engine's shared AutoGenerated junction); refusing --jobs %d, use "
            "--jobs 1" % (theory.id, jobs))


def _task(theory: Any, cfg: Any, cache: RunCache, runs_dir: Path,
          fingerprint: str, timeout: Optional[float], runner: Runner) -> PoolTask:
    def run(cancel: threading.Event) -> Any:
        return runner(theory, cfg, runs_dir, fingerprint, timeout,
                      cache=cache, cancel=cancel)
    return PoolTask(cfg.digest, run)


def run_selections(theory: Any, sels: Sequence[Mapping[str, str]],
                   runs_dir: Union[str, Path], fingerprint: str, *,
                   jobs: int = 1, timeout: Optional[float] = None,
                   progress: Any = None,
                   runner: Runner = run_configuration) -> List[PoolResult]:
    """Run each selection once (cache hits are reused); results sorted by digest."""
    check_jobs(theory, jobs)
    runs_dir = Path(runs_dir)
    runs_dir.mkdir(parents=True, exist_ok=True)
    classifier, cache = Classifier(theory), RunCache(runs_dir)
    cfgs = [configuration_for(theory, classifier, s) for s in sels]
    tasks = [_task(theory, c, cache, runs_dir, fingerprint, timeout, runner)
             for c in cfgs]
    return run_pool(tasks, jobs, progress)
