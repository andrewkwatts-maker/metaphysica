"""Load finished runs from a runs directory for the audit.

Layout: ``<runs>/<theory>/<fingerprint>/<digest>/`` (see runner.isolation). Runs
under the current fingerprint load; other fingerprints are listed as stale.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional, Tuple

from metaphysica.testground.audit.rows import load_rows
from metaphysica.testground.runner.isolation import read_stamp
from metaphysica.testground.runner.worker import RUN_LOG_NAME
from metaphysica.testground.sweep.selections import label

__all__ = ["LoadedRun", "Loaded", "load_runs", "read_json"]


@dataclass
class LoadedRun:
    id: str
    selection: Dict[str, str]
    root: Path
    status: str
    reason: str
    rows: Optional[Dict[str, Any]]
    reads: Optional[Dict[str, int]]
    failed_steps: List[Dict[str, Any]]


@dataclass
class Loaded:
    runs: Dict[str, LoadedRun] = field(default_factory=dict)
    stale: List[str] = field(default_factory=list)


def read_json(path: Path) -> Optional[Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _reads(root: Path) -> Optional[Dict[str, int]]:
    doc = read_json(root / "AutoGenerated" / "fork_reads.json")
    if not isinstance(doc, dict) or not isinstance(doc.get("reads"), dict):
        return None
    return {k: int(v) for k, v in doc["reads"].items()}


def _failed_steps(root: Path) -> List[Dict[str, Any]]:
    doc = read_json(root / "AutoGenerated" / "build_status.json")
    steps = doc.get("failed_steps") if isinstance(doc, dict) else None
    return [s for s in steps or () if isinstance(s, dict)]


def _load_one(root: Path) -> Optional[LoadedRun]:
    stamp = read_stamp(root)
    if not stamp or not isinstance(stamp.get("selection"), dict):
        return None
    log = read_json(root / RUN_LOG_NAME)
    if not isinstance(log, dict):
        return None      # started but never finished
    sel = dict(stamp["selection"])
    return LoadedRun(label(sel), sel, root, str(log.get("status", "")),
                     str(log.get("reason", "")), load_rows(root), _reads(root),
                     _failed_steps(root))


def load_runs(runs_dir: Path, theory_id: str, fingerprint: str) -> Loaded:
    """Finished runs under *fingerprint*; other fingerprint directories are stale."""
    base = Path(runs_dir) / theory_id
    out = Loaded()
    if not base.is_dir():
        return out
    for fp_dir in sorted(p for p in base.iterdir() if p.is_dir()):
        if fp_dir.name != fingerprint:
            out.stale.append(fp_dir.name)
            continue
        for root in sorted(p for p in fp_dir.iterdir() if p.is_dir()):
            run = _load_one(root)
            if run is not None:
                out.runs[run.id] = run
    return out
