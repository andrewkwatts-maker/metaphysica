"""Publish per-path patches, summaries and the path manifest.

Inputs: the main build ``M`` and a second identical build ``V`` (their
differences are the volatile keys), a directory ``R`` of per-path builds
(``<fork>--<option>/AutoGenerated`` plus ``DONE.json``), and the published
site root ``P``. A theory supplies labels and summaries through
``metaphysica.theories.<name>.results``: ``main_entry()``,
``deviation_entry(fork, option)`` and
``build_summary(path_id, main_dir, path_dir, changed)``.
"""
from __future__ import annotations

import hashlib
import importlib
import json
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple, Union

from .patch import count_by_file, file_ops, published_ok, roundtrip_ok
from .diff import split_pointer
from .volatile import detect, mask

PATH_ID = re.compile(r"^[A-Za-z0-9_]+(--[A-Za-z0-9_]+)?$")
EXCLUDED = ("paths/", "path_graph.json")
BOOKKEEPING = ("variants.json", "build_status.json")    # switch bookkeeping: patched, not counted


class PathFailed(Exception):
    """A path that cannot be published as a patch; the text is the reason."""


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def list_files(auto: Path) -> List[str]:
    """Every ``*.json`` under ``auto`` (posix-relative), minus the excluded."""
    names = [p.relative_to(auto).as_posix() for p in auto.rglob("*.json")]
    return sorted(n for n in names
                  if not any(n == e or n.startswith(e) for e in EXCLUDED))


def _auto(root: Path) -> Path:
    auto = Path(root) / "AutoGenerated"
    if not auto.is_dir():
        raise ValueError("no AutoGenerated directory under %s" % root)
    return auto


class Base:
    """The main build and its volatile masks, loaded once."""

    def __init__(self, main: Path, twins: Sequence[Path], published: Path,
                 declared: Optional[Dict[str, Sequence[str]]] = None) -> None:
        self.main, self.pub = _auto(main), _auto(published)
        self.declared = dict(declared or {})
        twin_autos = [_auto(t) for t in twins]
        self.raw: Dict[str, Any] = {}
        self.patterns: Dict[str, List[str]] = {}
        self.masked: Dict[str, Any] = {}
        for name in list_files(self.main):
            self._load_file(name, twin_autos)

    def _load_file(self, name: str, twin_autos: List[Path]) -> None:
        # Volatile = differs from main in ANY twin: a second identical build
        # catches run-to-run noise; a fast build twin of a full main catches
        # keys that depend on the build mode (2026-10-25: de_plane_gate). The
        # theory's declared stochastic subtrees are volatile even when twins agree.
        try:
            raw = _load(self.main / name)
            pats: set = set(self.declared.get(name, ()))
            for twin_auto in twin_autos:
                twin = twin_auto / name
                if twin.is_file():
                    pats |= detect(raw, _load(twin))
        except (ValueError, OSError):
            return
        pats = sorted(pats)
        self.raw[name], self.patterns[name] = raw, pats
        self.masked[name] = mask(raw, pats) if pats else raw


def path_patch(base: Base, path_auto: Path) -> Tuple[dict, List[str]]:
    """``(files, unverified)`` for one path build; ``PathFailed`` on a bad file."""
    files: Dict[str, dict] = {}
    unverified: List[str] = []
    for name, raw in base.raw.items():
        target = path_auto / name
        if not target.is_file():
            continue
        try:
            got = _load(target)
        except (ValueError, OSError) as exc:
            raise PathFailed("%s unreadable (%s)" % (name, exc))
        pats = base.patterns[name]
        ops = file_ops(raw, got, pats, base.masked[name])
        if not ops:
            continue
        if not roundtrip_ok(raw, got, ops, pats):
            raise PathFailed("round-trip failed for %s" % name)
        entry = _published_entry(base, name, raw, ops, pats)
        if entry is None:
            unverified.append(name)
        else:
            files[name] = entry
    return files, unverified


def _published_entry(base: Base, name: str, raw: Any, ops: list,
                     pats: List[str]) -> Optional[dict]:
    pub_file = base.pub / name
    if not pub_file.is_file():
        return None
    sha = _sha(pub_file)
    if sha != _sha(base.main / name):
        try:
            ok = published_ok(_load(pub_file), raw, ops, pats)
        except (ValueError, OSError):
            ok = False
        if not ok:
            return None
    return {"base_sha256": sha, "ops": ops}


def _changed(files: dict, unverified: List[str]) -> dict:
    by_file = count_by_file(files)
    results = {n: c for n, c in by_file.items() if n not in BOOKKEEPING}
    return {"count": sum(results.values()), "by_artifact": results,
            "bookkeeping_ops": sum(by_file.values()) - sum(results.values()),
            "unverified_files": unverified,
            "inert": not results and not unverified}


def _write(path: Path, doc: Any, indent: Optional[int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    seps = (",", ":") if indent is None else None
    text = json.dumps(doc, ensure_ascii=False, indent=indent, separators=seps)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text + "\n")


def enumerate_runs(runs: Path) -> List[dict]:
    """The ``DONE.json`` records under ``runs`` (only finished paths)."""
    found = []
    for done in sorted(Path(runs).glob("*/DONE.json")):
        rec = _load(done)
        pid = rec.get("path")
        if not isinstance(pid, str) or not PATH_ID.match(pid) or "--" not in pid:
            raise ValueError("bad path id in %s" % done)
        rec["dir"] = done.parent
        found.append(rec)
    return found


def _engine() -> dict:
    here = Path(__file__).resolve().parent
    try:
        from importlib.metadata import version
        ver: Optional[str] = version("metaphysica")
    except Exception:
        ver = None
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=here,
                             capture_output=True, text=True, timeout=20)
        commit = out.stdout.strip() or None
    except (OSError, subprocess.SubprocessError):
        commit = None
    return {"version": ver, "commit": commit}


def _theory_results(theory: str):
    if not re.match(r"^[a-z0-9_]+$", theory):
        raise ValueError("bad theory name %r" % theory)
    return importlib.import_module("metaphysica.theories.%s.results" % theory)


def _entry(res: Any, rec: dict, changed: dict) -> dict:
    entry = res.deviation_entry(rec["fork"], rec["option"])
    entry.update({"id": rec["path"], "computed": True,
                  "inert": changed["inert"], "changed_values": changed["count"],
                  "changed_artifacts": sorted(changed["by_artifact"]),
                  "build": {"exit": rec.get("exit"), "secs": rec.get("secs")}})
    return entry


_EXC_LINE = re.compile(r"^\w+(Error|Exception): .*")


def _build_status(root: Path) -> Optional[dict]:
    """``AutoGenerated/build_status.json`` of a build, or None when absent."""
    try:
        doc = _load(Path(root) / "AutoGenerated" / "build_status.json")
    except (OSError, ValueError):
        return None
    return doc if isinstance(doc, dict) else None


def _failed_steps(root: Path) -> List[dict]:
    status = _build_status(root)
    rows = status.get("failed_steps") if status else None
    return [r for r in rows if isinstance(r, dict)] if isinstance(rows, list) else []


def _log_reason(rec: dict) -> Optional[str]:
    """The last exception line of ``<runs>/<path_id>.log``, if there is one."""
    log = Path(rec["dir"]).parent / (rec["path"] + ".log")
    try:
        text = log.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return None
    found = [ln.strip() for ln in text.splitlines() if _EXC_LINE.match(ln)]
    return found[-1] if found else None


def volatile_ids(base: Base) -> frozenset:
    """Parameter ids whose value differs between builds of main."""
    out = set()
    for pat in base.patterns.get("parameters.json", []):
        parts = split_pointer(pat)
        if len(parts) >= 2 and parts[0] == "parameters" and parts[1] != "*"                 and (len(parts) == 2 or parts[2] == "value"):
            out.add(parts[1])
    return frozenset(out)


def _check_computed(res: Any, rec: dict) -> List[dict]:
    """The failed non-required steps; ``PathFailed`` if the path did not compute."""
    failed = _failed_steps(rec["dir"])
    required = set(getattr(res, "REQUIRED_STEPS", ()))
    for step in failed:
        if step.get("id") in required:
            raise PathFailed(step.get("reason") or "required step %s failed "
                             "(exit %s)" % (step.get("id"), step.get("exit")))
    if rec.get("exit") != 0 and _build_status(rec["dir"]) is None:
        raise PathFailed(_log_reason(rec)
                         or "build failed (exit %s)" % rec.get("exit"))
    return failed


def _publish_one(res: Any, base: Base, rec: dict, out: Path,
                 main_root: Path) -> Tuple[dict, dict]:
    failed = _check_computed(res, rec)
    path_auto = _auto(rec["dir"])
    files, unverified = path_patch(base, path_auto)
    changed = _changed(files, unverified)
    summary = res.build_summary(rec["path"], main_root, rec["dir"], changed,
                                volatile_ids(base))
    summary["failed_steps"] = failed
    keys = sorted("%s:%s" % (n, p) for n in files for p in base.patterns[n])
    patch = {"schema": "metaphysica.path_patch/1", "path": rec["path"],
             "files": files, "excluded_keys": keys}
    pdir = out / rec["path"]
    _write(pdir / "summary.json", summary, 1)
    _write(pdir / "patch.json", patch, None)
    entry = _entry(res, rec, changed)
    entry["failed_steps"] = [f.get("id") for f in failed]
    return entry, files


def publish(theory: str, main: Path, volatile: Union[Path, Sequence[Path]],
            runs: Path, published: Path, out: Path) -> dict:
    """Write ``out/index.json`` and ``out/<path_id>/{summary,patch}.json``.

    ``volatile`` is one twin build of main, or several.
    """
    twins = [Path(volatile)] if isinstance(volatile, (str, Path)) else         [Path(v) for v in volatile]
    checks = [("main", main), ("runs", runs), ("published", published)] +         [("volatile", t) for t in twins]
    for label, p in checks:
        if not Path(p).is_dir():
            raise ValueError("%s run is not a directory: %s" % (label, p))
    res = _theory_results(theory)
    base = Base(Path(main), twins, Path(published),
                getattr(res, "STOCHASTIC", None))
    entries, skipped, used = [], [], set()
    for rec in enumerate_runs(runs):
        try:
            entry, files = _publish_one(res, base, rec, Path(out), Path(main))
        except (PathFailed, ValueError) as exc:
            skipped.append({"id": rec["path"], "fork": rec.get("fork"),
                            "option": rec.get("option"), "reason": str(exc)})
            continue
        entries.append(entry)
        used.update(files)
    return _write_index(res, base, theory, Path(out), Path(main),
                        entries, skipped, used)


def _write_index(res: Any, base: Base, theory: str, out: Path, main: Path,
                 entries: List[dict], skipped: List[dict], used: set) -> dict:
    main_entry = res.main_entry()
    main_failed = _failed_steps(main)
    main_entry.update({"id": "main", "computed": True, "inert": False,
                       "changed_values": 0, "changed_artifacts": [],
                       "failed_steps": [f.get("id") for f in main_failed]})
    zero = {"count": 0, "by_artifact": {}, "bookkeeping_ops": 0,
            "unverified_files": [],
            "inert": False}
    main_summary = res.build_summary("main", main, main, zero)
    main_summary["failed_steps"] = main_failed
    _write(out / "main" / "summary.json", main_summary, 1)
    _write(out / "main" / "patch.json",
           {"schema": "metaphysica.path_patch/1", "path": "main", "files": {},
            "excluded_keys": []}, None)
    entries.sort(key=lambda e: e["id"])
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    index = {"schema": "metaphysica.paths/1", "theory": theory, "main": "main",
             "generated": stamp, "engine": _engine(),
             "base": {n: _sha(base.pub / n) for n in sorted(used)},
             "paths": [main_entry] + entries, "not_computed": skipped}
    _write(out / "index.json", index, 1)
    return index


def cmd_paths_publish(args: Any, theory: Any = None) -> int:
    """CLI handler for ``paths-publish``; the theory object is not needed."""
    index = publish(args.theory or "pm", Path(args.main_run),
                    [Path(v) for v in args.volatile_run], Path(args.runs),
                    Path(args.published), Path(args.out))
    paths = index["paths"]
    print("paths-publish: %d computed (%d inert), %d not computed -> %s" % (
        len(paths), sum(1 for p in paths if p["inert"]),
        len(index["not_computed"]), args.out))
    return 0
