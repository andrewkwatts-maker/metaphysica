from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Dict, FrozenSet, Mapping, Optional, Tuple

__all__ = ["Selection", "Rows", "Option", "differs", "changed", "load_rows"]

Selection = Mapping[str, str]
Rows = Mapping[str, Any]
Option = Tuple[str, str]

REL_TOL = 1e-12


def differs(a: Any, b: Any) -> bool:
    """True when two row values differ: rel 1e-12, NaN equals NaN, exact otherwise."""
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if math.isnan(a) and math.isnan(b):
            return False
        return not math.isclose(a, b, rel_tol=REL_TOL, abs_tol=0.0)
    return a != b


def changed(base: Rows, other: Rows) -> FrozenSet[str]:
    """Row keys whose value differs between *base* and *other* (a missing key is None)."""
    keys = set(base) | set(other)
    return frozenset(k for k in keys if differs(base.get(k), other.get(k)))


def load_rows(run_root: Path) -> Optional[Dict[str, Any]]:
    """Read `AutoGenerated/parameters.json` as {key: value}; None when absent."""
    path = Path(run_root) / "AutoGenerated" / "parameters.json"
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))["parameters"]
    return {k: v.get("value") for k, v in data.items()}
