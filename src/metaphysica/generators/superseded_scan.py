"""Scan every published text surface for prose presenting a retired pathway.

Active geometry is seed_43_joyce (D-025). A block that still presents b3 = 24,
twisted connected sums or fano_tcs as active is a hit, unless it sits inside a
"superseded path" callout (marked by SUPERSEDED_MARK). The vocabulary is the
retired b3 = 24 / TCS claims plus the claim of every DISABLED option in
variants.FORKS, so a newly disabled option is scanned for without an edit here.

Surfaces: sections.json, the other AutoGenerated files, Pages html and the
website source the static pages are generated from.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any, Dict, Iterable, Iterator, List, Optional, Pattern, Tuple

from metaphysica.generators._common import autogen_dir

#: Marker the shared callout puts in its text; hits inside it are fine.
SUPERSEDED_MARK = "Superseded path"

_B3_24 = re.compile(r"\bb\s*(?:_\s*\{?\s*3\s*\}?|₃|3)\s*(?:=|\?equiv|:)\s*24\b"
                    r"|\bb_?\{?3\}?\s*=\s*24\b|\bb₃\s*=\s*24\b"
                    r"|\bb3\s*=\s*24\b|\bbetti_?3\s*=\s*24\b", re.I)
_WORDS = re.compile(r"\bTCS\b|twisted[ -]connected[ -]sum|fano[_ -]?tcs", re.I)

#: A hit whose surrounding text carries one of these already says the geometry
#: is retired, so it is not presented as active.
_RETIRED = re.compile(
    r"off-path|retired|superseded|withdrawn|formerly|previously|earlier|"
    r"was false|falsified|abandoned|not among|seed_24|used to|no longer|"
    r"not a (?:twisted|TCS)|not (?:the )?TCS|excludes|stood at|"
    r"originally|old wording|\bwas (?:its|fitted|written)|artefact|"
    r"is not in it|suspended|record of|rejected|replaced|is OFF|now off|"
    r"published as|no published|not read off|not taken from|"
    r"relocated from|belonged to|read \"|typed|"
    r"not derived from|not reachable|status quo|diverges off|"
    r"Kovalev|Corti|Haskins|Nordstr|Reine Angew|Invent\. Math|arXiv", re.I)
#: A single token with no spaces is an identifier (option id, key), not prose.
_IDENT = re.compile(r"^[\w:.\-\[\]/#]+$")
_WINDOW = 220


_GAP = r"(?:\s|_|\{|\}|\$|\\|<[^>]*>)*"
_SUBSCRIPT = {"₃": "3", "₂": "2", "²": "^2"}


def _claim_regex(claim: str) -> Optional[Pattern]:
    """Whitespace/markup-tolerant regex for one formula claim, or None."""
    chars = [c for c in re.sub(r"[\s_{}$\\]", "", claim)]
    if len(chars) < 4 or not any(c.isdigit() for c in chars):
        return None
    parts = [re.escape(c) if not c.isdigit() else "(?:%s|%s)" % (c, "".join(
        k for k, v in _SUBSCRIPT.items() if v == c) or c) for c in chars]
    tail = (r"(?![\d.])(?=\s*(?:$|[,;.:)\]<|]|(?:and|or|with|gives|is|so)))"
            if chars[-1].isdigit() else "")
    return re.compile(_GAP.join(parts) + tail, re.I)


def _claim_forms(summary: str) -> List[str]:
    """The formula claim an option summary opens with (before ' -- ', ' via ').

    Only the first clause: later ones ("b_2 = 4") are shared with other paths.
    A clause whose right side has no number of its own is prose, not a claim.
    """
    head = re.split(r" -- | via | at |\(the |, so ", summary)[0]
    clause = re.split(r"[;,]", head)[0]
    sides = [x.strip() for x in clause.split("=")]
    if len(sides) < 2 or not re.search(r"(?<![_b])\d", sides[-1]):
        return []
    return [clause.strip(), "%s = %s" % (sides[0], sides[-1])]


def disabled_vocabulary(forks: Optional[Dict[str, Any]] = None) -> List[Pattern]:
    """Regexes for the claim of every DISABLED fork option, from the data."""
    if forks is None:
        from metaphysica.simulations.core.variants import FORKS as forks
    out = []
    for fork in forks.values():
        for opt in fork.options:
            if opt.status != "disabled":
                continue
            out += [r for r in map(_claim_regex, _claim_forms(opt.summary)) if r]
    return out


_VOCAB: List[Pattern] = []


def _vocab() -> List[Pattern]:
    if not _VOCAB:
        _VOCAB.extend(disabled_vocabulary())
    return _VOCAB


def _match(text: str):
    """First retired-claim match in text, or None."""
    m = _B3_24.search(text) or _WORDS.search(text)
    if m:
        return m
    for rx in _vocab():
        m = rx.search(text)
        if m:
            return m
    return None


#: A dict whose status says this, labels every string under it as retired.
_LABEL_STATUS = re.compile(r"disabled|off[-_ ]?path|retired|superseded|refuted", re.I)


def _is_labelled(node: Dict[str, Any]) -> bool:
    """True when a dict declares its own status as a retired pathway."""
    return any(isinstance(node.get(k), str) and _LABEL_STATUS.search(node[k])
               for k in ("status", "state", "verdict", "path_status"))


def _strings(node: Any, path: str, labelled: bool = False
             ) -> Iterator[Tuple[str, str, bool]]:
    """Yield (path, text, labelled) for every string under node."""
    if isinstance(node, str):
        yield path, node, labelled
    elif isinstance(node, dict):
        labelled = labelled or _is_labelled(node)
        for k, v in node.items():
            if k in ("html", "content_blocks"):
                continue  # html is derived; content_blocks duplicates contentBlocks
            yield from _strings(v, "%s.%s" % (path, k), labelled)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            yield from _strings(v, "%s[%d]" % (path, i), labelled)


def is_hit(text: str) -> bool:
    """True when text presents the retired geometry (identifiers are not prose)."""
    return not _IDENT.match(text) and _match(text) is not None


def scan_sections(sections: Dict[str, Any]) -> List[Dict[str, str]]:
    """All hits as dicts: section, path, in_callout, snippet."""
    hits = []
    for sid, sec in sections.items():
        for path, text, labelled in _strings(sec, sid):
            if not is_hit(text):
                continue
            m = _match(text)
            lo = max(0, m.start() - 60)
            near = text[max(0, m.start() - _WINDOW):m.end() + _WINDOW]
            hits.append({"section": sid, "path": path,
                         "in_callout": (labelled or SUPERSEDED_MARK in text
                                        or bool(_RETIRED.search(near))),
                         "snippet": text[lo:m.end() + 60].replace("\n", " ")})
    return hits


def load_hits(path: Path = None) -> List[Dict[str, str]]:
    """Scan the published sections.json."""
    path = path or autogen_dir() / "sections.json"
    if not path.is_file():
        raise SystemExit("superseded_scan: %s missing" % path)
    data = json.loads(path.read_text(encoding="utf-8"))
    return scan_sections(data["sections"])


#: Text surfaces beyond sections.json. Each maps to (subdirectory, suffixes).
SURFACES = ("sections", "autogen", "pages", "website")
_TEXT_SUFFIXES = (".json", ".md", ".txt", ".html", ".js")
WEBSITE_SRC = Path(__file__).resolve().parent.parent / "website"


def _line_hits(text: str, label: str) -> List[Dict[str, str]]:
    """One hit per line of a plain-text file that presents a retired claim."""
    hits, pos = [], 0
    for line in text.splitlines(True):
        m = _match(line)
        if m:
            near = text[max(0, pos + m.start() - _WINDOW):pos + m.end() + _WINDOW]
            hits.append({"section": label, "path": label,
                         "in_callout": (SUPERSEDED_MARK in near
                                        or bool(_RETIRED.search(near))),
                         "snippet": line[max(0, m.start() - 60):m.end() + 60]
                         .strip()})
        pos += len(line)
    return hits


def scan_file(path: Path, label: str) -> List[Dict[str, str]]:
    """Hits in one published file: JSON by string, anything else by line."""
    text = path.read_text(encoding="utf-8", errors="replace")
    if path.suffix == ".json":
        try:
            data = json.loads(text)
        except ValueError:
            return _line_hits(text, label)
        out = scan_sections({label: data})
        for h in out:
            h["section"] = label
        return out
    return _line_hits(text, label)


def surface_files(surface: str, root: Path) -> Iterator[Tuple[Path, str]]:
    """(file, label) for every text file of a surface under root."""
    base = {"autogen": root / "AutoGenerated", "pages": root / "Pages",
            "website": root}[surface]
    for f in sorted(base.rglob("*")):
        if not f.is_file() or f.suffix not in _TEXT_SUFFIXES:
            continue
        rel = f.relative_to(base).as_posix()
        if surface == "autogen" and rel == "sections.json":
            continue
        yield f, "%s/%s" % (surface, rel)


def scan_surface(surface: str, root: Path = None) -> List[Dict[str, str]]:
    """All hits on one surface. root is the published tree (website: source)."""
    if surface == "sections":
        return load_hits((root / "AutoGenerated" / "sections.json")
                         if root else None)
    if surface == "website":
        root = WEBSITE_SRC
    hits: List[Dict[str, str]] = []
    for f, label in surface_files(surface, root):
        hits += scan_file(f, label)
    return hits


def active_hits(hits: List[Dict[str, str]]) -> List[Dict[str, str]]:
    """Hits outside a superseded callout."""
    return [h for h in hits if not h["in_callout"]]


if __name__ == "__main__":
    if len(sys.argv) > 2:
        for sf in SURFACES:
            h = scan_surface(sf, Path(sys.argv[2]))
            print(sf, len(h), len(active_hits(h)))
        raise SystemExit(0)
    hs = load_hits()
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else None
    text = json.dumps(hs, indent=1, ensure_ascii=False)
    if out:
        out.write_text(text, encoding="utf-8")
    print(len(hs), len(active_hits(hs)))
