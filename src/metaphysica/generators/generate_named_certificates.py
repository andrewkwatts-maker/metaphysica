#!/usr/bin/env python3
"""Write the 97 *named* (per-category, semantic) certificate JSONs.

The pre-refactor build (``pre-refactor-v24.2`` baseline) emitted 97
certificate JSONs grouped under ``AutoGenerated/certificates/<category>/``.

There are two flavours in the baseline:

1. **Numbered gate certs** copied into a category subdir
   (``cosmology/G48_w0_equation_of_state.json``,
   ``geometry/G01_integer_root_parity.json``, ...). Same shape as the
   per-gate JSONs already emitted by
   :mod:`metaphysica.generators.generate_72_certificates`, just filed
   under the gate's physics category.

2. **Named semantic certs** documenting a specific physics claim with a
   different schema (``cosmology/dark_energy_alignment.json``,
   ``geometry/alpha_geometric.json``, ``particle/proton_lifetime.json``,
   ...). These reference one or more numbered gates and carry
   experimental-comparison / derivation-chain metadata.

Re-deriving every cert procedurally from the live registry would be a
sprint in itself. The pragmatic approach (per Sprint 6 #8 plan): ship the
verbatim baseline shapes as packaged data and copy them into the build's
``AutoGenerated/certificates/`` tree. The 72 numbered top-level
certificates produced by ``generate_72_certificates`` are *not* touched
— these per-category copies are sibling outputs.

The bundled JSON snapshots live at
``metaphysica/data/named_certificates/<category>/*.json``.

Run standalone:

    python -m metaphysica.generators.generate_named_certificates

Counts the files written, prints per-category totals, exits 0 on success.
"""
from __future__ import annotations

import json
import shutil
import sys
from pathlib import Path

from metaphysica.generators._common import autogen_dir as _autogen_dir


def _source_root() -> Path:
    """Directory of bundled baseline named-cert JSONs (one subdir per category)."""
    return Path(__file__).resolve().parent.parent / "data" / "named_certificates"


def _target_root() -> Path:
    """``AutoGenerated/certificates/`` under the active build output."""
    return _autogen_dir() / "certificates"


def write_named_certificates() -> dict[str, int]:
    """Copy every bundled named cert into ``AutoGenerated/certificates/<category>/``.

    Returns
    -------
    dict mapping category name -> number of cert files written.

    Raises
    ------
    FileNotFoundError
        If the bundled data tree is missing (developer install gone wrong).
    json.JSONDecodeError
        If any bundled snapshot is corrupt — we read+rewrite to validate
        and pretty-print uniformly with the rest of the build.
    """
    src = _source_root()
    if not src.is_dir():
        raise FileNotFoundError(
            f"Bundled named-certificate snapshots not found at {src}. "
            "Ensure the metaphysica.data package was installed correctly."
        )

    tgt = _target_root()
    tgt.mkdir(parents=True, exist_ok=True)

    per_category: dict[str, int] = {}

    for category_dir in sorted(p for p in src.iterdir() if p.is_dir()):
        category = category_dir.name
        out_dir = tgt / category
        out_dir.mkdir(parents=True, exist_ok=True)

        count = 0
        for cert_path in sorted(category_dir.glob("*.json")):
            # Round-trip through json to (a) validate structure and
            # (b) normalize formatting with the rest of AutoGenerated/.
            with cert_path.open("r", encoding="utf-8") as f:
                cert = json.load(f)
            out_path = out_dir / cert_path.name
            with out_path.open("w", encoding="utf-8") as f:
                json.dump(cert, f, indent=2, ensure_ascii=False)
            count += 1

        per_category[category] = count

    return per_category


def main() -> int:
    counts = write_named_certificates()
    total = sum(counts.values())
    print(f"\n=== Named Certificates Generated ===")
    for cat in sorted(counts):
        print(f"  {cat:16s}  {counts[cat]:3d}")
    print(f"  {'TOTAL':16s}  {total:3d}")
    print(f"\nOutput root: {_target_root()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
