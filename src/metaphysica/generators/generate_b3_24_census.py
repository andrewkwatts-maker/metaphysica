"""Census of every 24 in the simulation tree, classified. The sweep's worklist.

The b3_seed adoption (2026-09-22) made "24" ambiguous in the worst way: some
24s were b_3 and MOVED to 43, some are the bulk's spacelike core / the Leech
dimension / oscillator counts and correctly STAY 24, and some are unrelated
(hours, indices, tolerances). Three sims and four formulas had already
conflated the first two kinds; this census finds the rest, so the sweep works
a measured list instead of a grep and a prayer.

Classification is by CONTEXT LINE, two axes:

  kind:  VALUE  -- a live 24 in executable code
         PROSE  -- a 24 inside a comment, docstring or string literal
  class: B3_MOVES    -- context ties it to b3/b_3/betti/elder_kads and no
                        bulk marker: this 24 should now read the seed (43)
                        or be re-expressed; every one is sweep work.
         BULK_STAYS  -- context carries a bulk marker (D_space, Leech,
                        transverse, oscillator, (24,2), core): correct as 24.
         AMBIGUOUS   -- both markers or neither with b3 nearby: needs a
                        human read; the count is pinned and worked DOWN.

Output: AutoGenerated/b3_24_census.json with per-file, per-class counts and
the flagged lines, timestamp-stable via write_json_stable.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any, Dict

_SRC = Path(__file__).resolve().parents[1] / "simulations"

_B3 = re.compile(r"b3|b_3|betti|elder_kads", re.IGNORECASE)
_BULK = re.compile(
    r"D_space|D_core|leech|lattice|transverse|oscillat|\(24,\s*2\)|24,2"
    r"|spacelike|two.time|bosonic string|niemeier|hour", re.IGNORECASE)
_24 = re.compile(r"(?<![\d.>_])24(?![\d.])")
_COMMENTISH = re.compile(r"^\s*#|^\s*\"|^\s*'|\"\"\"|'''")


def classify_line(line: str) -> str:
    has_b3 = bool(_B3.search(line))
    has_bulk = bool(_BULK.search(line))
    if has_bulk and not has_b3:
        return "BULK_STAYS"
    if has_b3 and not has_bulk:
        return "B3_MOVES"
    if has_b3 and has_bulk:
        return "AMBIGUOUS"
    return "UNRELATED"


def census() -> Dict[str, Any]:
    per_file: Dict[str, Dict[str, Any]] = {}
    totals = {"B3_MOVES": 0, "BULK_STAYS": 0, "AMBIGUOUS": 0, "UNRELATED": 0}
    kinds = {"VALUE": 0, "PROSE": 0}

    for path in sorted(_SRC.rglob("*.py")):
        rel = path.relative_to(_SRC).as_posix()
        rows = []
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        for lineno, line in enumerate(text.splitlines(), 1):
            if not _24.search(line):
                continue
            cls = classify_line(line)
            if cls == "UNRELATED":
                totals[cls] += 1
                continue
            kind = "PROSE" if _COMMENTISH.search(line) else "VALUE"
            totals[cls] += 1
            kinds[kind] += 1
            rows.append({"line": lineno, "kind": kind, "class": cls,
                         "text": line.strip()[:160]})
        if rows:
            counts: Dict[str, int] = {}
            for r in rows:
                key = "%s_%s" % (r["class"], r["kind"])
                counts[key] = counts.get(key, 0) + 1
            per_file[rel] = {"counts": counts, "rows": rows}

    return {
        "what_this_counts": (
            "occurrences of the token 24 in simulation source, classified by "
            "context line. B3_MOVES entries are sweep work (the 24 was b_3 "
            "and the adopted seed is 43); BULK_STAYS are correct; AMBIGUOUS "
            "need a human read and the count only goes down."
        ),
        "totals": totals,
        "kinds": kinds,
        "n_files_flagged": len(per_file),
        "files": per_file,
    }


def main() -> int:
    from metaphysica.generators._common import autogen_dir, write_json_stable

    report = census()
    out = autogen_dir() / "b3_24_census.json"
    write_json_stable(out, report)
    t = report["totals"]
    print("b3-24 census: B3_MOVES=%d BULK_STAYS=%d AMBIGUOUS=%d over %d files"
          % (t["B3_MOVES"], t["BULK_STAYS"], t["AMBIGUOUS"],
             report["n_files_flagged"]))
    print("written:", out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
