# Main check
# ---------------------------------------------------------------------------

def run_crosscheck(
    tolerance: float = DEFAULT_TOLERANCE,
    verbose: bool = False,
    only_fails: bool = False,
    loose_tolerance: float = 0.01,  # 1% — AGREE_LOOSE bucket
) -> dict[str, Any]:
    from collections import Counter
    params = _load_parameters(PARAMS_JSON)
    context = _build_context(params)
    offer_policy = write_offer_policy(params)

    evaluator = EMLEvaluator(context, strict=False)

    results: list[dict[str, Any]] = []
    bucket_counts: Counter = Counter()
    n_agree = n_disagree = n_skip = n_no_value = 0
    n_error = 0

    for path, entry in sorted(params.items()):
        eml_desc = _get_eml_description(entry)
        if not eml_desc:
            n_skip += 1
            if verbose:
                results.append({"path": path, "status": "SKIP", "reason": "no eml_description"})
            continue

        registered_val = entry.get("value")
        if registered_val is None:
            n_no_value += 1
            results.append({
                "path": path,
                "status": "SKIP",
                "reason": "no registered value",
                "eml_description": eml_desc,
            })
            continue

        try:
            registered_float = float(registered_val)
        except (TypeError, ValueError):
            n_no_value += 1
            results.append({
                "path": path,
                "status": "SKIP",
                "reason": f"non-numeric value: {registered_val!r}",
                "eml_description": eml_desc,
            })
            continue

        err_msg: Optional[str] = None
        try:
            evaluated = evaluator.eval(eml_desc)
        except Exception as exc:
            evaluated = None
            err_msg = str(exc)

        if evaluated is None:
            # An expression that does not EVALUATE is a failure of the EML
            # representation, not a skip. Counting it as a skip removed it
            # from the denominator and inflated the agreement rate (2026-08
            # audit: 127 records were hidden this way, taking the reported
            # strict rate from 58.6% to 74.4%).
            n_error += 1
            bucket_counts["ERROR"] += 1
            rec = {
                "path": path,
                "status": "ERROR",
                "reason": err_msg or "eval raised exception",
                "registered": registered_float,
                "eml_description": eml_desc,
            }
            results.append(rec)
            if verbose:
                print(f"  ERROR  {path}: {err_msg}")
            continue

        if not math.isfinite(evaluated) or not math.isfinite(registered_float):
            n_skip += 1
            results.append({
                "path": path,
                "status": "SKIP",
                "reason": "non-finite value",
                "evaluated": evaluated,
                "registered": registered_float,
                "eml_description": eml_desc,
            })
            continue

        missing = list(evaluator.missing_refs)
        evaluator.missing_refs.clear()

        rel_err = _rel_error(evaluated, registered_float)
        status, diag = _classify(
            evaluated, registered_float, tolerance, loose_tolerance, missing,
        )
        bucket_counts[status] += 1

        rec: dict[str, Any] = {
            "path": path,
            "status": status,
            "evaluated": evaluated,
            "registered": registered_float,
            "rel_error": rel_err,
            "eml_description": eml_desc,
        }
        if diag:     rec["diagnostic"]   = diag
        if missing:  rec["missing_refs"] = missing

        results.append(rec)

        if status in ("AGREE", "AGREE_LOOSE"):
            n_agree += 1
            if verbose and not only_fails:
                print(f"  {status}  {path}  (eval={evaluated:.6g}  reg={registered_float:.6g})")
        else:
            n_disagree += 1
            print(
                f"  {status}  {path}\n"
                f"    evaluated={evaluated:.8g}  registered={registered_float:.8g}"
                f"  ({diag})"
            )

    total_with_desc = n_agree + n_disagree
    total_scored = total_with_desc + n_error   # errors count as failures
    total = len(params)

    print("\n" + "=" * 60)
    print(f"TOTAL parameters:          {total}")
    print(f"  with eml_description:    {total_with_desc + n_no_value}")
    print(f"  SKIP (no value/error):   {n_skip + n_no_value}")
    print()
    print(f"  AGREE  (<={tolerance:.1%}):              {bucket_counts.get('AGREE', 0)}")
    print(f"  AGREE_LOOSE  (<={loose_tolerance:.0%}):          {bucket_counts.get('AGREE_LOOSE', 0)}")
    print(f"  DISAGREE_SIGN (mag matches):  {bucket_counts.get('DISAGREE_SIGN', 0)}")
    print(f"  DISAGREE_SCALE (x10^k):       {bucket_counts.get('DISAGREE_SCALE', 0)}")
    print(f"  DISAGREE_MISSING_CTX:         {bucket_counts.get('DISAGREE_MISSING_CTX', 0)}")
    print(f"  DISAGREE_NONFINITE:           {bucket_counts.get('DISAGREE_NONFINITE', 0)}")
    print(f"  DISAGREE (other):             {bucket_counts.get('DISAGREE', 0)}")
    if total_with_desc > 0:
        strict = 100 * bucket_counts.get('AGREE', 0) / total_with_desc
        loose  = 100 * (bucket_counts.get('AGREE', 0) + bucket_counts.get('AGREE_LOOSE', 0)) / total_with_desc
        print()
        print(f"  ERROR (did not evaluate):     {n_error}")
        _print_error_breakdown(results)
        if total_scored > 0:
            print(f"  Strict rate counting errors:  {100*bucket_counts.get('AGREE',0)/total_scored:.1f}%")
        print(f"  Strict agreement rate:   {strict:.1f}%  (of those that evaluated)")
        print(f"  Loose  agreement rate:   {loose:.1f}%")
    print("=" * 60)

    summary = {
        "total": total,
        "with_eml_description": total_with_desc + n_no_value,
        "skip": n_skip + n_no_value,
        "buckets": dict(bucket_counts),
        "errors": n_error,
        "note": (
            "agreement_rate_strict/loose are computed over expressions that "
            "EVALUATED. agreement_rate_strict_all counts unevaluable "
            "expressions (ERROR) as failures and is the honest headline: an "
            "EML description that does not evaluate is a broken "
            "representation, not a skip."
        ),
        "agreement_rate_strict_all": (
            bucket_counts.get('AGREE', 0) / total_scored if total_scored > 0 else None
        ),
        "agreement_rate_strict": (
            bucket_counts.get('AGREE', 0) / total_with_desc if total_with_desc > 0 else None
        ),
        "agreement_rate_loose": (
            (bucket_counts.get('AGREE', 0) + bucket_counts.get('AGREE_LOOSE', 0))
            / total_with_desc if total_with_desc > 0 else None
        ),
        "eml_option_withheld": len(offer_policy["_unrenderable"]),
        "eml_option_offered": offer_policy["_offered_count"],
        "tolerance": tolerance,
        "loose_tolerance": loose_tolerance,
        "results": results,
    }

    OUTPUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    def _json_safe(obj: Any) -> Any:
        if isinstance(obj, float) and not math.isfinite(obj):
            return str(obj)
        if isinstance(obj, dict):
            return {k: _json_safe(v) for k, v in obj.items()}
        if isinstance(obj, list):
            return [_json_safe(v) for v in obj]
        return obj

    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(_json_safe(summary), f, indent=2)
    print(f"\nDetailed results -> {OUTPUT_JSON}")

    return summary


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="Cross-check eml_description fields in parameters.json")
    parser.add_argument("--tolerance", type=float, default=DEFAULT_TOLERANCE,
                        help=f"Relative tolerance for AGREE (default {DEFAULT_TOLERANCE})")
    parser.add_argument("--verbose", action="store_true",
                        help="Print AGREE lines too (default: only DISAGREE)")
    parser.add_argument("--only-fails", action="store_true",
                        help="Only print DISAGREE/ERROR lines")
    args = parser.parse_args()

    summary = run_crosscheck(
        tolerance=args.tolerance,
        verbose=args.verbose,
        only_fails=args.only_fails,
    )

    # Exit non-zero only when there are *real* disagreements (not loose agreements)
    real_disagreements = sum(
        v for k, v in summary["buckets"].items() if k.startswith("DISAGREE")
    )
    if real_disagreements > 0:
        sys.exit(1)


if __name__ == "__main__":
    main()
