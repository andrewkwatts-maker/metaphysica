"""
eml_param_crosscheck.py — Cross-check all eml_description strings in parameters.json.

For every parameter that has an eml_description field, parses and evaluates the
EML expression using EMLEvaluator and compares the result to the registered value.

Results are printed as a table and written to AutoGenerated/eml_crosscheck.json.

Usage:
    python scripts/eml_param_crosscheck.py
    python scripts/eml_param_crosscheck.py --verbose
    python scripts/eml_param_crosscheck.py --tolerance 0.05  # 5% rel tolerance
    python scripts/eml_param_crosscheck.py --only-fails
"""
from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path
from typing import Any, Optional

from metaphysica.generators._common import out_dir as _out_dir, autogen_dir as _autogen_dir
ROOT = _out_dir()
sys.path.insert(0, str(ROOT))

try:
    from eml_math.evaluator import EMLEvaluator
except ImportError as e:
    print(f"ERROR: cannot import eml_math.evaluator — {e}")
    print("Install or update eml-math: pip install -e H:/Github/EML-Math")
    sys.exit(1)

PARAMS_JSON = ROOT / "AutoGenerated" / "parameters.json"
OUTPUT_JSON = ROOT / "AutoGenerated" / "eml_crosscheck.json"
OFFER_JSON  = ROOT / "AutoGenerated" / "eml_offer_policy.json"

DEFAULT_TOLERANCE = 0.001  # 0.1% relative tolerance


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _load_parameters(path: Path) -> dict[str, Any]:
    """Load parameters.json and return the flat {dotted_path: entry} dict.

    parameters.json has the structure::
        {"version": ..., "parameters": {"ckm.V_cb": {...}, ...}}
    so we just return the inner "parameters" dict directly.
    """
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return data.get("parameters", data)


def _get_eml_description(entry: dict[str, Any]) -> str:
    """Return eml_description from an entry (top-level or inside metadata)."""
    desc = entry.get("eml_description", "")
    if not desc:
        desc = (entry.get("metadata") or {}).get("eml_description", "")
    return desc or ""


def _build_context(params: dict[str, Any]) -> dict[str, float]:
    """Build {name: float_value} context for EMLEvaluator from all params.

    Aliases (low → high priority, later wins on collision):
      1. last component  ``c``      (e.g. ``lambda_wolfenstein``)
      2. last two parts  ``b.c``    (e.g. ``ckm.lambda_wolfenstein``)
      3. full path       ``a.b.c``  (always available)
      4. FormulasRegistry seeds + symbols — canonical short names like
         ``b3 = 24``, ``chi_eff = 72``, ``M_Planck`` etc. These OVERRIDE
         heuristic short aliases so eml_descriptions referencing the
         well-known seed names get the seed value, not whatever happened
         to be at ``topology.b3_modular`` or ``geometry.chi_eff_total``.
    """
    ctx: dict[str, float] = {}

    # 1+2 — short / medium aliases (low priority)
    for path, entry in params.items():
        val = entry.get("value")
        if val is None: continue
        try:    f = float(val)
        except (TypeError, ValueError): continue
        if not math.isfinite(f): continue

        parts = path.split(".")
        ctx.setdefault(parts[-1], f)
        if len(parts) >= 2:
            ctx.setdefault(".".join(parts[-2:]), f)

    # 3 — full paths (override)
    for path, entry in params.items():
        val = entry.get("value")
        if val is None: continue
        try:    f = float(val)
        except (TypeError, ValueError): continue
        if not math.isfinite(f): continue
        ctx[path] = f

    # 4 — FormulasRegistry canonical seeds + symbols (highest priority)
    #     These are the names physicists actually use and that the
    #     eml_descriptions are written against.
    try:
        from metaphysica.simulations.core.FormulasRegistry import FormulasRegistry
        fr = FormulasRegistry()
        for src in ("get_all_seeds", "get_all_symbols_with_values"):
            if not hasattr(fr, src): continue
            try:    table = getattr(fr, src)()
            except Exception: continue
            if not isinstance(table, dict): continue
            for name, val in table.items():
                try:    f = float(val)
                except (TypeError, ValueError): continue
                if not math.isfinite(f): continue
                ctx[name] = f
    except ImportError:
        pass  # framework not available — fall back to params-only

    return ctx


def _print_error_breakdown(results: list, top: int = 12) -> None:
    """Group the ERROR rows by CAUSE rather than reporting a bare count.

    "ERROR (did not evaluate): 127" is a number nobody can act on. The 127
    are not 127 separate problems: they collapse into a handful of causes,
    and the largest is a single missing operator. Naming them turns a
    standing count into a work list, which is the same fix applied to the
    formula-render debug notes.
    """
    import re as _re
    from collections import Counter

    errs = [r for r in results if r.get("status") == "ERROR"]
    if not errs:
        return
    missing_attr: Counter = Counter()
    missing_name: Counter = Counter()
    prose_fields: list = []
    other: Counter = Counter()
    for rec in errs:
        reason = str(rec.get("reason", ""))
        m = _re.search(r"has no attribute '([A-Za-z_0-9]+)'", reason)
        if m:
            missing_attr[m.group(1)] += 1
            continue
        m = _re.search(r"name '([A-Za-z_0-9]+)' is not defined", reason)
        if m:
            missing_name[m.group(1)] += 1
            continue
        if "must start with" in reason:
            # The field holds a prose description, not an EML expression --
            # there is nothing here that could evaluate. Named separately
            # because "did not evaluate" implies a broken expression, and
            # these have no expression at all. They stay counted as
            # failures rather than skips: a prose-filled eml_description is
            # itself a defect, and moving them out of the denominator is
            # exactly the accounting that inflated the agreement rate
            # before the 2026-08 audit.
            prose_fields.append(rec.get("path", "?"))
            continue
        other[reason.split(":")[-1].strip()[:70] or "unknown"] += 1

    print()
    print("  [DEBUG] ERROR rows grouped by cause "
          "(these are failures, not skips):")
    if missing_attr:
        n = sum(missing_attr.values())
        print(f"    - {n:3d} missing eml_math.operators attribute(s) -- the "
              f"expression calls an operator the installed eml-math does "
              f"not provide:")
        for name, count in missing_attr.most_common(top):
            print(f"          {count:3d}x ops.{name}")
    if missing_name:
        n = sum(missing_name.values())
        print(f"    - {n:3d} undefined name(s) in the evaluation context -- "
              f"the symbol is used but never bound:")
        for name, count in missing_name.most_common(top):
            print(f"          {count:3d}x {name}")
    if prose_fields:
        print(f"    - {len(prose_fields):3d} eml_description holds PROSE, not an EML "
              f"expression -- there is no expression to evaluate; the field "
              f"needs one written (still counted as a failure, not a skip):")
        for path in prose_fields[:top]:
            print(f"          {path}")
        if len(prose_fields) > top:
            print(f"          ... and {len(prose_fields) - top} more")
    if other:
        n = sum(other.values())
        print(f"    - {n:3d} other:")
        for reason, count in other.most_common(top):
            print(f"          {count:3d}x {reason}")

    # DISAGREE_MISSING_CTX rows are not errors -- they evaluated -- but they
    # evaluated with 0.0 substituted for every eml_vec name absent from the
    # context, so the number they produce is meaningless and the row reads as
    # a physics discrepancy. Naming the missing references turns that bucket
    # into a work list too.
    missing_ctx = [r for r in results
                   if r.get("status") == "DISAGREE_MISSING_CTX"]
    if missing_ctx:
        refs: Counter = Counter()
        for rec in missing_ctx:
            for ref in _re.findall(r"eml_vec\(['\"]([^'\"]+)['\"]\)",
                                   str(rec.get("eml_description", ""))):
                refs[ref] += 1
        print()
        print(f"  [DEBUG] {len(missing_ctx)} row(s) evaluated with UNRESOLVED "
              f"references (0.0 substituted, so the value is meaningless -- "
              f"these are not physics disagreements):")
        for ref, count in refs.most_common(top):
            print(f"          {count:3d}x eml_vec('{ref}')")
        if len(refs) > top:
            print(f"          ... and {len(refs) - top} more distinct names")

    # Agreement reached WITH unresolved references is agreement by luck: the
    # expression was evaluated with 0.0 standing in for a name it needed, and
    # still landed within tolerance. Reported rather than reclassified --
    # moving these out of AGREE unilaterally would change the headline rate,
    # which is the author's call -- but leaving them silent would let a
    # coincidence count as a confirmation.
    lucky = [r for r in results
             if str(r.get("status", "")).startswith("AGREE")
             and r.get("missing_refs")]
    if lucky:
        print()
        print(f"  [DEBUG] {len(lucky)} row(s) AGREE despite unresolved "
              f"references -- agreement reached with 0.0 substituted for a "
              f"needed name, so it may be coincidental:")
        for rec in lucky[:top]:
            names = ", ".join(rec.get("missing_refs", [])[:3])
            print(f"          {rec.get('path','?')}  (missing: {names})")
        if len(lucky) > top:
            print(f"          ... and {len(lucky) - top} more")


def write_offer_policy(params: dict[str, Any], path: Path = None) -> dict[str, Any]:
    """Decide, per parameter, whether the site may offer an EML option.

    Mirrors the ``_unrenderable`` / ``_policy`` artifact that
    generate_formula_renders.py writes for formula diagrams, and uses the
    same decision module (eml_render_validity), so there is one place that
    answers "may this be shown as EML?" rather than two that can disagree.

    Suppression here is VISIBLE by construction: every withheld parameter is
    written out with its reason and its category, and the build prints the
    grouped list. Pages/parameters.html reads this file and omits the
    Normal|EML pill for the paths it names, so an entry in ``_unrenderable``
    IS the "no EML option" behaviour.
    """
    from collections import Counter
    from metaphysica.generators.eml_render_validity import (
        classify_eml_description, eml_operator_surface,
    )

    path = path or OFFER_JSON
    operators = eml_operator_surface()

    offered: list[str] = []
    unrenderable: dict[str, str] = {}
    categories: dict[str, str] = {}
    cat_counts: Counter = Counter()

    for ppath, entry in sorted(params.items()):
        desc = _get_eml_description(entry)
        if not desc:
            continue          # no pill is offered anyway; not a suppression
        ok, reason, category = classify_eml_description(desc, operators=operators)
        cat_counts[category] += 1
        if ok:
            offered.append(ppath)
        else:
            unrenderable[ppath] = reason
            categories[ppath] = category

    out = {
        "_v": 1,
        "_offered_count": len(offered),
        "_unrenderable": unrenderable,
        "_categories": categories,
        "_policy": {
            "require_operator": True,
            "operator_surface_size": len(operators),
            "note": (
                "an eml_description may be offered as an EML option only if "
                "it declares the 'EML: ' prefix, parses as an expression, "
                "calls only operators the installed eml-math provides, uses "
                "no indexed-family comprehension, and contains at least one "
                "operator. Whether it AGREES with the registered value is a "
                "separate question answered by eml_crosscheck.json -- a "
                "valid relation with an unregistered operand is still worth "
                "showing, and suppressing on disagreement would hide the "
                "discrepancies the cross-check exists to surface."
            ),
        },
    }
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)

    if unrenderable:
        by_cat: dict[str, list] = {}
        for ppath, cat in sorted(categories.items()):
            by_cat.setdefault(cat, []).append(ppath)
        print()
        print(f"  [DEBUG] EML option WITHHELD for {len(unrenderable)} "
              f"parameter(s) ({len(offered)} still offered):")
        for cat, items in sorted(by_cat.items(),
                                 key=lambda kv: (-len(kv[1]), kv[0])):
            print(f"    - {len(items):3d}x {cat}")
            for ppath in items:
                print(f"          {ppath}")
        print(f"  Offer policy -> {path}")
    return out


def _rel_error(evaluated: float, registered: float) -> Optional[float]:
    """Relative error between evaluated and registered values."""
    if registered == 0.0:
        return abs(evaluated - registered)
    return abs(evaluated - registered) / abs(registered)


def _classify(evaluated: float, registered: float, tolerance: float,
              loose: float, missing_refs: list) -> tuple[str, str]:
    """Return (status, diagnostic) — fine-grained AGREE/DISAGREE bucket."""
    if not (math.isfinite(evaluated) and math.isfinite(registered)):
        return "DISAGREE_NONFINITE", "non-finite"

    rel = _rel_error(evaluated, registered)
    if rel is not None and rel <= tolerance:
        return "AGREE", ""
    if rel is not None and rel <= loose:
        return "AGREE_LOOSE", f"within {loose:.0%}"

    # Unresolved references come FIRST among the disagreement diagnostics.
    #
    # An expression evaluated with 0.0 substituted for a missing name produces
    # a meaningless number, and whatever pattern that number happens to form
    # is an artifact rather than a diagnosis. gauge.qcd_canonical is the case
    # that showed it: ops.inv(eml_vec('alpha_s_inv')) with alpha_s_inv absent
    # becomes inv(0) = 1e300, whose ratio to the registered 1 is exactly
    # 10^300 -- so it was filed as "off by 10^300", a unit error, when the
    # actual fault is that alpha_s_inv is not in the registry at all.
    # Diagnosing the artifact instead of the cause sends the reader hunting
    # for a scale factor that does not exist.
    if missing_refs:
        return "DISAGREE_MISSING_CTX", f"missing: {', '.join(missing_refs[:3])}"

    # sign-flip: |evaluated + registered| ≈ 0  ⇒ evaluated == −registered
    if registered != 0 and abs(evaluated + registered) / abs(registered) <= tolerance:
        return "DISAGREE_SIGN", "sign flip — magnitudes match"

    # scale: ratio is a clean power of 10
    if evaluated != 0 and registered != 0:
        ratio = evaluated / registered
        if ratio > 0 and math.isfinite(ratio):
            log10 = math.log10(ratio)
            if math.isfinite(log10):
                nearest = round(log10)
                if abs(log10 - nearest) < 0.02 and nearest != 0:
                    return "DISAGREE_SCALE", f"off by 10^{nearest}"

    return "DISAGREE", f"rel_err={rel*100:.2f}%" if rel is not None else "no rel_err"


