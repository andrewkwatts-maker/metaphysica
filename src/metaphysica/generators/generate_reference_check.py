"""Formula-reference dead-link check.

Every ``{{formula:id}}`` marker and ``formula_id`` / ``formula_refs``
reference embedded in sections.json must resolve to a formula that exists
in formulas.json — otherwise the site renders a broken chip or a dead
"view details" link. The 2026-08 validation audit found four unresolvable
ids shipping silently (``bulk-metric-ratio``, ``cycle-separation``,
``harmonic-cycle-fraction``, ``metric-conversion``); this build step keeps
that class of regression impossible to miss.

Report: ``AutoGenerated/reference_check.json``. Exit code 0 always
(report-only), but unresolved references print as WARN lines in the build
log so they're visible without opening the JSON.
"""
from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Set

from metaphysica.generators._common import autogen_dir

_REF_RX = re.compile(r"\{\{formula:([^}]+)\}\}")


def _collect_strings(node: Any, out: List[str]) -> None:
    if isinstance(node, str):
        out.append(node)
    elif isinstance(node, dict):
        for v in node.values():
            _collect_strings(v, out)
    elif isinstance(node, list):
        for v in node:
            _collect_strings(v, out)


def _collect_field(node: Any, field: str, out: List[str]) -> None:
    if isinstance(node, dict):
        v = node.get(field)
        if isinstance(v, str):
            out.append(v)
        elif isinstance(v, list):
            out.extend(x for x in v if isinstance(x, str))
        for vv in node.values():
            _collect_field(vv, field, out)
    elif isinstance(node, list):
        for vv in node:
            _collect_field(vv, field, out)


def run_check() -> Dict[str, Any]:
    ag = autogen_dir()
    formulas_path = ag / "formulas.json"
    sections_path = ag / "sections.json"
    if not formulas_path.exists() or not sections_path.exists():
        return {
            "schema_version": 1,
            "error": "formulas.json / sections.json not present yet",
            "unresolved": [],
        }

    fdata = json.loads(formulas_path.read_text(encoding="utf-8"))
    formulas = fdata.get("formulas", fdata)
    if isinstance(formulas, dict):
        valid_ids: Set[str] = set(formulas.keys())
        valid_ids |= {f.get("id") for f in formulas.values() if isinstance(f, dict) and f.get("id")}
    else:
        valid_ids = {f.get("id") for f in formulas if isinstance(f, dict) and f.get("id")}
    valid_ids.discard(None)

    sdata = json.loads(sections_path.read_text(encoding="utf-8"))

    referenced: Dict[str, str] = {}   # id -> where-kind
    strings: List[str] = []
    _collect_strings(sdata, strings)
    for s in strings:
        for m in _REF_RX.finditer(s):
            referenced.setdefault(m.group(1).strip(), "{{formula:...}} marker")

    for field in ("formula_id", "formulaId"):
        vals: List[str] = []
        _collect_field(sdata, field, vals)
        for v in vals:
            referenced.setdefault(v.strip(), f"{field} content block")

    ref_lists: List[str] = []
    _collect_field(sdata, "formula_refs", ref_lists)
    _collect_field(sdata, "formulaRefs", ref_lists)
    for v in ref_lists:
        referenced.setdefault(v.strip(), "formula_refs list")

    unresolved = sorted(
        (
            {"id": rid, "via": via}
            for rid, via in referenced.items()
            if rid and rid not in valid_ids
        ),
        key=lambda d: d["id"],
    ) if referenced else []

    return {
        "schema_version": 1,
        "note": (
            "Dead-link check: formula ids referenced from sections.json that "
            "do not resolve in formulas.json. Empty = healthy."
        ),
        "summary": {
            "formulas": len(valid_ids),
            "referenced": len(referenced),
            "unresolved": len(unresolved),
        },
        "unresolved": unresolved,
    }


def main() -> int:
    report = run_check()
    out_path = autogen_dir() / "reference_check.json"
    out_path.write_text(json.dumps(report, indent=2, ensure_ascii=False),
                        encoding="utf-8")
    print("=" * 60)
    print("Formula-reference dead-link check")
    print("=" * 60)
    if "error" in report:
        print(f"  SKIPPED: {report['error']}")
        return 0
    s = report["summary"]
    print(f"  formulas: {s['formulas']}   referenced: {s['referenced']}   "
          f"unresolved: {s['unresolved']}")
    for u in report["unresolved"][:20]:
        print(f"  WARN unresolved formula id: {u['id']!r} (via {u['via']})")
    print(f"\nReport written to: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
