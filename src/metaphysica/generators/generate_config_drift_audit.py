"""Config-vs-registry SSOT drift audit.

``config.py`` carries ~62 hand-authored :class:`Formula` entries whose
``computed_value`` / ``experimental_value`` / ``sigma_deviation`` fields are
typed literals. The simulation registry (``AutoGenerated/parameters.json``,
703 canonical dotted paths) is the single source of truth those literals are
supposed to mirror — but nothing has ever enforced that, and audits keep
finding drift (stale w0 mechanisms, percent-errors stored in sigma fields,
pre-2024 PDG numbers).

This generator joins every config Formula onto the registry via its
``output_params`` paths (with an alias table for historical renames) and
reports three classes of finding into ``AutoGenerated/config_drift_audit.json``:

* ``DRIFT``   — config literal disagrees with the registry value beyond
  tolerance (relative 1e-3 by default; absolute for zeros).
* ``ORPHAN``  — config Formula's output_params resolve to no registry path
  (hand literal has NO authoritative source — the worst class).
* ``MATCH``   — config literal agrees with the registry.

The audit is **report-only** (always exits 0): its job is to make the
duplication visible on every build so drift can't silently accumulate.
Long-term direction (SSOT roadmap, see report "note" field): config.py
literals should be replaced by registry lookups at build time, and the
experimental anchors by dataset lookups — everything ultimately tracing to
the b3 = 24 seed or a cited measurement, never a bare literal.

Run via ``python -m metaphysica.generators.generate_config_drift_audit``.
"""
from __future__ import annotations

import json
import math
import sys
from typing import Any, Dict, List, Optional

from metaphysica.generators._common import autogen_dir

# Historical renames: config output_params path -> registry canonical path.
# Only add entries here when the rename is documented; unknown paths are
# reported as ORPHAN so they get fixed at the source instead of aliased
# forever.
PATH_ALIASES: Dict[str, str] = {
    "dark_energy.w0": "cosmology.w0_derived",
    "dark_energy.wa": "cosmology.wa_derived",
    # gauge.M_GUT deliberately NOT aliased to gauge.M_GUT_geometric:
    # the canonical ruling names three distinct scales (geometric 6.3e15,
    # RG-crossing 2.1e16, threshold 1.24e17) — binding the config's RG
    # value to the geometric registry path compared different quantities.
    "proton_decay.tau_p_years": "proton_decay.lifetime_years",
}

REL_TOL = 1e-3          # values within 0.1% count as MATCH
SIGMA_ABS_TOL = 0.15    # sigma fields within ±0.15σ count as MATCH


def _rel_close(a: float, b: float) -> bool:
    if a == b:
        return True
    if a == 0.0 or b == 0.0:
        return abs(a - b) < 1e-12
    return abs(a - b) / max(abs(a), abs(b)) <= REL_TOL


def _resolve(params: Dict[str, Any], path: str) -> Optional[Dict[str, Any]]:
    """Resolve a config output_params path to a registry record."""
    if path in params:
        return params[path]
    alias = PATH_ALIASES.get(path)
    if alias and alias in params:
        return params[alias]
    return None


def _num(v: Any) -> Optional[float]:
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        f = float(v)
        if math.isfinite(f):
            return f
    return None


def audit() -> Dict[str, Any]:
    from metaphysica.config import CoreFormulas

    params_path = autogen_dir() / "parameters.json"
    if not params_path.exists():
        return {
            "schema_version": 1,
            "error": f"{params_path} not found — run the simulation stage first",
            "findings": [],
        }
    registry = json.loads(params_path.read_text(encoding="utf-8")).get("parameters", {})

    findings: List[Dict[str, Any]] = []
    n_match = n_drift = n_orphan = 0

    for formula in CoreFormulas.get_all_formulas():
        fid = getattr(formula, "id", None) or "<no-id>"
        cfg_value = _num(getattr(formula, "computed_value", None))
        cfg_exp = _num(getattr(formula, "experimental_value", None))
        cfg_sigma = _num(getattr(formula, "sigma_deviation", None))
        out_paths = list(getattr(formula, "output_params", None) or [])

        if cfg_value is None and cfg_exp is None and cfg_sigma is None:
            continue  # display-only entry, nothing to cross-check

        record = None
        matched_path = None
        for p in out_paths:
            record = _resolve(registry, p)
            if record is not None:
                matched_path = p if p in registry else PATH_ALIASES.get(p, p)
                break

        if record is None:
            n_orphan += 1
            findings.append({
                "formula_id": fid,
                "verdict": "ORPHAN",
                "output_params": out_paths,
                "config_value": cfg_value,
                "config_experimental": cfg_exp,
                "config_sigma": cfg_sigma,
                "detail": "no registry path found — config literal has no "
                          "authoritative source to check against",
            })
            continue

        checks: List[Dict[str, Any]] = []
        drift = False

        reg_value = _num(record.get("value"))
        if cfg_value is not None and reg_value is not None:
            ok = _rel_close(cfg_value, reg_value)
            drift |= not ok
            checks.append({
                "field": "computed_value",
                "config": cfg_value,
                "registry": reg_value,
                "ok": ok,
            })

        reg_exp = _num(record.get("experimental_value"))
        if cfg_exp is not None and reg_exp is not None:
            ok = _rel_close(cfg_exp, reg_exp)
            drift |= not ok
            checks.append({
                "field": "experimental_value",
                "config": cfg_exp,
                "registry": reg_exp,
                "ok": ok,
            })

        reg_sigma = _num(record.get("sigma_deviation"))
        if cfg_sigma is not None and reg_sigma is not None:
            ok = abs(cfg_sigma - reg_sigma) <= SIGMA_ABS_TOL
            drift |= not ok
            checks.append({
                "field": "sigma_deviation",
                "config": cfg_sigma,
                "registry": reg_sigma,
                "ok": ok,
            })

        verdict = "DRIFT" if drift else "MATCH"
        if drift:
            n_drift += 1
        else:
            n_match += 1
        findings.append({
            "formula_id": fid,
            "verdict": verdict,
            "registry_path": matched_path,
            "registry_status": record.get("status"),
            "checks": checks,
        })

    return {
        "schema_version": 1,
        "note": (
            "SSOT drift audit: config.py Formula literals cross-checked "
            "against the simulation registry (parameters.json). DRIFT = "
            "literal disagrees with registry; ORPHAN = no registry source "
            "exists for the literal. Roadmap: replace config literals with "
            "registry lookups so every displayed number traces to the "
            "b3=24 derivation chain or a cited experimental dataset."
        ),
        "summary": {
            "checked": n_match + n_drift + n_orphan,
            "match": n_match,
            "drift": n_drift,
            "orphan": n_orphan,
        },
        "findings": findings,
    }


def main() -> int:
    report = audit()
    out_path = autogen_dir() / "config_drift_audit.json"
    out_path.write_text(json.dumps(report, indent=2, ensure_ascii=False),
                        encoding="utf-8")

    summary = report.get("summary", {})
    print("=" * 60)
    print("Config-vs-registry SSOT drift audit")
    print("=" * 60)
    if "error" in report:
        print(f"  SKIPPED: {report['error']}")
        return 0
    print(f"  checked: {summary.get('checked', 0):3d}   "
          f"match: {summary.get('match', 0):3d}   "
          f"drift: {summary.get('drift', 0):3d}   "
          f"orphan: {summary.get('orphan', 0):3d}")
    for f in report["findings"]:
        if f["verdict"] == "DRIFT":
            bad = [c for c in f.get("checks", []) if not c["ok"]]
            for c in bad:
                print(f"  [DRIFT] {f['formula_id']:32s} {c['field']:20s} "
                      f"config={c['config']!r:>14} registry={c['registry']!r}")
        elif f["verdict"] == "ORPHAN":
            print(f"  [ORPHAN] {f['formula_id']:32s} paths={f['output_params']}")
    print(f"\nReport written to: {out_path}")
    # Report-only: never fail the build. Drift is surfaced, not fatal.
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
