"""High-quality PDF rendering of the Principia Metaphysica paper via Playwright.

This is a *second*, higher-fidelity PDF output alongside the xhtml2pdf-based
``generate_pdf_paper.py`` (which produces ``Principia_Metaphysica_Paper.pdf``).

Where ``generate_pdf_paper.py`` reads ``sections.json`` and re-renders the
content through a server-side HTML pipeline, this generator drives the
**actual** JS-driven website pages through a headless Chromium so that
MathJax / formula renderers / dynamic parameter substitution all execute
before the PDF is captured. The result is ``Principia_Metaphysica_Paper_HQ.pdf``
under ``AutoGenerated/``.

Pipeline
--------
1. Spawn a local web server (``python -m metaphysica.website.serve``) on a
   free port pointing at the build's ``out_dir``.
2. For each section slug, navigate Chromium to
   ``http://localhost:<port>/Pages/<slug>.html``. If no per-slug page
   exists, fall back to ``paper.html#<slug>`` so the JS paper renderer
   scrolls to that anchor.
3. Wait for *any* of the known "content ready" signals
   (``pm-content-ready``, ``pm-data-ready``, ``pm-simulations-ready``,
   ``pm-plots-ready``, or MathJax startup completion). Hard 3s timeout
   per page so a broken renderer can't stall the build.
4. Capture the page with Chromium's built-in print-to-PDF.
5. Merge every per-section PDF into
   ``AutoGenerated/Principia_Metaphysica_Paper_HQ.pdf`` via
   :class:`pypdf.PdfWriter`.

CLI
---
    python -m metaphysica.generators.generate_pdf_playwright
        # render the full curated section list

    python -m metaphysica.generators.generate_pdf_playwright \
        --pages abstract,introduction,methodology
        # 3-section smoke render

If Playwright or pypdf isn't installed the generator exits with an
informational message and a 0 status code — the build pipeline must not
fail when the HQ render is unavailable.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""
from __future__ import annotations

import argparse
import os
import socket
import subprocess
import sys
import time
from pathlib import Path
from typing import List, Optional, Sequence

from metaphysica.generators._common import autogen_dir, out_dir

# Curated default list of section slugs. Each entry resolves first against
# ``Pages/<slug>.html``; if the file doesn't exist we fall back to
# ``paper.html#<slug>`` so the JS paper renderer scrolls to that anchor.
DEFAULT_SECTIONS: List[str] = [
    # Top-level paper sections (delivered via paper.html anchors)
    "abstract",
    "introduction",
    "methodology",
    "geometry",
    "gauge-unification",
    "fermions",
    "cosmology",
    "results",
    "discussion",
    "conclusion",
    # First-class Pages/*.html files (auxiliary content)
    "formulas",
    "parameters",
    "certificates",
    "appendices",
    "references",
]

# Page-load + content-ready timeouts, both in milliseconds.
NAV_TIMEOUT_MS = 30_000          # navigation hard cap
READY_TIMEOUT_MS = 3_000         # per-page content-ready signal cap

# Print-to-PDF formatting (A4, reasonable margins).
PDF_OPTIONS = {
    "format": "A4",
    "margin": {"top": "16mm", "bottom": "16mm",
               "left": "18mm", "right": "18mm"},
    "print_background": True,
    "prefer_css_page_size": True,
}

# JavaScript snippet that resolves as soon as the page signals it's done
# rendering (or after READY_TIMEOUT_MS, whichever is first).
_READY_JS = r"""
() => new Promise((resolve) => {
    const settle = (reason) => resolve(reason);
    const events = [
        'pm-content-ready',
        'pm-data-ready',
        'pm-simulations-ready',
        'pm-plots-ready',
    ];
    let done = false;
    const onEvent = (e) => {
        if (done) return;
        done = true;
        settle('event:' + e.type);
    };
    events.forEach(ev => window.addEventListener(ev, onEvent, { once: true }));
    // MathJax: resolve once startup promise completes (if MathJax is loaded).
    const mj = window.MathJax;
    if (mj && mj.startup && mj.startup.promise) {
        mj.startup.promise.then(() => {
            if (!done) { done = true; settle('mathjax-startup'); }
        }).catch(() => {});
    }
    // Hard timeout: stop waiting after READY_TIMEOUT_MS.
    setTimeout(() => {
        if (!done) { done = true; settle('timeout'); }
    }, %d);
});
""" % READY_TIMEOUT_MS


# ─────────────────────────────────────────────────────────────────────────────
# Server lifecycle
# ─────────────────────────────────────────────────────────────────────────────

def _find_free_port(start: int = 8765, scan: int = 200) -> int:
    """Return a bindable port starting from *start*."""
    for port in range(start, start + scan):
        try:
            with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
                sock.bind(("127.0.0.1", port))
                return port
        except OSError:
            continue
    return start


def _wait_until_port_open(host: str, port: int, timeout: float = 10.0) -> bool:
    """Poll *host:port* until it accepts a TCP connection or *timeout* elapses."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            with socket.create_connection((host, port), timeout=0.5):
                return True
        except OSError:
            time.sleep(0.1)
    return False


def _start_server(serve_root: Path, port: int) -> subprocess.Popen:
    """Spawn ``python -m metaphysica.website.serve`` rooted at *serve_root*."""
    env = os.environ.copy()
    env.pop("METAPHYSICA_OUT", None)  # serve.py doesn't need this; avoid surprises
    cmd = [
        sys.executable, "-m", "metaphysica.website.serve",
        "--root", str(serve_root),
        "--port", str(port),
        "--no-browser",
    ]
    return subprocess.Popen(
        cmd,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        env=env,
    )


# ─────────────────────────────────────────────────────────────────────────────
# URL resolution
# ─────────────────────────────────────────────────────────────────────────────

def _resolve_url(slug: str, base: str, serve_root: Path) -> str:
    """Return the URL to load for *slug*.

    Prefers ``Pages/<slug>.html`` if a real file exists; otherwise falls
    back to ``Pages/paper.html#<slug>`` so the JS paper renderer scrolls
    to the matching anchor.
    """
    slug = slug.strip().lstrip("#/")
    if not slug:
        return f"{base}/index.html"
    page_path = serve_root / "Pages" / f"{slug}.html"
    if page_path.is_file():
        return f"{base}/Pages/{slug}.html"
    return f"{base}/Pages/paper.html#{slug}"


# ─────────────────────────────────────────────────────────────────────────────
# Per-section rendering
# ─────────────────────────────────────────────────────────────────────────────

def _render_section_pdf(page, url: str, dest: Path) -> str:
    """Navigate *page* to *url*, wait for ready signal, write PDF to *dest*.

    Returns the ready-signal reason as a diagnostic string.
    """
    # Use ``load`` rather than ``networkidle``: the JS-driven pages keep
    # long-lived Firebase / analytics sockets open, so ``networkidle`` never
    # fires. We rely instead on the per-page _READY_JS signal (with a hard
    # READY_TIMEOUT_MS cap) to know when content is actually rendered.
    #
    # Two-step navigation: blank → target. Hash-only navigations (e.g.
    # ``paper.html#abstract`` after ``paper.html#introduction``) are otherwise
    # treated as same-document by Chromium and ``page.goto`` returns
    # instantly without re-running any rendering JS. Forcing about:blank in
    # between guarantees a full reload + ready-signal cycle for every section.
    page.goto("about:blank", wait_until="load", timeout=NAV_TIMEOUT_MS)
    page.goto(url, wait_until="load", timeout=NAV_TIMEOUT_MS)
    try:
        reason = page.evaluate(_READY_JS)
    except Exception as exc:
        reason = f"error:{type(exc).__name__}"
    page.emulate_media(media="print")
    page.pdf(path=str(dest), **PDF_OPTIONS)
    return str(reason)


# ─────────────────────────────────────────────────────────────────────────────
# Merge
# ─────────────────────────────────────────────────────────────────────────────

def _merge_pdfs(parts: Sequence[Path], dest: Path) -> int:
    """Concatenate *parts* into a single PDF at *dest*. Returns total page count."""
    from pypdf import PdfReader, PdfWriter

    writer = PdfWriter()
    total = 0
    for part in parts:
        try:
            reader = PdfReader(str(part))
        except Exception as exc:
            print(f"[hq-pdf]   skip {part.name}: {exc}")
            continue
        for page in reader.pages:
            writer.add_page(page)
            total += 1
    with dest.open("wb") as fh:
        writer.write(fh)
    return total


# ─────────────────────────────────────────────────────────────────────────────
# Main entry point
# ─────────────────────────────────────────────────────────────────────────────

def _parse_args(argv: Optional[Sequence[str]]) -> argparse.Namespace:
    p = argparse.ArgumentParser(
        prog="metaphysica.generators.generate_pdf_playwright",
        description=(
            "Render the JS-driven Principia Metaphysica pages to a single "
            "high-quality PDF via headless Chromium (playwright)."
        ),
    )
    p.add_argument(
        "--pages",
        default="",
        help=("Comma-separated list of section slugs to render. Each slug "
              "resolves first to Pages/<slug>.html, falling back to "
              "paper.html#<slug>. Empty = curated default list."),
    )
    p.add_argument(
        "--port",
        type=int,
        default=0,
        help="Local server port (0 = auto-pick a free port).",
    )
    p.add_argument(
        "--output",
        default="Principia_Metaphysica_Paper_HQ.pdf",
        help="Output filename under AutoGenerated/.",
    )
    return p.parse_args(argv)


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = _parse_args(argv)

    # ── Optional-dep guard. Both playwright + pypdf are optional; if either
    # ── is missing we skip cleanly so the parent build doesn't fail.
    try:
        from playwright.sync_api import sync_playwright  # noqa: F401
    except ImportError:
        print("[hq-pdf] playwright not installed, skipping HQ PDF "
              "(pip install playwright && playwright install chromium).")
        return 0
    try:
        import pypdf  # noqa: F401
    except ImportError:
        print("[hq-pdf] pypdf not installed, skipping HQ PDF "
              "(pip install pypdf).")
        return 0

    from playwright.sync_api import sync_playwright

    target_dir = out_dir()
    ag = autogen_dir()

    # Sanity check: the bundled website must be present in the serve root.
    if not (target_dir / "index.html").is_file():
        # Fall back to the bundled templates inside the installed package so
        # the smoke test works even when run against a fresh empty out_dir.
        from metaphysica.website import bundled_root
        serve_root = bundled_root()
        print(f"[hq-pdf] {target_dir / 'index.html'} not found; serving "
              f"bundled templates from {serve_root}.")
    else:
        serve_root = target_dir

    # Section list.
    sections: List[str]
    if args.pages.strip():
        sections = [s.strip() for s in args.pages.split(",") if s.strip()]
    else:
        sections = list(DEFAULT_SECTIONS)
    if not sections:
        print("[hq-pdf] no sections to render; nothing to do.")
        return 0

    port = args.port or _find_free_port()
    base = f"http://127.0.0.1:{port}"

    print(f"[hq-pdf] Starting local server on :{port} (root: {serve_root})")
    server = _start_server(serve_root, port)
    started_at = time.perf_counter()

    try:
        if not _wait_until_port_open("127.0.0.1", port, timeout=10.0):
            print(f"[hq-pdf] server failed to come up on :{port}; aborting.")
            return 1

        per_section_dir = ag / "_hq_pdf_parts"
        per_section_dir.mkdir(parents=True, exist_ok=True)
        parts: List[Path] = []

        with sync_playwright() as pw:
            try:
                browser = pw.chromium.launch(headless=True)
            except Exception as exc:
                print(f"[hq-pdf] Chromium launch failed: {exc}\n"
                      "        Run `playwright install chromium` to fix.")
                return 0
            context = browser.new_context(
                viewport={"width": 1280, "height": 1600},
            )
            page = context.new_page()

            for i, slug in enumerate(sections, start=1):
                url = _resolve_url(slug, base, serve_root)
                dest = per_section_dir / f"{i:03d}_{_slugify(slug)}.pdf"
                t0 = time.perf_counter()
                try:
                    reason = _render_section_pdf(page, url, dest)
                except Exception as exc:
                    print(f"[hq-pdf]   [{i}/{len(sections)}] {slug}: "
                          f"FAILED ({type(exc).__name__}: {exc})")
                    continue
                dt = time.perf_counter() - t0
                size = dest.stat().st_size if dest.exists() else 0
                print(f"[hq-pdf]   [{i}/{len(sections)}] {slug:24s} "
                      f"{dt:5.1f}s  {size:>9,}B  ready={reason}")
                parts.append(dest)

            context.close()
            browser.close()

        if not parts:
            print("[hq-pdf] No section PDFs rendered; aborting merge.")
            return 1

        target = ag / args.output
        total_pages = _merge_pdfs(parts, target)
        total_dt = time.perf_counter() - started_at
        size = target.stat().st_size
        print(f"[hq-pdf] OK: {target.name}  pages={total_pages}  "
              f"size={size:,}B  total_time={total_dt:.1f}s")
        return 0

    finally:
        if server.poll() is None:
            server.terminate()
            try:
                server.wait(timeout=5)
            except subprocess.TimeoutExpired:
                server.kill()


def _slugify(text: str) -> str:
    """Light slug sanitiser for filenames (no path chars, no spaces)."""
    safe = "".join(c if (c.isalnum() or c in "-_") else "_" for c in text)
    return safe[:64] or "section"


if __name__ == "__main__":
    sys.exit(main())
