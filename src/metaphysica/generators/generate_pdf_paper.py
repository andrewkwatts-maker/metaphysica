def _load_json(path: Path) -> Optional[Any]:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _flatten_parameters(params: Any) -> Dict[str, Any]:
    out: Dict[str, Any] = {}

    def _walk(node: Any, prefix: str) -> None:
        if isinstance(node, dict):
            for k, v in node.items():
                key = f"{prefix}.{k}" if prefix else k
                if isinstance(v, dict) and any(
                    isinstance(vv, (dict, list)) for vv in v.values()
                ):
                    _walk(v, key)
                else:
                    if isinstance(v, dict) and "value" in v:
                        out[key] = v["value"]
                        out[f"{key}.value"] = v["value"]
                    else:
                        out[key] = v
        else:
            out[prefix] = node

    if isinstance(params, dict):
        _walk(params, "")
    return out


def _resolve_value(flat: Dict[str, Any], key: str, default: str) -> str:
    if not flat:
        return default
    v = flat.get(key)
    if v is None:
        v = flat.get(f"{key}.value")
    if v is None:
        return default
    if isinstance(v, float):
        if v == 0 or 1e-3 <= abs(v) < 1e5:
            return f"{v:.4g}"
        return f"{v:.3e}"
    return str(v)


def _resolve_formula(formulas: Dict[str, Any], key: str, default: str) -> str:
    if not formulas:
        return default
    rec = formulas.get(key) or formulas.get("formulas", {}).get(key, {})
    if not rec:
        return default
    latex = rec.get("latex") or rec.get("arithma_latex") or default
    return f'$$ {latex} $$'


def _render_inline(html: str, flat_params: Dict[str, Any],
                   formulas: Dict[str, Any]) -> str:
    def _value_sub(m: re.Match) -> str:
        key = m.group(1)
        fallback = m.group(2)
        return f'<span class="value-inline">{escape(_resolve_value(flat_params, key, fallback))}</span>'

    def _formula_sub(m: re.Match) -> str:
        key = m.group(1)
        fallback = m.group(2)
        return f'<span class="formula-inline">{escape(_resolve_formula(formulas, key, fallback))}</span>'

    html = _PARAM_VALUE_PATTERN.sub(_value_sub, html)
    html = _FORMULA_REF_PATTERN.sub(_formula_sub, html)
    return html


def _strip_script_style(html: str) -> str:
    for tag in ("script", "style"):
        html = re.sub(
            rf"<{tag}\b[^>]*>.*?</{tag}>", "",
            html, flags=re.IGNORECASE | re.DOTALL,
        )
    return html


def _render_block(block: Dict[str, Any], flat_params: Dict[str, Any],
                  formulas: Dict[str, Any]) -> str:
    btype = (block.get("type") or "").lower()
    content = block.get("content") or ""
    if not isinstance(content, str):
        content = json.dumps(content)
    content = _strip_script_style(content)
    content = _render_inline(content, flat_params, formulas)

    if btype == "paragraph":
        return f"<p>{content}</p>"
    if btype == "heading":
        level = int(block.get("level") or 3)
        level = max(2, min(level, 4))
        return f"<h{level}>{content}</h{level}>"
    if btype == "subsection":
        return f"<h3>{content}</h3>"
    if btype == "formula":
        latex = block.get("latex") or block.get("formula") or content
        value = block.get("value")
        value_html = (
            f'<div class="value">numerical value: {escape(str(value))}</div>'
            if value is not None else ""
        )
        return (
            f'<div class="formula-block">'
            f'<div class="latex">{escape(str(latex))}</div>'
            f'{value_html}</div>'
        )
    if btype == "equation":
        latex = block.get("latex") or content
        return (
            f'<div class="formula-block">'
            f'<div class="latex">{escape(str(latex))}</div></div>'
        )
    if btype == "callout":
        return f'<div class="callout">{content}</div>'
    if btype == "note":
        return f'<div class="note">{content}</div>'
    if btype == "highlight_box":
        return f'<div class="highlight-box">{content}</div>'
    if btype == "list":
        items = block.get("items") or []
        rendered = "".join(
            f"<li>{_render_inline(_strip_script_style(str(it)), flat_params, formulas)}</li>"
            for it in items
        )
        tag = "ol" if block.get("ordered") else "ul"
        return f"<{tag}>{rendered}</{tag}>"
    if btype == "table":
        rows = block.get("rows") or []
        head = block.get("header") or block.get("headers")
        if not rows and not head:
            return ""
        body = []
        if head:
            body.append(
                "<tr>" + "".join(f"<th>{escape(str(h))}</th>" for h in head) + "</tr>"
            )
        for row in rows:
            cells = row if isinstance(row, (list, tuple)) else [row]
            body.append(
                "<tr>" + "".join(f"<td>{escape(str(c))}</td>" for c in cells) + "</tr>"
            )
        return "<table>" + "".join(body) + "</table>"
    return f"<p>{content}</p>"


def _section_order_key(sid: str, section: Dict[str, Any]) -> Tuple[float, str]:
    o = section.get("order")
    if isinstance(o, (int, float)):
        return float(o), str(sid)
    if isinstance(o, str):
        try:
            return float(o), str(sid)
        except ValueError:
            return 9999.0, str(sid)
    return 9999.0, str(sid)


def _render_section(sid: str, section: Dict[str, Any],
                    flat_params: Dict[str, Any],
                    formulas: Dict[str, Any]) -> str:
    title = escape(str(section.get("title") or sid))
    abstract = section.get("abstract")
    blocks = section.get("contentBlocks") or section.get("content_blocks") or []

    parts: List[str] = [f'<div class="section-page"><h1>{title}</h1>']
    if abstract:
        text = _render_inline(
            _strip_script_style(str(abstract)), flat_params, formulas
        )
        parts.append(f'<p><em>{text}</em></p>')

    for block in blocks:
        if isinstance(block, dict):
            parts.append(_render_block(block, flat_params, formulas))
        else:
            parts.append(f"<p>{escape(str(block))}</p>")

    parts.append("</div>")
    return "\n".join(parts)


def _cover_page(version: str, count: int) -> str:
    return (
        '<div class="pdf-cover">'
        '<h1>Principia Metaphysica</h1>'
        '<div class="subtitle">A G2-Manifold Unification of Fundamental Physics</div>'
        f'<div class="meta">Version {escape(str(version))} &mdash; {count} sections<br/>'
        'Auto-generated from the simulation registry via <code>metaphysica.build()</code><br/>'
        'Single seed: b<sub>3</sub> = 24 (third Betti number of the G<sub>2</sub> manifold)'
        '</div></div>'
    )


def _table_of_contents(items: List[Tuple[str, str]]) -> str:
    rows = "".join(
        f"<tr><td>{escape(sid)}</td><td>{escape(title)}</td></tr>"
        for sid, title in items
    )
    return (
        '<div class="section-page"><h1>Table of Contents</h1>'
        f'<table>{rows}</table></div>'
    )


def main() -> int:
    out = out_dir()
    ag = autogen_dir()
    sections_path = ag / "sections.json"
    if not sections_path.exists():
        print(f"[pdf] sections.json not found at {sections_path}; skipping PDF build.")
        return 0

    try:
        from xhtml2pdf import pisa
    except ImportError:
        print("[pdf] xhtml2pdf not installed; skipping PDF build "
              "(pip install metaphysica[pdf] to enable).")
        return 0

    sections_blob = _load_json(sections_path) or {}
    sections = sections_blob.get("sections") or {}
    version = sections_blob.get("version") or "unknown"

    params_blob = _load_json(ag / "parameters.json") or {}
    formulas_blob = _load_json(ag / "formulas.json") or {}
    if isinstance(formulas_blob, dict) and "formulas" in formulas_blob:
        formulas_map = formulas_blob["formulas"]
    else:
        formulas_map = formulas_blob

    flat_params = _flatten_parameters(params_blob)

    ordered = sorted(
        sections.items(), key=lambda kv: _section_order_key(kv[0], kv[1])
    )
    toc_entries = [
        (sid, str(s.get("title") or sid))
        for sid, s in ordered if isinstance(s, dict)
    ]

    parts: List[str] = [
        '<html><head><meta charset="utf-8"><style>',
        _CSS,
        '</style></head><body>',
        _cover_page(version, len(ordered)),
        _table_of_contents(toc_entries),
    ]
    for sid, s in ordered:
        if not isinstance(s, dict):
            continue
        parts.append(_render_section(sid, s, flat_params, formulas_map))
    parts.append('</body></html>')

    html = "\n".join(parts)

    target = ag / "Principia_Metaphysica_Paper.pdf"
    print(f"[pdf] Rendering {len(ordered)} sections -> {target}")
    with target.open("wb") as fh:
        result = pisa.CreatePDF(html, dest=fh, encoding="utf-8")
    if result.err:
        print(f"[pdf] {result.err} non-fatal errors during generation; output preserved.")
    size = target.stat().st_size
    print(f"[pdf] OK ({size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
