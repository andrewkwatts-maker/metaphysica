"""Generate a PDF version of the Principia Metaphysica paper.

Concatenates the rendered HTML pages (abstract, introduction, methodology,
results, discussion, foundations, integrity, plus appendices) into a
single PDF saved as ``AutoGenerated/Principia_Metaphysica_Paper.pdf``.

The HTML pages live under ``out/Pages/`` after the bundled website is
copied (Stage 0 of :func:`metaphysica.build.build`). The simulation
JSON outputs they consume must already exist under
``out/AutoGenerated/`` (i.e. the sim run + JSON generators must have
run first).

This is intentionally a *static* PDF — it captures the website's paper
content as it stands when the build runs. The historical hand-curated
4.5 MB paper PDF (``Principia_Metaphysica_v24.1_Paper.pdf``) is a
separate artefact that is NOT regenerated here.

Implementation: uses ``xhtml2pdf`` (pure-Python) so the build doesn't
depend on system libs (Pango / Cairo / wkhtmltopdf).
"""
from __future__ import annotations

import sys
from pathlib import Path

from metaphysica.generators._common import out_dir, autogen_dir


# Pages to include, in document order. Missing pages are skipped with a
# warning rather than failing the build.
PAGES = [
    "abstract",
    "introduction",
    "methodology",
    "foundations",
    "results",
    "discussion",
    "integrity",
    "appendices",
]


HEADER = """\
<html><head><meta charset="utf-8"><style>
  @page {{ size: A4; margin: 1.5cm; }}
  body {{ font-family: 'Helvetica', sans-serif; font-size: 10pt; line-height: 1.4; color: #222; }}
  h1 {{ font-size: 18pt; margin-top: 1em; border-bottom: 2px solid #444; }}
  h2 {{ font-size: 14pt; margin-top: 1em; color: #444; }}
  h3 {{ font-size: 12pt; margin-top: 0.8em; color: #555; }}
  pre, code {{ font-family: 'Courier New', monospace; font-size: 9pt;
    background: #f6f6f6; padding: 2px 4px; }}
  table {{ border-collapse: collapse; margin: 0.5em 0; }}
  td, th {{ border: 1px solid #aaa; padding: 4px 8px; }}
  .pdf-cover {{ text-align: center; margin: 4cm 0; }}
  .pdf-section {{ page-break-before: always; }}
</style></head><body>
<div class="pdf-cover">
  <h1 style="border:none">Principia Metaphysica</h1>
  <p><em>Auto-generated by metaphysica-build</em></p>
  <p>Build dir: {out_dir}</p>
</div>
"""

FOOTER = "</body></html>\n"


def _read_page_body(html_path: Path) -> str:
    """Strip <head>/<script>/<nav>/<footer> chrome from a page so the PDF
    only carries the paper content. Falls back to the raw file if parsing
    fails."""
    try:
        from html.parser import HTMLParser
    except Exception:
        return html_path.read_text(encoding="utf-8", errors="ignore")
    try:
        text = html_path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""
    # Cheap extraction: find <body>...</body>; strip <script>/<style>/<nav>/<footer>.
    import re
    m = re.search(r"<body[^>]*>(.*?)</body>", text, re.IGNORECASE | re.DOTALL)
    body = m.group(1) if m else text
    for tag in ("script", "style", "nav", "footer", "header"):
        body = re.sub(rf"<{tag}\b[^>]*>.*?</{tag}>", "",
                      body, flags=re.IGNORECASE | re.DOTALL)
    return body


def main() -> int:
    out = out_dir()
    pages_dir = out / "Pages"
    if not pages_dir.is_dir():
        print(f"[pdf] Pages/ not found at {pages_dir}; skipping PDF build.")
        return 0
    try:
        from xhtml2pdf import pisa
    except ImportError:
        print("[pdf] xhtml2pdf not installed; skipping PDF build "
              "(pip install xhtml2pdf to enable).")
        return 0

    sections = []
    for name in PAGES:
        path = pages_dir / f"{name}.html"
        if not path.exists():
            print(f"[pdf] (skip) {path.name} not found")
            continue
        body = _read_page_body(path)
        sections.append(f'<div class="pdf-section"><h1>{name.title()}</h1>\n{body}\n</div>')

    if not sections:
        print("[pdf] no paper pages found; skipping.")
        return 0

    html = HEADER.format(out_dir=out) + "\n".join(sections) + FOOTER

    target = autogen_dir() / "Principia_Metaphysica_Paper.pdf"
    print(f"[pdf] Rendering {len(sections)} sections -> {target}")
    with target.open("wb") as fh:
        result = pisa.CreatePDF(html, dest=fh)
    if result.err:
        print(f"[pdf] {result.err} errors during PDF generation; output may be incomplete")
        return 0  # don't fail the build on cosmetic PDF issues
    size = target.stat().st_size
    print(f"[pdf] OK ({size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
