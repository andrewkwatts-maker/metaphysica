"""Generate a publication-grade PDF of the Principia Metaphysica paper.

Renders the paper directly from ``AutoGenerated/sections.json`` plus the
companion ``parameters.json``, ``formulas.json``, and ``GATES_72*.json``
so the PDF carries fully baked content — not the JS-shell HTML the
website serves to browsers.

The old implementation passed the website's empty page shells through
``xhtml2pdf``; since xhtml2pdf cannot execute JavaScript, every
``data-pm-value`` placeholder + ``[pm-formula]`` widget rendered as
literal HTML markup or blank space, producing a 10-page stub. This
generator resolves those references at build time and produces a
PDF whose page count is proportional to the actual content (~250 pp).

The implementation walks ``sections.json``'s 82 sections in ``order``,
turns each section's ``contentBlocks`` array into HTML via a
block-type dispatcher (paragraph / heading / formula / callout / note
/ list / table / equation / subsection / highlight_box), inlines the
matching figures from ``AutoGenerated/plots/``, and emits one xhtml2pdf
pass.

The historical hand-curated ``Principia_Metaphysica_v24.1_Paper.pdf``
is quarantined under ``H:\\Github\\_deprecated_PrincipiaMetaphysica\\``
and is no longer regenerated.
"""
from __future__ import annotations

