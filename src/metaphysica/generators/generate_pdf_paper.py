_PARAM_VALUE_PATTERN = re.compile(
    r'<span\s+class="pm-value"\s+data-pm-value="([^"]+)"[^>]*>([^<]*)</span>',
    flags=re.IGNORECASE,
)
_FORMULA_REF_PATTERN = re.compile(
    r'<span\s+class="pm-formula"\s+data-pm-formula="([^"]+)"[^>]*>([^<]*)</span>',
    flags=re.IGNORECASE,
)


