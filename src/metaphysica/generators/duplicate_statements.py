"""Find parameters stated by more than one published formula with different latex.

A parameter is stated once when exactly one distinct latex string has it as an
output. Where several differ, the formula the parameter's ``derivation_formula``
names is the keeper and the others should refer to it ("see (id)") or share its
latex. A group whose keeper is unnamed, or not among its formulas, has no
keeper and needs an owner decision.

Pure functions over the published ``formulas.json`` / ``parameters.json`` dicts.
"""
from __future__ import annotations

import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Dict, List, Optional


@dataclass(frozen=True)
class Group:
    """One parameter with several differing statements."""
    param: str
    formulas: tuple
    keeper: Optional[str]   # derivation_formula when it is one of the formulas


def normalise(latex: str) -> str:
    """Latex with whitespace removed, so layout alone is not a difference."""
    return re.sub(r"\s+", "", latex or "")


def derivation_formula(param: Dict[str, Any],
                       parameters: Optional[Dict[str, Dict[str, Any]]] = None
                       ) -> Optional[str]:
    """The formula id a parameter record names as its derivation, if any.

    A record that is an alias of another parameter takes the target's name.
    """
    meta = param.get("metadata") or {}
    meta = meta if isinstance(meta, dict) else {}
    named = meta.get("derivation_formula") or param.get("derivation_formula")
    target = meta.get("alias_of")
    if not named and target and parameters and target in parameters:
        return derivation_formula(parameters[target])
    return named or None


def by_output(formulas: Dict[str, Dict[str, Any]]) -> Dict[str, List[str]]:
    """Output parameter -> ids of the formulas that list it."""
    out: Dict[str, List[str]] = {}
    for fid, f in formulas.items():
        for p in f.get("output_params") or []:
            out.setdefault(p, []).append(fid)
    return out


def duplicate_groups(formulas: Dict[str, Dict[str, Any]],
                     parameters: Dict[str, Dict[str, Any]]) -> List[Group]:
    """Groups of more than one formula with differing latex, sorted by parameter."""
    groups = []
    for param, ids in sorted(by_output(formulas).items()):
        if len({normalise(formulas[i].get("latex", "")) for i in ids}) < 2:
            continue
        named = derivation_formula(parameters.get(param, {}), parameters)
        groups.append(Group(param, tuple(sorted(ids)), named if named in ids else None))
    return groups


def load(root: Path):
    """(formulas, parameters) of a published tree; fails early when missing."""
    out = []
    for name, key in (("formulas", "formulas"), ("parameters", "parameters")):
        path = root / "AutoGenerated" / ("%s.json" % name)
        if not path.is_file():
            raise SystemExit("duplicate_statements: %s missing" % path)
        out.append(json.loads(path.read_text(encoding="utf-8"))[key])
    return out[0], out[1]


if __name__ == "__main__":
    fs, ps = load(Path(sys.argv[1]))
    gs = duplicate_groups(fs, ps)
    print(len(gs), "groups;", sum(g.keeper is None for g in gs), "without keeper")
    for g in gs:
        print(g.param, g.keeper, ",".join(g.formulas))
