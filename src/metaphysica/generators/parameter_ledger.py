"""Parameter ledger: one justification class and one falsifiability record per row.

Measures and reports; it never changes a value or a status.

Reads the published ``parameters.json``, ``formulas.json``, ``free_variables.json``
and ``falsification_report.json`` and writes ``AutoGenerated/parameter_ledger.json``.

The registry's own ``derivation_chain`` field is empty on every row in the
published build, so the chain used here is rebuilt from the formula graph: a
parameter's producers are the formulas that list it in ``output_params`` or
that it names in ``derivation_formula``; their ``input_params`` are its parents.
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Set, Tuple

# --------------------------------------------------------------------------
# Classes and the single label table
# --------------------------------------------------------------------------
GEOMETRY, ACTION, MEASURED_INPUT = "GEOMETRY", "ACTION", "MEASURED_INPUT"
CALIBRATED, FITTED, ANSATZ = "CALIBRATED", "FITTED", "ANSATZ"
CONVENTION, UNJUSTIFIED = "CONVENTION_SYSTEM", "UNJUSTIFIED"
CLASSES = (GEOMETRY, ACTION, MEASURED_INPUT, CALIBRATED, FITTED, ANSATZ,
           CONVENTION, UNJUSTIFIED)
CHAIN = "CHAIN"  # label whose class is decided by the chain

#: Every status label the registry uses -> class, or CHAIN. Unknown label: error.
LABEL_CLASS: Dict[str, str] = {
    "ESTABLISHED": MEASURED_INPUT, "MEASURED": MEASURED_INPUT,
    "CALIBRATED": CALIBRATED,
    "FITTED": FITTED, "FITTED_COMPOSITE": FITTED, "RETRODICTED_VARIANT": FITTED,
    "ANSATZ": ANSATZ, "SPECULATIVE": ANSATZ,
    "SYSTEM": CONVENTION, "VALIDATION": CONVENTION, "COMPUTED": CONVENTION,
    "DERIVED": CHAIN, "GEOMETRIC": CHAIN, "PREDICTED": CHAIN,
    "PREDICTIONS": CHAIN, "TOPOLOGY_CANDIDATE": CHAIN, "TERMINAL": CHAIN,
    "ANCHORED": CHAIN, "FALSIFIED": CHAIN, "EXACT": CHAIN, "FOUNDATIONAL": CHAIN,
}
#: Labels whose meaning is not settled by their name; each is listed for the owner.
AMBIGUOUS_LABELS = ("VALIDATION", "SYSTEM", "COMPUTED", "TERMINAL", "FOUNDATIONAL",
                    "EXACT", "ANCHORED", "PREDICTIONS", "TOPOLOGY_CANDIDATE",
                    "RETRODICTED_VARIANT", "FITTED_COMPOSITE", "SPECULATIVE")
#: Sources whose rows are the framework's geometric anchors (leaves are accepted).
ANCHOR_SOURCES = frozenset({"geometric_anchors", "four_face_g2_structure",
                            "g2_geometry_v16_0", "closed_geometry_certificate"})
#: Sources that would earn ACTION (master-ladder terms). Empty today; E1/E3 fill it.
ACTION_SOURCES: frozenset = frozenset()
#: Weakness order among grounded leaf classes; GEOMETRY/ACTION need not appear.
_WEAK = {CALIBRATED: 2, FITTED: 3, ANSATZ: 4}

OBSERVED_STATES = ("PASS", "TENSION", "FAIL", "MARGINAL")


class UnknownLabel(ValueError):
    """A status label the ledger has no class for."""


def label_class(label: Optional[str]) -> str:
    """Class (or CHAIN) for a status label; fail early on an unknown label."""
    if label not in LABEL_CLASS:
        raise UnknownLabel("no class for status label %r" % (label,))
    return LABEL_CLASS[label]


# --------------------------------------------------------------------------
# Formula graph
# --------------------------------------------------------------------------
def producers(params: Dict[str, Any], formulas: Dict[str, Any]) -> Dict[str, List[str]]:
    """param -> formula ids that produce it (output_params or derivation_formula)."""
    prod: Dict[str, List[str]] = defaultdict(list)
    for fid, f in formulas.items():
        for out in f.get("output_params") or []:
            prod[out].append(fid)
    for name, row in params.items():
        fid = row.get("derivation_formula") if isinstance(row, dict) else None
        if fid and fid not in prod.get(name, []):
            prod[name].append(fid)
    return prod


def _is_num(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool)


def parents(name: str, prod: Dict[str, List[str]], formulas: Dict[str, Any],
            params: Dict[str, Any]) -> Tuple[List[str], List[str]]:
    """(input params, problems) one step up from *name*. Problems are missing links."""
    ins: List[str] = []
    problems: List[str] = []
    for fid in prod.get(name, []):
        f = formulas.get(fid)
        if f is None:
            problems.append("formula %s not found" % fid)
            continue
        for i in f.get("input_params") or []:
            if i == name:
                continue  # a formula that restates its own output is a check, not a parent
            if i not in params:
                problems.append("input %s of %s not a row" % (i, fid))
            elif i not in ins:
                ins.append(i)
    return ins, problems


def walk(name: str, prod, formulas, params) -> Dict[str, Any]:
    """Transitive closure of *name*: leaves, missing links, and ``loop``.

    ``loop`` is true only when *name* can reach itself. A row that merely sits
    downstream of some other cycle is not itself circular (``reaches_cycle``).
    """
    seen: Set[str] = set()
    leaves: List[str] = []
    problems: List[str] = []
    loop = False
    cyc = False
    stack: List[Tuple[str, Tuple[str, ...]]] = [(name, ())]
    while stack:
        node, path = stack.pop()
        if node in path:
            if node == name:
                loop = True
            else:
                cyc = True
            continue
        if node in seen:
            continue
        seen.add(node)
        ins, probs = parents(node, prod, formulas, params)
        problems.extend(probs)
        if not prod.get(node) and node != name:
            leaves.append(node)
        stack.extend((i, path + (node,)) for i in ins)
    return {"closure": sorted(seen - {name}), "leaves": sorted(leaves),
            "loop": loop, "reaches_cycle": cyc, "problems": sorted(set(problems))}


# --------------------------------------------------------------------------
# Justification class
# --------------------------------------------------------------------------
def _cited(row: Dict[str, Any]) -> bool:
    src = row.get("experimental_source") or row.get("source")
    return bool(src) and str(src).lower() not in ("unknown", "none")


def is_anchor_leaf(row: Dict[str, Any]) -> bool:
    """A leaf that ends a chain in geometry: anchor source, or a topological integer."""
    v = row.get("value")
    if row.get("source") in ANCHOR_SOURCES and row.get("status") in (
            "GEOMETRIC", "DERIVED", "ANCHORED", "EXACT", "FOUNDATIONAL"):
        return True
    return _is_num(v) and float(v).is_integer() and row.get("status") == "GEOMETRIC"


def leaf_class(row: Dict[str, Any]) -> Optional[str]:
    """Class a leaf row grounds a chain in, or None when it grounds nothing."""
    cls = label_class(row.get("status"))
    if row.get("source") in ACTION_SOURCES:
        return ACTION
    if cls == MEASURED_INPUT:
        return MEASURED_INPUT if _cited(row) else None
    if cls in (CALIBRATED, FITTED, ANSATZ):
        return cls
    if cls == CHAIN and is_anchor_leaf(row):
        return GEOMETRY
    return None


def _from_leaves(leaf_rows: Dict[str, Optional[str]]) -> Tuple[str, str]:
    grounded = {k: c for k, c in leaf_rows.items() if c}
    if not grounded:
        return UNJUSTIFIED, "chain ends in nothing grounded (%d leaves)" % len(leaf_rows)
    weak = [c for c in grounded.values() if c in _WEAK]
    if weak:
        worst = max(weak, key=_WEAK.get)
        return worst, "chain reaches a %s leaf" % worst
    for c in (ACTION, GEOMETRY, MEASURED_INPUT):
        if c in grounded.values():
            return c, "chain ends in %s leaves" % c
    return UNJUSTIFIED, "no grounded leaf"


def classify(name: str, row: Dict[str, Any], prod, formulas, params) -> Dict[str, Any]:
    """The one justification class for *name*, with its evidence."""
    base = label_class(row.get("status"))
    out: Dict[str, Any] = {"label": row.get("status")}
    if base != CHAIN:
        cls = base
        if base == MEASURED_INPUT and not _cited(row):
            cls = UNJUSTIFIED
        out.update(cls=cls, evidence="label %s" % row.get("status"))
        return out
    w = walk(name, prod, formulas, params)
    out.update(loop=w["loop"], problems=w["problems"], n_leaves=len(w["leaves"]))
    if w["loop"]:
        out.update(cls=UNJUSTIFIED, evidence="chain loops")
    elif w["problems"]:
        out.update(cls=UNJUSTIFIED, evidence="chain names a missing row: " + w["problems"][0])
    elif not w["leaves"] and not prod.get(name):
        cls = GEOMETRY if is_anchor_leaf(row) else UNJUSTIFIED
        out.update(cls=cls, evidence="no producing formula; anchor leaf" if cls == GEOMETRY
                   else "chain is empty and the row is not an anchor")
    else:
        lc = {k: leaf_class(params[k]) for k in w["leaves"]}
        cls, why = _from_leaves(lc)
        out.update(cls=cls, evidence=why, leaf_classes=dict(Counter(v or "NONE" for v in lc.values())))
    return out


# --------------------------------------------------------------------------
# Falsifiability
# --------------------------------------------------------------------------
def _close(a: Any, b: Any, rel: float = 1e-9) -> bool:
    if not (_is_num(a) and _is_num(b)):
        return False
    return abs(a - b) <= rel * max(abs(a), abs(b), 1e-300)


def circular_kinds(name: str, row: Dict[str, Any], cls: str, closure: Iterable[str],
                   params: Dict[str, Any]) -> List[str]:
    """Reasons a row's test is a retrodiction (empty list when it is not)."""
    kinds: List[str] = []
    exp = row.get("experimental_value")
    if row.get("status") in ("PREDICTED", "DERIVED", "PREDICTIONS") and _is_num(exp) and exp:
        if not float(exp).is_integer():
            for d in closure:
                dr = params[d]
                if _close(dr.get("value"), exp) or (
                        dr.get("experimental_source") == row.get("experimental_source")
                        and _close(dr.get("experimental_value"), exp)):
                    kinds.append("chain contains its own datum via " + d)
                    break
    if cls in (CALIBRATED, FITTED) and row.get("validation_status") == "PASS":
        kinds.append("calibrated/fitted row scored PASS against its own datum")
    return kinds


def falsifiability(name: str, row: Dict[str, Any], cls: str,
                   killed: Dict[str, str]) -> Dict[str, Any]:
    """State and record for one row. Only physical observables get a test state."""
    val = row.get("validation_status")
    exp = row.get("experimental_value")
    if cls == CONVENTION:
        return {"state": "NOT_OBSERVABLE", "reason": "convention/bookkeeping"}
    if val in OBSERVED_STATES and _is_num(exp):
        return {"state": "TESTED_NOW", "verdict": val, "value": row.get("value"),
                "experimental_value": exp, "uncertainty": row.get("experimental_uncertainty"),
                "sigma": row.get("sigma_deviation"), "bound_type": row.get("bound_type")}
    if name in killed:
        return {"state": "TESTABLE", "kill_switch": killed[name]}
    if _is_num(exp) and row.get("status") in ("PREDICTED", "PREDICTIONS"):
        return {"state": "UNSCORED", "experimental_value": exp,
                "reason": "datum present but no verdict recorded"}
    if row.get("status") in ("PREDICTED", "PREDICTIONS"):
        return {"state": "UNFALSIFIABLE",
                "reason": "prediction with no experimental value and no named test"}
    return {"state": "NOT_OBSERVABLE", "reason": "intermediate or unscored quantity"}


#: kill switch -> (registry id, scale from the report's unit to the registry's, report key)
KILL_SWITCHES: Dict[str, Tuple[str, float, str]] = {
    "ALP_Principia_Metric": ("alp.mass_meV", 1.0, "predicted_mass_meV"),
    "Fifth_Force": ("portals.alp_fifth_force_range_m", 1.0, "predicted_value"),
    "Proton_Decay": ("proton_decay.tau_p_years", 1.0, "predicted_lifetime"),
    "Sterile_Neutrino": ("portals.sterile_mixing_sin2_2theta", 1.0, "predicted_mixing"),
    "KK_Gravitons": ("geometry.m_KK_central", 1.0, "predicted_mass"),
}


def link_kill_switches(report: Dict[str, Any], params: Dict[str, Any],
                       rel: float = 1e-3) -> List[Dict[str, Any]]:
    """Each kill switch with its registry id and whether the numbers agree."""
    detail = report.get("detailed_risk_analysis", {})
    out = []
    for key, d in detail.items():
        rid, scale, field = KILL_SWITCHES.get(key, (None, 1.0, None))
        rec: Dict[str, Any] = {"test": key, "registry_id": rid,
                               "report_value": d.get(field) if field else None,
                               "kill_condition": d.get("note") or d.get("kill_condition"),
                               "status": d.get("status")}
        reg = params.get(rid, {}).get("value") if rid else None
        rec["registry_value"] = reg
        rec["agrees"] = bool(rid) and _close(reg, rec["report_value"], rel)
        if rid is None:
            rec["finding"] = "no registry id: qualitative or unlinked"
        elif not rec["agrees"]:
            rec["finding"] = "report and registry values differ"
        out.append(rec)
    return out


# --------------------------------------------------------------------------
# Value conflicts
# --------------------------------------------------------------------------
#: Groups named by the owner brief: the same b3 under four names and two values.
EXTRA_GROUPS: Dict[str, List[str]] = {
    "b3": ["geometry.elder_kads", "topology.elder_kads", "topology.b3_modular",
           "particle.b3", "cosmology.b3"],
}


def conflict_groups(params: Dict[str, Any], dup: Dict[str, List[str]]) -> Dict[str, List[str]]:
    """Name groups: free_set duplicate groups plus same-final-name rows."""
    groups = {k: list(v) for k, v in dup.items()}
    groups.update({k: list(v) for k, v in EXTRA_GROUPS.items()})
    by_tail: Dict[str, List[str]] = defaultdict(list)
    for name, row in params.items():
        if _is_num(row.get("value")):
            by_tail[name.rsplit(".", 1)[-1]].append(name)
    for tail, names in by_tail.items():
        if len(names) > 1:
            groups["same_name:" + tail] = names
    return groups


def _value_buckets(names: List[str], params: Dict[str, Any]) -> List[List[str]]:
    buckets: List[List[str]] = []
    for n in names:
        v = params[n].get("value")
        for b in buckets:
            if _close(params[b[0]].get("value"), v, 1e-6):
                b.append(n)
                break
        else:
            buckets.append([n])
    return buckets


def find_conflicts(params, dup, readers_of) -> List[Dict[str, Any]]:
    """Groups naming one quantity with different values, plus rows reading the off-path value."""
    out = []
    for gname, names in conflict_groups(params, dup).items():
        names = [n for n in names if n in params and _is_num(params[n].get("value"))]
        buckets = _value_buckets(names, params)
        if len(buckets) < 2:
            continue
        buckets.sort(key=lambda b: (-len(b), b[0]))
        off = [n for b in buckets[1:] for n in b]
        readers = sorted(set(r for n in off for r in readers_of.get(n, ())))
        out.append({"group": gname, "values": {b[0]: params[b[0]]["value"] for b in buckets},
                    "on_path": buckets[0], "off_path": off, "n_readers": len(readers),
                    "readers_per_row": {n: len(readers_of.get(n, ())) for n in names},
                    "readers": readers[:50]})
    return sorted(out, key=lambda c: -c["n_readers"])


def reader_index(params, prod, formulas) -> Dict[str, Set[str]]:
    """name -> rows whose closure contains it."""
    idx: Dict[str, Set[str]] = defaultdict(set)
    for name in params:
        if prod.get(name):
            for d in walk(name, prod, formulas, params)["closure"]:
                idx[d].add(name)
    return idx


# --------------------------------------------------------------------------
# Assembly
# --------------------------------------------------------------------------
def build_ledger(params, formulas, free_vars, report, dup=None) -> Dict[str, Any]:
    """The whole ledger as a JSON-ready dict."""
    prod = producers(params, formulas)
    kills = link_kill_switches(report, params)
    killed = {k["registry_id"]: k["test"] for k in kills if k["registry_id"]}
    rows: Dict[str, Any] = {}
    for name, row in params.items():
        j = classify(name, row, prod, formulas, params)
        closure = walk(name, prod, formulas, params)["closure"] if prod.get(name) else []
        circ = circular_kinds(name, row, j["cls"], closure, params)
        rows[name] = {"class": j["cls"], "evidence": j["evidence"], "label": row.get("status"),
                      "source": row.get("source"), "falsifiability": falsifiability(
                          name, row, j["cls"], killed), "circular": circ}
    return _assemble(rows, params, prod, formulas, free_vars, kills, dup or {})


def _assemble(rows, params, prod, formulas, free_vars, kills, dup) -> Dict[str, Any]:
    fv_bad = [r["name"] for r in free_vars.get("rows", [])
              if r["name"] in rows and rows[r["name"]]["class"] in (GEOMETRY, ACTION)]
    ambiguous = {}
    for lab in AMBIGUOUS_LABELS:
        ex = [n for n, r in rows.items() if r["label"] == lab]
        if ex:
            ambiguous[lab] = {"count": len(ex), "example": ex[0]}
    return {
        "schema": "parameter_ledger/1",
        "note": "Measured only. No value or status was changed. derivation_chain is empty "
                "on every registry row, so chains are rebuilt from formulas.json.",
        "counts": counts(rows), "rows": rows, "kill_switches": kills,
        "free_variable_cross_check": {"rows_in_derived_class": fv_bad},
        "ambiguous_labels": ambiguous,
        "value_conflicts": find_conflicts(params, dup, reader_index(params, prod, formulas)),
        "unjustified_by_module": unjustified_by_module(rows),
    }


def counts(rows: Dict[str, Any]) -> Dict[str, Any]:
    """Counts per class and per state, plus the four ratcheted numbers."""
    cls = Counter(r["class"] for r in rows.values())
    st = Counter(r["falsifiability"]["state"] for r in rows.values())
    return {
        "by_class": dict(cls), "by_state": dict(st),
        "unjustified": cls.get(UNJUSTIFIED, 0),
        "ansatz_plus_fitted": cls.get(ANSATZ, 0) + cls.get(FITTED, 0),
        "unfalsifiable_predictions": st.get("UNFALSIFIABLE", 0),
        "circular": sum(1 for r in rows.values() if r["circular"]),
    }


def unjustified_by_module(rows: Dict[str, Any]) -> Dict[str, int]:
    """UNJUSTIFIED rows grouped by their source module, largest first."""
    c = Counter(str(r["source"]) for r in rows.values() if r["class"] == UNJUSTIFIED)
    return dict(c.most_common())


# --------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------
def _load(path: Path) -> Dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default="AutoGenerated", help="folder with the published json")
    ap.add_argument("--out", default="AutoGenerated/parameter_ledger.json")
    a = ap.parse_args(argv)
    root = Path(a.root)
    params = _load(root / "parameters.json").get("parameters", {})
    if not params:
        print("parameter_ledger: no parameters.json under %s" % root, file=sys.stderr)
        return 1
    from metaphysica.simulations.core import free_set
    ledger = build_ledger(params, _load(root / "formulas.json").get("formulas", {}),
                          _load(root / "free_variables.json"),
                          _load(root / "falsification_report.json"),
                          free_set.duplicate_groups(params))
    out = Path(a.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(ledger, indent=1, default=str), encoding="utf-8")
    print("parameter_ledger: %d rows -> %s" % (len(ledger["rows"]), out))
    print(json.dumps(ledger["counts"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
