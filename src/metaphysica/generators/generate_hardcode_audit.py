"""Hard-coded experimental-constant audit (SSOT enforcement, simulation layer).

The experimental datasets under ``simulations/data/experimental/`` are the
single source of truth for measured values (PDG 2024, NuFIT, CODATA 2022,
DESI), served to code through
:class:`metaphysica.simulations.data.experimental_data_loader.ExperimentalDataLoader`.
In practice only a handful of modules use the loader; the rest paste the
numbers inline — which is how the repo accumulated stale copies (0.2245 vs
0.22500, 125.10 vs 125.20, 80.377 vs 80.3692) that the 2026-08 physics audit
had to chase down file by file.

This generator makes that class of bug visible on every build. It:

1. Flattens every value in the experimental JSONs into a lookup table.
2. AST-walks every ``.py`` under ``simulations/PM/`` + ``simulations/base/``
   and extracts float literals (ignoring trivial constants).
3. Classifies each literal that resembles a dataset value:

   * ``EXACT_DUP`` — matches a dataset value to 1e-9 relative: the module
     hard-codes a number the loader could supply. Works today, rots later.
   * ``STALE_DUP`` — within 2% of a dataset value but NOT equal: almost
     certainly a stale copy of an older release of the same measurement.

Report lands in ``AutoGenerated/hardcode_audit.json``; the console prints
per-file counts and every STALE_DUP. Report-only (exit 0) — the goal is a
monotonically shrinking count as modules migrate to the loader / registered
parameters, not a broken build.
"""
from __future__ import annotations

import ast
import json
import math
from pathlib import Path
from typing import Any, Dict, List, Tuple

from metaphysica.generators._common import autogen_dir

SRC_ROOT = Path(__file__).resolve().parents[1]        # src/metaphysica
EXP_DIR = SRC_ROOT / "simulations" / "data" / "experimental"
SCAN_ROOTS = [
    SRC_ROOT / "simulations" / "PM",
    SRC_ROOT / "simulations" / "base",
]

# Literals that are ubiquitous math/physics scaffolding, never worth flagging.
TRIVIAL = {0.0, 1.0, -1.0, 2.0, 3.0, 4.0, 0.5, 0.25, 10.0, 100.0, 1000.0,
            0.1, 0.01, 0.001, 24.0, 144.0, 288.0, 48.0, 8.0, 12.0}

EXACT_REL = 1e-9
STALE_REL = 0.02


def _flatten(prefix: str, node: Any, out: Dict[str, float]) -> None:
    if isinstance(node, dict):
        for k, v in node.items():
            _flatten(f"{prefix}.{k}" if prefix else str(k), v, out)
    elif isinstance(node, (int, float)) and not isinstance(node, bool):
        f = float(node)
        if math.isfinite(f) and abs(f) > 1e-30:
            out[prefix] = f


def load_dataset_values() -> Dict[str, float]:
    """Flatten every numeric leaf of every experimental JSON to path -> value."""
    table: Dict[str, float] = {}
    for path in sorted(EXP_DIR.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except Exception:
            continue
        _flatten(path.stem, data, table)
    # Drop metadata-ish leaves (years, schema versions) — they collide with
    # ordinary numbers constantly and are not measurements.
    return {
        k: v for k, v in table.items()
        if not any(t in k.lower() for t in (
            "year", "schema", "version", "arxiv", "n_points", "count",
        ))
    }


def _sig_match(lit: float, ref: float) -> bool:
    """True when `lit` matches `ref` at the precision `lit` was written to."""
    if lit == ref:
        return True
    if ref == 0.0:
        return False
    return abs(lit - ref) / abs(ref) <= EXACT_REL


def extract_literals(py_path: Path) -> List[Tuple[int, float]]:
    try:
        tree = ast.parse(py_path.read_text(encoding="utf-8"))
    except Exception:
        return []
    lits: List[Tuple[int, float]] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Constant) and isinstance(node.value, float):
            f = node.value
            if not math.isfinite(f):
                continue
            if f in TRIVIAL or abs(f) in TRIVIAL:
                continue
            # Skip low-information literals (fewer than 3 significant digits
            # can match datasets by coincidence).
            digits = f"{abs(f):.12e}".split("e")[0].replace(".", "").rstrip("0")
            if len(digits) < 3:
                continue
            lits.append((node.lineno, f))
    return lits


def audit() -> Dict[str, Any]:
    dataset = load_dataset_values()
    findings: List[Dict[str, Any]] = []
    files_scanned = 0

    for root in SCAN_ROOTS:
        for py_path in sorted(root.rglob("*.py")):
            rel = py_path.relative_to(SRC_ROOT).as_posix()
            files_scanned += 1
            for lineno, lit in extract_literals(py_path):
                best: Tuple[str, float, str] | None = None
                for key, ref in dataset.items():
                    if _sig_match(lit, ref):
                        best = (key, ref, "EXACT_DUP")
                        break
                    if ref != 0.0 and abs(lit - ref) / abs(ref) <= STALE_REL:
                        # Prefer the closest stale candidate.
                        if best is None or abs(lit - ref) < abs(lit - best[1]):
                            best = (key, ref, "STALE_DUP")
                if best is None:
                    continue
                key, ref, cls = best
                findings.append({
                    "file": rel,
                    "line": lineno,
                    "literal": lit,
                    "dataset_key": key,
                    "dataset_value": ref,
                    "class": cls,
                })

    n_exact = sum(1 for f in findings if f["class"] == "EXACT_DUP")
    n_stale = sum(1 for f in findings if f["class"] == "STALE_DUP")
    per_file: Dict[str, int] = {}
    for f in findings:
        per_file[f["file"]] = per_file.get(f["file"], 0) + 1

    return {
        "schema_version": 1,
        "note": (
            "SSOT enforcement audit (simulation layer): float literals in "
            "PM/base simulation modules that duplicate values held by the "
            "experimental datasets. EXACT_DUP should migrate to "
            "ExperimentalDataLoader / registered parameters; STALE_DUP is a "
            "drifted copy of a measurement and is a live correctness bug. "
            "STALE_DUP matching is heuristic (2% window) — verify before "
            "editing, the neighbour may be a legitimately different quantity."
        ),
        "summary": {
            "files_scanned": files_scanned,
            "dataset_values": len(dataset),
            "exact_dup": n_exact,
            "stale_dup": n_stale,
            "files_with_findings": len(per_file),
        },
        "worst_files": sorted(per_file.items(), key=lambda kv: -kv[1])[:15],
        "findings": findings,
    }


def main() -> int:
    report = audit()
    out_path = autogen_dir() / "hardcode_audit.json"
    out_path.write_text(json.dumps(report, indent=2, ensure_ascii=False),
                        encoding="utf-8")
    s = report["summary"]
    print("=" * 60)
    print("Hard-coded experimental-constant audit (SSOT)")
    print("=" * 60)
    print(f"  files scanned: {s['files_scanned']}   dataset values: {s['dataset_values']}")
    print(f"  EXACT_DUP (should use loader): {s['exact_dup']}")
    print(f"  STALE_DUP (drifted copies):    {s['stale_dup']}")
    print("  worst files:")
    for f, n in report["worst_files"][:8]:
        print(f"    {n:3d}  {f}")
    stale = [f for f in report["findings"] if f["class"] == "STALE_DUP"]
    if stale:
        print("  stale copies (verify + migrate):")
        for f in stale[:20]:
            print(f"    {f['file']}:{f['line']}  {f['literal']!r} vs "
                  f"{f['dataset_key']} = {f['dataset_value']!r}")
    print(f"\nReport written to: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
