#!/usr/bin/env python3
"""Re-render the paper sections that read the statistical rigor report.

Sections 7-9 and the Theory Analysis (DiscussionV16) take chi^2 and the
scoreboard from ``AutoGenerated/statistical_rigor_report.json`` through
``conclusions.load_fit_summary``. "Run all simulations" renders them BEFORE
that report is written, so a fresh build published "NOT AVAILABLE" in
sections.json and formulas.json. This second pass re-renders only those
simulations and patches only their section and formula ids; every other key
is left as written.

Run: ``python -m metaphysica.generators.refresh_paper_conclusions``
(honours ``METAPHYSICA_OUT`` like every generator).

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

from metaphysica.generators._common import autogen_dir

#: Simulations whose output depends on conclusions.load_fit_summary.
_DEPENDENT = ("DiscussionV16",)


#: (module, class) pairs of the D-025 core text; they read the fit summary,
#: the certificate and the path summaries, so a build refreshes them too.
_CORE_TEXT = (("abstract", "AbstractV17_2"),
              ("introduction", "IntroductionV16"),
              ("introduction", "IntroductionExtendedV16"))


def _module_sims(modules: List[str]) -> List[Any]:
    """One instance of every simulation class defined in each dotted module."""
    import importlib
    import inspect

    from metaphysica.simulations.base import SimulationBase

    sims: List[Any] = []
    for name in modules:
        mod = importlib.import_module(name)
        found = [c for _, c in inspect.getmembers(mod, inspect.isclass)
                 if issubclass(c, SimulationBase) and c is not SimulationBase
                 and c.__module__ == mod.__name__]
        if not found:
            raise SystemExit("refresh_paper_conclusions: no simulation in "
                             + name)
        sims.extend(c() for c in found)
    return sims


def _simulations(with_core_text: bool = False,
                 modules: List[str] = ()) -> List[Any]:
    """Instantiate the report-dependent paper simulations."""
    import importlib

    from metaphysica.simulations.PM.paper import discussion

    sims = [getattr(discussion, name)() for name in _DEPENDENT]
    if with_core_text:
        for mod, name in _CORE_TEXT:
            module = importlib.import_module(
                "metaphysica.simulations.PM.paper." + mod)
            sims.append(getattr(module, name)())
    return sims + _module_sims(list(modules))


def _render(with_core_text: bool = False, modules: List[str] = ()) -> Tuple[Dict[str, Any], Dict[str, Any]]:
    """Register the simulations into a fresh registry; return the exports."""
    from metaphysica.simulations.base.registry import PMRegistry

    registry = PMRegistry()
    for sim in _simulations(with_core_text, modules):
        sim.inject_section(registry)
    return registry.export_sections(), registry.export_formulas()


def _read(path: Path) -> Dict[str, Any]:
    """Load a wrapper file, failing early with a clear message."""
    if not path.is_file():
        raise SystemExit(
            "refresh_paper_conclusions: %s is missing; run 'Run all "
            "simulations' first." % path)
    return json.loads(path.read_text(encoding="utf-8"))


def _write(path: Path, payload: Dict[str, Any]) -> None:
    """Write with the same settings as the run-all path."""
    from metaphysica.simulations.run_all_simulations import NumpyJSONEncoder

    with open(path, "w", encoding="utf-8") as fh:
        json.dump(payload, fh, indent=2, ensure_ascii=False,
                  cls=NumpyJSONEncoder)


#: Keys derived from the rendered text by earlier steps; stale once the text
#: changes, so they are dropped rather than carried over.
_STALE_DERIVED = ("html",)


def _is_blank(value: Any) -> bool:
    """True for None, "" and an empty list; never ambiguous on arrays."""
    return value is None or (isinstance(value, (str, list)) and not value)


def _merge(old: Dict[str, Any], fresh: Dict[str, Any]) -> Dict[str, Any]:
    """Fresh entry, keeping keys (e.g. module references) the old one added."""
    merged = dict(fresh)
    for key, value in old.items():
        if key in _STALE_DERIVED:
            continue
        if key not in merged or (_is_blank(merged[key]) and bool(value)):
            merged[key] = value
    return merged


def _patch(wrapper: Dict[str, Any], field: str,
           fresh: Dict[str, Any]) -> int:
    """Replace the fresh ids inside ``wrapper[field]``; return the count."""
    target = wrapper[field]
    for key, entry in fresh.items():
        target[key] = _merge(target.get(key, {}), entry)
    wrapper["count"] = len(target)
    return len(fresh)


def refresh(with_core_text: bool = False,
            modules: List[str] = ()) -> Tuple[int, int]:
    """Patch sections.json and formulas.json; return (sections, formulas)."""
    base = autogen_dir()
    sec_path, frm_path = base / "sections.json", base / "formulas.json"
    sections, formulas = _read(sec_path), _read(frm_path)
    fresh_sections, fresh_formulas = _render(with_core_text, modules)
    n_sec = _patch(sections, "sections", fresh_sections)
    n_frm = _patch(formulas, "formulas", fresh_formulas)
    _write(sec_path, sections)
    _write(frm_path, formulas)
    return n_sec, n_frm


def main(argv: List[str] = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    mods: List[str] = []
    if "--modules" in argv:
        at = argv.index("--modules")
        if at + 1 >= len(argv):
            raise SystemExit("--modules needs a comma-separated module list")
        mods = [m for m in argv[at + 1].split(",") if m]
    n_sec, n_frm = refresh(with_core_text="--core-text" in argv, modules=mods)
    print("refresh_paper_conclusions: patched %d section(s), %d formula(s)"
          % (n_sec, n_frm))
    return 0


if __name__ == "__main__":
    sys.exit(main())
