"""Build gate: every published math string parses under the site's own MathJax.

Runs tools/texcheck/check.js (Track F1) on this build's formulas.json,
sections.json and Pages/. Exits non-zero on any render error. An installed
wheel has no tools/texcheck and is skipped with the reason; a checkout that
has the checker but not node or its node_modules fails, naming the fix.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Optional

TEXCHECK = Path(__file__).resolve().parents[3] / "tools" / "texcheck"


def checker_problem(texcheck: Path, node: Optional[str]) -> Optional[str]:
    """Why the checker can't run in a checkout that ships it, or None."""
    if node is None:
        return "node is not installed; the render gate needs it"
    if not (texcheck / "node_modules" / "mathjax-full").is_dir():
        return "run `npm ci` in %s to install mathjax-full" % texcheck
    return None


def inputs(out_dir: Path) -> List[Path]:
    """The published surfaces of a build; each must exist."""
    paths = [out_dir / "AutoGenerated" / "formulas.json",
             out_dir / "AutoGenerated" / "sections.json",
             out_dir / "Pages"]
    missing = [str(p) for p in paths if not p.exists()]
    if missing:
        raise FileNotFoundError("render gate inputs missing: %s" % missing)
    return paths


def main(out_dir: Path = Path.cwd(), texcheck: Path = TEXCHECK) -> int:
    if not texcheck.is_dir():
        print("  render gate SKIPPED: no tools/texcheck (installed package)")
        return 0
    node = shutil.which("node")
    problem = checker_problem(texcheck, node)
    if problem:
        print("  render gate FAILED: " + problem, file=sys.stderr)
        return 2
    proc = subprocess.run([node, str(texcheck / "check.js"),
                           *map(str, inputs(out_dir))],
                          capture_output=True, text=True, encoding="utf-8",
                          cwd=str(texcheck))
    if proc.returncode not in (0, 1):
        print(proc.stderr[-2000:], file=sys.stderr)
        return proc.returncode
    report = out_dir / "AutoGenerated" / "tex_render_report.json"
    report.write_text(proc.stdout, encoding="utf-8")
    print("  render gate: report in %s" % report)
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
