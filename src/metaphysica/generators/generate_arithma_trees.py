"""
generate_arithma_trees.py — Pre-generate Arithma symbolic-AST JSON for all formulas.

Reads ``AutoGenerated/formulas.json`` and, for each formula that carries an
``arithma_latex`` field (populated by ``add_formula(..., arithma=...)``),
emits a compact JSON file at ``AutoGenerated/arithma_trees.json`` keyed by
formula ID. This is the Arithma analogue of ``generate_eml_trees.py`` —
the website's formula renderer can consume it to show the symbolic-AST
view side-by-side with the rendered LaTeX, and the audit script uses it
as a cheap dry-run cross-check.

Schema::

    {
      "_v": 1,
      "f": {
        "<formula-id>": {
          "latex":     "...",          // Arithma's .to_latex() rendering
          "evaluated": 1.234,           // Arithma's .evaluate({}) result, or None
          "kind":      "lit|div|mul|sub|add|..."  // best-effort top-op classifier
        }, ...
      }
    }

Usage:
    python -m metaphysica.generators.generate_arithma_trees
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from metaphysica.generators._common import out_dir as _out_dir
ROOT = _out_dir()
sys.path.insert(0, str(ROOT))

try:
    import arithma  # type: ignore[import-not-found]
    ARITHMA_AVAILABLE = True
except ImportError:
    arithma = None  # type: ignore[assignment]
    ARITHMA_AVAILABLE = False

FORMULAS_JSON = ROOT / "AutoGenerated" / "formulas.json"
OUTPUT_JSON = ROOT / "AutoGenerated" / "arithma_trees.json"


def _classify(latex_str: str) -> str:
    """Best-effort top-operator classifier from the Arithma LaTeX."""
    s = (latex_str or "").strip()
    if "\\frac" in s or "/" in s:
        return "div"
    if "\\cdot" in s or "*" in s or "\\times" in s:
        return "mul"
    if "+" in s:
        return "add"
    if "-" in s and not s.startswith("-"):
        return "sub"
    return "lit"


def main() -> int:
    if not FORMULAS_JSON.exists():
        print(f"  formulas.json not found — skipping Arithma tree generation "
              f"(run simulations first: pip install metaphysica[sims])")
        return 0

    with open(FORMULAS_JSON, encoding="utf-8") as f:
        data = json.load(f)

    formulas: dict = data.get("formulas", data)

    entries: dict = {}
    n_ok = n_skip = n_err = 0

    for fid, formula in formulas.items():
        latex_str = formula.get("arithma_latex") or ""
        value = formula.get("value")

        if not latex_str:
            n_skip += 1
            continue

        # The simulations dump the rendered LaTeX directly because the
        # arithma.Expression objects don't pickle through JSON. We can
        # optionally re-parse to evaluate, but Arithma's API doesn't yet
        # expose a `from_latex` path — so we trust the stored value.
        try:
            entries[fid] = {
                "latex": latex_str,
                "evaluated": value,
                "kind": _classify(latex_str),
            }
            n_ok += 1
        except Exception as exc:
            entries[fid] = {
                "latex": latex_str,
                "evaluated": None,
                "kind": "error",
                "error": str(exc),
            }
            n_err += 1

    out = {
        "_v": 1,
        "arithma_available": ARITHMA_AVAILABLE,
        "f": entries,
    }

    OUTPUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    with open(OUTPUT_JSON, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, separators=(",", ":"))

    size_kb = OUTPUT_JSON.stat().st_size / 1024
    print("Arithma tree generation complete:")
    print(f"  Parsed:  {n_ok}")
    print(f"  Errors:  {n_err}")
    print(f"  Skipped: {n_skip}")
    print(f"  Output:  {OUTPUT_JSON}  ({size_kb:.1f} KB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
