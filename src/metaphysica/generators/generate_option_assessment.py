"""Assess every option of every fork (D-026): physics, provable, economy, tightening.

Reads the published paths (``paths/index.json``, ``paths/<id>/summary.json``,
``paths/<id>/patch.json``), ``parameters.json`` and, if present, the formula
audit ``data/formula_audit.json``.  Writes ``option_assessment.json``.

Axes, each relative to main (the active option of every fork):

* P physics: change in PASS and FAIL rows and in chi2.  INVALID (the sweep
  refused the option), INERT (no data consequence) or COMPUTED.
* R provable: share of the changed parameters whose registry status is
  GEOMETRIC or DERIVED, before and after the option.
* E economy: change in the number of free-status parameters among the changed
  ones, read from the patch.  Unexplained literals are summed from the audit
  for the rows the option moves (a level, not a delta: not used in dominance).
* T tightening: removes a CALIBRATED or FITTED parameter, or a free variable,
  with no more FAIL rows.
* guard: rows behind the P gain whose audit class is C24 or H are subtracted
  from P and listed as "fit at 24".  Without the audit the guard is OPEN and
  an apparent winner is only a provisional candidate.

The generator flags candidates; adoption is an owner ruling.  Nothing is
guessed: missing inputs are OPEN.

Build placement: this runs in the full build after the path graph export,
reading the paths already published under ``AutoGenerated/paths`` (publishing
is the separate testground command, so re-run this after every paths-publish).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple

SCHEMA = "metaphysica.option_assessment/1"
PROVABLE = {"GEOMETRIC", "DERIVED"}
FREE = {"FITTED", "CALIBRATED", "INPUT", "FITTED_COMPOSITE"}
TUNED = {"FITTED", "CALIBRATED", "FITTED_COMPOSITE"}
FIT_CLASSES = {"C24", "H"}
BUNDLED_AUDIT = Path(__file__).resolve().parent.parent / "data" / "formula_audit.json"
RANK = {"PASS": 0, "MARGINAL": 1, "TENSION": 2, "FAIL": 3}


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _read_optional(path: Path) -> Optional[Any]:
    return _load(path) if path.is_file() else None


def _unescape(seg: str) -> str:
    return seg.replace("~1", "/").replace("~0", "~")


def _board(summary: Dict[str, Any]) -> Tuple[int, int, float]:
    sb, chi = summary["scoreboard"], summary.get("chi2") or {}
    return int(sb.get("PASS", 0)), int(sb.get("FAIL", 0)), float(chi.get("value", 0.0))


def score_physics(entry: Optional[Dict[str, Any]], summary: Optional[Dict[str, Any]],
                  main: Dict[str, Any], refusal: Optional[str]) -> Dict[str, Any]:
    """P axis: INVALID with reason, INERT, COMPUTED with deltas, or OPEN."""
    if refusal is not None:
        return {"state": "INVALID", "reason": refusal}
    if entry is None or summary is None:
        return {"state": "OPEN", "reason": "option not swept"}
    if entry.get("inert"):
        return {"state": "INERT", "d_pass": 0, "d_fail": 0, "d_chi2": 0.0}
    p, f, c = _board(summary)
    mp, mf, mc = _board(main)
    return {"state": "COMPUTED", "d_pass": p - mp, "d_fail": f - mf,
            "d_chi2": round(c - mc, 6)}


def _param_ops(patch: Optional[Dict[str, Any]]) -> Dict[str, Dict[str, Any]]:
    """Parameter name -> {"status": new status or None, "added": bool}."""
    out: Dict[str, Dict[str, Any]] = {}
    block = ((patch or {}).get("files", {}) or {}).get("parameters.json") or {}
    for op in block.get("ops", []):
        segs = op["path"].split("/")
        if len(segs) < 3 or segs[1] != "parameters":
            continue
        rec = out.setdefault(_unescape(segs[2]), {"status": None, "added": False})
        if len(segs) == 3 and op["op"] == "add" and isinstance(op.get("value"), dict):
            rec["status"], rec["added"] = op["value"].get("status"), True
        elif len(segs) == 4 and segs[3] == "status" and "value" in op:
            rec["status"] = op["value"]
    return out


def _statuses(patch: Optional[Dict[str, Any]],
              params: Dict[str, Any]) -> List[Tuple[Optional[str], Optional[str]]]:
    """(status before, status after) of every parameter the patch touches."""
    pairs = []
    for name, rec in _param_ops(patch).items():
        before = None if rec["added"] else (params.get(name) or {}).get("status")
        pairs.append((before, rec["status"] or before))
    return pairs


def score_provable(patch: Optional[Dict[str, Any]], params: Dict[str, Any]) -> Dict[str, Any]:
    """R axis: provable share of the changed parameters, before and after."""
    pairs = _statuses(patch, params)
    if not pairs:
        return {"state": "COMPUTED", "changed": 0, "share_before": None,
                "share_after": None, "d_share": 0.0, "by_status": {}}
    n = len(pairs)
    before = sum(1 for b, _ in pairs if b in PROVABLE) / n
    after = sum(1 for _, a in pairs if a in PROVABLE) / n
    by: Dict[str, int] = {}
    for _, a in pairs:
        by[str(a)] = by.get(str(a), 0) + 1
    return {"state": "COMPUTED", "changed": n, "share_before": round(before, 4),
            "share_after": round(after, 4), "d_share": round(after - before, 4),
            "by_status": by,
            "calibrated_or_fitted": sum(1 for _, a in pairs if a in TUNED)}


def _literals(rows: List[str], audit: Optional[List[Dict[str, Any]]]) -> Any:
    if audit is None:
        return "OPEN"
    byp = {a["path"]: a for a in audit}
    return sum(int(byp[r].get("unexplained_literals", 0)) for r in rows if r in byp)


def score_economy(patch: Optional[Dict[str, Any]], params: Dict[str, Any],
                  rows: List[str], audit: Optional[List[Dict[str, Any]]]) -> Dict[str, Any]:
    """E axis: change in free-status parameter count, literals in moved rows."""
    pairs = _statuses(patch, params)
    d_free = sum(1 for _, a in pairs if a in FREE) - sum(1 for b, _ in pairs if b in FREE)
    return {"state": "COMPUTED", "d_free": d_free, "literals": _literals(rows, audit)}


def tightens(patch: Optional[Dict[str, Any]], params: Dict[str, Any],
             econ: Dict[str, Any], adj_d_fail: Optional[int]) -> bool:
    """T axis: drops a CALIBRATED/FITTED parameter or a free variable, no worse on FAIL."""
    if adj_d_fail is None or adj_d_fail > 0:
        return False
    dropped = any(b in TUNED and a not in TUNED for b, a in _statuses(patch, params))
    return dropped or econ["d_free"] < 0


def moved_rows(patch: Optional[Dict[str, Any]],
               validations: Optional[List[Dict[str, Any]]]) -> Optional[List[Dict[str, Any]]]:
    """Validation rows whose verdict the patch changes; None when not attributable."""
    if validations is None or patch is None:
        return None
    block = (patch.get("files", {}) or {}).get("validation_report.json") or {}
    rows = []
    for op in block.get("ops", []):
        segs = op["path"].split("/")
        if len(segs) == 4 and segs[1] == "validations" and segs[3] == "verdict":
            row = validations[int(segs[2])]
            rows.append({"path": row["path"], "main": row["verdict"],
                         "path_verdict": op["value"]})
    return rows


def guard(rows: Optional[List[Dict[str, Any]]],
          audit: Optional[List[Dict[str, Any]]]) -> Dict[str, Any]:
    """Overfitting guard: improved rows classed C24 or H; OPEN if not attributable."""
    if audit is None:
        return {"state": "OPEN", "reason": "no formula audit", "fit_at_24": []}
    if rows is None:
        return {"state": "OPEN", "reason": "rows not attributable", "fit_at_24": []}
    cls = {a["path"]: a.get("class") for a in audit}
    gains = [r for r in rows if r["path_verdict"] in RANK and r["main"] in RANK
             and RANK[r["main"]] > RANK[r["path_verdict"]]]
    unknown = sorted(r["path"] for r in gains if r["path"] not in cls)
    fit = [r for r in gains if cls.get(r["path"]) in FIT_CLASSES]
    state = "OPEN" if unknown else ("FIT_AT_24" if fit else "CLEAR")
    return {"state": state, "fit_at_24": fit, "unaudited": unknown}


def _adjust(p: Dict[str, Any], g: Dict[str, Any]) -> Dict[str, Any]:
    """Subtract guarded rows from the pass/fail deltas; chi2 is not row-attributable."""
    if p["state"] != "COMPUTED":
        return {"d_pass": 0, "d_fail": 0, "d_chi2": 0.0}
    dp, df, dc = p["d_pass"], p["d_fail"], p["d_chi2"]
    for r in g.get("fit_at_24", []):
        dp -= (r["path_verdict"] == "PASS") - (r["main"] == "PASS")
        df -= (r["path_verdict"] == "FAIL") - (r["main"] == "FAIL")
    return {"d_pass": dp, "d_fail": df, "d_chi2": None if g.get("fit_at_24") else dc}


def dominates(adj: Dict[str, Any], d_share: float, d_free: int) -> Tuple[bool, List[str]]:
    """No worse on every axis and strictly better on one; reasons name the axes."""
    axes = {"P_pass": adj["d_pass"], "P_fail": -adj["d_fail"], "R": d_share, "E": -d_free}
    if adj["d_chi2"] is not None:
        axes["P_chi2"] = -adj["d_chi2"]
    worse = [k for k, v in axes.items() if v < 0]
    better = [k for k, v in axes.items() if v > 0]
    if worse:
        return False, ["worse on " + ",".join(worse)]
    if not better:
        return False, ["tie with the active option on every axis"]
    return True, ["better on " + ",".join(better)]


def _verdict(out: Dict[str, Any], p: Dict[str, Any], g: Dict[str, Any],
             dom: bool, why: List[str]) -> Dict[str, Any]:
    reasons = list(why)
    if p["state"] == "INERT":
        out.update(candidate=False, provisional=False,
                   reasons=["inert: no data consequence"] + reasons)
        return out
    if g["state"] == "FIT_AT_24":
        reasons.append("fit at 24: " + ", ".join(r["path"] for r in g["fit_at_24"]))
    if g["state"] == "OPEN":
        reasons.append("guard OPEN: " + g.get("reason", "rows without audit class"))
    out["candidate"] = bool(dom and g["state"] in ("CLEAR", "FIT_AT_24"))
    out["provisional"] = bool(dom and g["state"] == "OPEN")
    out["reasons"] = reasons
    return out


def assess_option(fork: str, opt: str, ctx: Dict[str, Any]) -> Dict[str, Any]:
    """One option's four axes, guard and candidate flag."""
    pid = f"{fork}--{opt}"
    entry = ctx["entries"].get(pid)
    summary = _read_optional(ctx["paths"] / pid / "summary.json") if entry else None
    patch = _read_optional(ctx["paths"] / pid / "patch.json") if entry else None
    p = score_physics(entry, summary, ctx["main_summary"], ctx["refused"].get(pid))
    out: Dict[str, Any] = {"option": opt, "path": pid, "P": p}
    if p["state"] in ("INVALID", "OPEN"):
        out.update(candidate=False, provisional=False, reasons=[p["reason"]])
        return out
    rows = moved_rows(patch, ctx["validations"])
    g = guard(rows, ctx["audit"])
    adj = _adjust(p, g)
    r = score_provable(patch, ctx["params"])
    e = score_economy(patch, ctx["params"], [x["path"] for x in rows or []], ctx["audit"])
    dom, why = dominates(adj, r["d_share"], e["d_free"])
    out.update(R=r, E=e, T=tightens(patch, ctx["params"], e, adj["d_fail"]),
               guard=g, P_adjusted=adj)
    return _verdict(out, p, g, dom, why)


def fork_table() -> Dict[str, Dict[str, Any]]:
    """Fork id -> {"active": id, "options": {id: option status}} from FORKS."""
    from metaphysica.simulations.core.variants import FORKS
    return {fid: {"active": f.default(), "options": {o.id: o.status for o in f.options}}
            for fid, f in FORKS.items()}


def assess(index: Dict[str, Any], forks: Dict[str, Dict[str, Any]], paths: Path,
           params: Dict[str, Any], validations: Optional[List[Dict[str, Any]]],
           audit: Optional[List[Dict[str, Any]]]) -> Dict[str, Any]:
    """The whole assessment: every alternative of every fork."""
    main = next(p for p in index["paths"] if p["id"] == "main")
    ctx = {"entries": {p["id"]: p for p in index["paths"]},
           "refused": {n["id"]: n["reason"] for n in index.get("not_computed", [])},
           "paths": paths, "params": params, "validations": validations, "audit": audit,
           "main_summary": _load(paths / "main" / "summary.json")}
    out_forks = {}
    for fid, f in forks.items():
        active = (main.get("selection") or {}).get(fid, f.get("active"))
        alts = [dict(assess_option(fid, o, ctx), status=s)
                for o, s in f["options"].items() if o != active]
        out_forks[fid] = {"active": active, "alternatives": alts}

    def flagged(key: str) -> List[str]:
        return [f"{fid}--{a['option']}" for fid, f in out_forks.items()
                for a in f["alternatives"] if a.get(key)]
    return {"schema": SCHEMA, "audit": "present" if audit is not None else "OPEN",
            "engine": index.get("engine"), "forks": out_forks,
            "candidates": flagged("candidate"), "provisional": flagged("provisional")}


def _args(argv: Optional[List[str]]) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--paths", required=True, help="published paths dir")
    ap.add_argument("--parameters", required=True, help="parameters.json")
    ap.add_argument("--audit", default=None,
                    help="formula audit (default: the bundled data/formula_audit.json if present)")
    ap.add_argument("--optional", action="store_true",
                    help="exit 0 with a notice when the paths index is missing (build use)")
    ap.add_argument("--validation", default=None,
                    help="validation_report.json (default: beside --parameters)")
    ap.add_argument("--out", required=True, help="option_assessment.json to write")
    return ap.parse_args(argv)


def main(argv: Optional[List[str]] = None) -> int:
    a = _args(argv)
    paths = Path(a.paths)
    if not (paths / "index.json").is_file():
        if a.optional:
            print(f"option assessment: SKIPPED, {paths / 'index.json'} not published")
            return 0
        print(f"error: {paths / 'index.json'} is missing; run paths-publish first",
              file=sys.stderr)
        return 2
    val_path = Path(a.validation) if a.validation \
        else Path(a.parameters).parent / "validation_report.json"
    val = _read_optional(val_path)
    audit = _read_optional(Path(a.audit) if a.audit else BUNDLED_AUDIT)
    doc = assess(_load(paths / "index.json"), fork_table(), paths,
                 _load(Path(a.parameters))["parameters"],
                 val["validations"] if val else None, audit)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(doc, indent=2, ensure_ascii=False), encoding="utf-8")
    print(f"option assessment: {len(doc['candidates'])} candidate(s), "
          f"{len(doc['provisional'])} provisional (audit {doc['audit']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
