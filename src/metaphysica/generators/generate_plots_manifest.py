#!/usr/bin/env python3
"""Generate plots-manifest.json.

Auto-generated index of all ``AutoGenerated/plots/*.png`` and ``*.pdf`` files
with their last-modified timestamps and sizes. Used by the web UI to render
a plots gallery and detect stale figures.

The plots themselves are visual proofs of derivations that all trace back
to the seed b3 = 24 (G2 manifold topology).
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

from metaphysica.generators._common import autogen_dir

# Lightweight category inference from filename keywords.
CATEGORY_KEYWORDS = {
    "validation": ("gate", "certificate", "primary_gates"),
    "geometry": ("manifold", "torsion", "pattern", "m27", "g2"),
    "convergence": ("convergence", "scatter"),
    "discovery": ("alp", "discovery"),
    "statistics": ("pvalue", "p_value", "distribution"),
}


def _categorize(name: str) -> str:
    n = name.lower()
    for cat, kws in CATEGORY_KEYWORDS.items():
        if any(k in n for k in kws):
            return cat
    return "general"


def _humanize(stem: str) -> str:
    s = stem.replace("_", " ").replace("-", " ")
    return " ".join(w.capitalize() for w in s.split())


def main() -> int:
    ag = autogen_dir()
    plots_dir = ag / "plots"
    plots_dir.mkdir(parents=True, exist_ok=True)

    entries: List[Dict[str, Any]] = []
    seen_ids = set()

    for path in sorted(plots_dir.iterdir()):
        if not path.is_file():
            continue
        suffix = path.suffix.lower()
        if suffix not in {".png", ".pdf", ".svg", ".jpg", ".jpeg"}:
            continue
        stat = path.stat()
        mtime = datetime.fromtimestamp(stat.st_mtime, tz=timezone.utc)
        slug = path.stem.lower().replace("_", "-")
        # disambiguate png vs pdf of the same stem
        plot_id = slug
        if plot_id in seen_ids:
            plot_id = f"{slug}-{suffix.lstrip('.')}"
        seen_ids.add(plot_id)
        # Browsers cannot render a PDF inside <img>. Flag what is directly
        # displayable and, for PDFs, point at the PNG sibling the plot
        # generators emit alongside — the gallery showed 4 broken images
        # before this (figure1..figure4 are PDF+PNG pairs).
        renderable = suffix in {".png", ".svg", ".jpg", ".jpeg"}
        preview_name = path.name
        if not renderable:
            for alt_suffix in (".png", ".svg", ".jpg"):
                candidate = path.with_suffix(alt_suffix)
                if candidate.exists():
                    preview_name = candidate.name
                    renderable = True
                    break

        entries.append({
            "id": plot_id,
            "file": path.name,
            "preview_file": preview_name,
            "renderable": renderable,
            "title": _humanize(path.stem),
            "category": _categorize(path.name),
            "format": suffix.lstrip("."),
            "size_bytes": stat.st_size,
            "size_kb": round(stat.st_size / 1024.0, 1),
            "modified_utc": mtime.isoformat().replace("+00:00", "Z"),
            "path": f"AutoGenerated/plots/{path.name}",
            "preview_path": f"AutoGenerated/plots/{preview_name}",
        })

    manifest = {
        "name": "Plots Manifest",
        "generated_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        "generator": "metaphysica.generators.generate_plots_manifest",
        "plots_dir": "AutoGenerated/plots/",
        "total_plots": len(entries),
        "seed_provenance": "All plots visualize derivations rooted in b3 = 24.",
        "plots": entries,
    }

    out = ag / "plots-manifest.json"
    out.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"plots-manifest: {len(entries)} plot(s)")
    print(f"  -> {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
