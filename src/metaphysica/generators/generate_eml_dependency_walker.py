"""generate_eml_dependency_walker.py — Sprint 3 #5 (EML counterpart of S3.4).

Walks every formula's EML operator tree back to the LIVE b₃ seed and writes
``AutoGenerated/eml_dependency_chains.json`` keyed by formula id. This is
the EML counterpart of ``generate_arithma_dependency_walker.py`` (S3.4)
and shares :mod:`metaphysica.generators._dependency_walk_common` for the
detection rules and JSON envelope.

Tree source, one per formula (preferred → fallback):
  1. ``parsed``      — the formula's own expression (``eml_tree_str``, else an
                       ``EML:``-prefixed ``eml_description``) parsed in-process
                       with eml_math, exactly as ``generate_eml_trees`` does.
  2. ``compact`` / ``pure_eml`` — ``eml_trees.json``, used only when eml_math
                       cannot be imported.
  3. ``string_scan`` — the same expression text, scanned with the same leaf
                       rules (marked ``degraded_walk``).
  ``no_expression``  — the formula carries no EML expression at all.

b₃ detection (see ``_dependency_walk_common``):
  - ROOTED: a leaf that names b₃ -- ``b3_leaf()``, ``flavour_b3_leaf()``,
    ``b3``/``b_3``/``elder_kads``/``topology.elder_kads``.
  - AMBIGUOUS: no such leaf, but a bare scalar equal to the live b₃. Counted
    apart; never rooted.
  - The three counts partition ``total_formulas``.

WHY THE COUNT USED TO MOVE BETWEEN RUNS
=======================================
The walk itself is a pure function of its inputs, but it silently changed
INSTRUMENT with the state of the disk. With ``eml_trees.json`` present it
walked parsed trees, where ``b3_leaf()`` is a childless node no rule
recognised; without it -- a ``--only``/``--skip-sims`` build, a standalone
run, a different output root -- it fell back to scanning the raw string for
the substring ``"b3"``, which DID match ``b3_leaf``. On one unchanged
formulas.json that is 113 rooted with the cache and 208 without it, and a
partially stale cache lands anywhere in between. Detection also keyed on
the value 24, so the count moved with whichever seed the trees were built
under. Now every representation applies one label-based rule set, the tree
is parsed from the formula's own current string rather than read from a
separately generated file, and ``tree_source_counts`` / ``cache_check``
record which instrument each formula was measured with.

Usage:
    python -m metaphysica.generators.generate_eml_dependency_walker
    python -m metaphysica.generators.generate_eml_dependency_walker \\
        --autogen <dir-with-formulas.json> --out <path.json>
"""
from __future__ import annotations

import argparse
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

from metaphysica.generators._common import autogen_dir
from metaphysica.generators._dependency_walk_common import (
    B3_LABEL_TOKENS,
    NUMERIC_KINDS,
    formula_tree_sites,
    is_b3_label,
    is_b3_scalar,
    live_seed,
    matches_template,
    scan_expression,
    seed_header,
    site_verdict,
    truncate_paths,
)

VERSION = "1.1"


# ── Compact-tree walker ──────────────────────────────────────────────────────
#
# Compact node form (from eml_math.tree.to_compact):
#   leaf     : [label, kind_char]
#   internal : [label, kind_char, child1, child2, …]
#
# We collect:
#   - depth     : longest root→leaf chain length
#   - leaves    : total leaf count
#   - b3        : leaves that NAME b₃ (b3_leaf, flavour_b3_leaf, b3, …)
#   - raw_seed  : numeric leaves equal to the live b₃ (ambiguous)
#   - paths     : root→leaf token sequences ending at either kind of leaf

def _walk(node, path, out_paths, counts, b3) -> int:
    """Recurse over a compact EML node. Returns the subtree depth."""
    if not isinstance(node, list) or len(node) < 2:
        counts["leaves"] += 1
        return 0

    label    = str(node[0])
    kind     = str(node[1])
    children = node[2:]
    here     = path + [label]

    if not children:
        counts["leaves"] += 1
        if kind in NUMERIC_KINDS:
            if is_b3_scalar(label, b3):
                counts["raw_seed"] += 1
                out_paths.append(here)
        elif is_b3_label(label):
            # b3_leaf() / flavour_b3_leaf() parse to a childless COMPOUND
            # node carrying the function name; b3 / elder_kads to a vec.
            counts["b3"] += 1
            out_paths.append(here)
        return 0

    max_child_depth = 0
    for c in children:
        d = _walk(c, here, out_paths, counts, b3)
        if d + 1 > max_child_depth:
            max_child_depth = d + 1
    return max_child_depth


def _chain(counts: Dict[str, int], paths, depth: int, source: str) -> dict:
    rooted = counts["b3"] > 0
    ambiguous = (not rooted) and counts["raw_seed"] > 0
    return {
        "depth":                 int(depth),
        "leaves":                int(counts["leaves"]),
        "b3_leaf_count":         int(counts["b3"]),
        "raw_seed_leaves_count": int(counts["raw_seed"]),
        "b3_rooted":             bool(rooted),
        "ambiguous":             bool(ambiguous),
        "paths":                 truncate_paths(paths),
        "tree_source":           source,
        "degraded_walk":         source in ("string_scan", "no_expression"),
    }


def _chain_for_tree(tree, source: str, b3) -> dict:
    counts = {"leaves": 0, "b3": 0, "raw_seed": 0}
    paths: List[List[str]] = []
    depth = _walk(tree, [], paths, counts, b3)
    return _chain(counts, paths, depth, source)


def _chain_for_string(expr: Optional[str], b3) -> dict:
    """Fallback: the expression text, scanned with the tree's own rules."""
    if not expr:
        return _chain({"leaves": 0, "b3": 0, "raw_seed": 0}, [], 0,
                      "no_expression")
    labels, scalars = scan_expression(expr, b3)
    paths = ([["<string-scan>", t] for t in labels]
             + [["<string-scan>", s] for s in scalars])
    return _chain({"leaves": 0, "b3": len(labels), "raw_seed": len(scalars)},
                  paths, 0, "string_scan")


# ── Which expression a formula's tree is built from ──────────────────────────

def tree_expression(formula: dict) -> Tuple[Optional[str], Optional[str]]:
    """``(expression, field)`` -- the same choice ``generate_eml_trees`` makes."""
    ts = formula.get("eml_tree_str", "") or ""
    if ts:
        return f"EML: {ts}", "eml_tree_str"
    ed = formula.get("eml_description", "") or ""
    if ed and ed.startswith("EML:"):
        return ed, "eml_description"
    return None, None


def _select_cached_tree(entry):
    """eml_trees.json carries "c" (compact ops tree) and "p" (pure eml)."""
    if not isinstance(entry, dict):
        return None, None
    if isinstance(entry.get("c"), list) and len(entry["c"]) >= 2:
        return entry["c"], "compact"
    if isinstance(entry.get("p"), list) and len(entry["p"]) >= 2:
        return entry["p"], "pure_eml"
    return None, None


def load_parser() -> Optional[Callable[[str], list]]:
    """eml_math's parser in compact mode, or None when it is not importable.

    Errors map to ``["<error>", "?"]``, the entry ``generate_eml_trees``
    writes for the same failure, so a parsed walk and a cached walk of the
    same string agree.
    """
    try:
        from eml_math.tree import parse_eml_tree, to_compact
    except Exception:                                    # noqa: BLE001
        return None

    def parse(expr: str) -> list:
        try:
            return to_compact(parse_eml_tree(expr, expand_eml=False))
        except Exception:                                # noqa: BLE001
            return ["<error>", "?"]

    return parse


# ── What the source says about the published trees ───────────────────────────

def _status(chain: dict) -> str:
    return ("rooted" if chain["b3_rooted"]
            else "ambiguous" if chain["ambiguous"] else "not_rooted")


def _site_ref(s: Dict[str, Any]) -> str:
    return f"{s['file']}:{s['line']}"


def _interpolation_report(formulas: dict, chains: dict,
                          sites: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Formulas whose walked tree string was BUILT from runtime values."""
    computed = [s for s in sites if s["field"] and s["how"]]
    hit_ids: List[str] = []
    used = set()
    for fid in sorted(formulas):
        formula = formulas[fid] or {}
        expr, field = tree_expression(formula)
        if not expr:
            continue
        text = formula.get(field) or ""
        for s in computed:
            if s["field"] != field:
                continue
            if s["formula_id"] is not None:
                if s["formula_id"] != fid:
                    continue
            elif formula.get("source_simulation") not in s["simulations"]:
                # Computed id (a loop over theorems): attribute by the
                # simulation that registered it, from the same file.
                continue
            if not matches_template(text, s["fragments"]):
                continue
            hit_ids.append(fid)
            used.add(_site_ref(s))
            chains[fid]["interpolated_tree"] = True
            if s["names_b3"]:
                chains[fid]["interpolated_names_b3"] = True
            break

    st = Counter(_status(chains[f]) for f in hit_ids)
    return {
        "note": (
            "Formulas whose walked tree string is BUILT from runtime values "
            "(f-string / %-format / .format / computed) at its Formula(...) "
            "site, so the string carries the number the expression evaluated "
            "to rather than a leaf, and the walk cannot see a provenance that "
            "is not in the string. Reported, not repaired: the count is the "
            "ratchet, and each is fixed by emitting a labelled leaf "
            "(b3_leaf(), eml_vec(...)) instead of the value."
        ),
        "count": len(hit_ids),
        "rooted": st.get("rooted", 0),
        "ambiguous": st.get("ambiguous", 0),
        "not_rooted": st.get("not_rooted", 0),
        "naming_b3": sum(1 for f in hit_ids
                         if chains[f].get("interpolated_names_b3")),
        "formula_ids": hit_ids,
        "sites": len(computed),
        "sites_by_how": dict(sorted(Counter(s["how"] for s in computed).items())),
        "sites_naming_b3": sum(1 for s in computed if s["names_b3"]),
        "unattributed_sites": sorted(_site_ref(s) for s in computed
                                     if _site_ref(s) not in used),
        "site_list": [
            {"site": _site_ref(s), "how": s["how"], "field": s["field"],
             "formula_id": s["formula_id"], "names_b3": s["names_b3"]}
            for s in computed
        ],
    }


def _registration_report(formulas: dict, sites: List[Dict[str, Any]],
                         b3) -> Dict[str, Any]:
    """Formula ids registered at more than one site whose trees disagree."""
    by_id: Dict[str, List[Dict[str, Any]]] = {}
    for s in sites:
        if s["formula_id"]:
            by_id.setdefault(s["formula_id"], []).append(s)
    conflicts = []
    for fid in sorted(by_id):
        group = by_id[fid]
        if len(group) < 2:
            continue
        verdicts = {_site_ref(s): site_verdict(s, b3) for s in group}
        if len(set(verdicts.values())) < 2:
            continue
        conflicts.append({
            "formula_id": fid,
            "published_from": (formulas.get(fid) or {}).get("source_simulation"),
            "sites": verdicts,
        })
    return {
        "note": (
            "Formula ids registered by more than one Formula(...) site whose "
            "tree strings disagree about b3. The registry keeps the LAST "
            "registration, so these verdicts depend on simulation order and "
            "on which optional simulations imported. A computed string is "
            "judged by its literal text only."
        ),
        "count": len(conflicts),
        "ids": conflicts,
    }


# ── The walk ────────────────────────────────────────────────────────────────

def walk(formulas: dict,
         eml_trees: Optional[dict] = None,
         *,
         seed: Optional[Tuple[int, int, str]] = None,
         parser: Any = "auto",
         sites: Optional[List[Dict[str, Any]]] = None) -> dict:
    """Return the full ``eml_dependency_chains.json`` payload.

    Pure: nothing is read from or written to disk except, when *sites* is
    None, the package's simulation sources, scanned for how each formula's
    tree string is built.

    Args:
        formulas:  ``formulas.json["formulas"]``.
        eml_trees: ``eml_trees.json["f"]`` or None.
        seed:      ``(b3, b2, path)``; default the live seed.
        parser:    ``"auto"`` (eml_math if importable), a callable
                   ``expr -> compact tree``, or None/False for no parser.
        sites:     precomputed :func:`formula_tree_sites`, ``[]`` to skip.
    """
    seed = seed if seed is not None else live_seed()
    b3 = seed[0]
    if parser == "auto":
        parser = load_parser()
    parser = parser or None
    eml_trees = eml_trees if isinstance(eml_trees, dict) else None

    chains: Dict[str, dict] = {}
    sources: Counter = Counter()
    stale: List[str] = []
    missing = compared = 0
    b3_rooted = ambiguous = non_rooted = 0

    # Sorted, so the artifact is byte-stable whatever order the simulations
    # registered in. (The counts never depended on order.)
    for fid in sorted(formulas):
        formula = formulas[fid] or {}
        expr, _field = tree_expression(formula)
        cached, cached_source = _select_cached_tree(
            eml_trees.get(fid) if eml_trees is not None else None)

        if expr is None:
            chain = _chain_for_string(None, b3)
        elif parser is not None:
            tree = parser(expr)
            chain = _chain_for_tree(tree, "parsed", b3)
            if eml_trees is not None:
                if cached_source != "compact":
                    missing += 1
                else:
                    compared += 1
                    if cached != tree:
                        stale.append(fid)
        elif cached is not None:
            chain = _chain_for_tree(cached, cached_source, b3)
        else:
            chain = _chain_for_string(expr, b3)

        chains[fid] = chain
        sources[chain["tree_source"]] += 1
        if chain["b3_rooted"]:
            b3_rooted += 1
        elif chain["ambiguous"]:
            ambiguous += 1
        else:
            non_rooted += 1

    assert b3_rooted + ambiguous + non_rooted == len(formulas)

    if sites is None:
        sites = formula_tree_sites()

    tree_source_counts = {k: sources.get(k, 0) for k in
                          ("parsed", "compact", "pure_eml", "string_scan",
                           "no_expression")}
    tree_source_counts["degraded"] = (tree_source_counts["string_scan"]
                                      + tree_source_counts["no_expression"])

    if parser is None:
        cache_check: Dict[str, Any] = {
            "status": "not checked: eml_math not importable, walked "
                      + ("eml_trees.json" if eml_trees is not None
                         else "expression strings")}
    elif eml_trees is None:
        cache_check = {"status": "eml_trees.json absent; trees parsed in-process"}
    else:
        cache_check = {
            "status": "compared",
            "note": ("eml_trees.json entries that differ from a fresh parse "
                     "of the same formulas.json: the cache is stale, or was "
                     "written by a different eml_math. The walk used the "
                     "fresh parse either way."),
            "compared": compared,
            "stale": len(stale),
            "missing": missing,
            "stale_ids": stale[:50],
        }

    interpolated = _interpolation_report(formulas, chains, sites)
    registration = _registration_report(formulas, sites, b3)

    return {
        "version":              VERSION,
        "kind":                 "eml",
        **seed_header(seed),
        "total_formulas":       len(formulas),
        "b3_rooted_count":      b3_rooted,
        "ambiguous_count":      ambiguous,
        "non_b3_rooted_count":  non_rooted,
        "rules": {
            "rooted":    "a leaf naming b3: " + ", ".join(sorted(B3_LABEL_TOKENS)),
            "ambiguous": "no such leaf, but a bare scalar equal to the live "
                         "b3; never counted rooted",
            "partition": "b3_rooted + ambiguous + non_b3_rooted = total",
        },
        "tree_source_counts":   tree_source_counts,
        "cache_check":          cache_check,
        "interpolated_trees":   interpolated,
        "registration_conflicts": registration,
        "chains":               chains,
    }


def _load(path: Path, key: str) -> Optional[dict]:
    if not path.is_file():
        return None
    with open(path, encoding="utf-8") as fp:
        return json.load(fp).get(key, {})


def main(argv: Optional[List[str]] = None, *,
         autogen: Optional[Path] = None,
         out_path: Optional[Path] = None) -> int:
    """Walk ``<autogen>/formulas.json`` and write the chains file.

    ``autogen`` defaults to :func:`autogen_dir` and ``out_path`` to
    ``<autogen>/eml_dependency_chains.json``; both can also be given on the
    command line (``--autogen``, ``--out``) so the walk can be measured
    against a copy without writing into a published artifact tree.
    """
    ap = argparse.ArgumentParser(prog="generate_eml_dependency_walker")
    ap.add_argument("--autogen", type=Path, default=None,
                    help="directory holding formulas.json (and eml_trees.json)")
    ap.add_argument("--out", type=Path, default=None,
                    help="output path for eml_dependency_chains.json")
    args = ap.parse_args(argv or [])
    ag = Path(autogen or args.autogen or autogen_dir())
    out_path = Path(out_path or args.out or ag / "eml_dependency_chains.json")

    formulas = _load(ag / "formulas.json", "formulas")
    if formulas is None:
        print(f"ERROR: {ag / 'formulas.json'} not found. Run the simulation build first.")
        return 1
    eml_trees = _load(ag / "eml_trees.json", "f")

    out = walk(formulas, eml_trees)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8") as fp:
        json.dump(out, fp, ensure_ascii=False, separators=(",", ":"))

    chains = out["chains"]
    size_kb = out_path.stat().st_size / 1024
    avg_depth = sum(c["depth"] for c in chains.values()) / max(1, len(chains))
    src = out["tree_source_counts"]
    interp = out["interpolated_trees"]

    print("EML dependency walker complete:")
    print(f"  Seed:              {out['root_seed']} ({out['seed']['path']})")
    print(f"  Total formulas:    {out['total_formulas']}")
    print(f"  b3-rooted:         {out['b3_rooted_count']}")
    print(f"  Ambiguous (={out['seed']['b3']}):  {out['ambiguous_count']}")
    print(f"  Non-b3-rooted:     {out['non_b3_rooted_count']}")
    print(f"  Avg tree depth:    {avg_depth:.2f}")
    print("  Tree source:       " + "  ".join(f"{k}={v}" for k, v in src.items()))
    if out["cache_check"].get("status") == "compared":
        print(f"  Cache check:       stale={out['cache_check']['stale']}  "
              f"missing={out['cache_check']['missing']}")
    print(f"  Interpolated:      {interp['count']} formulas "
          f"({interp['naming_b3']} hide a b3 name) from {interp['sites']} sites")
    print(f"  Order-dependent:   {out['registration_conflicts']['count']} ids "
          f"registered twice with disagreeing trees")
    print(f"  Output:            {out_path}  ({size_kb:.1f} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
