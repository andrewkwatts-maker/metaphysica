"""
eml_math — thin operator-tree adapter for v25.0 physics modules.
================================================================

Purpose
-------
The Sprint 4 v25.0 physics lift (`yukawa_derivation`, `re_t_sector`,
`vacuum_selection`, `strong_cp_axion`, `baryogenesis`, `soft_susy_breaking`)
needs a single, uniform call site for recording the symbolic derivation tree
of every parameter it computes. Those modules use this pattern::

    tree = eml_operator_tree("yukawa_derivation")
    tree.register_derivation(
        param="theta_13_rad",
        formula="arcsin(sqrt(2)/3) - delta_b3",
        value=0.1485,
    )

This module is a thin adapter on top of the existing
:mod:`metaphysica.simulations.core.eml_integration` so it does **not**
duplicate the EML operator wrappers — it just provides the
``eml_operator_tree`` class with an ``register_derivation`` /
``get_tree`` API, persists results into ``AutoGenerated/eml_trees_v25.json``
(overlay-safe), and cross-links the formula text to ``b3_leaf()`` whenever
the formula text mentions ``b3``, ``b_3``, or the literal ``24``.

Persistence layout
------------------
``AutoGenerated/eml_trees_v25.json`` follows the shape::

    {
        "yukawa_derivation": {
            "theta_13_rad": {
                "formula": "arcsin(sqrt(2)/3) - delta_b3",
                "value": 0.1485,
                "b3_traceback": true
            },
            ...
        },
        "re_t_sector": { ... },
        ...
    }

The file is kept *separate* from the main ``eml_trees.json`` so the Sprint 3
``arithma_dependency_walker`` and the Sprint 4 dependency resolver can pick
up v25.0 derivations without having to disambiguate them against the legacy
EML trees.

Overlay-safe semantics
----------------------
``register_derivation`` does an in-place merge:

1. Load existing JSON if the file exists.
2. Ensure ``self.name`` slot is present (dict).
3. Update *only* the ``param`` key under ``self.name``.
4. Save back.

Two trees with different names never collide; two registrations under the
same name + same param simply overwrite the prior entry for that param.

Public surface
--------------

* :class:`eml_operator_tree` — construct via ``eml_operator_tree(name)``.
* :meth:`eml_operator_tree.register_derivation` — append a derivation.
* :meth:`eml_operator_tree.get_tree` — return the in-memory tree dict.

Re-exports
----------
For convenience the most-commonly-used EML operator factories from
:mod:`eml_integration` are re-exported so v25.0 modules can do::

    from metaphysica.simulations.core.eml_tree_adapter import (
        eml_operator_tree, eml_scalar, eml_add, eml_mul, b3_leaf,
    )

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any, Dict

# Re-export the canonical operator wrappers so v25.0 modules have a single
# import surface (`from ...core.eml_math import ...`) rather than reaching
# into eml_integration directly.
