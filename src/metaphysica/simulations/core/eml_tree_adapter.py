# ── Persistence file --------------------------------------------------------

#: Name of the on-disk JSON file under ``AutoGenerated/`` that this adapter
#: writes into. v25.0 derivations are kept *separate* from the legacy
#: ``eml_trees.json`` so the dependency walker can pick them up without
#: disambiguation logic.
TREES_FILENAME = "eml_trees_v25.json"


# ── b3 traceback detector ---------------------------------------------------

#: Pre-compiled detector for any formula text that mentions b3 / b_3 / 24.
#: Used by :meth:`eml_operator_tree.register_derivation` to flag derivations
#: that cross-link back to the G2 third Betti number seed.
#:
#: Word-boundary on either side to avoid matching ``24`` inside ``2400`` or
#: ``b3`` inside ``b30``. Whitespace, brackets, math operators, dots, and
#: end-of-string all count as boundaries.
_B3_PATTERN = re.compile(
    r"(?:\b|^)(?:b3|b_3|b_\{3\}|24)(?:\b|$)",
    re.IGNORECASE,
)


def _formula_has_b3_traceback(formula: str) -> bool:
    """Return True iff *formula* text mentions b3 / b_3 / 24."""
    if not formula:
        return False
    return bool(_B3_PATTERN.search(formula))


# ── On-disk helpers ---------------------------------------------------------


def _trees_path() -> Path:
    """Resolve the on-disk path for ``eml_trees_v25.json``.

    Defers import of :func:`metaphysica.generators._common.autogen_dir` to call
    time so importing this module never has the side effect of creating
    ``AutoGenerated/``.
    """
    from metaphysica.generators._common import autogen_dir

    return autogen_dir() / TREES_FILENAME


def _load_trees() -> Dict[str, Dict[str, Dict[str, Any]]]:
    """Load the on-disk tree dict, or return an empty dict if missing."""
    path = _trees_path()
    if not path.exists():
        return {}
    try:
        with path.open("r", encoding="utf-8") as fh:
            data = json.load(fh)
    except json.JSONDecodeError:
        # Corrupt file — treat as empty rather than crashing the build.
        return {}
    if not isinstance(data, dict):
        return {}
    return data


def _save_trees(trees: Dict[str, Dict[str, Dict[str, Any]]]) -> None:
    """Write *trees* out as pretty JSON."""
    path = _trees_path()
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as fh:
        json.dump(trees, fh, indent=2, sort_keys=True)
        fh.write("\n")


# ── Public adapter class ----------------------------------------------------


class eml_operator_tree:
    """Thin adapter that records v25.0 EML derivations to disk.

    Parameters
    ----------
    name:
        Logical name of the physics module owning these derivations
        (e.g. ``"yukawa_derivation"``, ``"re_t_sector"``). Two adapters
        with the same name share the same on-disk slot — registrations
        merge rather than collide.

    Example
    -------
    >>> tree = eml_operator_tree("re_t_sector")
    >>> tree.register_derivation(
    ...     param="ReT_VEV",
    ...     formula="b3 * exp(-S_inst) / (2*pi)",
    ...     value=10.86,
    ... )  # doctest: +SKIP
    >>> tree.get_tree()["ReT_VEV"]["b3_traceback"]  # doctest: +SKIP
    True
    """

    __slots__ = ("name",)

    def __init__(self, name: str) -> None:
        if not isinstance(name, str) or not name:
            raise ValueError(
                f"eml_operator_tree(name=...) requires a non-empty string, "
                f"got {name!r}"
            )
        self.name = name

    # ── Recording API ------------------------------------------------------

    def register_derivation(
        self,
        param: str,
        formula: str,
        value: Any,
    ) -> Dict[str, Any]:
        """Record a single ``param → (formula, value)`` derivation.

        The entry is stored under ``trees[self.name][param]`` in
        ``AutoGenerated/eml_trees_v25.json``. The operation is overlay-safe:
        existing entries under other names are preserved verbatim; existing
        entries under the same name + different param are preserved;
        existing entries under the same name + same param are overwritten.

        A ``b3_traceback`` flag is added to the entry when the formula text
        mentions ``b3``, ``b_3``, or ``24`` — see :func:`_formula_has_b3_traceback`.

        Parameters
        ----------
        param:
            Canonical parameter name (e.g. ``"theta_13_rad"``).
        formula:
            Free-form symbolic / EML-style string describing the derivation
            (e.g. ``"arcsin(sqrt(2)/3) - delta_b3"``).
        value:
            Numerical value (typically ``float``, but ``int`` / ``str`` are
            accepted for non-numeric / placeholder cases). Must be
            JSON-serialisable.

        Returns
        -------
        dict
            The entry as written, including the ``b3_traceback`` flag.
        """
        if not isinstance(param, str) or not param:
            raise ValueError(
                f"register_derivation(param=...) requires a non-empty string, "
                f"got {param!r}"
            )
        if not isinstance(formula, str):
            raise TypeError(
                f"register_derivation(formula=...) requires a string, "
                f"got {type(formula).__name__}"
            )

        entry: Dict[str, Any] = {
            "formula": formula,
            "value": value,
            "b3_traceback": _formula_has_b3_traceback(formula),
        }

        trees = _load_trees()
        bucket = trees.setdefault(self.name, {})
        if not isinstance(bucket, dict):
            # Defensive: replace a malformed slot rather than crashing.
            bucket = {}
            trees[self.name] = bucket
        bucket[param] = entry
        _save_trees(trees)
        return entry

    # ── Read API -----------------------------------------------------------

    def get_tree(self) -> Dict[str, Dict[str, Any]]:
        """Return the in-memory mapping of ``param → entry`` for this tree.

        Loads fresh from disk on every call (cheap, and keeps semantics
        clean when multiple adapters share the same name across processes).
        """
        trees = _load_trees()
        bucket = trees.get(self.name, {})
        if not isinstance(bucket, dict):
            return {}
        return bucket

    # ── Dunders ------------------------------------------------------------

    def __repr__(self) -> str:  # pragma: no cover - trivial
        return f"eml_operator_tree(name={self.name!r})"


