"""One place that knows where `parameters.json` is, and says when it is missing.

WHY THIS MODULE EXISTS
======================
The lookup was open-coded in at least three places, and two of them were
broken in the same two ways:

    free_set._params        `Path(__file__).parents[3]` resolves to `src/`,
                            which the build never writes to, leaving an
                            absolute Windows path from the author's machine as
                            the only candidate that could match. On a Linux
                            container it returned an EMPTY dict, and five tests
                            then failed with messages about the physics while
                            the fault was a path.
    b3_path._registry       a CWD-relative `AutoGenerated/parameters.json` plus
                            the same Windows path, so it returned None
                            everywhere else and every registry cross-check it
                            fed was silently skipped.

Both failed by returning a benign-looking empty value. That is the shape worth
designing against: a missing INPUT presenting as a RESULT. So this module
returns the provenance alongside the rows and makes the unavailable case carry
its own explanation.

WHAT IS DELIBERATELY NOT A FALLBACK
===================================
The bundled wheel snapshot `metaphysica/data/parameters.json`. Measured
2026-09-22 it carries 620 of the 808 rows a build produces and 111 shared rows
hold DIFFERENT values, so falling back to it would feed stale numbers into
reductions that report themselves as verified. A caller that genuinely wants
the bundled snapshot should read it by name and say so.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, List, Optional

__all__ = [
    "candidate_paths",
    "params_source",
    "load_parameters",
    "parameter_value",
]

#: The repository root. `parents[3]` is `src/` and was the original off-by-one;
#: this is spelled with a comment because getting it wrong is silent.
_REPO_ROOT = Path(__file__).resolve().parents[4]


def candidate_paths() -> List[Path]:
    """Where the artifact may live, in preference order.

    `autogen_dir()` is the build's OWN resolver (`METAPHYSICA_OUT`, else the
    CWD) and is reused rather than reimplemented so the two cannot drift.
    """
    import glob

    candidates: List[Path] = []
    try:
        from metaphysica.generators._common import autogen_dir

        candidates.append(autogen_dir() / "parameters.json")
    except ImportError:                    # generators not importable
        pass

    candidates += [
        _REPO_ROOT / "AutoGenerated" / "parameters.json",
        # `python -m metaphysica.build --out ./site` is the documented standard
        # command, so its output is a first-class location rather than a guess.
        _REPO_ROOT / "site" / "AutoGenerated" / "parameters.json",
        _REPO_ROOT.parent / "PrincipiaMetaphysica" / "AutoGenerated"
        / "parameters.json",
        Path("H:/Github/PrincipiaMetaphysica/AutoGenerated/parameters.json"),
    ]
    candidates += [Path(p) for p in glob.glob("AutoGenerated/parameters.json")]

    seen, unique = set(), []
    for path in candidates:
        key = str(path)
        if key not in seen:
            seen.add(key)
            unique.append(path)
    return unique


def params_source() -> Dict[str, Any]:
    """The parameter rows AND where they came from, or why there are none.

    Returns a dict with `available`, `path`, `n_rows`, `params` and `checked`;
    when unavailable it also carries `why`. Callers that only want the rows
    should use `load_parameters()`, but anything that REPORTS a result computed
    from them should surface the provenance too.
    """
    checked: List[str] = []
    for path in candidate_paths():
        checked.append(str(path))
        try:
            if not path.is_file():
                continue
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):      # unreadable, or not JSON
            continue
        rows = payload.get("parameters") if isinstance(payload, dict) else None
        if isinstance(rows, dict) and rows:
            return {"available": True, "path": str(path), "n_rows": len(rows),
                    "params": rows, "checked": checked}

    return {
        "available": False,
        "path": None,
        "n_rows": 0,
        "params": {},
        "checked": checked,
        "why": (
            "no readable parameters.json with a non-empty 'parameters' object "
            "at any candidate location. AutoGenerated/ is gitignored and "
            "carries no tracked files, so `python -m metaphysica.build --out "
            "./site` must run before anything that reads it. The bundled wheel "
            "snapshot is NOT used as a fallback because it is a stale subset."
        ),
    }


def load_parameters() -> Dict[str, Any]:
    """Just the rows. Empty when no artifact is reachable."""
    return params_source()["params"]


def parameter_value(name: str,
                    params: Optional[Dict[str, Any]] = None) -> Optional[float]:
    """One row's numeric value, or None if the row or the artifact is absent.

    None is genuinely ambiguous here -- absent artifact, absent row, or a
    non-numeric value -- so a caller that must distinguish them should use
    `params_source()` and check `available` itself.
    """
    params = params if params is not None else load_parameters()
    row = params.get(name)
    value = row.get("value") if isinstance(row, dict) else None
    return float(value) if isinstance(value, (int, float)) else None
