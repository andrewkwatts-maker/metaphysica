def unnamed_declarations(root: Optional[Path] = None) -> List[Dict[str, str]]:
    """Non-derived declarations whose path is computed, not literal.

    They cannot become rows -- there is no name to put in one -- but they
    are a registration surface, and a surface that no sweep can see is
    exactly how a count goes stale. Reported so the absence is visible.
    """
    out = []
    for call in iter_parameter_calls(root):
        status = call.status or (call.classification if call.foreign_kwargs else None)
        if status in NON_DERIVED_STATUSES and call.path is None:
            out.append({
                "location": f"{_rel(call.file)}:{call.lineno}",
                "callee": call.callee,
                "status": status,
                "note": (
                    "path is a variable, so no row can name it; check by "
                    "hand that the quantities it writes are covered"
                ),
            })
    return out


def _merge_duplicate_rows(rows: List[LedgerRow]) -> List[LedgerRow]:
    """One row per quantity, not per declaration.

    Five paths in this tree are declared twice -- once as
    ``Parameter(status=...)`` and again as ``registry.set_param(status=...)``
    -- and counting both would inflate the free-variable count by counting
    declarations instead of free variables. The surviving row keeps every
    location and every note, so the second declaration is still visible.
    """
    merged: Dict[str, LedgerRow] = {}
    for row in rows:
        existing = merged.get(row.name)
        if existing is None:
            merged[row.name] = row
            continue
        if row.location not in existing.notes:
            existing.notes.append(
                f"ALSO DECLARED AT {row.location} (status {row.status})"
            )
        seen = {(e.get("location"), e.get("kind")) for e in existing.role_evidence}
        for ev in row.role_evidence:
            if (ev.get("location"), ev.get("kind")) not in seen:
                existing.role_evidence.append(ev)
        for note in row.notes:
            if note not in existing.notes:
                existing.notes.append(note)
        if existing.value is None:
            existing.value = row.value
        existing.role = _role_from_consumers([
            Consumer(location=e.get("location", ""), function=e.get("function", ""),
                     kind=e.get("kind", ""), detail=e.get("detail", ""))
            for e in existing.role_evidence
        ]) if existing.role != ROLE_PERMITTED_OR_SCALE else existing.role
    return list(merged.values())


def build_ledger(root: Optional[Path] = None) -> Dict[str, Any]:
    """Sweep the tree and return the ledger.

    Every count in the result is a ``len()`` over rows that were found.
    """
    rows = _merge_duplicate_rows(sweep_parameter_rows(root) + sweep_anchor_rows())
    rows.sort(key=lambda r: (r.role, r.status, r.name))

    by_role: Dict[str, int] = {role: 0 for role in ROLES}
    by_status: Dict[str, int] = {}
    for row in rows:
        by_role[row.role] = by_role.get(row.role, 0) + 1
        by_status[row.status] = by_status.get(row.status, 0) + 1

    permitted = by_role[ROLE_PERMITTED_OR_SCALE]
    return {
        "schema": "free_variables/1",
        "generator": "metaphysica.simulations.core.free_variable_ledger",
        "what_this_counts": (
            "Quantities this framework did not derive, swept from the tree. "
            "free_variable_count is len(rows) -- no literal anywhere in this "
            "file states it."
        ),
        "free_variable_count": len(rows),
        "free_variable_count_excluding_permitted": len(rows) - permitted,
        "count_by_role": by_role,
        "count_by_status": dict(sorted(by_status.items())),
        "roles": {
            ROLE_PERMITTED_OR_SCALE:
                "reduction/scale-setting choice; the one permitted bucket",
            ROLE_COMPARISON_ONLY:
                "measured value read only to score a prediction against it",
            ROLE_LOAD_BEARING_INPUT:
                "measured or chosen value that flows into a registered output",
            ROLE_UNRESOLVED:
                "no consumer traced, or the row contradicts its own status",
        },
        "superseded_claims": {
            "validation.calibrated_count": 0,
            "statistical_rigor_validator.calculate_effective_dof": 3,
            "abstract.calibration_inputs": 3,
            "note": (
                "All three were literals. None was computed. They are "
                "recorded here so the replacement is auditable, not so the "
                "old numbers keep circulating."
            ),
        },
        "derived_from_free_variables": _derived_from_free_variables(),
        "unnamed_declarations": unnamed_declarations(root),
        "rows": [r.to_dict() for r in rows],
    }


def free_variable_count(root: Optional[Path] = None) -> int:
    """The one number: how many quantities the framework did not derive."""
    return build_ledger(root)["free_variable_count"]


def _ledger_artifacts() -> Iterator[Path]:
    out = os.environ.get("METAPHYSICA_OUT")
    if out:
        yield Path(out) / "AutoGenerated" / "free_variables.json"
    yield _package_root().parents[1] / "AutoGenerated" / "free_variables.json"
    yield _package_root() / "data" / "free_variables.json"


@lru_cache(maxsize=1)
def published_free_variable_count() -> int:
    """The single published free-variable count, for parameter definitions.

    Reads ``AutoGenerated/free_variables.json`` when the build has written
    it and falls back to sweeping the tree when it has not. Same shape as
    ``registry_paths``: the artifact is the fast path, the sweep is the
    truth, and neither is a hand-maintained literal.

    Cached because a parameter table is built many times per run and the
    sweep costs seconds.
    """
    for cand in _ledger_artifacts():
        try:
            if cand.is_file():
                data = json.loads(cand.read_text(encoding="utf-8"))
                value = data.get("free_variable_count")
                if isinstance(value, int):
                    return value
        except (OSError, ValueError):  # pragma: no cover - defensive
            continue
    return free_variable_count()


def write_ledger(out_dir: Path, root: Optional[Path] = None) -> Path:
    """Emit ``<out_dir>/AutoGenerated/free_variables.json``."""
    ledger = build_ledger(root)
    target = Path(out_dir) / "AutoGenerated"
    target.mkdir(parents=True, exist_ok=True)
    path = target / "free_variables.json"
    path.write_text(json.dumps(ledger, indent=2, sort_keys=False) + "\n",
                    encoding="utf-8")
    return path


def main(argv: Optional[Sequence[str]] = None) -> int:  # pragma: no cover
    import argparse

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "--out",
        default=os.environ.get("METAPHYSICA_OUT") or ".",
        help="directory to write AutoGenerated/ into (default: $METAPHYSICA_OUT)",
    )
    args = ap.parse_args(argv)

    ledger = build_ledger()
    path = write_ledger(Path(args.out))
    print(f"free_variables.json -> {path}")
    print(f"free variable count: {ledger['free_variable_count']}")
    for role, n in ledger["count_by_role"].items():
        print(f"  {role:22} {n}")
    print("  by status: " + ", ".join(
        f"{k}={v}" for k, v in ledger["count_by_status"].items()))
    return 0


