def _registry_values() -> Dict[str, Any]:
    """Values from whichever parameters.json artifact is available."""
    candidates = []
    out = os.environ.get("METAPHYSICA_OUT")
    if out:
        candidates.append(Path(out) / "AutoGenerated" / "parameters.json")
    candidates.append(_package_root().parents[1] / "AutoGenerated" / "parameters.json")
    candidates.append(_package_root() / "data" / "parameters.json")
    for cand in candidates:
        try:
            if cand.is_file():
                data = json.loads(cand.read_text(encoding="utf-8"))
                params = data.get("parameters", data)
                return {k: v.get("value") if isinstance(v, dict) else v
                        for k, v in params.items()}
        except (OSError, ValueError):  # pragma: no cover - defensive
            continue
    return {}


def _closing_derivation_for_status(status: str, name: str) -> str:
    """What would have to exist for this row to stop being a free variable.

    Stated as a requirement on evidence, never as a guess at the physics:
    inventing the missing derivation here would be the same failure the
    ledger exists to measure.
    """
    if status == "MEASURED":
        return (
            f"An expression for {name} in terms of the framework's own "
            f"invariants that reproduces the registered value without "
            f"reading the experimental number back in."
        )
    if status in ("FITTED", "FITTED_COMPOSITE"):
        return (
            f"A closed form replacing the fitted literal, derived before "
            f"the comparison and scored against {name}'s datasource row "
            f"rather than tuned to it."
        )
    if status == "CALIBRATED":
        return (
            f"Either a derivation of {name} from the geometry, or an "
            f"explicit ruling that it is one of the permitted "
            f"scale-setting inputs -- it is currently neither."
        )
    if status == "ANSATZ":
        return (
            f"A proof of the asserted step. The module states the "
            f"assertion; nothing yet derives it."
        )
    return f"Unclassified status {status!r}: no closing condition stated."


def sweep_parameter_rows(root: Optional[Path] = None) -> List[LedgerRow]:
    """Ledger rows for every non-derived ``Parameter(...)`` declaration."""
    values = _registry_values()
    rows: List[LedgerRow] = []
    for call in iter_parameter_calls(root):
        status = call.status
        notes: List[str] = []

        if call.foreign_kwargs:
            # These calls pass kwargs that Parameter has no field for, so
            # they raise TypeError the moment they execute -- they are
            # unreachable. They are kept rather than dropped because one of
            # them declares classification="FITTED" with the source
            # "Chosen to produce reasonable GUT-scale corrections": a fit
            # that no count has ever included because the code around it
            # cannot run.
            if call.classification not in NON_DERIVED_STATUSES:
                continue
            status = call.classification
            notes.append(
                "UNREACHABLE: this Parameter(...) call passes "
                + ", ".join(call.foreign_kwargs)
                + ", none of which is a field of Parameter, so it raises "
                  "TypeError if executed. The fit is declared but never runs."
            )

        if call.callee == "set_param":
            notes.append(
                "Registered directly with registry.set_param, bypassing the "
                "Parameter(...) declaration surface. A sweep of parameter "
                "declarations alone does not see it."
            )

        if status not in NON_DERIVED_STATUSES:
            continue

        if call.path is None:
            # A declaration whose path is a variable. The only one in the
            # tree is register_anchors' own loop, which writes the twenty
            # MEASURED anchors that sweep_anchor_rows already covers by
            # name. Counting it would add a phantom row; dropping it
            # silently would hide a whole registration surface, so it is
            # reported separately by :func:`unnamed_declarations`.
            continue

        name = call.path
        consumers = (
            trace_consumers(call.path) if call.path else []
        )
        if _SCALE_DECLARATION_RE.search(call.description or ""):
            role = ROLE_PERMITTED_OR_SCALE
            evidence = [{
                "location": f"{_rel(call.file)}:{call.lineno}",
                "function": "<own description>",
                "kind": "SELF_DECLARED_SCALE_SETTING",
                "detail": "the row's own description declares it scale-setting",
            }]
        else:
            role = _role_from_consumers(consumers)
            evidence = [asdict(c) for c in consumers]

        admissions = admits_a_fit(call.description or "")
        if admissions and status not in NON_DERIVED_STATUSES:  # pragma: no cover
            notes.append(f"description admits a fit: {admissions}")

        rows.append(LedgerRow(
            name=name,
            value=values.get(call.path) if call.path else None,
            location=f"{_rel(call.file)}:{call.lineno}",
            status=status,
            source_kind="PARAMETER_CALL",
            role=role,
            role_evidence=evidence,
            closing_derivation=_closing_derivation_for_status(status, name),
            description=(call.description or "")[:400],
            notes=notes,
        ))
    return rows


def sweep_anchor_rows() -> List[LedgerRow]:
    """Ledger rows for the anchors registered with ``status="MEASURED"``."""
    from metaphysica.simulations.PM.geometry.geometric_anchors_core import (
        MEASURED_ANCHORS,
        GeometricAnchors,
    )

    anchors = GeometricAnchors(24)
    exported = set(anchors.get_all_anchors())
    lines = _anchor_property_lines()
    core = _anchors_core_path()

    rows: List[LedgerRow] = []
    for name in sorted(MEASURED_ANCHORS):
        consumers = _anchor_internal_consumers(name, exported)
        consumers += trace_consumers(f"geometry.{name}", skip_file=core)
        role = _role_from_consumers(consumers)

        notes: List[str] = []
        admissions = admits_a_fit(_anchor_source(name))
        if admissions or "phenom" in name.lower():
            # Declared MEASURED, but the property's own source calls it a
            # fit. A fit is not a measurement: no experiment reports it, and
            # nothing external constrains it. The role is forced to
            # UNRESOLVED so it cannot be waved through as a free
            # COMPARISON_ONLY row, and the contradiction is recorded for the
            # author rather than resolved here -- changing the registered
            # status is a published-provenance change and belongs to them.
            role = ROLE_UNRESOLVED
            notes.append(
                "DECLARED MEASURED BUT IS A FIT: the property source says "
                "so in its own words. Not a measurement; open ruling."
            )

        if not consumers:
            notes.append(
                "No executing consumer traced: registered and exported to "
                "the website, but nothing reads it into a computation."
            )

        rows.append(LedgerRow(
            name=f"geometry.{name}",
            value=anchors.get_all_anchors().get(name),
            location=f"{_rel(core)}:{lines.get(name, 0)}",
            status="MEASURED",
            source_kind="GEOMETRIC_ANCHOR",
            role=role,
            role_evidence=[asdict(c) for c in consumers],
            closing_derivation=_closing_derivation_for_status("MEASURED", name),
            description=_anchor_source(name).split("\n")[1].strip()[:400]
            if "\n" in _anchor_source(name) else "",
            notes=notes,
        ))
    return rows


def _derived_from_free_variables() -> List[Dict[str, Any]]:
    """Anchors registered ``GEOMETRIC``/``tuning_free`` that read a MEASURED one.

    Not ledger rows -- they are consequences, not free variables. Recorded
    because ``register_anchors`` stamps every non-MEASURED anchor with
    ``"derivation": "Derived from b3=24 topological invariant"`` and
    ``"tuning_free": True``, and for these the b3 input does no work at all:
    they are arithmetic on experimental numbers.
    """
    from metaphysica.simulations.PM.geometry.geometric_anchors_core import (
        MEASURED_ANCHORS,
        GeometricAnchors,
    )

    tree = ast.parse(_anchors_core_path().read_text(encoding="utf-8"))
    deps: Dict[str, Set[str]] = {}
    for fn in ast.walk(tree):
        if not isinstance(fn, ast.FunctionDef):
            continue
        deps[fn.name] = {
            n.attr for n in ast.walk(fn)
            if isinstance(n, ast.Attribute)
            and isinstance(n.value, ast.Name)
            and n.value.id == "self"
            and n.attr != fn.name
        }

    def taint(name: str, seen: Optional[Set[str]] = None) -> Set[str]:
        seen = seen or set()
        if name in seen:
            return set()
        seen.add(name)
        found: Set[str] = set()
        for dep in deps.get(name, ()):
            if dep in MEASURED_ANCHORS:
                found.add(dep)
            elif dep in deps:
                found |= taint(dep, seen)
        return found

    out = []
    for name in sorted(GeometricAnchors(24).get_all_anchors()):
        if name in MEASURED_ANCHORS or name == "get_all_anchors":
            continue
        inherited = sorted(taint(name))
        if inherited:
            out.append({
                "name": f"geometry.{name}",
                "registered_as": "GEOMETRIC (fundamental=True, tuning_free=True)",
                "inherits_from": [f"geometry.{d}" for d in inherited],
                "finding": (
                    "registered as a tuning-free consequence of b3 = 24, but "
                    "its value is arithmetic on experimental input; b3 does "
                    "no work in it"
                ),
            })
    return out


