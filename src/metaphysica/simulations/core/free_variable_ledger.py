@dataclass(frozen=True)
class ParameterCall:
    """One ``Parameter(...)`` call site, reduced to its literal metadata."""

    path: Optional[str]
    status: Optional[str]
    description: str
    file: Path
    lineno: int
    #: kwargs that are not fields of ``simulation_base.Parameter``. A call
    #: carrying any of these cannot execute -- see
    #: :func:`sweep_parameter_rows`.
    foreign_kwargs: Tuple[str, ...] = ()
    #: ``classification=`` where present. A second, undeclared status
    #: vocabulary rides in on the foreign-kwarg calls.
    classification: Optional[str] = None
    #: The callee the declaration was made through. ``Parameter`` is the
    #: declarative surface; ``set_param`` writes straight into the registry
    #: at run time and bypasses it entirely.
    callee: str = "Parameter"


#: Fields of ``metaphysica.simulations.base.simulation_base.Parameter``.
#: Resolved live so this cannot drift from the dataclass.
def _parameter_fields() -> Set[str]:
    from dataclasses import fields as _fields

    from metaphysica.simulations.base.simulation_base import Parameter

    return {f.name for f in _fields(Parameter)}


#: Callees through which a quantity enters the registry with a status.
#: ``set_param`` is here because a sweep that only reads ``Parameter(...)``
#: misses every value written straight into the registry at run time -- the
#: ledger gate found two that way, ``bridge_ede.entropy_damping.classification``
#: (FITTED) and ``yukawa.phi_fit`` (ANSATZ), neither of which has ever
#: appeared in any count.
_DECLARING_CALLEES = frozenset({"Parameter", "set_param"})


def iter_parameter_calls(root: Optional[Path] = None) -> Iterator[ParameterCall]:
    """Yield every status-carrying declaration under ``root``.

    Literal metadata only: a ``status=`` built at runtime yields ``None``
    and is reported rather than guessed at.
    """
    root = root or simulations_root()
    known = _parameter_fields()
    for path in _iter_python_files(root):
        tree = _parse(path)
        if tree is None:
            continue
        # `from ... import Parameter as Knob` must not hide a declaration
        # behind the local name. Resolved per file rather than assumed away.
        aliases = {c: c for c in _DECLARING_CALLEES}
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom):
                for alias in node.names:
                    if alias.name in _DECLARING_CALLEES and alias.asname:
                        aliases[alias.asname] = alias.name
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            fn = node.func
            local = fn.id if isinstance(fn, ast.Name) else getattr(fn, "attr", None)
            name = aliases.get(local)
            if name is None:
                continue
            kw = {k.arg: k.value for k in node.keywords if k.arg}
            # Only Parameter has a fixed field set to be foreign to.
            foreign = tuple(sorted(set(kw) - known)) if name == "Parameter" else ()
            ident = _const(kw.get("path"))
            if ident is None:
                ident = _const(kw.get("id"))
            yield ParameterCall(
                path=ident,
                status=_const(kw.get("status")),
                description=(_const(kw.get("description"))
                             or _const(kw.get("source")) or ""),
                file=path,
                lineno=node.lineno,
                foreign_kwargs=foreign,
                classification=_const(kw.get("classification")),
                callee=name,
            )


