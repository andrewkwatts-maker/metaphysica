#: Rows whose own description declares them a unit- or scale-setting choice.
#: This is the one permitted bucket, so entry is by the row's *own words*,
#: matched here, and never by a hand-kept list of paths -- a list would let
#: a row be waved into the permitted bucket without saying anything about
#: itself.
_SCALE_DECLARATION_RE = re.compile(
    r"\bscale\s+calibration\b|\bsetting\s+physical\s+scales\b"
    r"|\bscale-setting\b|\bcoefficient\s+relating\b.*\bscale\b"
    r"|\bsets?\s+the\s+(?:overall\s+)?(?:unit|scale)\b"
    r"|\breduction\s+scale\b",
    re.IGNORECASE,
)


#: Evidence kinds that make a row load-bearing, strongest first. A value
#: that reaches a registered output, or that a simulation declares it needs
#: in order to run, is one the framework was told rather than derived.
_LOAD_BEARING_KINDS = frozenset({
    "READ_INTO_REGISTERED_OUTPUT",
    "ANCHOR_FEEDS_EXPORTED_ANCHOR",
    "DECLARED_AS_INPUT",
})

#: Evidence kinds that only ever reach a comparison.
_COMPARISON_KINDS = frozenset({"READ_FOR_COMPARISON", "CROSS_CHECK_GROUP"})


def _role_from_consumers(consumers: Sequence[Consumer]) -> str:
    """Role from traced evidence only.

    No evidence means UNRESOLVED, never a default. A fitted value that
    nothing reads is still a free variable; calling it COMPARISON_ONLY
    would be a guess dressed as a finding.
    """
    kinds = {c.kind for c in consumers}
    if _LOAD_BEARING_KINDS & kinds:
        return ROLE_LOAD_BEARING_INPUT
    if _COMPARISON_KINDS & kinds:
        return ROLE_COMPARISON_ONLY
    return ROLE_UNRESOLVED


