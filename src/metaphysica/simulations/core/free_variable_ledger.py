"""The free-variable ledger: one measured count of what is not derived.

WHY THIS EXISTS
---------------
The framework publishes "zero fitted parameters". Three places in the tree
answer the question "how many free variables?" and they do not agree:

* ``validation.calibrated_count`` = 0 -- a literal in
  ``PM/paper/abstract.py``, annotated "EDOF=3: calibrations are
  scale-setting, not fitted".
* ``StatisticalRigorValidator.calculate_effective_dof`` returns 3, and its
  own body says ``# ANSATZ: EDOF=3 is a judgment ... not a numerical
  computation``.
* ``abstract.calibration_inputs`` = 3, whose description names the three as
  "(VEV, alpha_GUT, Re(T))" while
  ``PM/validation/information_bottleneck_distiller.py`` names a *different*
  three, ``["M_Planck", "alpha_EM", "m_H"]``.

None of the three is computed. This module is the measuring instrument that
replaces them: it sweeps the tree for every quantity that is not derived,
records where it lives and what it does, and emits
``AutoGenerated/free_variables.json``. The count is a ``len()`` over rows
that were found, never a literal -- add a fit to the tree and the number
moves on the next build.

WHAT COUNTS AS A ROW
--------------------
Three populations, swept separately because they are declared differently.
A row is a *quantity*, not a declaration: five paths are declared twice and
are merged, because a count of declarations is not a count of free
variables.

1. ``Parameter(...)`` calls whose ``status=`` literal is one of
   :data:`NON_DERIVED_STATUSES`. The operative status vocabulary is
   ``PRESERVED_PARAMETER_STATUSES`` in ``run_all_simulations.py``; the five
   named here are the subset that admits the value did not come out of the
   geometry.
2. The geometric anchors registered with ``status="MEASURED"`` by
   ``geometric_anchors_core.register_anchors`` -- raw NuFIT / Planck /
   SH0ES / PDG / DESI numbers. These never appear as a ``Parameter(...)``
   ``status`` literal, so an AST sweep of declarations alone misses all of
   them.
3. ``registry.set_param(status=...)`` calls, which write straight into the
   registry and bypass the ``Parameter`` surface entirely. This population
   was found by the ledger gate in ``tests/test_free_variable_ledger.py``,
   not by design: ``bridge_ede.entropy_damping.classification`` (FITTED)
   and ``yukawa.phi_fit`` (ANSATZ) had never appeared in any count.

One declaration cannot become a row: ``register_anchors``' own loop, whose
``path`` is a variable. It writes the twenty anchors of population 2, which
are already covered by name; it is reported by :func:`unnamed_declarations`
rather than dropped, because a registration surface no sweep can see is how
a count goes stale.

ROLES
-----
Every row gets exactly one role, and for rows 2 the role is *derived from a
traced consumer*, never asserted:

``PERMITTED_OR_SCALE``
    A reduction- or scale-setting quantity. The one permitted bucket: a
    theory is allowed to be told what its units are.
``COMPARISON_ONLY``
    A measured value read only to score a prediction against it. Costs
    nothing -- the prediction still had to be made without it.
``LOAD_BEARING_INPUT``
    A measured or chosen value that flows into a derivation whose result is
    itself registered. This is the expensive bucket: every one of these is a
    number the framework was told rather than derived, and downstream
    "predictions" inherit it.
``UNRESOLVED``
    No consumer could be traced, or the row's own description contradicts
    its declared status. Deliberately not a synonym for "harmless".

HOW A CONSUMER IS TRACED
------------------------
:func:`trace_consumers` finds every *executing* read of a registry path --
``registry.get("geometry.X")``, ``_reg_value(...)``, ``_get_param(...)`` --
and ignores mentions inside prose, ``eml_description`` strings and comments,
which are not consumers. From the assignment target of each read it
taint-propagates through the enclosing function; if a tainted name reaches a
**value position in a returned dict whose keys are registry paths**, the
read fed a registered output and the row is ``LOAD_BEARING_INPUT``.
Otherwise the read only ever reached a comparison and the row is
``COMPARISON_ONLY``. The same taint runs over ``self.<anchor>`` inside
``GeometricAnchors``, because an anchor consumed by another anchor property
that ``get_all_anchors`` exports is load-bearing without leaving the file.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""
