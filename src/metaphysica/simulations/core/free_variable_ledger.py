def _package_root() -> Path:
    """``src/metaphysica`` for a checkout, the installed package otherwise."""
    return Path(__file__).resolve().parents[2]


def simulations_root() -> Path:
    return _package_root() / "simulations"


def _rel(path: Path) -> str:
    """Repo-relative when we are in a checkout, package-relative otherwise."""
    root = _package_root()
    try:
        return str(Path("src/metaphysica") / path.resolve().relative_to(root))
    except ValueError:
        return str(path)


def _iter_python_files(root: Path) -> Iterator[Path]:
    for path in sorted(root.rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        yield path


def _parse(path: Path) -> Optional[ast.Module]:
    try:
        return ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):  # pragma: no cover - defensive
        return None


def _const(node: Optional[ast.AST]) -> Optional[Any]:
    return node.value if isinstance(node, ast.Constant) else None


