#: Accessors that read a registry path at run time. A path named anywhere
#: else -- prose, an ``eml_description``, a comment -- is a mention, not a
#: consumer, and must not be allowed to promote a row to load-bearing.
_REGISTRY_READERS = frozenset({
    "get", "_reg_value", "_get_param", "get_param", "get_value", "value_of",
})


def _annotate_parents(tree: ast.AST) -> None:
    for parent in ast.walk(tree):
        for child in ast.iter_child_nodes(parent):
            child.__dict__["_fvl_parent"] = parent


def _enclosing_function(node: ast.AST) -> Optional[ast.AST]:
    cur = node.__dict__.get("_fvl_parent")
    while cur is not None:
        if isinstance(cur, (ast.FunctionDef, ast.AsyncFunctionDef)):
            return cur
        cur = cur.__dict__.get("_fvl_parent")
    return None


def _assignment_target(node: ast.AST) -> Optional[str]:
    """The single Name a read is assigned to, if it is assigned to one."""
    cur = node.__dict__.get("_fvl_parent")
    while cur is not None and not isinstance(cur, ast.stmt):
        cur = cur.__dict__.get("_fvl_parent")
    if isinstance(cur, ast.Assign) and len(cur.targets) == 1:
        tgt = cur.targets[0]
        if isinstance(tgt, ast.Name):
            return tgt.id
    if isinstance(cur, ast.AnnAssign) and isinstance(cur.target, ast.Name):
        return cur.target.id
    return None


_REGISTRY_PATH_RE = re.compile(r"^[a-z_][a-z0-9_]*\.[A-Za-z_][A-Za-z0-9_.]*$")


def _returned_registry_values(fn: ast.AST) -> List[ast.AST]:
    """Value expressions of returned dicts whose keys look like registry paths.

    A module registers its outputs by returning ``{"cosmology.x": value}``.
    Reaching a value position in one of those dicts is what makes an input
    load-bearing: the published number now depends on it.
    """
    out: List[ast.AST] = []
    for node in ast.walk(fn):
        if not isinstance(node, ast.Return) or not isinstance(node.value, ast.Dict):
            continue
        for key, val in zip(node.value.keys, node.value.values):
            k = _const(key)
            if isinstance(k, str) and _REGISTRY_PATH_RE.match(k):
                out.append(val)
    return out


def _taint(fn: ast.AST, seed: str) -> Set[str]:
    """Names in ``fn`` that carry ``seed``'s value, by assignment closure.

    Deliberately a fixed point over plain assignments only. It under-reports
    rather than over-reports: a value laundered through a container or a
    helper call will be missed and the row stays COMPARISON_ONLY, which is
    the conservative direction for a count that is meant to be a floor on
    honesty, not a ceiling.
    """
    tainted = {seed}
    changed = True
    while changed:
        changed = False
        for node in ast.walk(fn):
            if not isinstance(node, (ast.Assign, ast.AnnAssign)):
                continue
            value = node.value
            if value is None:
                continue
            used = {n.id for n in ast.walk(value) if isinstance(n, ast.Name)}
            if not (used & tainted):
                continue
            targets = node.targets if isinstance(node, ast.Assign) else [node.target]
            for tgt in targets:
                for n in ast.walk(tgt):
                    if isinstance(n, ast.Name) and n.id not in tainted:
                        tainted.add(n.id)
                        changed = True
    return tainted


def _reaches_registered_output(fn: ast.AST, seed: str) -> bool:
    tainted = _taint(fn, seed)
    for val in _returned_registry_values(fn):
        for n in ast.walk(val):
            if isinstance(n, ast.Name) and n.id in tainted:
                return True
    return False


#: Names under which a module declares what it PRODUCES. A path listed
#: there is the module naming its own output, which is the opposite of a
#: consumer -- counting it made every fitted CKM element look like it was
#: being compared against something.
_OUTPUT_DECLARATION_NAMES = frozenset({
    "output_params", "outputs", "get_outputs", "output_parameters",
    "provides", "registered_paths", "REGISTERED_PATHS", "run", "run_eml",
    "generate_parameters", "get_parameters", "get_output_param_definitions",
})

#: Names under which a module declares what it CONSUMES.
_INPUT_DECLARATION_NAMES = frozenset({
    "required_inputs", "requires", "inputs", "REQUIRED_INPUTS",
    "required_params",
})

#: Names that render a path into the paper or the website. Being printed is
#: not being used: a number quoted in a formula caption or a section body
#: has not entered any computation, and letting presentation count as a
#: consumer is exactly how a displayed experimental value comes to look
#: like a working part of the theory.
_PRESENTATION_NAMES = frozenset({
    "formulas", "get_formulas", "get_section_content", "content",
    "PARAM_REFS", "param_refs", "paramRefs", "get_content",
    "section_content", "blocks", "get_references",
})


def _container_context(node: ast.AST) -> str:
    """The nearest enclosing name that says what a path list is FOR.

    Looks at the assignment target, then the enclosing function. A path in
    ``required_inputs`` means something different from the same path in
    ``output_params``, and only the surrounding name distinguishes them.
    """
    cur = node.__dict__.get("_fvl_parent")
    while cur is not None:
        if isinstance(cur, ast.Assign) and len(cur.targets) == 1:
            tgt = cur.targets[0]
            if isinstance(tgt, ast.Name):
                return tgt.id
            if isinstance(tgt, ast.Attribute):
                return tgt.attr
        if isinstance(cur, ast.AnnAssign) and isinstance(cur.target, ast.Name):
            return cur.target.id
        if isinstance(cur, (ast.FunctionDef, ast.AsyncFunctionDef)):
            return cur.name
        cur = cur.__dict__.get("_fvl_parent")
    return ""


def _declaration_kind(node: ast.AST, parent: ast.AST) -> Optional[Tuple[str, str]]:
    """Classify a path that sits in a literal container, or drop it.

    Returns ``None`` when the mention says nothing about consumption.
    """
    if isinstance(parent, ast.Dict):
        # A key is a registration: "this module produces this path". Values
        # are looked at elsewhere. Either way, not a consumer.
        return None
    if not isinstance(parent, (ast.List, ast.Tuple, ast.Set)):
        return None
    ctx = _container_context(node)
    if ctx in _OUTPUT_DECLARATION_NAMES or ctx in _PRESENTATION_NAMES:
        return None
    if ctx in _INPUT_DECLARATION_NAMES:
        return ("DECLARED_AS_INPUT",
                f"listed in {ctx}: the declaring simulation states it needs "
                f"this value to run")
    if "output" in ctx.lower() or "produce" in ctx.lower():
        return None
    return ("CROSS_CHECK_GROUP",
            f"listed in {ctx or '<module-level list>'}: a curated group, "
            f"read for cross-checking rather than fed into a derivation")


_CONSUMER_INDEX: Dict[Tuple[str, str], Dict[str, List[Consumer]]] = {}


def _build_consumer_index(root: Path) -> Dict[str, List[Consumer]]:
    """One pass over the tree, indexing every path mention by path.

    Built once and cached: tracing each of the ~sixty ledger rows with its
    own full-tree walk turned a second of work into minutes.
    """
    index: Dict[str, List[Consumer]] = {}
    for path in _iter_python_files(root):
        tree = _parse(path)
        if tree is None:
            continue
        _annotate_parents(tree)
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Constant) and isinstance(node.value, str)):
                continue
            key = node.value
            if not _REGISTRY_PATH_RE.match(key):
                continue
            parent = node.__dict__.get("_fvl_parent")
            if not isinstance(parent, ast.Call):
                declared = _declaration_kind(node, parent)
                if declared is not None:
                    kind, detail = declared
                    fn = _enclosing_function(node)
                    index.setdefault(key, []).append(Consumer(
                        location=f"{_rel(path)}:{node.lineno}",
                        function=getattr(fn, "name", "<module>"),
                        kind=kind,
                        detail=detail,
                    ))
                continue
            fnode = parent.func
            reader = fnode.attr if isinstance(fnode, ast.Attribute) else getattr(fnode, "id", "")
            if reader not in _REGISTRY_READERS:
                continue
            enclosing = _enclosing_function(node)
            target = _assignment_target(node)
            if enclosing is not None and target and _reaches_registered_output(enclosing, target):
                kind = "READ_INTO_REGISTERED_OUTPUT"
                detail = (
                    f"{reader}(...) -> {target}, which reaches a value position "
                    f"in a returned registry dict"
                )
            else:
                kind = "READ_FOR_COMPARISON"
                detail = (
                    f"{reader}(...)"
                    + (f" -> {target}" if target else "")
                    + ", never reaches a returned registry value"
                )
            index.setdefault(key, []).append(Consumer(
                location=f"{_rel(path)}:{node.lineno}",
                function=getattr(enclosing, "name", "<module>"),
                kind=kind,
                detail=detail,
            ))
    return index


def trace_consumers(
    registry_path: str,
    root: Optional[Path] = None,
    skip_file: Optional[Path] = None,
) -> List[Consumer]:
    """Every executing read of ``registry_path``, classified by what it feeds.

    Mentions in prose and ``eml_description`` strings are not returned: they
    do not execute, and treating them as consumers is precisely how a
    displayed number gets mistaken for a used one.
    """
    root = root or _package_root()
    cache_key = (str(root.resolve()), "")
    if cache_key not in _CONSUMER_INDEX:
        _CONSUMER_INDEX[cache_key] = _build_consumer_index(root)
    found = _CONSUMER_INDEX[cache_key].get(registry_path, ())
    if skip_file is None:
        return list(found)
    # The defining file is not a consumer of its own parameter: counting it
    # would make every row load-bearing on itself.
    skip_rel = _rel(skip_file)
    return [c for c in found if c.location.rsplit(":", 1)[0] != skip_rel]


def _anchor_internal_consumers(anchor: str, exported: Set[str]) -> List[Consumer]:
    """Anchors that consume ``anchor`` and are themselves exported.

    ``get_all_anchors`` is excluded on purpose: it exports everything, so
    counting it as a consumer would make every anchor load-bearing and the
    classification would carry no information.
    """
    path = _anchors_core_path()
    src = path.read_text(encoding="utf-8")
    tree = ast.parse(src)
    out: List[Consumer] = []
    for fn in ast.walk(tree):
        if not isinstance(fn, ast.FunctionDef) or fn.name in ("get_all_anchors", anchor):
            continue
        if fn.name not in exported:
            continue
        for node in ast.walk(fn):
            if (isinstance(node, ast.Attribute)
                    and isinstance(node.value, ast.Name)
                    and node.value.id == "self"
                    and node.attr == anchor):
                out.append(Consumer(
                    location=f"{_rel(path)}:{node.lineno}",
                    function=fn.name,
                    kind="ANCHOR_FEEDS_EXPORTED_ANCHOR",
                    detail=(
                        f"self.{anchor} is read by {fn.name}, which "
                        f"get_all_anchors exports and register_anchors "
                        f"registers as geometry.{fn.name}"
                    ),
                ))
                break
    return out


