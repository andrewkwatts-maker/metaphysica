@dataclass(frozen=True)
class Consumer:
    """One traced use of a quantity, with enough detail to re-check it."""

    location: str          # "<file>:<line>", repo-relative
    function: str          # enclosing function or property
    kind: str              # READ_INTO_REGISTERED_OUTPUT | READ_FOR_COMPARISON
                           # | ANCHOR_FEEDS_EXPORTED_ANCHOR | CROSS_CHECK_GROUP
    detail: str            # what the trace actually saw


@dataclass
class LedgerRow:
    """One quantity this framework did not derive."""

    name: str
    value: Any
    location: str                       # "<file>:<line>", repo-relative
    status: str                         # as declared in the tree
    source_kind: str                    # PARAMETER_CALL | GEOMETRIC_ANCHOR
    role: str
    role_evidence: List[Dict[str, str]] = field(default_factory=list)
    closing_derivation: str = ""
    description: str = ""
    notes: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


