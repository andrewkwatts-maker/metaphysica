def _anchors_core_path() -> Path:
    return simulations_root() / "PM" / "geometry" / "geometric_anchors_core.py"


def _anchor_property_lines() -> Dict[str, int]:
    """Anchor name -> the line its property is defined on."""
    tree = _parse(_anchors_core_path())
    out: Dict[str, int] = {}
    if tree is None:  # pragma: no cover - defensive
        return out
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef):
            out.setdefault(node.name, node.lineno)
    return out


def _anchor_source(name: str) -> str:
    """Docstring + body source of an anchor property, comments included.

    The comments matter: ``alpha_T_phenomenological`` says nothing in its
    docstring about being a fit, and everything in the trailing
    ``# From fit to data``.
    """
    src = _anchors_core_path().read_text(encoding="utf-8")
    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, ast.FunctionDef) and node.name == name:
            seg = ast.get_source_segment(src, node)
            if seg:
                return seg
    return ""


