#: Statuses from ``PRESERVED_PARAMETER_STATUSES`` that admit the value was
#: not derived. Each is a different way of not deriving something:
#:
#:   FITTED            -- fitted to data
#:   FITTED_COMPOSITE  -- a composite of fitted pieces
#:   CALIBRATED        -- set to reproduce one measurement
#:   ANSATZ            -- asserted, with a stated reason but no derivation
#:   MEASURED          -- read straight out of an experiment
#:
#: Anything outside this set claims, at some strength, to have come out of
#: the geometry, and so is not a free variable *by its own declaration*.
#: Whether that declaration is true is the honesty guard's business, not
#: this set's.
NON_DERIVED_STATUSES = frozenset({
    "FITTED",
    "FITTED_COMPOSITE",
    "CALIBRATED",
    "ANSATZ",
    "MEASURED",
})

#: Statuses whose whole content is the claim "this came out of the theory".
#: A description that admits a fit under one of these is a contradiction
#: inside a single ``Parameter(...)`` call.
DERIVATION_CLAIMING_STATUSES = frozenset({
    "DERIVED", "GEOMETRIC", "PREDICTED", "PREDICTIONS", "EXACT", "COMPUTED",
    "COMPUTATIONAL", "FOUNDATIONAL", "ESTABLISHED", "TERMINAL", "VALIDATED",
})

# --------------------------------------------------------------------------
# the honesty guard's vocabulary
# --------------------------------------------------------------------------

#: Phrases that are an *admission* that a number was chosen to match, in the
#: affirmative. Deliberately narrow: a bare mention of the word "fitted" is
#: not an admission -- half the tree's prose says "not a fitted quantity" or
#: "originally fitted, now DERIVED", and a guard that fired on those would
#: be noise a reader learns to ignore.
FIT_ADMISSION_PATTERNS: Tuple[str, ...] = (
    r"\bis\s+(?:a\s+)?fitted\b",
    r"\bare\s+fitted\b",
    r"\bfitted\s+to\s+(?:data|the\s|experiment|observation|NuFIT|PDG|Planck|DESI|SH0ES)",
    r"\bfit\s+to\s+data\b",
    r"\bphenomenological\s+fit\b",
    r"\btuned\s+to\b",
    r"\bcalibrated\s+to\b",
    r"\bback-?solved\b",
    r"\bchosen\s+so\b",
    r"\bchosen\s+to\s+(?:produce|match|reproduce|give)\b",
)

#: Contexts in which an admission phrase is not an admission: a denial, a
#: historical note, or a superseded value being named in order to be
#: disowned.
FIT_EXONERATION_PATTERNS: Tuple[str, ...] = (
    r"\bnot\s+(?:a\s+)?fitted\b",
    r"\brather\s+than\s+fitted\b",
    r"\boriginally\s+fitted,\s*now\b",
    r"\bno\s+longer\s+fitted\b",
    r"\bsuperseded\b",
    r"\bsemi-fitted\)\s*to\s+DERIVED\b",
)

_ADMIT_RE = tuple(re.compile(p, re.IGNORECASE) for p in FIT_ADMISSION_PATTERNS)
_EXON_RE = tuple(re.compile(p, re.IGNORECASE) for p in FIT_EXONERATION_PATTERNS)


def admits_a_fit(text: str) -> List[str]:
    """Return the admission phrases in ``text``, or ``[]``.

    An admission that sits inside an exonerating context returns ``[]`` --
    "not a fitted quantity" is a denial, not a confession.
    """
    if not text:
        return []
    if any(rx.search(text) for rx in _EXON_RE):
        return []
    return [rx.pattern for rx in _ADMIT_RE if rx.search(text)]


