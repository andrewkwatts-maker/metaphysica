"""Typed access to canonical registry parameter paths.

WHY THIS EXISTS
---------------
Call sites address the registry with bare strings ("topology.elder_kads",
"cosmology.s8_pm_predicted", ...). A typo'd path fails at *lookup* time, in
whatever simulation happens to run first, with a KeyError that names the
symptom rather than the mistake. This module makes the path namespace a
checkable surface:

- ``PATHS`` is the set of canonical dotted paths, **generated from the live
  registry artifact** (AutoGenerated/parameters.json), never hand-typed --
  a hand-typed list would be a fifth constant store, the exact ORPHAN class
  generate_config_drift_audit.py exists to surface.
- ``validate(path)`` raises immediately on an unknown path and names the
  nearest canonical paths, so the failure points at the typo.
- Attribute access spells paths as identifiers: ``P.topology__elder_kads``
  == "topology.elder_kads", validated at access time.

Deliberately additive: existing ``get_param("...")`` call sites keep
working. New call sites can route through ``validate``/attribute access and
get loud, early failure.

No literal fallback list. If no registry artifact can be found, lookups
fail loudly -- a bundled snapshot is used only as the last candidate, and
it is itself a build artifact, not a hand-maintained list.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""
from __future__ import annotations

import difflib
import json
import os
from functools import lru_cache
from pathlib import Path as _FsPath
from typing import FrozenSet

__all__ = ["PATHS", "validate", "P", "refresh"]


def _candidate_files():
    raw = os.environ.get("METAPHYSICA_OUT")
    if raw:
        yield _FsPath(raw) / "AutoGenerated" / "parameters.json"
    # repo checkout layout: src/metaphysica/simulations/core/ -> repo root
    root = _FsPath(__file__).resolve().parents[4]
    yield root / "AutoGenerated" / "parameters.json"
    # bundled build artifact (shipped in the wheel)
    yield _FsPath(__file__).resolve().parents[2] / "data" / "parameters.json"


@lru_cache(maxsize=1)
def _load_paths() -> FrozenSet[str]:
    for candidate in _candidate_files():
        if candidate.is_file():
            data = json.loads(candidate.read_text(encoding="utf-8"))
            params = data.get("parameters", data)
            return frozenset(params.keys())
    raise FileNotFoundError(
        "no parameters.json found (METAPHYSICA_OUT, repo AutoGenerated/, or "
        "bundled data/) -- registry paths cannot be validated without the "
        "artifact, and inventing a hardcoded list here would defeat the point"
    )


def refresh() -> None:
    """Drop the cached path set (e.g. after a rebuild in-process)."""
    _load_paths.cache_clear()


class _PathNamespace:
    """Attribute access for canonical paths: ``P.topology__elder_kads``.

    Double underscore maps to the dot. Access validates against the live
    artifact, so a typo fails at the *reference*, not at first lookup.
    """

    def __getattr__(self, name: str) -> str:
        path = name.replace("__", ".")
        return validate(path)

    def __contains__(self, path: str) -> bool:
        return path in PATHS()


def PATHS() -> FrozenSet[str]:
    """The canonical path set from the live registry artifact."""
    return _load_paths()


def validate(path: str) -> str:
    """Return *path* unchanged iff canonical; raise with suggestions if not."""
    paths = _load_paths()
    if path in paths:
        return path
    nearest = difflib.get_close_matches(path, paths, n=3, cutoff=0.6)
    hint = f"; nearest: {', '.join(nearest)}" if nearest else ""
    raise KeyError(f"'{path}' is not a canonical registry path{hint}")


#: Singleton attribute-style accessor.
P = _PathNamespace()
