"""Snapshot of the path summaries the paper prose quotes (D-025).

The abstract, introduction and superseded-path callouts compare the active
path with the retired seed_24 path. Those figures come from a published path
sweep, which every build cannot see: a path run writes to a fresh output
directory with no ``paths/``. Reading ``autogen_dir()/paths`` made every path
run print OPEN where main printed numbers, so every path differed from main
in ~30 sections. The prose therefore reads this committed snapshot, the same
input for every run, which records the sweep it came from.

Refresh it after ``paths-publish``:

    python -m metaphysica.simulations.PM.paper.path_snapshot <site>/AutoGenerated/paths

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, Optional

SNAPSHOT = Path(__file__).resolve().parents[3] / "data" / "path_comparison.json"
PATHS = ("main", "b3_seed--seed_24")
SCHEMA = "metaphysica.path_comparison/1"


def load(name: str, snapshot: Path = SNAPSHOT) -> Optional[Dict[str, Any]]:
    """The snapshot entry for ``name``, or None when absent or malformed."""
    if not snapshot.is_file():
        return None
    try:
        entry = json.loads(snapshot.read_text(encoding="utf-8"))["paths"][name]
        entry["scoreboard"]["PASS"], entry["scoreboard"]["FAIL"]
        entry["chi2"]["value"], entry["chi2"]["dof"]
        return entry
    except (ValueError, KeyError, TypeError):
        return None


def build(paths_dir: Path) -> Dict[str, Any]:
    """Snapshot dict from a published paths directory; fails early."""
    index = paths_dir / "index.json"
    if not index.is_file():
        raise FileNotFoundError("no paths index at %s" % index)
    meta = json.loads(index.read_text(encoding="utf-8"))
    out: Dict[str, Any] = {"schema": SCHEMA, "engine": meta.get("engine"),
                           "generated": meta.get("generated"), "paths": {}}
    for name in PATHS:
        f = paths_dir / name / "summary.json"
        if not f.is_file():
            raise FileNotFoundError("no summary for path %s at %s" % (name, f))
        s = json.loads(f.read_text(encoding="utf-8"))
        out["paths"][name] = {"scoreboard": s["scoreboard"], "chi2": s["chi2"]}
    return out


def write(paths_dir: Path, snapshot: Path = SNAPSHOT) -> Dict[str, Any]:
    data = build(paths_dir)
    snapshot.write_text(json.dumps(data, indent=1, sort_keys=True) + "\n",
                        encoding="utf-8")
    return data


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit("usage: path_snapshot <site>/AutoGenerated/paths")
    d = write(Path(sys.argv[1]))
    print("path snapshot: engine %s, %s -> %s" % (d["engine"], d["generated"],
                                                   SNAPSHOT))
