_IDENTITY = (0, 0, 0)


def _point() -> Dict[str, Any]:
    from metaphysica.simulations.PM.geometry.intersection_tensor import (
        canonical_point,
    )

    return canonical_point()


def _nonidentity(elements: Dict[Tuple[int, ...], Any]) -> List[Tuple[int, ...]]:
    return sorted(label for label in elements if any(label))


def _compose_label(a: Sequence[int], b: Sequence[int]) -> Tuple[int, ...]:
    return tuple((x + y) % 2 for x, y in zip(a, b))


def _cocycle(elements, sigma, tau) -> List[int]:
    """Integer translation carried by lift(sigma) lift(tau) lift(sigma tau)^-1.

    Shifts are stored in HALF-UNITS (1 means 1/2). The composite's shift is
    s_sigma + sigma . s_tau, and subtracting the stored shift of sigma tau
    must leave an INTEGER vector or the lifts do not close into a group --
    asserted, because a broken assignment must be loud, not absorbed.
    """
    signs_s, h_s = elements[tuple(sigma)]
    _, h_t = elements[tuple(tau)]
    _, h_st = elements[_compose_label(sigma, tau)]
    out: List[int] = []
    for i in range(7):
        twice = h_s[i] + signs_s[i] * h_t[i] - h_st[i]
        if twice % 2 != 0:
            raise ValueError(
                "shift cocycle is not integral at coordinate %d for %s * %s: "
                "the assignment's lifts do not close into a group"
                % (i, tuple(sigma), tuple(tau))
            )
        out.append(twice // 2)
    return out


def abelianization_presentation(point: Optional[Dict[str, Any]] = None
                                ) -> Dict[str, Any]:
    """Integer relation rows for (G/E)^ab over t_1..t_7, g_sigma (7 lifts)."""
    point = point if point is not None else _point()
    elements = {tuple(k): v for k, v in point["elements"].items()} \
        if isinstance(point["elements"], dict) else dict(point["elements"])
    labels = _nonidentity(elements)
    col = {("t", i): i for i in range(7)}
    col.update({("g", lab): 7 + j for j, lab in enumerate(labels)})
    n_cols = 7 + len(labels)

    rows: List[List[int]] = []

    def _row() -> List[int]:
        return [0] * n_cols

    # 2 t_i = 0 for every coordinate flipped by SOME element (coinvariance).
    flipped_by_any = set()
    for lab in labels:
        signs, _ = elements[lab]
        for i in range(7):
            if signs[i] == -1:
                flipped_by_any.add(i)
    for i in sorted(flipped_by_any):
        r = _row()
        r[col[("t", i)]] = 2
        rows.append(r)

    # g_sigma + g_tau - g_{sigma tau} - c . t = 0, for all ordered pairs.
    for sigma in labels:
        for tau in labels:
            c = _cocycle(elements, sigma, tau)
            r = _row()
            r[col[("g", sigma)]] += 1
            r[col[("g", tau)]] += 1
            st = _compose_label(sigma, tau)
            if any(st):
                r[col[("g", st)]] -= 1
            for i in range(7):
                r[col[("t", i)]] -= c[i]
            rows.append(r)

    # Armstrong: each SINGULAR element dies, and so do the translations on
    # its flipped coordinates (its fixed-point translates differ by exactly
    # those). Fixed coordinates carry shift 0 for a singular element -- that
    # is what singular MEANS -- asserted rather than trusted.
    singular_labels = []
    for entry in point["singular"]:
        lab = tuple(entry[0])
        singular_labels.append(lab)
        signs, halves = elements[lab]
        for i in range(7):
            if signs[i] == 1 and halves[i] % 2 != 0:
                raise ValueError(
                    "element %s is listed singular but carries a half shift "
                    "on its fixed coordinate %d, so it acts freely" % (lab, i))
        r = _row()
        r[col[("g", lab)]] = 1
        rows.append(r)
        for i in range(7):
            if signs[i] == -1:
                r = _row()
                r[col[("t", i)]] = 1
                rows.append(r)

    return {
        "columns": (["t_%d" % i for i in range(7)]
                    + ["g_%s" % (lab,) for lab in labels]),
        "rows": rows,
        "n_generators": n_cols,
        "singular_labels": singular_labels,
        "what_generators_are": (
            "t_i are deck translations (loop classes); g_sigma are lifts of "
            "group elements. Neither is a Betti number."
        ),
    }


def h1_of_resolution(point: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
    """H_1(Y, Z) of the resolved quotient, by Smith normal form."""
    from sympy import Matrix
    from sympy.matrices.normalforms import smith_normal_form

    pres = abelianization_presentation(point)
    m = Matrix(pres["rows"])
    snf = smith_normal_form(m.T)  # columns = generators after transpose
    n_gen = pres["n_generators"]

    diag = [int(snf[i, i]) for i in range(min(snf.rows, snf.cols))]
    invariant_factors = [abs(d) for d in diag if abs(d) > 1]
    rank_of_relations = sum(1 for d in diag if d != 0)
    free_rank = n_gen - rank_of_relations

    return {
        "invariant_factors": sorted(invariant_factors),
        "free_rank": free_rank,
        "is_trivial": free_rank == 0 and not invariant_factors,
        "n_generators": n_gen,
        "n_relations": len(pres["rows"]),
        "note": (
            "free_rank must agree with b_1 = 0 (derived, R5) whenever the "
            "assignment is on the Joyce family; the torsion is information "
            "b_1 cannot see"
        ),
    }


def pi1_triviality_criterion(point: Optional[Dict[str, Any]] = None
                             ) -> Dict[str, Any]:
    """Sufficient criterion for pi_1(Y) = 1 EXACTLY, in the full group.

    If (a) the singular elements span Gamma = (Z/2)^3 over F_2, and (b) every
    coordinate is flipped by at least one singular element, then every
    generator of G lies in E: singular lifts directly; each t_i as a quotient
    of two fixed-point translates of a singular element flipping i; every
    remaining lift as a product of singular lifts and killed translations.
    Then G = E and pi_1 is trivial -- not merely its abelianisation.
    """
    point = point if point is not None else _point()
    elements = {tuple(k): v for k, v in point["elements"].items()} \
        if isinstance(point["elements"], dict) else dict(point["elements"])
    singular_labels = [tuple(e[0]) for e in point["singular"]]

    # (a) F_2 span of the singular labels, by closure under composition.
    span = set()
    span.add((0, 0, 0))
    for lab in singular_labels:
        span |= {_compose_label(lab, s) for s in list(span)}
    spans_gamma = len(span) == 8

    # (b) coverage of the 7 coordinates by singular flips.
    covered = set()
    for lab in singular_labels:
        signs, _ = elements[lab]
        covered |= {i for i in range(7) if signs[i] == -1}
    covers_all = covered == set(range(7))

    return {
        "singular_span_is_gamma": spans_gamma,
        "singular_flips_cover_all_coordinates": covers_all,
        "pi1_provably_trivial": spans_gamma and covers_all,
        "counts": (
            "the span counts GROUP ELEMENTS over F_2; the coverage counts "
            "COORDINATES; neither is a cohomology class"
        ),
    }


def wilson_line_verdict(point: Optional[Dict[str, Any]] = None
                        ) -> Dict[str, Any]:
    """Is the discrete-Wilson-line dock open on this assignment?"""
    h1 = h1_of_resolution(point)
    crit = pi1_triviality_criterion(point)

    if crit["pi1_provably_trivial"]:
        status = "CLOSED_BY_DERIVATION"
        sentence = (
            "pi_1(Y) = 1: the singular elements span Gamma and their flips "
            "cover every coordinate, so G = E exactly. Hom(pi_1, G_gauge) is "
            "trivial and NO discrete Wilson line exists on this assignment. "
            "With intersection couplings dead (admissibility IS disjointness) "
            "and no codimension-7 conical points, this closes the last known "
            "singularity-free flavour mechanism; flavour data on this path is "
            "a costed boundary input."
        )
    elif h1["is_trivial"]:
        status = "H1_TRIVIAL_PI1_UNRESOLVED"
        sentence = (
            "H_1(Y) = 0 but the triviality criterion does not apply, so a "
            "perfect-group pi_1 is not excluded by this computation alone; "
            "the dock is not open for ABELIAN Wilson lines, and the "
            "non-abelian question is recorded as unresolved."
        )
    else:
        status = "OPEN"
        sentence = (
            "H_1(Y) = %s (+ free rank %d): pi_1 is nontrivial, so discrete "
            "Wilson lines EXIST on this assignment and the flavour boundary "
            "acquires a second dock that needs no singularity at all."
            % (["Z/%d" % d for d in h1["invariant_factors"]], h1["free_rank"])
        )

    return {
        "status": status,
        "h1": h1,
        "criterion": crit,
        "sentence": sentence,
        "layer": "TOPOLOGICAL",
        "fork_dependence": (
            "none: pi_1 of the resolved manifold depends on the assignment's "
            "group data only, not on any metric or form convention"
        ),
    }


