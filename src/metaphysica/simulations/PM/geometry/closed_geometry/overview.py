def overview_document() -> Dict[str, Any]:
    """The JSON artifact: the seed in force and the layers."""
    from metaphysica.simulations.PM.geometry.b3_path import (
        resolve_path,
        seed_values,
    )

    seed = resolve_path()
    b3, b2 = seed_values(seed)
    return {
        "generator": "metaphysica.simulations.PM.geometry.closed_geometry."
                     "overview",
        "seed": seed,
        "b2": b2,
        "b3": b3,
        "layer_order": list(LAYER_ORDER),
        "layers": layers(),
    }


def overview_html(doc: Optional[Dict[str, Any]] = None) -> str:
    """The main page's 'theory at a glance' section, between the markers."""
    doc = doc or overview_document()
    cards = []
    for i, layer in enumerate(doc["layers"], 1):
        items = "".join("<li>%s</li>" % it for it in layer["items"])
        cards.append(
            '<article class="pm-layer" id="layer-%s">'
            '<h3><span class="pm-layer-num">%d</span> %s</h3>'
            "<p>%s</p>%s</article>"
            % (layer["key"], i, layer["title"], layer["lead"],
               "<ul>%s</ul>" % items if items else ""))
    return (
        MARK_BEGIN + "\n"
        '<section id="theory-at-a-glance" class="pm-overview">'
        "<h2>The theory at a glance</h2>"
        '<p class="pm-overview-intro">Read top down: what is assumed, what '
        "is borrowed from established physics, what is derived and how, "
        "what was corrected, and what is still open. Generated from the "
        "engine&rsquo;s provenance registry and closed-geometry certificate "
        "for the seed in force (b<sub>2</sub>, b<sub>3</sub>) = (%d, %d).</p>"
        '<div class="pm-layers">%s</div></section>\n'
        % (doc["b2"], doc["b3"], "".join(cards))
        + MARK_END
    )


def inject(index_path: Path, doc: Optional[Dict[str, Any]] = None) -> bool:
    """Replace the marked block of `index_path` in place.

    Returns False (and writes nothing) when the page carries no markers, so a
    page without the section is left alone rather than guessed at.
    """
    text = index_path.read_text(encoding="utf-8")
    i = text.find(MARK_BEGIN)
    j = text.find(MARK_END)
    if i < 0 or j < i:
        return False
    new = text[:i] + overview_html(doc) + text[j + len(MARK_END):]
    if new != text:
        index_path.write_text(new, encoding="utf-8")
    return True


def main(argv: Optional[List[str]] = None) -> int:
    """Build step: the JSON artifact, and the section in ./index.html."""
    out = Path(os.environ.get("METAPHYSICA_OUT") or Path.cwd())
    doc = overview_document()
    target = out / "AutoGenerated" / "theory_overview.json"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(doc, indent=2, ensure_ascii=False),
                      encoding="utf-8")
    index = out / "index.html"
    injected = index.is_file() and inject(index, doc)
    print("theory overview: %d layers -> %s; index.html %s"
          % (len(doc["layers"]), target,
             "updated" if injected else "has no overview markers"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
