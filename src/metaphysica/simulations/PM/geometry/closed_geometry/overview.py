LAYER_ORDER = ("postulates", "standard", "selection", "certificate",
               "findings", "corrections", "open", "data")

MARK_BEGIN = ("<!-- PM:THEORY-OVERVIEW:BEGIN generated by "
              "closed_geometry.overview; edits inside are overwritten -->")
MARK_END = "<!-- PM:THEORY-OVERVIEW:END -->"

_TITLES = {
    "postulates": "What the model postulates",
    "standard": "Standard physics it builds on",
    "selection": "How the geometry is selected",
    "certificate": "The closed geometry, proved",
    "findings": "What the model found",
    "corrections": "What was corrected",
    "open": "What is open",
    "data": "Where it stands against data",
}

# ASCII math in the registry rows -> HTML. Applied AFTER escaping, so every
# tag below is ours. Order matters: chi_eff before chi, pi_1 before b_k.
_PRETTY = (
    (r"chi_eff", "&chi;<sub>eff</sub>"),
    (r"(?<![&\w])chi\b", "&chi;"),
    (r"\bpi_1\b", "&pi;<sub>1</sub>"),
    (r"(?<![&\w])pi\b", "&pi;"),
    (r"(?<![&\w])phi\b", "&phi;"),
    (r"(?<![&\w])Gamma\b", "&Gamma;"),
    (r"\b([bnYTNk])_(\d+|eff|gen)\b", r"\1<sub>\2</sub>"),
    (r"\(Z/2\)", "(&#8484;/2)"),
    (r"Sp\(2,R\)", "Sp(2,&#8477;)"),
    (r"\bG2\b", "G<sub>2</sub>"),
    (r"\bE8\b", "E<sub>8</sub>"),
    (r"\bK4\b", "K<sub>4</sub>"),
    (r"\bA1\b", "A<sub>1</sub>"),
    (r"\bG4\b", "G<sub>4</sub>"),
    (r"\^(\d+)", r"<sup>\1</sup>"),
    (r"sqrt\(", "&radic;("),
    (r"&gt;=", "&ge;"),
    (r"&lt;=", "&le;"),
    (r" x ", " &times; "),
)


def pretty(text: str) -> str:
    """Escape a registry sentence and typeset its ASCII math as HTML."""
    out = _html.escape(text, quote=False)
    for pattern, repl in _PRETTY:
        out = re.sub(pattern, repl, out)
    return out


def _label_number(label: str) -> int:
    m = re.search(r"(\d+)", label or "")
    return int(m.group(1)) if m else 0


def _cites(keys) -> str:
    from metaphysica.simulations.PM.geometry.closed_geometry.references import (
        short_cite,
    )

    return "; ".join(short_cite(k) for k in keys)


def _rows(kind: str) -> List[str]:
    from metaphysica.simulations.PM.geometry.closed_geometry.provenance import (
        by_kind,
    )

    items = []
    for p in by_kind(kind):
        if kind == "STANDARD" and not p.verified:
            continue        # never rendered as cited until its source is checked
        text = pretty(p.technical)
        if p.references:
            cite = " (%s)" % _cites(p.references)
            text = (text[:-1] + cite + "." if text.endswith(".")
                    else text + cite)
        items.append(text)
    return items


def layers() -> List[Dict[str, Any]]:
    """The eight layers of the top-down story, generated."""
    from metaphysica.simulations.PM.geometry.closed_geometry.certificate import (
        certificate,
    )
    from metaphysica.simulations.PM.geometry.closed_geometry.provenance import (
        by_kind,
    )
    from metaphysica.simulations.PM.geometry.geometry_narration import render
    from metaphysica.simulations.PM.geometry.joyce_reachability import (
        reachable_set,
    )

    def r(template: str) -> str:
        return render(template, "html")

