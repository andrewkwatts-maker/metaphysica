"""The model, top down: one source for the paper abstract and the main page.

WHY THIS EXISTS
===============
The author asked (2026-09-30, 2026-10-01) that the paper abstract, the main
page and the beginner guide present the theory in ONE order: what the model
postulates, the standard physics it uses (cited), how the geometry is selected
and why, the closed geometry (the certificate), what the model found, what it
corrected, what is open, and where it stands against data. Written by hand on
each surface that story drifts -- the main page still claimed b_3 = 24, a TCS
construction and "resolved" problems long after the engine moved on. Here it
is generated from the provenance registry, the certificate and the live seed,
and every surface renders the same layers.

USE
===
    layers()            the eight layers as dicts {key, title, lead, items}
                        (lead and items are HTML fragments)
    overview_html()     the main page's section, between the markers below
    inject(path)        replace the marked block in an index.html in place
    python -m metaphysica.simulations.PM.geometry.closed_geometry.overview
                        build step: writes AutoGenerated/theory_overview.json
                        and injects the section into ./index.html when the
                        build's output directory has one

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

