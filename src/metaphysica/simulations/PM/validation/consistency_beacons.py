def run_all_beacons() -> List[ConsistencyBeacon]:
    """Run every beacon and return the collected records (in order)."""
    return [
        beacon_km_unitarity(),
        beacon_nufit_delta_m21(),
        beacon_nufit_delta_m31(),
        beacon_e8_freudenthal_dimension(),
        beacon_alpha_em_running(),
        beacon_jarlskog_bound(),
        beacon_g2_spinor_bundle_dimension(),
        beacon_weyl_character_g2_fundamental(),
    ]


def write_report(beacons: List[ConsistencyBeacon], out_path: Path | None = None) -> Path:
    """Write the beacons report to disk and return the path written.

    Honours ``METAPHYSICA_OUT`` so the file lands in the active build
    directory alongside the rest of the AutoGenerated/* tree. Falls
    back to REPO_ROOT/AutoGenerated/ when the env-var is not set.
    """
    if out_path is None:
        out_env = os.environ.get("METAPHYSICA_OUT")
        base = Path(out_env) if out_env else REPO_ROOT
        out_path = base / "AutoGenerated" / "consistency_beacons.json"
    out_path.parent.mkdir(parents=True, exist_ok=True)

    payload = {
        "schema_version": 1,
        "count": len(beacons),
        "n_pass": sum(1 for b in beacons if b.status == "PASS"),
        "n_fail": sum(1 for b in beacons if b.status == "FAIL"),
        "beacons": [asdict(b) for b in beacons],
        "note": (
            "Textbook consistency beacons: cross-checks against standard "
            "physics references. NOT predictions of the Principia "
            "Metaphysica model — these are independent identities the "
            "framework should satisfy to be consistent with the "
            "textbooks. Failures here indicate a drift bug, not a novel "
            "prediction."
        ),
    }
    out_path.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    return out_path


def main() -> int:
    beacons = run_all_beacons()
    path = write_report(beacons)
    print("=" * 60)
    print("Consistency beacons")
    print("=" * 60)
    for b in beacons:
        marker = "PASS" if b.status == "PASS" else "FAIL"
        print(f"  [{marker}] {b.id:48s} delta={b.delta_pct:>7.3f}%  {b.name}")
    n_pass = sum(1 for b in beacons if b.status == "PASS")
    print(f"\n{n_pass}/{len(beacons)} beacons pass. Report written to: {path}")
    return 0 if n_pass == len(beacons) else 1


if __name__ == "__main__":
    raise SystemExit(main())
