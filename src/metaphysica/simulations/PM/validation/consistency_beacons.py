"""Textbook consistency beacons (v2.2.0 Phase 3).

Seven cross-checks that any physics framework should satisfy. These are
**not** predictions of the Principia Metaphysica model — they are
independent identities from standard textbooks whose satisfaction
strengthens the credibility of the surrounding framework by
demonstrating it isn't drifting away from standard-model results.

Every beacon emits a ``ConsistencyBeacon`` record containing::

    {
        "id":         str,   # canonical id, e.g. "beacon.km_unitarity"
        "name":       str,   # short human-readable name
        "reference":  str,   # textbook / paper citation
        "value":      float, # observed / computed value
        "expected":   float, # textbook value
        "delta_pct":  float, # 100 * |value - expected| / |expected|
        "tolerance":  float, # pass threshold (delta_pct must be below)
        "status":     str,   # "PASS" or "FAIL"
        "note":       str,   # one-line context
    }

Records land in ``AutoGenerated/GATES_CERTIFICATES.json`` under a new
``consistency_beacons`` key so the website's certificates page can
surface them under a "Textbook consistency beacons" section — visually
separated from the 72 gates so they're never conflated with framework
predictions.

Run via ``python -m metaphysica.simulations.PM.validation.consistency_beacons``.
"""
from __future__ import annotations

import json
import math
import os
import sys
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any, Dict, List


REPO_ROOT = Path(__file__).resolve().parents[4]


@dataclass
class ConsistencyBeacon:
    """One textbook cross-check outcome."""

    id: str
    name: str
    reference: str
    value: float
    expected: float
    delta_pct: float
    tolerance: float
    status: str
    note: str


def _mk(
    *,
    beacon_id: str,
    name: str,
    reference: str,
    value: float,
    expected: float,
    tolerance: float,
    note: str,
) -> ConsistencyBeacon:
    """Construct a ``ConsistencyBeacon`` with automatic delta + pass/fail.

    Handles the zero-expected edge case (uses absolute value comparison).
    """
    if expected == 0.0:
        delta = abs(value - expected)
        delta_pct = float(delta)
    else:
        delta_pct = 100.0 * abs(value - expected) / abs(expected)
    status = "PASS" if delta_pct <= tolerance else "FAIL"
    return ConsistencyBeacon(
        id=beacon_id,
        name=name,
        reference=reference,
        value=float(value),
        expected=float(expected),
        delta_pct=float(delta_pct),
        tolerance=float(tolerance),
        status=status,
        note=note,
    )


