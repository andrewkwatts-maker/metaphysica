#!/usr/bin/env python3
"""
Statistical Rigor Validator - Principia Metaphysica
====================================================

Fit statistics for the validation report, computed from its rows.

One scored row per observable: aliases of one measurement are reported under
``duplicates`` and left out of chi2 (see ``observables.py``). Only predictions
are scored; input, fitted, calibrated, circular, identity and unit-check rows
are reported in their own block and never count as PASS.

The report publishes, each with its N: (a) all scored predictions with
recorded falsifications included, (b) the same without the rows recorded as
falsified, (c) the top contributors with each row's share of chi2. The
effective-DOF p-value is a labelled ANSATZ, not a computation.

Output:
    statistical_rigor_report.json

Copyright (c) 2026 Andrew Keith Watts. All rights reserved.
"""

import json
import logging
from pathlib import Path
from typing import Dict, Any
from scipy.stats import chi2
from datetime import datetime

# Add parent directory to path
import sys
REPO_ROOT = Path(__file__).parent.parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

from metaphysica.simulations.PM.validation import observables
from metaphysica.simulations.validation import fit_partition

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger("StatisticalRigor")


#: Verdicts the validation report itself declines to score two-sidedly.
#: These rows carry an experimental value and an uncertainty, so they
#: survived the "has an uncertainty" filter, but the report has already
#: judged them not comparable. Two of them dominated the global
#: chi-squared before this exclusion existed: gauge.M_GUT_GEOMETRIC
#: compares 2.1e16 GeV against 1.67e34 -- a proton LIFETIME in years, not
#: a mass -- contributing 3.4e38 on its own, and axion.omega_h2 added
#: 1.6e5. Including a row the report calls UNBOUNDED is not conservative;
#: it is a category error with a very loud number attached.
NON_SCORING_VERDICTS = frozenset({"UNBOUNDED", "INPUT", "IDENTITY",
                                  "UNIT_CHECK", "CIRCULAR"})

#: Verdicts that DO carry a two-sided comparison. A fit statistic must
#: range over all of these -- excluding TENSION and FAIL is what made
#: the fit look perfect.
SCORING_VERDICTS = frozenset({"PASS", "MARGINAL", "TENSION", "FAIL"})

#: Bound types that express a two-sided comparison and therefore have a
#: residual. A "lower"/"upper" bound has a margin, not a sigma.
TWO_SIDED_BOUND_TYPES = frozenset({"measured", "central_value"})



class StatisticalRigorValidator:
    """Chi-squared, p-value and the fit summary, all computed from report rows."""

    def __init__(self, validation_file: str = None):
        """
        Initialize validator with validation data.

        Args:
            validation_file: Path to validation_report.json (optional)
        """
        if validation_file is None:
            import os as _os
            _out_env = _os.environ.get("METAPHYSICA_OUT")
            _base = Path(_out_env) if _out_env else REPO_ROOT
            validation_file = _base / "AutoGenerated" / "validation_report.json"

        self.validation_file = Path(validation_file)

        if not self.validation_file.exists():
            raise FileNotFoundError(
                f"validation_report.json not found at {self.validation_file}. "
                "This validator previously fell back to chi^2 = 0.23 and "
                "DoF = 25 -- literals carried over from v23.9 -- and then "
                "published a full statistical report, p-value and "
                "'TOO_GOOD' verdict computed from no data at all. A missing "
                "input is a build failure, not a licence to invent one. Run "
                "the validation step first, or pass validation_file."
            )
        with open(self.validation_file, "r") as f:
            self.data = json.load(f)
        self.partition = observables.partition_rows(
            self._adapt_report_rows(self.data), SCORING_VERDICTS)
        # One scored row per observable; the fit is over these only.
        self.validation_results = self.partition["scored"]
        self.chi_sq, self.dof_claimed = self._chi_squared_from_rows(
            self.validation_results)
        logger.info(
            f"Loaded validation data: chi^2 = {self.chi_sq}, "
            f"N = {self.dof_claimed} scored predictions "
            f"({len(self.partition['duplicates'])} duplicates, "
            f"{len(self.partition['non_predictions'])} non-predictions "
            "reported separately)")

    @staticmethod
    def _chi_squared_from_rows(rows):
        """Return (chi^2, N) over the given rows, failing on a malformed row.

        Degrees of freedom is the row count: nothing is subtracted for
        fitted parameters, because the rows that were fitted are not scored
        (see ``observables.NON_PREDICTION_STATUSES``).
        """
        out = fit_partition.chi_squared(rows)
        return out["chi_squared"], out["n"]

    @staticmethod
    def _adapt_validation_rows(data):
        """Per-parameter rows from validation_report.json.

        This read ``data.get("sigma_table", [])``. No such key exists -- the
        report calls it ``validations`` -- so the list was always empty and
        every downstream method logged "No validation results available" and
        returned {}. The failure was quiet because the SUMMARY block does
        load, so the constructor still reported "Loaded validation data:
        chi^2 = ..., DoF = ...", which reads like success. The validator has
        therefore been producing nothing while appearing healthy.

        The field names differ as well as the key, so this adapts rather
        than merely renaming:

            predicted_value  <- value
            uncertainty      <- experimental_uncertainty
            status           <- verdict

        Rows without an experimental uncertainty are dropped: the consumer
        divides by it, and an INPUT or UNBOUNDED row has nothing to compare
        against. ``sigma_table`` is still honoured first so an older report
        keeps working.
        """
        legacy = data.get("sigma_table")
        if legacy:
            return legacy

        rows = []
        for entry in data.get("validations", []):
            uncertainty = entry.get("experimental_uncertainty")
            predicted = entry.get("value")
            experimental = entry.get("experimental_value")
            if uncertainty in (None, 0) or predicted is None or experimental is None:
                continue
            if entry.get("verdict") in NON_SCORING_VERDICTS:
                continue
            # One-sided bounds carry an uncertainty but no sigma: the
            # registry declines to compute one because "how far above the
            # floor" is not a residual. Including them would contribute
            # ((value - bound)/unc)^2 terms that mean nothing --
            # gauge.M_GUT_GEOMETRIC sits 20x above its inferred 1e15 GeV
            # floor, which is a PASS, not a 23-sigma discrepancy. Same test
            # the registry uses when deciding to compute sigma at all.
            if entry.get("bound_type") not in TWO_SIDED_BOUND_TYPES:
                continue
            rows.append({
                "path": entry.get("path"),
                # recalculate_with_theory_uncertainty reads "name"; the
                # report calls it "path". Both are emitted so neither
                # consumer has to know about the other's spelling.
                "name": entry.get("path"),
                "status": entry.get("verdict"),
                "predicted_value": predicted,
                "experimental_value": experimental,
                "uncertainty": uncertainty,
                "sigma": entry.get("sigma"),
                # The REGISTRY label, distinct from the verdict. A row can
                # be FALSIFIED (the framework has withdrawn the claim) and
                # still FAIL (it is scored and it misses). Both are needed:
                # see _chi_squared_split.
                "registry_status": entry.get("registry_status"),
                "bound_type": entry.get("bound_type"),
            })
        return rows

    @staticmethod
    def _adapt_report_rows(data):
        """Every report row in the validator's field names, with ``comparable``.

        ``comparable`` is true when the row has a two-sided comparison: an
        experimental value, an uncertainty above zero and a measured or
        central-value bound. Non-prediction rows are kept whether or not they
        are comparable, so they can be reported in their own block.
        """
        legacy = data.get("sigma_table")
        if legacy:
            return [dict(r, comparable=True) for r in legacy]
        rows = []
        for entry in data["validations"]:
            unc = entry.get("experimental_uncertainty")
            pred, exp = entry.get("value"), entry.get("experimental_value")
            comparable = (bool(unc) and pred is not None and exp is not None
                          and entry.get("bound_type") in TWO_SIDED_BOUND_TYPES)
            rows.append({
                "path": entry.get("path"), "name": entry.get("path"),
                "status": entry.get("verdict"),
                "predicted_value": pred, "experimental_value": exp,
                "uncertainty": unc, "sigma": entry.get("sigma"),
                "registry_status": entry.get("registry_status"),
                "bound_type": entry.get("bound_type"),
                "comparable": comparable})
        return rows

    def calculate_effective_dof(self) -> int:
        """Effective degrees of freedom: an ANSATZ, returned as 3.

        The claim is that the testable parameters descend from three
        independent seeds. It is a judgement about derivation structure, not a
        computation (no Jacobian is evaluated), and accepting it as proven
        would beg the question the chi-squared is meant to answer. It is NOT
        the number of free variables; see :meth:`free_variable_count`.

        The p-value taken with it is labelled as ansatz-dependent in the
        report. The row-count p-value is reported beside it.
        """
        # ANSATZ: EDOF=3 is a judgment (b₃, φ, θ₁₃ are the proposed independent
        # seeds) not a numerical computation.  The claim that all other parameters
        # are derived from these three is the theory's central assertion; accepting
        # it as proven would beg the question.  A genuine EDOF estimate would
        # require computing the rank of the real Jacobian (see generate_jacobian_matrix).
        #
        # It stays at 3 because moving it moves reduced chi-squared and every
        # verdict downstream, which is an author ruling. What it no longer
        # does is double as the free-variable count: the docstring above
        # asserts "θ₁₃ remains the ONLY fitted parameter", and the ledger
        # measures the tree instead. See :meth:`free_variable_count` and
        # ``simulations/core/free_variable_ledger.py``; the two numbers are
        # reported side by side by :meth:`calculate_p_value_with_edof` so the
        # gap between the ansatz and the measurement is visible rather than
        # implicit.
        return 3

    @staticmethod
    def free_variable_count() -> int:
        """Non-derived quantities in the tree, measured rather than asserted.

        This is the number the three published literals (0, 3, 3) and
        ``generate_statistics``'s fourth (1) were all trying to be. It is
        NOT the EDOF used by the chi-squared arithmetic: EDOF is an ansatz
        about how many *independent seeds* the theory has, this is a count
        of how many quantities it did not derive, and conflating them is
        what let "zero fitted parameters" stand.
        """
        from metaphysica.simulations.core.free_variable_ledger import (
            published_free_variable_count,
        )

        return published_free_variable_count()

    def calculate_p_value_with_edof(self) -> Dict[str, Any]:
        """
        Calculate p-value using Effective Degrees of Freedom (EDOF).

        Traditional approach:
            DOF = 25 → reduced χ² = chi_sq/25 → p (upper tail) ≈ 1.0 (too good!)

        EDOF approach:
            EDOF = 3 → reduced χ² = chi_sq/3 → p (upper tail, chi_sq≈0.23) ≈ 0.97 (TOO_GOOD)
            [Prior snapshot: χ²=5.75 → reduced 1.917 → p≈0.11 (Trust Zone) — no longer current]

        This fixes the "suspiciously perfect fit" problem by properly accounting
        for the topological correlation structure.

        Returns:
            Dictionary with chi-squared, EDOF, reduced chi-squared, p-value, status
        """
        edof = self.calculate_effective_dof()
        chi_sq = self.chi_sq  # Use original chi-squared (NO theory uncertainty injection)
        reduced_chi_sq = chi_sq / edof

        logger.info(f"Calculating p-value with EDOF = {edof}")
        logger.info(f"χ² = {chi_sq:.3f}, reduced χ² = {reduced_chi_sq:.3f}")

        # Calculate p-value using chi-squared distribution (upper tail)
        # p = P(X > χ²) where X ~ χ²(EDOF)
        p_value = 1 - chi2.cdf(chi_sq, edof)

        # Determine credibility status
        if 0.05 <= p_value <= 0.95:
            status = "CREDIBLE"
            is_credible = True
            interpretation = "Good fit without overfitting. Model has appropriate predictive power."
        elif p_value > 0.95:
            status = "TOO_GOOD"
            is_credible = False
            interpretation = "Suspiciously perfect fit. May indicate overfitting or overestimated uncertainties."
        elif p_value >= 0.01:
            status = "MARGINAL"
            is_credible = True
            interpretation = "Model slightly underperforms but still statistically acceptable."
        else:
            status = "POOR_FIT"
            is_credible = False
            interpretation = "Model does not adequately describe the data."

        logger.info(f"p-value = {p_value:.4f}, status = {status}")

        free_variables = self.free_variable_count()

        return {
            "chi_squared": chi_sq,
            "effective_dof": edof,
            "effective_dof_is_ansatz": True,
            "traditional_dof": self.dof_claimed,
            # Reported alongside EDOF on purpose. EDOF = 3 is an assertion
            # about independent seeds; this is a measured count of what the
            # tree does not derive. Printing only the first is how "zero
            # fitted parameters" survived.
            "free_variable_count": free_variables,
            "free_variable_count_source": (
                "metaphysica.simulations.core.free_variable_ledger "
                "(AutoGenerated/free_variables.json)"
            ),
            "reduced_chi_squared": reduced_chi_sq,
            "p_value": p_value,
            "status": status,
            "is_credible": is_credible,
            "interpretation": interpretation,
            "justification": (
                "EDOF = 3 is an ANSATZ, not a computation: the claim is that the "
                "testable parameters descend from three independent seeds. "
                "Accepting it as proven would beg the question the chi-squared is "
                "meant to answer, and a genuine estimate would need the rank of a "
                "real Jacobian, which is not computed here. It is also NOT the "
                f"number of free variables: the ledger measures {free_variables} "
                "non-derived quantities in this tree. The two numbers answer "
                "different questions and are both reported here."
            ),
            "comparison": {
                "traditional_approach": {
                    "dof": self.dof_claimed,
                    "reduced_chi_sq": self.chi_sq / self.dof_claimed,
                    "issue": "Assumes independence - inappropriate for topologically unified theory"
                },
                "edof_approach": {
                    "edof": edof,
                    "reduced_chi_sq": reduced_chi_sq,
                    "advantage": "Properly accounts for topological correlation structure"
                }
            }
        }

    def _row_count_p_value(self) -> float:
        """Upper-tail p of chi^2 with dof = N scored predictions."""
        return float(1 - chi2.cdf(self.chi_sq, self.dof_claimed))

    @staticmethod
    def _p_value_status(p_value: float) -> str:
        """Credibility band of a p-value."""
        if 0.05 <= p_value <= 0.95:
            return "CREDIBLE"
        if p_value > 0.95:
            return "TOO_GOOD"
        return "MARGINAL" if p_value >= 0.01 else "POOR_FIT"

    def generate_report(self) -> Dict[str, Any]:
        """Generate the statistical rigor report; every number is from rows."""
        logger.info("Generating statistical rigor report...")
        edof_results = self.calculate_p_value_with_edof()
        fit = fit_partition.fit_summary(self.validation_results)
        part = self.partition
        return {
            "framework": "Principia Metaphysica",
            "test_date": datetime.now().isoformat(),
            "test_name": "Statistical rigor validation: one scored row per observable",
            "scaffold_notes": {
                "edof_ansatz": (
                    "EDOF=3 is a qualitative judgment, not computed from a "
                    "Jacobian rank. The EDOF p-value depends entirely on it and "
                    "is illustrative; the row-count p-value is in summary."
                ),
            },
            "chi_squared_from_rows": {
                **fit,
                "dof_definition": "N scored predictions, nothing subtracted",
                "note": (
                    "all_scoring_rows is the headline: scored predictions, "
                    "recorded falsifications included, duplicates removed. "
                    "excluding_falsified is the same without the rows "
                    "recorded as FALSIFIED. Neither hides the other."),
            },
            "duplicates": part["duplicates"],
            "undeclared_duplicates": part["undeclared_duplicates"],
            "non_predictions": {
                "note": "reported, never scored, never counted as PASS",
                "rows": part["non_predictions"],
            },
            "edof_analysis": edof_results,
            "summary": {
                # The headline verdict comes from the row-count p-value (N
                # scored rows, nothing subtracted), never from the EDOF=3
                # ansatz, which stays reported beside it.
                "status": self._p_value_status(self._row_count_p_value()),
                "status_basis": "row-count p-value, N scored predictions",
                "status_edof_ansatz": edof_results["status"],
                "chi_squared": self.chi_sq,
                "n_scored": self.dof_claimed,
                "reduced_chi_squared_n": self.chi_sq / self.dof_claimed,
                "p_value_n_dof": self._row_count_p_value(),
                "p_value_edof_ansatz": edof_results["p_value"],
                "n_duplicates": len(part["duplicates"]),
                "n_non_predictions": len(part["non_predictions"]),
            },
        }

    def save_report(self, report: Dict[str, Any], output_path: Path = None):
        """Save statistical rigor report to JSON."""
        if output_path is None:
            import os as _os
            _out_env = _os.environ.get("METAPHYSICA_OUT")
            _base = Path(_out_env) if _out_env else REPO_ROOT
            output_path = _base / "AutoGenerated" / "statistical_rigor_report.json"

        output_path.parent.mkdir(parents=True, exist_ok=True)

        with open(output_path, 'w') as f:
            json.dump(report, f, indent=2)

        logger.info(f"Report saved: {output_path}")
        return output_path


def main():
    """Generate statistical rigor validation report."""
    validator = StatisticalRigorValidator()
    report = validator.generate_report()
    output_path = validator.save_report(report)
    fit = report["chi_squared_from_rows"]
    allr, live = fit["all_scoring_rows"], fit["excluding_falsified"]
    print("=" * 70)
    print(" STATISTICAL RIGOR VALIDATION")
    print("=" * 70)
    print(f" (a) all scored predictions: chi^2 = {allr['chi_squared']:.4g}, "
          f"N = {allr['n']}")
    print(f" (b) without recorded falsifications: "
          f"chi^2 = {live['chi_squared']:.4g}, N = {live['n']}")
    for row in fit["top_contributors"][:3]:
        print(f" (c) {row['path']}: share {row['share']:.1%}")
    print(f" Status: {report['summary']['status']}")
    print(f" Report: {output_path}")
    return report


if __name__ == "__main__":
    main()

