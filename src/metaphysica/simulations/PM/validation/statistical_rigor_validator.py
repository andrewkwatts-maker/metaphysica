#!/usr/bin/env python3
"""
Statistical Rigor Validator - Principia Metaphysica
====================================================

Fit statistics for the validation report, computed from its rows.

One scored row per observable: aliases of one measurement are reported under
``duplicates`` and left out of chi2 (see ``observables.py``). Only predictions
are scored; input, fitted, calibrated, circular, identity and unit-check rows
are reported in their own block and never count as PASS.

The report publishes, each with its N: (a) all scored predictions with
recorded falsifications included, (b) the same without the rows recorded as
falsified, (c) the top contributors with each row's share of chi2. The
effective-DOF p-value is a labelled ANSATZ, not a computation.

Output:
    statistical_rigor_report.json

Copyright (c) 2026 Andrew Keith Watts. All rights reserved.
"""

import json
import logging
import os
from pathlib import Path
from typing import Dict, Any
from scipy.stats import chi2
from datetime import datetime

# Add parent directory to path
import sys
REPO_ROOT = Path(__file__).parent.parent.parent.parent
sys.path.insert(0, str(REPO_ROOT))

logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger("StatisticalRigor")


def report_path() -> Path:
    """The report's path: $METAPHYSICA_OUT (else the repo root)/AutoGenerated."""
    _out_env = os.environ.get("METAPHYSICA_OUT")
    _base = Path(_out_env) if _out_env else REPO_ROOT
    return _base / "AutoGenerated" / "statistical_rigor_report.json"


def remove_stale_report(path: Path = None) -> None:
    """Delete an existing report before a run computes a new one.

    Under ``build --keep-going`` a run that raised used to leave the
    previous build's report in place, and the statistics refresh read it as
    this build's. With it removed, a failed run leaves no report and the
    refresh raises on the missing file.
    """
    path = report_path() if path is None else Path(path)
    if path.exists():
        path.unlink()
        logger.info(f"Removed previous report: {path}")


if __name__ == "__main__":
    # Run as a build step (python -m): remove the previous report before the
    # project imports below, so an import that fails leaves no report either.
    remove_stale_report()

from metaphysica.simulations.PM.validation import observables  # noqa: E402
from metaphysica.simulations.validation import fit_partition  # noqa: E402


#: Verdicts that carry a two-sided comparison; ``observables.partition_rows``
#: scores only rows with one of these. Every other verdict (UNBOUNDED, INPUT,
#: IDENTITY, UNIT_CHECK, CIRCULAR, ...) is left out of the fit by that test.
#: A fit statistic must range over all of these -- excluding TENSION and FAIL
#: is what made the fit look perfect.
SCORING_VERDICTS = frozenset({"PASS", "MARGINAL", "TENSION", "FAIL"})

#: Credibility bands of a p-value: CREDIBLE in [P_CREDIBLE_LOW,
#: P_CREDIBLE_HIGH], TOO_GOOD above, MARGINAL in [P_MARGINAL_LOW,
#: P_CREDIBLE_LOW), POOR_FIT below. ``_p_value_status`` applies them and the
#: band text is formatted from them.
P_CREDIBLE_LOW = 0.05
P_CREDIBLE_HIGH = 0.95
P_MARGINAL_LOW = 0.01

#: Bound types that express a two-sided comparison and therefore have a
#: residual. A "lower"/"upper" bound has a margin, not a sigma.
TWO_SIDED_BOUND_TYPES = frozenset({"measured", "central_value"})



class StatisticalRigorValidator:
    """Chi-squared, p-value and the fit summary, all computed from report rows."""

    def __init__(self, validation_file: str = None):
        """
        Initialize validator with validation data.

        Args:
            validation_file: Path to validation_report.json (optional)
        """
        if validation_file is None:
            import os as _os
            _out_env = _os.environ.get("METAPHYSICA_OUT")
            _base = Path(_out_env) if _out_env else REPO_ROOT
            validation_file = _base / "AutoGenerated" / "validation_report.json"

        self.validation_file = Path(validation_file)

        if not self.validation_file.exists():
            raise FileNotFoundError(
                f"validation_report.json not found at {self.validation_file}. "
                "A missing input is a build failure. Run the validation "
                "step that writes it first, or pass validation_file."
            )
        with open(self.validation_file, "r") as f:
            self.data = json.load(f)
        self.partition = observables.partition_rows(
            self._adapt_report_rows(self.data), SCORING_VERDICTS)
        # One scored row per observable; the fit is over these only.
        self.validation_results = self.partition["scored"]
        self.chi_sq, self.dof_claimed = self._chi_squared_from_rows(
            self.validation_results)
        logger.info(
            f"Loaded validation data: chi^2 = {self.chi_sq}, "
            f"N = {self.dof_claimed} scored predictions "
            f"({len(self.partition['duplicates'])} duplicates, "
            f"{len(self.partition['non_predictions'])} non-predictions "
            "reported separately)")

    @staticmethod
    def _chi_squared_from_rows(rows):
        """Return (chi^2, N) over the given rows, failing on a malformed row.

        Degrees of freedom is the row count: nothing is subtracted for
        fitted parameters, because the rows that were fitted are not scored
        (see ``observables.NON_PREDICTION_STATUSES``).
        """
        out = fit_partition.chi_squared(rows)
        return out["chi_squared"], out["n"]

    def _require_scored_rows(self) -> None:
        """Raise when there is no scored row: chi^2 / N would divide by zero."""
        if self.dof_claimed:
            return
        raise ValueError(
            f"{self.validation_file} has no scored prediction rows (a row "
            "with an experimental value, an uncertainty above zero, a "
            "measured or central_value bound and a scoring verdict), so "
            "reduced chi^2 = chi^2 / N and the p-values cannot be computed. "
            "Run the validation step that writes scored rows first.")

    @staticmethod
    def _adapt_report_rows(data):
        """Every report row in the validator's field names, with ``comparable``.

        ``comparable`` is true when the row has a two-sided comparison: an
        experimental value, an uncertainty above zero and a measured or
        central-value bound. Non-prediction rows are kept whether or not they
        are comparable, so they can be reported in their own block.
        """
        legacy = data.get("sigma_table")
        if legacy:
            return [dict(r, comparable=True) for r in legacy]
        rows = []
        for entry in data["validations"]:
            unc = entry.get("experimental_uncertainty")
            pred, exp = entry.get("value"), entry.get("experimental_value")
            comparable = (bool(unc) and pred is not None and exp is not None
                          and entry.get("bound_type") in TWO_SIDED_BOUND_TYPES)
            rows.append({
                "path": entry.get("path"), "name": entry.get("path"),
                "status": entry.get("verdict"),
                "predicted_value": pred, "experimental_value": exp,
                "uncertainty": unc, "sigma": entry.get("sigma"),
                "registry_status": entry.get("registry_status"),
                "bound_type": entry.get("bound_type"),
                "comparable": comparable})
        return rows

    def calculate_effective_dof(self) -> int:
        """Return 3, the effective degrees of freedom: an ANSATZ.

        The claim is that the testable parameters descend from three
        independent seeds. It is a judgement about derivation structure, not a
        computation (no Jacobian is evaluated), and accepting it as proven
        would beg the question the chi-squared is meant to answer. It is NOT
        the number of free variables; see :meth:`free_variable_count`.

        The p-value taken with it is labelled as ansatz-dependent in the
        report. The row-count p-value is reported beside it.
        """
        # ANSATZ: EDOF=3 is a judgment (b₃, φ, θ₁₃ are the proposed independent
        # seeds) not a numerical computation.  The claim that all other parameters
        # are derived from these three is the theory's central assertion; accepting
        # it as proven would beg the question.  A genuine EDOF estimate would
        # require the rank of a real Jacobian, which no code here computes.
        #
        # Changing it is an author ruling. It is not the free-variable
        # count, which the ledger measures (:meth:`free_variable_count`);
        # :meth:`calculate_p_value_with_edof` reports both side by side.
        return 3

    @staticmethod
    def free_variable_count() -> int:
        """Return the count of non-derived quantities the ledger measures.

        The value is ``free_variable_ledger.published_free_variable_count()``
        (from ``AutoGenerated/free_variables.json``). It is NOT the EDOF
        used by the chi-squared arithmetic: EDOF is an ansatz about how many
        independent seeds the theory has; this counts the quantities the
        tree does not derive.
        """
        from metaphysica.simulations.core.free_variable_ledger import (
            published_free_variable_count,
        )

        return published_free_variable_count()

    @staticmethod
    def _band_text(status: str) -> str:
        """The p-value range of a credibility band, from the band constants."""
        return {
            "CREDIBLE": f"p in [{P_CREDIBLE_LOW}, {P_CREDIBLE_HIGH}]",
            "TOO_GOOD": f"p > {P_CREDIBLE_HIGH}",
            "MARGINAL": f"p in [{P_MARGINAL_LOW}, {P_CREDIBLE_LOW})",
            "POOR_FIT": f"p < {P_MARGINAL_LOW}",
        }[status]

    def calculate_p_value_with_edof(self) -> Dict[str, Any]:
        """Return the EDOF side-figure dict: p_value, status and reduced chi^2.

        ``p_value`` is the upper tail of the row chi^2 with dof = the EDOF
        ansatz, ``status`` its credibility band; the dict also carries the
        free-variable count and the dof comparison. The EDOF value is a
        judgment, not a computation (see
        :meth:`calculate_effective_dof`), so this p-value and its band are a
        labelled side figure, never the verdict. The verdict is
        ``summary.status`` from :meth:`_row_count_p_value` (dof = N scored
        predictions); ``is_verdict`` is False here and ``verdict_source``
        names the summary key.
        """
        self._require_scored_rows()
        edof = self.calculate_effective_dof()
        chi_sq = self.chi_sq
        p_value = float(1 - chi2.cdf(chi_sq, edof))
        status = self._p_value_status(p_value)
        logger.info(f"EDOF side figure: chi^2 = {chi_sq:.4g}, EDOF = {edof}, "
                    f"p = {p_value:.4g} ({status}, not the verdict)")
        free_variables = self.free_variable_count()
        return {
            "chi_squared": chi_sq,
            "effective_dof": edof,
            "effective_dof_is_ansatz": True,
            "traditional_dof": self.dof_claimed,
            "free_variable_count": free_variables,
            "free_variable_count_source": (
                "metaphysica.simulations.core.free_variable_ledger "
                "(AutoGenerated/free_variables.json)"),
            "reduced_chi_squared": chi_sq / edof,
            "p_value": p_value,
            "status": status,
            "is_credible": status in ("CREDIBLE", "MARGINAL"),
            "is_verdict": False,
            "verdict_source": "summary.status (row-count p-value, summary.p_value)",
            "interpretation": (
                f"{self._band_text(status)} under EDOF = {edof} (ansatz); a "
                "side figure, not the verdict, which is summary.status."),
            "justification": self._edof_justification(edof, free_variables),
            "comparison": self._dof_comparison(edof, chi_sq / edof),
        }

    @staticmethod
    def _edof_justification(edof: int, free_variables: int) -> str:
        """Why EDOF is an ansatz and differs from the free-variable count."""
        return (
            f"EDOF = {edof} is an ANSATZ, not a computation: the claim is that "
            f"the testable parameters descend from {edof} independent seeds. "
            "Accepting it as proven would beg the question the chi-squared is "
            "meant to answer, and a genuine estimate would need the rank of a "
            "real Jacobian, which is not computed here. It is also NOT the "
            f"number of free variables: the ledger measures {free_variables} "
            "non-derived quantities in this tree. The two numbers answer "
            "different questions and are both reported here.")

    def _dof_comparison(self, edof: int, reduced_edof: float) -> Dict[str, Any]:
        """Reduced chi^2 under dof = N (the verdict) and under the EDOF ansatz."""
        return {
            "traditional_approach": {
                "dof": self.dof_claimed,
                "reduced_chi_sq": self.chi_sq / self.dof_claimed,
                "role": "the verdict: N scored predictions, nothing subtracted",
            },
            "edof_approach": {
                "edof": edof,
                "reduced_chi_sq": reduced_edof,
                "role": "side figure: EDOF is an ansatz, not a Jacobian rank",
            },
        }

    def _row_count_p_value(self) -> float:
        """Upper-tail p of chi^2 with dof = N scored predictions."""
        return float(1 - chi2.cdf(self.chi_sq, self.dof_claimed))

    @staticmethod
    def _p_value_status(p_value: float) -> str:
        """Credibility band of a p-value, from the P_* band constants."""
        if P_CREDIBLE_LOW <= p_value <= P_CREDIBLE_HIGH:
            return "CREDIBLE"
        if p_value > P_CREDIBLE_HIGH:
            return "TOO_GOOD"
        return "MARGINAL" if p_value >= P_MARGINAL_LOW else "POOR_FIT"

    def _summary(self, edof: Dict[str, Any], part: Dict[str, Any]) -> Dict[str, Any]:
        """The verdict block: status and headline p-value from dof = N.

        ``status`` and ``p_value`` (with its alias ``p_value_n_dof``) come
        from the row chi^2 over the N scored predictions, nothing
        subtracted, so ``dof`` is a count and ``dof_is_ansatz`` is False.
        The EDOF reading (:meth:`calculate_effective_dof`) is copied in only
        under keys that say ``edof_ansatz``.
        """
        p_value = self._row_count_p_value()
        return {
            "status": self._p_value_status(p_value),
            "status_basis": "row-count p-value, N scored predictions",
            "status_edof_ansatz": edof["status"],
            "chi_squared": self.chi_sq,
            "n_scored": self.dof_claimed,
            "dof": self.dof_claimed,
            "dof_is_ansatz": False,
            "reduced_chi_squared_n": self.chi_sq / self.dof_claimed,
            "p_value": p_value,
            "p_value_basis": "upper tail of chi^2 with dof = N scored predictions",
            "p_value_n_dof": p_value,
            "p_value_edof_ansatz": edof["p_value"],
            "n_duplicates": len(part["duplicates"]),
            "n_non_predictions": len(part["non_predictions"]),
        }

    def generate_report(self) -> Dict[str, Any]:
        """Generate the statistical rigor report; every number is from rows."""
        logger.info("Generating statistical rigor report...")
        self._require_scored_rows()
        edof_results = self.calculate_p_value_with_edof()
        fit = fit_partition.fit_summary(self.validation_results)
        part = self.partition
        return {
            "framework": "Principia Metaphysica",
            "test_date": datetime.now().isoformat(),
            "test_name": "Statistical rigor validation: one scored row per observable",
            "scaffold_notes": {
                "edof_ansatz": (
                    f"EDOF = {edof_results['effective_dof']} is a qualitative "
                    "judgment, not computed from a "
                    "Jacobian rank. The EDOF p-value depends entirely on it and "
                    "is a side figure; the verdict and the headline p-value "
                    "are summary.status and summary.p_value (dof = N)."
                ),
            },
            "chi_squared_from_rows": {
                **fit,
                "dof_definition": "N scored predictions, nothing subtracted",
                "note": (
                    "all_scoring_rows is the headline: scored predictions, "
                    "recorded falsifications included, duplicates removed. "
                    "excluding_falsified is the same without the rows "
                    "recorded as FALSIFIED. Neither hides the other."),
            },
            "duplicates": part["duplicates"],
            "undeclared_duplicates": part["undeclared_duplicates"],
            "non_predictions": {
                "note": "reported, never scored, never counted as PASS",
                "rows": part["non_predictions"],
            },
            "edof_analysis": edof_results,
            "summary": self._summary(edof_results, part),
        }

    def save_report(self, report: Dict[str, Any], output_path: Path = None):
        """Save statistical rigor report to JSON (default: report_path())."""
        if output_path is None:
            output_path = report_path()

        output_path.parent.mkdir(parents=True, exist_ok=True)

        with open(output_path, 'w') as f:
            json.dump(report, f, indent=2)

        logger.info(f"Report saved: {output_path}")
        return output_path


def main():
    """Remove the previous report, then compute and save a new one."""
    remove_stale_report()
    validator = StatisticalRigorValidator()
    report = validator.generate_report()
    output_path = validator.save_report(report)
    fit = report["chi_squared_from_rows"]
    allr, live = fit["all_scoring_rows"], fit["excluding_falsified"]
    print("=" * 70)
    print(" STATISTICAL RIGOR VALIDATION")
    print("=" * 70)
    print(f" (a) all scored predictions: chi^2 = {allr['chi_squared']:.4g}, "
          f"N = {allr['n']}")
    print(f" (b) without recorded falsifications: "
          f"chi^2 = {live['chi_squared']:.4g}, N = {live['n']}")
    for row in fit["top_contributors"][:3]:
        print(f" (c) {row['path']}: share {row['share']:.1%}")
    print(f" Status: {report['summary']['status']}")
    print(f" Report: {output_path}")
    return report


if __name__ == "__main__":
    main()

