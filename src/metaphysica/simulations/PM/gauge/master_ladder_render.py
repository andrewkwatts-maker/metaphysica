def step_actions() -> Dict[str, Action]:
    """The ladder's actions at the recommended owner options, keyed by step id."""
    opts = L.resolve_options()
    conv = L._CONVENTION[opts[5]]
    return {"26D": S.action_26(opts[2], int(opts[4]), conv), "13D": S.action_13(conv),
            "6D": S.action_6(conv), "4D": S.action_4(conv)}


def formula_latex(formula_id: str) -> str:
    """Published latex of a rendered formula; fails early for any other id."""
    if formula_id in WHOLE_ACTION:
        return action_latex(step_actions()[WHOLE_ACTION[formula_id]])
    if formula_id in TERM_FORMULAS:
        term_key = TERM_FORMULAS[formula_id][0]
        if term_key not in S.TERM_LATEX:
            raise KeyError("%s: no ladder term %s" % (formula_id, term_key))
        return TERM_FORMULAS[formula_id][1]
    raise KeyError("formula %s is not rendered from the ladder" % formula_id)


def ladder_step(formula_id: str) -> str:
    """The ladder step an EOM formula varies in its derivation."""
    return EOM_STEPS[formula_id]
