def published_ids(root: str = "") -> List[str]:
    """Sorted formula ids matching the action pattern; raises if the file is absent."""
    root = root or os.environ.get("PM_PUBLISHED_ROOT", DEFAULT_ROOT)
    path = os.path.join(root, "AutoGenerated", "formulas.json")
    if not os.path.isfile(path):
        raise FileNotFoundError("published formulas not found: %s" % path)
    with open(path, encoding="utf-8") as fh:
        formulas = json.load(fh)["formulas"]
    return sorted(k for k in formulas if PATTERN.search(k))


def build_rows(ids: List[str]) -> List[tuple]:
    unmapped = [i for i in ids if i not in MAP]
    if unmapped:
        raise KeyError("published action formulas with no ladder mapping: %s" % unmapped)
    return [(i,) + MAP[i] for i in ids]


def render(rows: List[tuple]) -> str:
    n = Counter(r[1] for r in rows)
    out = ["# Master ladder map: published action formulas (L2a)", "",
           "Read-only cross-check against `formulas.json` (ids matching `action|lagrang`). "
           "Generated by `metaphysica.simulations.PM.gauge.master_ladder_map`; no formula "
           "is edited here. Rendering from the ladder is lane L2c.", "",
           "Counts: step %d, reduction %d, retire %d, out of scope %d (total %d)."
           % (n["step"], n["reduction"], n["retire"], n["out"], len(rows)), "",
           "| Formula id | Kind | Ladder target | Note |", "|---|---|---|---|"]
    out += ["| %s | %s | %s | %s |" % r for r in rows]
    return "\n".join(out) + "\n"


def main(argv: List[str]) -> int:
    if len(argv) != 2:
        print("usage: master_ladder_map OUT.md", file=sys.stderr)
        return 2
    with open(argv[1], "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(build_rows(published_ids())))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
