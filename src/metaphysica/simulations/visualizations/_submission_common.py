"""
Submission Figures - Shared Helpers
====================================

Shared style + data loading helpers for the four publication-quality
submission figures (Figure 1-4). Each figure module configures rcParams
via :func:`apply_publication_rcparams` and resolves output paths through
:func:`plots_dir`.

Inputs that may not yet be generated at first-run time
(``parameters.json``, ``statistical_rigor_report.json``) are loaded via
:func:`load_parameters` / :func:`load_statistics`, which raise
``FileNotFoundError`` so the figure modules can handle that gracefully.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict

from metaphysica.generators._common import autogen_dir


def plots_dir() -> Path:
    """Resolve ``<METAPHYSICA_OUT>/AutoGenerated/plots`` lazily."""
    p = autogen_dir() / "plots"
    p.mkdir(parents=True, exist_ok=True)
    return p


def apply_publication_rcparams() -> None:
    """Apply the journal-submission rcParams (serif, grid, etc)."""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({
        "font.size": 12,
        "axes.labelsize": 14,
        "axes.titlesize": 16,
        "xtick.labelsize": 11,
        "ytick.labelsize": 11,
        "legend.fontsize": 11,
        "figure.titlesize": 18,
        "font.family": "serif",
        "font.serif": ["Times New Roman", "DejaVu Serif"],
        "mathtext.fontset": "dejavuserif",
        "axes.grid": True,
        "grid.alpha": 0.3,
        "grid.linestyle": "--",
        "lines.linewidth": 2,
        "axes.linewidth": 1.2,
    })


def _autogen() -> Path:
    return autogen_dir()


def load_parameters() -> Dict[str, Any]:
    """Load ``AutoGenerated/parameters.json``.

    Raises:
        FileNotFoundError: when the parameters artifact has not been
            generated yet.
    """
    path = _autogen() / "parameters.json"
    if not path.exists():
        raise FileNotFoundError(
            f"parameters.json not found at {path} - "
            "run the simulation pipeline first."
        )
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def load_statistics() -> Dict[str, Any]:
    """Load ``AutoGenerated/statistical_rigor_report.json``.

    Raises:
        FileNotFoundError: when the statistics artifact has not been
            generated yet.
    """
    path = _autogen() / "statistical_rigor_report.json"
    if not path.exists():
        raise FileNotFoundError(
            f"statistical_rigor_report.json not found at {path} - "
            "run the statistics generator first."
        )
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


__all__ = [
    "plots_dir",
    "apply_publication_rcparams",
    "load_parameters",
    "load_statistics",
]
