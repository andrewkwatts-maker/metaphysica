#!/usr/bin/env python3
"""
Primary Gates Visualization (thin wrapper)
==========================================

Wrapper module that exposes a standalone ``main()`` entry point for the
``primary_gates.png`` artifact, which is actually produced by the
``generate_primary_gates_focus`` method inside
:mod:`metaphysica.simulations.visualizations.certificate_dashboard`.

This wrapper exists so the all-plots ledger can list ``primary_gates``
as its own runnable module, independent of the certificate dashboard's
sibling artifact.

Output: ``AutoGenerated/plots/primary_gates.png``

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import sys
from pathlib import Path

from metaphysica.generators._common import autogen_dir
from metaphysica.simulations.visualizations.certificate_dashboard import (
    generate_gates_focus,
)


def _plots_dir() -> Path:
    """Resolve ``<METAPHYSICA_OUT>/AutoGenerated/plots`` lazily."""
    p = autogen_dir() / "plots"
    p.mkdir(parents=True, exist_ok=True)
    return p


def main() -> int:
    """Generate the Primary Gates focus visualization.

    Returns:
        ``0`` on success, ``1`` if the image could not be produced.
    """
    print("=" * 60)
    print("Generating Primary Gates Focus Visualization")
    print("=" * 60)

    # Ensure output dir exists before delegating.
    _plots_dir()

    output_path = generate_gates_focus()

    print("\n" + "=" * 60)
    print("Primary Gates Complete")
    print("=" * 60)
    if output_path is None:
        print("  [ERROR] generate_gates_focus() returned None")
        return 1

    size = Path(output_path).stat().st_size
    print(f"  Output: {output_path}")
    print(f"[viz] OK primary_gates.png ({size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
