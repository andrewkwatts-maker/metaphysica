#!/usr/bin/env python3
"""
Figure 1: M^27(24,1,2) Bulk Decomposition Diagram
==================================================

Publication-quality diagram showing
``M^27(24,1,2) = Lambda_24 ⊕ T^1 ⊕ S_EIS``: the 24D Leech lattice core,
1D unified time fiber, and (0,2) sampler / averaging sector.

Outputs (both):
- ``AutoGenerated/plots/figure1_m27_decomposition.png``
- ``AutoGenerated/plots/figure1_m27_decomposition.pdf``

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

from metaphysica.simulations.visualizations._submission_common import (
    apply_publication_rcparams,
    plots_dir,
)


def generate_figure1_m27_decomposition() -> tuple[Path, Path] | None:
    """Generate Figure 1 as both PNG and PDF.

    Returns:
        ``(png_path, pdf_path)`` on success, ``None`` if matplotlib is
        unavailable.
    """
    try:
        import matplotlib.pyplot as plt
        from matplotlib.patches import FancyBboxPatch
    except ImportError:
        print("Warning: matplotlib not available.")
        return None

    apply_publication_rcparams()
    print("\n[Figure 1] Generating M27 Bulk Decomposition Diagram...")

    fig, ax = plt.subplots(figsize=(14, 10))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 10)
    ax.axis("off")

    # Title
    ax.text(5, 9.5, r"$M^{27}(24,1,2)$ Bulk Decomposition",
            ha="center", fontsize=20, fontweight="bold")
    ax.text(5, 9.0, r"$M^{27}(24,1,2) = \Lambda_{24} \oplus T^1 \oplus \mathcal{S}_{\mathrm{EIS}}$",
            ha="center", fontsize=16, style="italic")

    # Main M27 box
    main_box = FancyBboxPatch((0.5, 3.5), 9, 4.8,
                              boxstyle="round,pad=0.1",
                              edgecolor="black", facecolor="lightblue",
                              linewidth=3, alpha=0.3)
    ax.add_patch(main_box)
    ax.text(5, 8.0, r"$M^{27}(24,1,2)$ - 27D Spacetime",
            ha="center", fontsize=15, fontweight="bold")

    # Leech Lattice Λ24 (24D G2 core)
    leech_box = FancyBboxPatch((1.0, 5.0), 3.5, 2.5,
                               boxstyle="round,pad=0.08",
                               edgecolor="darkblue", facecolor="lightcyan",
                               linewidth=2.5, alpha=0.6)
    ax.add_patch(leech_box)
    ax.text(2.75, 7.0, r"$\Lambda_{24}$ (Leech Lattice)",
            ha="center", fontsize=13, fontweight="bold")
    ax.text(2.75, 6.5, r"24D G$_2$ Core", ha="center", fontsize=11)
    ax.text(2.75, 6.1, r"12 $\times$ $(2,0)$ Bridge Pairs", ha="center", fontsize=10)
    ax.text(2.75, 5.65, r"$b_3 = 24$ (Betti Number)", ha="center", fontsize=9)
    ax.text(2.75, 5.3, r"G$_2$ Holonomy", ha="center", fontsize=9, style="italic")

    # Unified Time T1 (1D)
    time_box = FancyBboxPatch((5.2, 5.0), 2.0, 2.5,
                              boxstyle="round,pad=0.08",
                              edgecolor="darkred", facecolor="mistyrose",
                              linewidth=2.5, alpha=0.6)
    ax.add_patch(time_box)
    ax.text(6.2, 7.0, r"$T^1$ (Time Fiber)",
            ha="center", fontsize=13, fontweight="bold")
    ax.text(6.2, 6.5, r"1D Timelike", ha="center", fontsize=11)
    ax.text(6.2, 6.0, r"Structure $(24,1,2)$", ha="center", fontsize=10)
    ax.text(6.2, 5.5, r"Unified Clock", ha="center", fontsize=9, style="italic")

    # Central Sampler S_EIS (0,2)
    sampler_box = FancyBboxPatch((7.8, 5.0), 1.7, 2.5,
                                 boxstyle="round,pad=0.08",
                                 edgecolor="darkgreen", facecolor="honeydew",
                                 linewidth=2.5, alpha=0.6)
    ax.add_patch(sampler_box)
    ax.text(8.65, 7.0, r"$\mathcal{S}_{\mathrm{EIS}}$",
            ha="center", fontsize=13, fontweight="bold")
    ax.text(8.65, 6.5, r"Central Sampler", ha="center", fontsize=10)
    ax.text(8.65, 6.1, r"$(0,2)$ Dimensions", ha="center", fontsize=9)
    ax.text(8.65, 5.65, r"Averaging", ha="center", fontsize=9, style="italic")
    ax.text(8.65, 5.3, r"Architecture", ha="center", fontsize=9, style="italic")

    # Dimensional Descent Chain
    ax.text(5, 3.0, "Dimensional Descent Chain:",
            ha="center", fontsize=14, fontweight="bold")

    descent_y = 2.3
    descent_text = [
        (r"$27D$", "Full Bulk"),
        (r"$\rightarrow$", ""),
        (r"$13D$", "Intermediate"),
        (r"$\rightarrow$", ""),
        (r"$7D$", r"G$_2$ Manifold"),
        (r"$\rightarrow$", ""),
        (r"$4D$", "Spacetime"),
    ]

    x_positions = np.linspace(2, 8, len(descent_text))
    for x, (dim, label) in zip(x_positions, descent_text):
        if dim == r"$\rightarrow$":
            ax.text(x, descent_y, dim, ha="center", fontsize=16, fontweight="bold")
        else:
            box = FancyBboxPatch((x - 0.3, descent_y - 0.15), 0.6, 0.35,
                                 boxstyle="round,pad=0.03",
                                 edgecolor="purple", facecolor="lavender",
                                 linewidth=1.5, alpha=0.5)
            ax.add_patch(box)
            ax.text(x, descent_y + 0.05, dim, ha="center", fontsize=12, fontweight="bold")
            if label:
                ax.text(x, descent_y - 0.35, label, ha="center", fontsize=8, style="italic")

    # Metric formula at bottom
    metric_box = FancyBboxPatch((1.0, 0.3), 8, 0.8,
                                boxstyle="round,pad=0.05",
                                edgecolor="gray", facecolor="lightyellow",
                                linewidth=1.5, alpha=0.4)
    ax.add_patch(metric_box)
    ax.text(5, 0.85, r"Metric:", ha="center", fontsize=11, fontweight="bold")
    ax.text(5, 0.55,
            r"$ds^2 = -dt^2 + \sum_{i=1}^{12} (dy_{1i}^2 + dy_{2i}^2) + (ds_1^2 + ds_2^2)$",
            ha="center", fontsize=11, style="italic")

    # Save both PNG and PDF
    out_dir = plots_dir()
    png_path = out_dir / "figure1_m27_decomposition.png"
    pdf_path = out_dir / "figure1_m27_decomposition.pdf"
    plt.savefig(png_path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.savefig(pdf_path, bbox_inches="tight", facecolor="white")
    plt.close()

    print(f"  OK Saved: {png_path}")
    print(f"  OK Saved: {pdf_path}")
    return png_path, pdf_path


def main() -> int:
    """Generate Figure 1 (PNG + PDF).

    Returns:
        ``0`` on success, ``1`` on failure.
    """
    print("=" * 60)
    print("Generating Figure 1: M27 Decomposition")
    print("=" * 60)

    result = generate_figure1_m27_decomposition()
    if result is None:
        return 1
    png_path, _pdf_path = result
    size = Path(png_path).stat().st_size
    print(f"[viz] OK figure1_m27_decomposition.png ({size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
