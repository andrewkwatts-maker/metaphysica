#!/usr/bin/env python3
"""
Figure 1: Bulk Decomposition Diagram of the Path in Force
=========================================================

Publication-quality diagram of the bulk the ``bulk_signature`` fork selects:
its dimension, its signature and its timelike directions. On the adopted path
that is ``M^26(24,2)``: 24 spatial plus 2 timelike dimensions, one time per
13D(12,1) shadow. Every number in a label is computed from the selected
option, so a forced option draws its own bulk.

The withdrawn three-sector reading (a lattice core, one time fibre and a
(0,2) sampler) is not an option of the fork, so nothing here can draw it.

The module and its two output files keep the pre-ruling ``m27`` name because
``generators/all_plots.py`` and the plot paths refer to it.

Outputs (both):
- ``AutoGenerated/plots/figure1_m27_decomposition.png``
- ``AutoGenerated/plots/figure1_m27_decomposition.pdf``

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import NamedTuple

import numpy as np

from metaphysica.simulations.core.variants import resolve
from metaphysica.simulations.visualizations._submission_common import (
    apply_publication_rcparams,
    load_parameters,
    plots_dir,
)

B3_ROW = "topology.elder_kads"
BULK_FORK = "bulk_signature"
#: Rank of the Leech lattice: a property of the lattice, not of the path.
LEECH_RANK = 24
DESCENT_Y = 2.3
SPACE_X = 3.1
TIME_X = 7.4

#: (xy, width, height, pad, edge colour, face colour, line width, alpha)
_BOXES = (
    ((0.5, 3.5), 9.0, 4.8, 0.1, "black", "lightblue", 3, 0.3),        # bulk
    ((1.0, 5.0), 4.2, 2.5, 0.08, "darkblue", "lightcyan", 2.5, 0.6),  # space
    ((5.8, 5.0), 3.2, 2.5, 0.08, "darkred", "mistyrose", 2.5, 0.6),   # time
    ((1.0, 0.3), 8.0, 0.8, 0.05, "gray", "lightyellow", 1.5, 0.4),    # metric
)


class Label(NamedTuple):
    """One centred text label of the figure."""

    x: float
    y: float
    text: str
    style: dict


def b3_from_registry(params_data: dict) -> int:
    """b3 of Y_7 from the registry row; a missing row or value raises KeyError."""
    value = params_data["parameters"][B3_ROW]["value"]
    if value is None:
        raise KeyError(f"{B3_ROW} has no value")
    return int(value)


def bulk_from_path() -> tuple[int, int]:
    """``(space, times)`` of the bulk on the path in force.

    Parsed from the selected ``bulk_signature`` option id (``24_2`` is 24
    spatial and 2 timelike dimensions); an id of another shape raises
    ValueError.
    """
    option = resolve(BULK_FORK)
    parts = option.split("_")
    if len(parts) != 2 or not all(p.isdigit() and int(p) > 0 for p in parts):
        raise ValueError(
            f"{BULK_FORK} option {option!r} is not '<space>_<times>'")
    return int(parts[0]), int(parts[1])


def shadow_signature(space: int, times: int) -> tuple[int, int] | None:
    """``(space, 1)`` of one shadow, one time per shadow.

    ``None`` for a one-time bulk, which has no shadow split. A bulk whose
    spatial dimensions do not divide evenly over its times raises ValueError.
    """
    if times == 1:
        return None
    if space % times:
        raise ValueError(
            f"{space} spatial dimensions do not split over {times} shadows")
    return space // times, 1


def _bulk_tex(space: int, times: int) -> str:
    return rf"$M^{{{space + times}}}({space},{times})$"


def _plural(count: int, noun: str) -> str:
    return f"{count} {noun}" if count == 1 else f"{count} {noun}s"


def status_line(space: int, times: int) -> str:
    """The progress line printed while the figure is generated."""
    return (f"[Figure 1] Generating M^{space + times}({space},{times}) "
            "bulk decomposition diagram...")


def title_labels(space: int, times: int) -> list[Label]:
    """Title, the dimension count and the heading of the bulk box."""
    bulk, total = _bulk_tex(space, times), space + times
    return [
        Label(5, 9.5, f"{bulk} Bulk Decomposition",
              {"fontsize": 20, "fontweight": "bold"}),
        Label(5, 9.0,
              rf"{space} spatial $\oplus$ {times} timelike = {total} dimensions",
              {"fontsize": 16, "style": "italic"}),
        Label(5, 8.0, f"{bulk} - {total}D Spacetime",
              {"fontsize": 15, "fontweight": "bold"}),
    ]


def space_labels(space: int, b3: int) -> list[Label]:
    """Labels of the spatial box (Y_7 with G2 holonomy sits inside it).

    The Leech lattice line is drawn only for a spatial sector of its rank, and
    the bridge pair line only when the spatial dimensions pair up.
    """
    labels = [
        Label(SPACE_X, 7.05, _plural(space, "Spatial Dimension"),
              {"fontsize": 13, "fontweight": "bold"}),
        Label(SPACE_X, 6.7, rf"Signature $({space},0)$", {"fontsize": 11}),
    ]
    if space == LEECH_RANK:
        labels.append(Label(SPACE_X, 6.35,
                            rf"$\Lambda_{{{LEECH_RANK}}}$ (Leech Lattice)",
                            {"fontsize": 10}))
    if space % 2 == 0:
        labels.append(Label(SPACE_X, 6.0,
                            rf"{space // 2} $\times$ $(2,0)$ Bridge Pairs",
                            {"fontsize": 10}))
    labels += [
        Label(SPACE_X, 5.65, rf"$b_3 = {b3}$ of $Y_7$ (registry)",
              {"fontsize": 9}),
        Label(SPACE_X, 5.3, r"$Y_7$: G$_2$ Holonomy",
              {"fontsize": 9, "style": "italic"}),
    ]
    return labels


def time_labels(space: int, times: int) -> list[Label]:
    """Labels of the timelike box: every time of the bulk, one per shadow."""
    labels = [
        Label(TIME_X, 7.05, _plural(times, "Timelike Dimension"),
              {"fontsize": 13, "fontweight": "bold"}),
        Label(TIME_X, 6.6, rf"Signature $(0,{times})$", {"fontsize": 11}),
    ]
    shadow = shadow_signature(space, times)
    if shadow is not None:
        labels += [
            Label(TIME_X, 6.15, "One Time per Shadow", {"fontsize": 10}),
            Label(TIME_X, 5.7,
                  rf"{times} $\times$ {sum(shadow)}D$({shadow[0]},{shadow[1]})$"
                  " Shadows",
                  {"fontsize": 10, "style": "italic"}),
        ]
    return labels


def descent_chain(space: int, times: int) -> list[tuple[str, str]]:
    """``(dimension, caption)`` steps from the bulk down to 4D spacetime."""
    chain = [(rf"${space + times}D$", "Full Bulk")]
    shadow = shadow_signature(space, times)
    if shadow is not None:
        chain.append((rf"${sum(shadow)}D$",
                      rf"Shadow $({shadow[0]},{shadow[1]})$"))
    return chain + [(r"$7D$", r"G$_2$ Manifold"), (r"$4D$", "Spacetime")]


def _descent_xs(steps: int) -> np.ndarray:
    """x of every step and of the arrow between two steps, left to right."""
    return np.linspace(2, 8, 2 * steps - 1)


def descent_labels(space: int, times: int) -> list[Label]:
    """Labels of the dimensional descent chain, arrows included."""
    chain = descent_chain(space, times)
    labels = [Label(5, 3.0, "Dimensional Descent Chain:",
                    {"fontsize": 14, "fontweight": "bold"})]
    for index, x in enumerate(_descent_xs(len(chain))):
        if index % 2:
            labels.append(Label(x, DESCENT_Y, r"$\rightarrow$",
                                {"fontsize": 16, "fontweight": "bold"}))
            continue
        dim, caption = chain[index // 2]
        labels.append(Label(x, DESCENT_Y + 0.05, dim,
                            {"fontsize": 12, "fontweight": "bold"}))
        labels.append(Label(x, DESCENT_Y - 0.35, caption,
                            {"fontsize": 8, "style": "italic"}))
    return labels


def metric_tex(space: int, times: int) -> str:
    """Flat metric of the bulk: one minus sign per time, one plus per space."""
    time_terms = " ".join(rf"- dt_{a}^2" for a in range(1, times + 1))
    return rf"$ds^2 = {time_terms} + \sum_{{i=1}}^{{{space}}} dy_i^2$"


def metric_labels(space: int, times: int) -> list[Label]:
    """Heading and formula of the metric box."""
    return [
        Label(5, 0.95, rf"Metric, signature $({space},{times})$:",
              {"fontsize": 11, "fontweight": "bold"}),
        Label(5, 0.52, metric_tex(space, times),
              {"fontsize": 11, "style": "italic"}),
    ]


def figure1_labels(b3: int, space: int, times: int) -> list[Label]:
    """Every text label the figure draws for a bulk of *space* + *times*."""
    return (title_labels(space, times) + space_labels(space, b3)
            + time_labels(space, times) + descent_labels(space, times)
            + metric_labels(space, times))


def _draw_boxes(ax, descent_steps: int) -> None:
    """Draw the bulk, space, time and metric boxes and one box per descent step."""
    from matplotlib.patches import FancyBboxPatch

    for xy, width, height, pad, edge, face, line_width, alpha in _BOXES:
        ax.add_patch(FancyBboxPatch(
            xy, width, height, boxstyle=f"round,pad={pad}", edgecolor=edge,
            facecolor=face, linewidth=line_width, alpha=alpha))
    for x in _descent_xs(descent_steps)[::2]:
        ax.add_patch(FancyBboxPatch(
            (x - 0.3, DESCENT_Y - 0.15), 0.6, 0.35, boxstyle="round,pad=0.03",
            edgecolor="purple", facecolor="lavender", linewidth=1.5, alpha=0.5))


def _draw_labels(ax, labels: list[Label]) -> None:
    for label in labels:
        ax.text(label.x, label.y, label.text, ha="center", **label.style)


def generate_figure1_m27_decomposition(
        params_data: dict | None = None) -> tuple[Path, Path] | None:
    """Generate Figure 1 as both PNG and PDF.

    Args:
        params_data: parsed ``parameters.json``; read from disk when omitted.

    Returns:
        ``(png_path, pdf_path)`` on success, ``None`` if matplotlib is
        unavailable.
    """
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("Warning: matplotlib not available.")
        return None

    b3 = b3_from_registry(params_data if params_data is not None else load_parameters())
    space, times = bulk_from_path()
    apply_publication_rcparams()
    print("\n" + status_line(space, times))

    _fig, ax = plt.subplots(figsize=(14, 10))
    ax.set_xlim(0, 10)
    ax.set_ylim(0, 10)
    ax.axis("off")
    _draw_boxes(ax, len(descent_chain(space, times)))
    _draw_labels(ax, figure1_labels(b3, space, times))

    # Save both PNG and PDF
    out_dir = plots_dir()
    png_path = out_dir / "figure1_m27_decomposition.png"
    pdf_path = out_dir / "figure1_m27_decomposition.pdf"
    plt.savefig(png_path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.savefig(pdf_path, bbox_inches="tight", facecolor="white")
    plt.close()

    print(f"  OK Saved: {png_path}")
    print(f"  OK Saved: {pdf_path}")
    return png_path, pdf_path


def main() -> int:
    """Generate Figure 1 (PNG + PDF).

    Returns:
        ``0`` on success, ``1`` on failure.
    """
    print("=" * 60)
    print("Generating Figure 1: bulk decomposition of the path in force")
    print("=" * 60)

    result = generate_figure1_m27_decomposition()
    if result is None:
        return 1
    png_path, _pdf_path = result
    size = Path(png_path).stat().st_size
    print(f"[viz] OK figure1_m27_decomposition.png ({size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
