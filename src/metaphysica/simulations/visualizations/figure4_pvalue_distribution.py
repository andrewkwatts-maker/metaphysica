#!/usr/bin/env python3
"""
Figure 4: p-value Distribution (EDOF=3 Validation)
====================================================

chi^2 distribution under EDOF = 3 (and traditional DOF for comparison),
marking the PM observed chi^2 and shading the credible / poor-fit /
too-good zones.

Outputs (both):
- ``AutoGenerated/plots/figure4_pvalue_distribution.png``
- ``AutoGenerated/plots/figure4_pvalue_distribution.pdf``

Data dependency:
    ``AutoGenerated/statistical_rigor_report.json`` (produced by the
    statistics generator). If absent, ``main()`` returns 1 and logs the
    missing artifact -- it does not synthesize fake data.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any, Dict

import numpy as np
from scipy.stats import chi2

from metaphysica.simulations.visualizations._submission_common import (
    apply_publication_rcparams,
    load_statistics,
    plots_dir,
)


def generate_figure4_pvalue_distribution(
    stats_data: Dict[str, Any],
) -> tuple[Path, Path] | None:
    """Generate Figure 4 as both PNG and PDF.

    Args:
        stats_data: Parsed ``statistical_rigor_report.json`` content
            with an ``"edof_analysis"`` mapping.

    Returns:
        ``(png_path, pdf_path)`` on success, ``None`` on failure.
    """
    try:
        import matplotlib.pyplot as plt
    except ImportError:
        print("Warning: matplotlib not available.")
        return None

    apply_publication_rcparams()
    print("\n[Figure 4] Generating p-value Distribution (EDOF=3)...")

    edof_data = stats_data["edof_analysis"]
    chi_sq_obs = edof_data["chi_squared"]
    edof = edof_data["effective_dof"]
    traditional_dof = edof_data["traditional_dof"]
    p_value_obs = edof_data["p_value"]

    print(f"  chi^2 = {chi_sq_obs:.3f}, EDOF = {edof}, p-value = {p_value_obs:.4f}")

    fig, ax = plt.subplots(figsize=(14, 10))
    chi_sq_range = np.linspace(0, 20, 1000)

    pdf_edof = chi2.pdf(chi_sq_range, edof)
    pdf_trad = chi2.pdf(chi_sq_range, traditional_dof)

    ax.plot(chi_sq_range, pdf_edof, "b-", linewidth=3,
            label=f"chi^2 Distribution (EDOF = {edof})")
    ax.plot(chi_sq_range, pdf_trad, "gray", linestyle="--", linewidth=2.5,
            label=f"chi^2 Distribution (Traditional DOF = {traditional_dof})",
            alpha=0.6)

    # Trust zone: p in [0.05, 0.95].
    chi_sq_lower = chi2.ppf(0.05, edof)
    chi_sq_upper = chi2.ppf(0.95, edof)
    trust_zone = (chi_sq_range >= chi_sq_lower) & (chi_sq_range <= chi_sq_upper)
    ax.fill_between(chi_sq_range, 0, pdf_edof, where=trust_zone,
                    alpha=0.3, color="green",
                    label="Trust Zone (p in [0.05, 0.95])")
    too_good = chi_sq_range < chi_sq_lower
    ax.fill_between(chi_sq_range, 0, pdf_edof, where=too_good,
                    alpha=0.3, color="red",
                    label="Too Good (p > 0.95)")
    poor_fit = chi_sq_range > chi_sq_upper
    ax.fill_between(chi_sq_range, 0, pdf_edof, where=poor_fit,
                    alpha=0.3, color="orange",
                    label="Poor Fit (p < 0.05)")

    ax.axvline(chi_sq_obs, color="darkblue", linestyle="-", linewidth=4,
               label=f"PM Observed: chi^2 = {chi_sq_obs:.3f}", zorder=10)

    ax.annotate(
        f"PM Result:\nchi^2 = {chi_sq_obs:.3f}\np = {p_value_obs:.3f}\n(CREDIBLE)",
        xy=(chi_sq_obs, chi2.pdf(chi_sq_obs, edof)),
        xytext=(chi_sq_obs + 3, chi2.pdf(chi_sq_obs, edof) + 0.05),
        fontsize=13, fontweight="bold", color="darkblue",
        bbox=dict(boxstyle="round,pad=0.6", facecolor="lightyellow",
                  alpha=0.9, edgecolor="darkblue", linewidth=2.5),
        arrowprops=dict(arrowstyle="->", lw=3, color="darkblue",
                        connectionstyle="arc3,rad=0.3"),
    )

    ax.axvline(edof, color="green", linestyle=":", linewidth=2.5, alpha=0.7,
               label=f"Expected Value: chi^2 = {edof}")

    ax.set_xlabel(r"$\chi^2$ Value", fontsize=16, fontweight="bold")
    ax.set_ylabel("Probability Density", fontsize=16, fontweight="bold")
    ax.set_title(
        r"Statistical Validation: $\chi^2$ Distribution with EDOF = 3" + "\n"
        "Principia Metaphysica v24.1 Fit Quality Assessment",
        fontsize=18, fontweight="bold", pad=20,
    )
    ax.legend(loc="upper right", fontsize=11, framealpha=0.95, edgecolor="black",
              fancybox=True, shadow=True)
    ax.grid(True, alpha=0.3, linestyle="--", linewidth=0.8)
    ax.set_xlim(0, 18)
    ax.set_ylim(0, None)

    trad_red = edof_data["comparison"]["traditional_approach"]["reduced_chi_sq"]
    comparison_text = (
        "EDOF vs. Traditional DOF:\n"
        f"- EDOF = {edof}: Reduced chi^2 = {edof_data['reduced_chi_squared']:.3f}\n"
        f"- Traditional DOF = {traditional_dof}: Reduced chi^2 = {trad_red:.3f}\n"
        "\n"
        "EDOF properly accounts for topological\n"
        "correlation structure (3 independent seeds).\n"
        "Traditional DOF assumes independence,\n"
        "which violates PM's unified topology."
    )
    ax.text(0.02, 0.98, comparison_text,
            transform=ax.transAxes, fontsize=10,
            verticalalignment="top", horizontalalignment="left",
            bbox=dict(boxstyle="round,pad=0.6", facecolor="white", alpha=0.9,
                      edgecolor="black", linewidth=1.5))

    out_dir = plots_dir()
    png_path = out_dir / "figure4_pvalue_distribution.png"
    pdf_path = out_dir / "figure4_pvalue_distribution.pdf"
    plt.savefig(png_path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.savefig(pdf_path, bbox_inches="tight", facecolor="white")
    plt.close()

    print(f"  OK Saved: {png_path}")
    print(f"  OK Saved: {pdf_path}")
    return png_path, pdf_path


def main() -> int:
    """Generate Figure 4 (PNG + PDF). Requires statistical_rigor_report.json."""
    print("=" * 60)
    print("Generating Figure 4: p-value Distribution")
    print("=" * 60)

    try:
        stats_data = load_statistics()
    except FileNotFoundError as exc:
        print(f"  [SKIP] {exc}")
        return 1

    result = generate_figure4_pvalue_distribution(stats_data)
    if result is None:
        return 1
    png_path, _pdf_path = result
    size = Path(png_path).stat().st_size
    print(f"[viz] OK figure4_pvalue_distribution.png ({size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
