"""PM per-path summaries and manifest entries (contracts s3 and s4).

Sources, as ``file:pointer`` inside ``AutoGenerated/``; anything absent is null:

* scoreboard: ``validation_report.json:/validations/*/verdict``. PASS, MARGINAL,
  TENSION and FAIL are counted as they are; SKIP is every other verdict (INPUT,
  UNBOUNDED, IDENTITY), i.e. rows that are not scored against data.
* chi2: ``statistics.json:/framework_statistics/chi_squared`` (value) and
  ``/framework_statistics/degrees_of_freedom`` (dof).
* gates: ``theory_output.json:/gate_checks`` (``gate_id``, ``result == "PASS"``,
  ``details.note`` as the detail).
* certificate: ``theory_output.json:/certificates`` (``id``, ``status == "PASS"``).
* n_gen: ``parameters.json:/parameters/topology.n_gen/value``; the target is the
  three observed generations (``N_GEN_TARGET``).
* key_values: ``parameters.json:/parameters/<id>`` (``value``, ``units``,
  ``experimental_value``, ``sigma_deviation``, ``metadata.description``).
* labels, status, question, summary, consequence, selection:
  ``metaphysica.simulations.core.variants`` (``FORKS``, ``active_selection()``).
"""
from __future__ import annotations

import json
import math
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

N_GEN_TARGET = 3
# Build steps (ids from metaphysica.build) whose failure means the path did not
# compute: the step that runs every simulation. Others (audits, certificates)
# only land in ``failed_steps``.
REQUIRED_STEPS = ("run_all_simulations",)
# Subtrees filled from an unseeded RNG, so they differ between any two builds even
# when the twins happen to agree (statistical_rigor_validator.generate_jacobian_matrix
# is a declared STUB of np.random entries). Publish treats them as volatile.
STOCHASTIC = {"statistical_rigor_report.json": ("/jacobian_analysis",)}
MAX_KEY_VALUES = 40
HEADLINE = (
    "geometry.alpha_inverse",                # fine-structure constant, inverse
    "geometry.sin2_theta_W",                 # weak mixing angle
    "geometry.alpha_s",                      # strong coupling at M_Z
    "geometry.alpha_gut_inv",                # unified coupling, inverse
    "cosmology.w0_derived",                  # dark-energy equation of state
    "fermion.mass_ratio_proton_electron",    # proton/electron mass ratio
    "neutrino.mass_sum",                     # sum of neutrino masses (eV)
    "topology.n_gen",                        # number of generations
)
SCORED = ("PASS", "MARGINAL", "TENSION", "FAIL")
_DECISION = re.compile(r"\bD-\d{3}\b")


def _load(root: Path, name: str) -> Any:
    try:
        return json.loads((Path(root) / "AutoGenerated" / name)
                          .read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None


def _get(doc: Any, *keys: Any) -> Any:
    for key in keys:
        try:
            doc = doc[key]
        except (KeyError, IndexError, TypeError):
            return None
    return doc


def _scoreboard(root: Path) -> Optional[dict]:
    rows = _get(_load(root, "validation_report.json"), "validations")
    if not isinstance(rows, list):
        return None
    out = {k: 0 for k in SCORED + ("SKIP",)}
    for row in rows:
        verdict = row.get("verdict") if isinstance(row, dict) else None
        out[verdict if verdict in SCORED else "SKIP"] += 1
    return out


def _chi2(root: Path) -> Optional[dict]:
    stats = _get(_load(root, "statistics.json"), "framework_statistics")
    value, dof = _get(stats, "chi_squared"), _get(stats, "degrees_of_freedom")
    if value is None and dof is None:
        return None
    return {"value": value, "dof": dof}


def _gates(root: Path) -> Optional[list]:
    rows = _get(_load(root, "theory_output.json"), "gate_checks")
    if not isinstance(rows, list):
        return None
    return [{"id": r.get("gate_id"), "passed": r.get("result") == "PASS",
             "detail": _get(r, "details", "note")}
            for r in rows if isinstance(r, dict)]


def _certificate(root: Path) -> Optional[list]:
    rows = _get(_load(root, "theory_output.json"), "certificates")
    if not isinstance(rows, list):
        return None
    return [{"id": r.get("id"), "holds": r.get("status") == "PASS"}
            for r in rows if isinstance(r, dict)]


def _params(root: Path) -> Optional[dict]:
    params = _get(_load(root, "parameters.json"), "parameters")
    return params if isinstance(params, dict) else None


def _n_gen(params: Optional[dict]) -> Optional[dict]:
    value = _get(params, "topology.n_gen", "value")
    if value is None:
        return None
    return {"value": value, "target": N_GEN_TARGET,
            "holds": value == N_GEN_TARGET}


def _number(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) \
        and math.isfinite(x)


def _relative(value: float, main: float) -> float:
    if value == main:
        return 0.0
    return abs(value - main) / abs(main) if main else math.inf


def _key_value(pid: str, rec: dict, main_rec: Optional[dict],
               volatile: bool = False) -> dict:
    return {"id": pid, "volatile": volatile,
            "label": _get(rec, "metadata", "description") or pid,
            "unit": rec.get("units") or _get(rec, "metadata", "units"),
            "value": rec.get("value"),
            "main": _get(main_rec, "value"),
            "experimental": rec.get("experimental_value"),
            "sigma": rec.get("sigma_deviation")}


def _key_values(params: Optional[dict], main_params: Optional[dict],
                volatile: frozenset = frozenset()) -> Optional[list]:
    """Moved parameters, largest first, then the headline ones.

    A ``volatile`` id differs between two builds of main, so its difference
    is not this path's result: it never ranks as moved, and a headline entry
    carries ``volatile: true``.
    """
    if params is None:
        return None
    moved = []
    for pid, rec in params.items():
        if pid in volatile:
            continue
        main_rec = (main_params or {}).get(pid)
        if not isinstance(rec, dict) or not isinstance(main_rec, dict):
            continue
        a, b = rec.get("value"), main_rec.get("value")
        if _number(a) and _number(b) and a != b:
            moved.append((_relative(a, b), pid))
    moved.sort(key=lambda t: (-t[0], t[1]))
    ids = [pid for _, pid in moved[:MAX_KEY_VALUES]]
    ids += [h for h in HEADLINE if h in params and h not in ids]
    return [_key_value(pid, params[pid], (main_params or {}).get(pid),
                       pid in volatile)
            for pid in ids if isinstance(params[pid], dict)]


def build_summary(path_id: str, main_dir: Path, path_dir: Path,
                  changed: dict, volatile_ids: frozenset = frozenset()) -> dict:
    """The ``metaphysica.path_summary/1`` document for one path."""
    params = _params(path_dir)
    return {"schema": "metaphysica.path_summary/1", "path": path_id,
            "scoreboard": _scoreboard(path_dir), "chi2": _chi2(path_dir),
            "gates": _gates(path_dir), "certificate": _certificate(path_dir),
            "n_gen": _n_gen(params),
            "key_values": _key_values(params, _params(main_dir), volatile_ids),
            "changed": {"count": changed["count"],
                        "by_artifact": changed["by_artifact"],
                        "bookkeeping_ops": changed.get("bookkeeping_ops", 0)},
            "unverified_files": list(changed.get("unverified_files", [])),
            "inert": changed["inert"]}


def _variants():
    from metaphysica.simulations.core import variants
    return variants


def _decision_refs(*texts: Optional[str]) -> List[str]:
    found = {m for t in texts if t for m in _DECISION.findall(t)}
    return sorted(found)


def main_entry() -> dict:
    """Manifest fields of the main path (everything but the run results)."""
    return {"kind": "main", "label": "Main path", "status": "active",
            "selection": dict(_variants().active_selection()),
            "deviation": None,
            "why": "The active path: every fork at its adopted option.",
            "decision_refs": []}


def deviation_entry(fork: str, option: str) -> dict:
    """Manifest fields of the single-option deviation ``fork = option``."""
    var = _variants()
    spec = var.FORKS.get(fork)
    opt = next((o for o in spec.options if o.id == option), None) if spec else None
    if opt is None:
        raise ValueError("unknown fork option %s--%s" % (fork, option))
    active = var.active_selection()
    selection = dict(active)
    selection[fork] = option
    return {"kind": "deviation", "label": "%s = %s" % (fork, option),
            "status": opt.status, "selection": selection,
            "deviation": {"fork": fork, "option": option,
                          "from": active.get(fork), "question": spec.question},
            "summary": opt.summary, "consequence": opt.consequence,
            "decision_refs": _decision_refs(spec.notes, opt.summary,
                                            opt.consequence)}
