"""PM's reader for `testground rank`: one finished run root to its four tiers.

consistent  the switch_search verdict for the run's selection (measurement-free)
ladder      AutoGenerated/action_ladder.json: failing correspondence checks plus
            the established-physics checks that FAIL (L1/L2); the total is every
            check the ladder evaluated
gates       gates.total_failed / gates.total_passed in parameters.json (read as
            published; the gate modules decide what applies to a path)
chi2        validation_report.json rows that predict: a numeric sigma, no scoring
            exclusion, and not an INPUT, CALIBRATED or CALIBRATION_CHECK row

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, List, Mapping, Optional, Tuple

from metaphysica.testground.theory import RunReading

__all__ = ["PmRanking", "chi2_of", "ladder_of", "gates_of"]

#: Rows that are not predictions, by registry status or by verdict.
NOT_PREDICTIONS = frozenset({"INPUT", "CALIBRATED", "CALIBRATION_CHECK"})


def _load(root: Path, name: str) -> Optional[Mapping[str, Any]]:
    try:
        doc = json.loads((Path(root) / "AutoGenerated" / name)
                         .read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return doc if isinstance(doc, dict) else None


def chi2_of(report: Mapping[str, Any]) -> Tuple[float, int]:
    """(chi-squared, rows used) over the prediction rows of a validation report."""
    total, used = 0.0, 0
    for r in report.get("validations") or ():
        sigma = r.get("sigma")
        if not isinstance(sigma, (int, float)) or isinstance(sigma, bool):
            continue
        if r.get("scoring_exclusion_reason"):
            continue
        if NOT_PREDICTIONS & {r.get("registry_status"), r.get("verdict")}:
            continue
        total += float(sigma) ** 2
        used += 1
    return total, used


def ladder_of(doc: Mapping[str, Any]) -> Tuple[int, int]:
    """(failed, total) ladder checks: correspondence steps and established physics."""
    est = doc["established_counts"]
    checks = sum(len(s.get("checks") or ()) for s in doc["ladder"]["steps"])
    return (len(doc["failing_checks"]) + int(est["FAILS"]),
            checks + sum(int(v) for v in est.values()))


def gates_of(params: Mapping[str, Any]) -> Tuple[int, int]:
    """(failed, applicable = passed + failed) from the published gate counts."""
    failed = int(params["gates.total_failed"]["value"])
    return failed, failed + int(params["gates.total_passed"]["value"])


def _consistent(selection: Mapping[str, str]) -> Optional[bool]:
    from metaphysica.simulations.core.switch_search import evaluate_combination
    try:
        return bool(evaluate_combination(dict(selection))["internally_consistent"])
    except Exception:  # noqa: BLE001 -- unevaluable is reported as missing
        return None


class PmRanking:
    """RankingProvider for the PM theory."""

    def read(self, root: Path, selection: Mapping[str, str]) -> RunReading:
        missing: List[str] = []
        consistent = _consistent(selection)
        if consistent is None:
            missing.append("consistency")
        ladder = self._part(root, "action_ladder.json", ladder_of, missing)
        params = _load(root, "parameters.json")
        gates = self._gates(params, missing)
        report = self._part(root, "validation_report.json", chi2_of, missing)
        chi2, dof = report if report else (None, None)
        return RunReading(consistent, *(ladder or (None, None)),
                          *(gates or (None, None)), chi2, dof,
                          tuple(sorted(missing)))

    @staticmethod
    def _part(root: Path, name: str, fn: Any, missing: List[str]):
        doc = _load(root, name)
        try:
            if doc is None:
                raise KeyError(name)
            return fn(doc)
        except (KeyError, TypeError, ValueError):
            missing.append(name)
            return None

    @staticmethod
    def _gates(params: Optional[Mapping[str, Any]], missing: List[str]):
        try:
            return gates_of(params["parameters"])
        except (KeyError, TypeError, ValueError):
            missing.append("gates.total_failed/total_passed")
            return None
