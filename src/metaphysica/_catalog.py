def get_catalog() -> Dict[str, Dict[str, EntityRef]]:
    """Return ``{kind: {normalised_key: EntityRef}}`` (cached singleton).

    First call performs the on-disk scan; subsequent calls return the
    same dict object. Call :func:`reset_catalog` to force a rescan.
    """
    global _CATALOG
    if _CATALOG is not None:
        return _CATALOG
    with _LOCK:
        if _CATALOG is not None:
            return _CATALOG
        dirs = _candidate_dirs()
        formulas, _ = _load_formulas(dirs)
        cat: Dict[str, Dict[str, EntityRef]] = {
            KIND_QUARK: _load_quarks(),
            KIND_CONSTANT: _load_constants(),
            KIND_PARAMETER: _load_parameters(dirs),
            KIND_FORMULA: formulas,
            KIND_GATE: _load_gates(dirs),
            KIND_CERTIFICATE: _load_certificates(dirs),
            KIND_SECTION: _load_sections(dirs),
            KIND_PLOT: _load_plots(dirs),
            KIND_DERIVATION: _load_derivations(dirs),
            KIND_REFERENCE: _load_references(dirs),
            KIND_SIMULATION: _load_simulations(dirs),
        }
        _CATALOG = cat
        return cat


def resolve(name: str, *, kind: Optional[str] = None) -> EntityRef:
    """Look up *name* across the catalog, optionally narrowed to *kind*.

    Raises :class:`metaphysica._errors.MetaphysicaKeyError` if no match,
    or :class:`MetaphysicaAmbiguityError` on multi-kind collisions when
    *kind* is not specified.
    """
    from ._errors import (
        MetaphysicaAmbiguityError,
        MetaphysicaKeyError,
        closest_matches,
    )

    cat = get_catalog()
    norm = _normalise(name)

    if kind is not None:
        if kind not in cat:
            raise MetaphysicaKeyError(name, kind=kind)
        table = cat[kind]
        if norm in table:
            return table[norm]
        raise MetaphysicaKeyError(
            name,
            suggestions=closest_matches(name, [r.canonical_id for r in table.values()]),
            kind=kind,
        )

    hits: List[EntityRef] = []
    for k in _PROBE_ORDER:
        table = cat.get(k, {})
        if norm in table:
            hits.append(table[norm])
    if not hits:
        # Aggregate suggestions across every kind, prioritise canonical ids.
        all_ids = [
            r.canonical_id for table in cat.values() for r in table.values()
        ]
        raise MetaphysicaKeyError(
            name, suggestions=closest_matches(name, all_ids)
        )
    if len(hits) > 1:
        raise MetaphysicaAmbiguityError(
            name, [(r.kind, r.canonical_id) for r in hits]
        )
    return hits[0]


def list_kind(kind: str) -> List[str]:
    """Return every canonical id registered under *kind* (sorted)."""
    cat = get_catalog()
    table = cat.get(kind, {})
    # De-dupe by canonical_id (the same ref shows up under multiple
    # alias keys), then sort.
    return sorted({r.canonical_id for r in table.values()})


