def _load_plots(dirs: List[Path]) -> Dict[str, EntityRef]:
    """Index ``plots-manifest.json`` + the PNG/PDF artefacts."""
    out: Dict[str, EntityRef] = {}
    src = _first_existing("plots-manifest.json", dirs)
    if src is None:
        return out
    data = _load_json(src)
    if not isinstance(data, dict):
        return out
    plots = data.get("plots")
    if not isinstance(plots, list):
        return out
    plot_root = src.parent / "plots"
    for p in plots:
        if not isinstance(p, dict):
            continue
        pid = p.get("id") or p.get("file") or p.get("name")
        if not pid:
            continue
        ref = EntityRef(
            kind=KIND_PLOT,
            canonical_id=str(pid),
            source=src,
            payload=p,
        )
        # Bind any on-disk plot file we can find for this id.
        for fmt in ("png", "pdf", "svg"):
            candidate = plot_root / f"{Path(p.get('file', pid)).stem}.{fmt}"
            if candidate.exists():
                ref.artefacts[fmt] = candidate
        aliases = [pid]
        for k in ("file", "title", "label"):
            v = p.get(k)
            if isinstance(v, str):
                aliases.append(v)
        _add(out, aliases, ref)
    return out


def _load_derivations(dirs: List[Path]) -> Dict[str, EntityRef]:
    """Index bundled + build-output derivation chains."""
    out: Dict[str, EntityRef] = {}
    candidates: List[Path] = []
    # Bundled cache first.
    bundled = _bundled_data_dir() / "derivations"
    if bundled.is_dir():
        candidates.extend(sorted(bundled.glob("*.json")))
    # Build-output cache layered on top (overwrites bundled if same id).
    for d in dirs:
        derdir = d / "AutoGenerated" / "derivations"
        if derdir.is_dir():
            candidates.extend(sorted(derdir.glob("*.json")))
    for jf in candidates:
        data = _load_json(jf)
        if not isinstance(data, dict):
            continue
        did = data.get("id") or jf.stem
        ref = EntityRef(
            kind=KIND_DERIVATION,
            canonical_id=str(did),
            source=jf,
            payload=data,
        )
        _add(out, [did, jf.stem], ref)
    return out


def _load_references(dirs: List[Path]) -> Dict[str, EntityRef]:
    """Index ``references.json``."""
    out: Dict[str, EntityRef] = {}
    src = _first_existing("references.json", dirs)
    if src is None:
        return out
    data = _load_json(src)
    if not isinstance(data, dict):
        return out
    refs = data.get("references")
    if isinstance(refs, dict):
        items = refs.items()
    elif isinstance(refs, list):
        items = ((r.get("id") or r.get("key") or str(i), r) for i, r in enumerate(refs))
    else:
        return out
    for rid, payload in items:
        if not isinstance(payload, dict):
            continue
        ref = EntityRef(
            kind=KIND_REFERENCE,
            canonical_id=str(rid),
            source=src,
            payload=payload,
        )
        aliases = [rid]
        for k in ("title", "label", "key", "doi", "arxiv"):
            v = payload.get(k)
            if isinstance(v, str):
                aliases.append(v)
        _add(out, aliases, ref)
    return out


def _load_simulations(dirs: List[Path]) -> Dict[str, EntityRef]:
    """Index ``simulations-index.json``."""
    out: Dict[str, EntityRef] = {}
    src = _first_existing("simulations-index.json", dirs)
    if src is None:
        return out
    data = _load_json(src)
    if not isinstance(data, dict):
        return out
    categories = data.get("categories") or {}
    if not isinstance(categories, dict):
        return out
    for cat_key, cat in categories.items():
        for s in (cat or {}).get("scripts", []) or []:
            if not isinstance(s, dict):
                continue
            sid = s.get("file") or s.get("path")
            if not sid:
                continue
            ref = EntityRef(
                kind=KIND_SIMULATION,
                canonical_id=str(s.get("path") or sid),
                source=src,
                payload=s,
            )
            _add(out, [sid, s.get("path") or sid], ref)
    return out


