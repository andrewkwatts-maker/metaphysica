"""Entity catalog for the unified ``metaphysica.get()`` dispatcher.

The catalog is a lazily-built index over every retrievable thing in the
framework: formulas, parameters, gates, certificates, sections,
particles (quarks + future leptons), curated constants, plots,
derivations, references, simulations.

Each entry is an :class:`EntityRef` carrying:

* ``kind``  — one of CATEGORICAL ``KIND_*`` strings.
* ``canonical_id`` — the registry-native ID (e.g. ``"pmns-theta-13"``,
  ``"constants.M_PLANCK"``, ``"G01"``).
* ``source`` — absolute :class:`~pathlib.Path` to the JSON / on-disk file
  the entry resolved from. Backends read from here.
* ``payload`` — the parsed JSON record for the entity (eagerly read at
  catalog-build time for cheap entities; deferred to ``payload()`` for
  large fields like formula renders).

Resolution order
----------------

The catalog inspects three locations, first-hit wins:

1. ``METAPHYSICA_OUT`` env var (set by :func:`metaphysica.build`).
2. ``./AutoGenerated/`` relative to the current working directory.
3. Bundled ``src/metaphysica/data/`` snapshot (always present in the
   wheel; covers quarks + curated constants + cached derivation chains).

Missing-data behaviour
----------------------

If no registry is found for a kind, that kind's entries simply do not
appear in the catalog. ``get()`` raises :class:`MetaphysicaKeyError` with
a "did you mean" hint *plus* a "no <kind> registry available — run
``metaphysica.build()`` first" advisory when applicable.

Thread-safety
-------------

The catalog is cached via a module-level singleton built on first
access. Subsequent accesses are lock-free dict reads. To force a
re-scan (e.g. after a fresh ``build()`` mid-process), call
:func:`reset_catalog`.
"""
from __future__ import annotations

import json
import os
import re
import sys
import threading
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, Iterable, List, Optional, Tuple

# Kind constants — keep stable; the public API echoes these as strings.
KIND_QUARK = "quark"
KIND_CONSTANT = "constant"
KIND_PARAMETER = "parameter"
KIND_FORMULA = "formula"
KIND_GATE = "gate"
KIND_CERTIFICATE = "certificate"
KIND_SECTION = "section"
KIND_PLOT = "plot"
KIND_DERIVATION = "derivation"
KIND_REFERENCE = "reference"
KIND_SIMULATION = "simulation"

KINDS: Tuple[str, ...] = (
    KIND_QUARK,
    KIND_CONSTANT,
    KIND_PARAMETER,
    KIND_FORMULA,
    KIND_GATE,
    KIND_CERTIFICATE,
    KIND_SECTION,
    KIND_PLOT,
    KIND_DERIVATION,
    KIND_REFERENCE,
    KIND_SIMULATION,
)

# Probe order for prefix-free name resolution: most-specific first so the
# regex-anchored kinds (gates) beat the broader text-keyed kinds.
_PROBE_ORDER: Tuple[str, ...] = (
    KIND_GATE,        # G01..G72 — regex-anchored
    KIND_QUARK,       # short alias set, low collision risk
    KIND_CONSTANT,    # curated set
    KIND_PARAMETER,   # full dotted key set
    KIND_FORMULA,     # kebab-case IDs
    KIND_SECTION,     # section-* IDs
    KIND_PLOT,        # plots-manifest IDs
    KIND_CERTIFICATE, # G##_<slug>
    KIND_DERIVATION,  # <sector>_chain
    KIND_REFERENCE,
    KIND_SIMULATION,
)


@dataclass
class EntityRef:
    """A handle to one retrievable entity in the framework."""

    kind: str
    canonical_id: str
    #: Absolute path to the source registry file or on-disk artefact.
    source: Path
    #: Parsed JSON record (eagerly populated for cheap entities).
    payload: Dict[str, Any] = field(default_factory=dict)
    #: Per-entity alternate render artefacts already on disk
    #: (e.g. PNG path for plots). Backends consult this dict by format.
    artefacts: Dict[str, Path] = field(default_factory=dict)


_LOCK = threading.Lock()
_CATALOG: Optional[Dict[str, Dict[str, EntityRef]]] = None
#: Set by :func:`metaphysica.build` after a successful build so the
#: catalog can pick up the freshest outputs even when METAPHYSICA_OUT is
#: not set in the calling shell.
_LAST_BUILD_DIR: Optional[Path] = None


def set_last_build_dir(path: Optional[Path]) -> None:
    """Record the most recent ``build(out_dir=...)`` target.

    Called by :func:`metaphysica.build` to plumb the freshly-built outputs
    through to the catalog without requiring the user to also set
    ``METAPHYSICA_OUT``. Resets the cached catalog so the next ``get()``
    call sees the new outputs.
    """
    global _LAST_BUILD_DIR
    _LAST_BUILD_DIR = Path(path).resolve() if path else None
    reset_catalog()


def reset_catalog() -> None:
    """Discard the cached catalog so the next ``get()`` rescans the disk.

    Useful in tests and notebook workflows where the user rebuilds mid-
    session.
    """
    global _CATALOG
    with _LOCK:
        _CATALOG = None


