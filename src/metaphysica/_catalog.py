def _candidate_dirs() -> List[Path]:
    """Return the ordered list of dirs to search for AutoGenerated outputs.

    Each entry, if it exists, is a directory whose ``AutoGenerated/``
    subdir is scanned.
    """
    out: List[Path] = []
    if _LAST_BUILD_DIR is not None and _LAST_BUILD_DIR.exists():
        out.append(_LAST_BUILD_DIR)
    env = os.environ.get("METAPHYSICA_OUT")
    if env:
        p = Path(env)
        if p.exists() and p not in out:
            out.append(p)
    cwd = Path.cwd()
    if cwd not in out and (cwd / "AutoGenerated").exists():
        out.append(cwd)
    return out


def _bundled_data_dir() -> Path:
    """Return ``src/metaphysica/data/`` next to this module.

    Always present in editable + wheel installs.
    """
    return Path(__file__).resolve().parent / "data"


def _load_json(path: Path) -> Optional[Any]:
    """Read and parse a JSON file. Return ``None`` on read/parse failure.

    The catalog tolerates missing/corrupt files at scan time so a single
    broken registry doesn't poison the whole index. Errors are routed
    through stderr (loud enough to debug but not fatal).
    """
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError) as exc:
        print(
            f"[metaphysica._catalog] WARN: failed to load {path}: "
            f"{type(exc).__name__}: {exc}",
            file=sys.stderr,
        )
        return None


def _first_existing(name: str, dirs: Iterable[Path]) -> Optional[Path]:
    """Find *name* under ``<dir>/AutoGenerated/`` across candidate dirs."""
    for d in dirs:
        candidate = d / "AutoGenerated" / name
        if candidate.exists():
            return candidate
    return None


