def _copy_static(out_dir: Path) -> None:
    """Copy bundled website templates (index.html, Pages/, css/, js/) into out_dir."""
    from metaphysica.website import copy_static
    copy_static(out_dir)


def _run(label: str, cmd: List[str], cwd: Path) -> float:
    print(f"\n=== {label} ===")
    if cmd == ["__copy_static__"]:
        print(f"$ python -c 'metaphysica.website.copy_static({cwd!s})'")
        t0 = time.perf_counter()
        _copy_static(cwd)
        return time.perf_counter() - t0
    # Plain-script steps (e.g. dev-time auditors under repo-root scripts/):
    # if the script doesn't exist (likely because this build is running
    # from an installed wheel rather than the source tree), skip cleanly.
    if len(cmd) >= 2 and cmd[1].endswith(".py") and not Path(cmd[1]).exists():
        print(f"  - {label}: SKIPPED (source-only script not present at {cmd[1]})")
        return 0.0
    print(f"$ {' '.join(cmd)}")
    t0 = time.perf_counter()
    # Generators / sims discover the output directory via the METAPHYSICA_OUT
    # env var. cwd is set to out_dir so any legacy `Path("AutoGenerated/...")`
    # references resolve into the right place.
    env = os.environ.copy()
    env["METAPHYSICA_OUT"] = str(cwd)
    # Force UTF-8 stdio so subprocess prints with Unicode arrows ('→'),
    # mathematical glyphs (e.g. 'θ', 'σ'), etc. do not crash on Windows
    # consoles whose default cp1252 codepage can't encode them. Falsification
    # oracle + several validation modules hit this previously.
    env.setdefault("PYTHONIOENCODING", "utf-8")
    subprocess.run(cmd, cwd=cwd, env=env, check=True)
    return time.perf_counter() - t0


def build(
    out_dir: Optional[Path] = None,
    *,
    fast: bool = False,
    skip_sims: bool = False,
    only: Optional[str] = None,
    hq_pdf: bool = False,
) -> int:
    """Run the full simulation + generation pipeline into *out_dir*.

    Returns 0 on success, the failing step's exit code on failure.
    """
    out_dir = Path(out_dir or Path.cwd()).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "AutoGenerated").mkdir(parents=True, exist_ok=True)

    selected = []
    opt_in_flags = {"hq_pdf": hq_pdf}
    _sims_available = _optional_deps_available(
        OPTIONAL_DEPS["Run all simulations"][1]
    )
    for label, cmd, is_extra in STEPS:
        if only:
            if only.lower() not in label.lower():
                continue
        else:
            if skip_sims and label == "Run all simulations":
                continue
            if fast and is_extra:
                continue
            # Opt-in-only steps (e.g. the playwright HQ PDF) are skipped
            # unless their flag is set, even when --fast is off.
            if label in HQ_ONLY and not opt_in_flags.get(HQ_ONLY[label], False):
                continue
        # Skip steps whose optional deps are not installed.
        if label in OPTIONAL_DEPS:
            extra, modules = OPTIONAL_DEPS[label]
            if not _optional_deps_available(modules):
                print(f"  - {label}: SKIPPED (install with `pip install metaphysica[{extra}]`)")
                continue
        # And skip anything that CONSUMES the simulation output when the step
        # producing it was itself skipped. A missing optional extra should
        # yield an incomplete build, never a failed one.
        if not _sims_available and label not in STANDALONE_STEPS:
            print(f"  - {label}: SKIPPED (needs simulation output; "
                  f"install with `pip install metaphysica[sims]`)")
            continue
        selected.append((label, cmd))

    if not selected:
        print("No build steps selected.")
        return 1

    print(f"Build plan: {len(selected)} step(s) -> {out_dir}")
    for label, _ in selected:
        print(f"  - {label}")

    timings = []
    overall = time.perf_counter()
    for label, cmd in selected:
        try:
            elapsed = _run(label, cmd, out_dir)
            timings.append((label, elapsed, "OK"))
        except subprocess.CalledProcessError as exc:
            if label in NON_FATAL:
                timings.append((label, 0.0, f"WARN ({exc.returncode})"))
                print(f"\n*** {label} exited with code {exc.returncode} "
                      "(non-fatal — output may still be partially written)")
                continue
            timings.append((label, 0.0, f"FAILED ({exc.returncode})"))
            print(f"\n*** Build halted: {label} exited with code {exc.returncode}")
            _summarise(timings, time.perf_counter() - overall)
            return exc.returncode
        except Exception as exc:
            timings.append((label, 0.0, "FAILED"))
            print(f"\n*** Build halted: {label} raised {type(exc).__name__}: {exc}")
            _summarise(timings, time.perf_counter() - overall)
            return 1

    _summarise(timings, time.perf_counter() - overall)
    print(f"\nBuild complete. Open {out_dir / 'index.html'} or `cd {out_dir} && python -m http.server 8000`.")
    return 0


def _summarise(timings, total: float) -> None:
    print("\n--- Build summary ---")
    for label, elapsed, status in timings:
        print(f"  {status:14s}  {elapsed:7.1f}s   {label}")
    print(f"  {'TOTAL':14s}  {total:7.1f}s")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="metaphysica-build: regenerate the full static website",
    )
    parser.add_argument("--out", type=Path, default=None,
                        help="output directory (default: current working directory)")
    parser.add_argument("--fast", action="store_true",
                        help="skip plot regeneration")
    parser.add_argument("--skip-sims", action="store_true",
                        help="skip the simulation run; only refresh downstream generators")
    parser.add_argument("--only", metavar="STEP",
                        help="run only the step whose label contains STEP (case-insensitive substring match)")
    parser.add_argument("--hq-pdf", action="store_true", dest="hq_pdf",
                        help="also generate the high-quality playwright-rendered PDF "
                             "(opt-in: ~5min full render, captures MathJax / JS output)")
    args = parser.parse_args()
    return build(out_dir=args.out, fast=args.fast,
                 skip_sims=args.skip_sims, only=args.only,
                 hq_pdf=args.hq_pdf)


if __name__ == "__main__":
    sys.exit(main())
