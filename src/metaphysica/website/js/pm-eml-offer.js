/**
 * pm-eml-offer.js - one answer to "may this formula show an EML control?"
 *
 * A formula is offered only when eml_trees.json holds a tree for its id and
 * eml_offer_policy.json (formulas.withheld) does not list it. Both files are
 * produced by generators/generate_eml_trees.py from one rule set.
 *
 *   PMEmlOffer.ready            Promise, resolves once both files are read
 *   PMEmlOffer.isOffered(id)    boolean; false until ready, when withheld or no tree
 *   PMEmlOffer.reason(id)       withhold reason string or null
 *   PMEmlOffer.tree(id)         the {p, c, x} entry or null
 *   PMEmlOffer.applyTo(root)    hide EML toggles/blocks on [data-eml-id] scopes
 *
 * Classic script, no dependencies. Paths resolve from this script's URL.
 */
(function (global) {
    'use strict';

    var base = (function () {
        var cs = document.currentScript;
        var src = cs && cs.src ? cs.src : global.location.href;
        return new URL('../AutoGenerated/', src).href;
    })();

    var trees = {};
    var withheld = {};
    var loaded = false;

    /** Fetch one JSON file; resolves to null (and logs info) when unavailable. */
    function getJson(name) {
        return fetch(base + name).then(function (r) {
            if (!r.ok) throw new Error(name + ' HTTP ' + r.status);
            return r.json();
        }).catch(function (e) {
            console.info('[pm-eml-offer] ' + e.message);
            return null;
        });
    }

    var ready = Promise.all([getJson('eml_trees.json'), getJson('eml_offer_policy.json')])
        .then(function (res) {
            var t = res[0], p = res[1];
            trees = (t && t.f) ? t.f : {};
            withheld = (p && p.formulas && p.formulas.withheld) ? p.formulas.withheld : {};
            loaded = true;
            return api;
        });

    /** Withhold reason for a formula id, or null. */
    function reason(id) {
        return Object.prototype.hasOwnProperty.call(withheld, id) ? withheld[id] : null;
    }

    /** The tree entry for an id, or null. */
    function tree(id) {
        return Object.prototype.hasOwnProperty.call(trees, id) ? trees[id] : null;
    }

    /** True when an EML control may be drawn for this formula id. */
    function isOffered(id) {
        return loaded && !!id && reason(id) === null && tree(id) !== null;
    }

    /** Remove the EML toggle button and EML block from one scope. */
    function suppress(scope) {
        scope.querySelectorAll('.math-toggle-btn[data-mode="eml"]').forEach(function (b) { b.remove(); });
        scope.querySelectorAll('.math-mode-block[data-mode="eml"], .math-mode-inline[data-mode="eml"]')
            .forEach(function (b) { b.remove(); });
        scope.setAttribute('data-math-mode', 'normal');
        scope.setAttribute('data-eml-withheld', reason(scope.getAttribute('data-eml-id')) || 'no_tree');
    }

    /** Hide EML controls on every [data-eml-id] scope whose formula is not offered. */
    function applyTo(root) {
        (root || document).querySelectorAll('[data-eml-id]').forEach(function (scope) {
            if (!isOffered(scope.getAttribute('data-eml-id'))) suppress(scope);
        });
    }

    var api = { ready: ready, isOffered: isOffered, reason: reason, tree: tree, applyTo: applyTo };
    global.PMEmlOffer = api;
    ready.then(function () { applyTo(document); });
})(window);
