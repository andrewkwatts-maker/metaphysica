"""Bundled static website templates (index.html, Pages/, css/, js/).

Use :func:`copy_static` to materialise the bundled files into an output
directory — the rest of :mod:`metaphysica.build` then drops the
generated JSON / JS data files alongside them.
"""
from __future__ import annotations

import shutil
from pathlib import Path

# The bundled static files live next to this __init__.py inside the wheel /
# editable install. Editable installs and most wheel installs both expose
# them as real on-disk files, so a plain shutil.copytree works.
_HERE = Path(__file__).resolve().parent

_BUNDLED = (
    "index.html",
    "Pages",
    "css",
    "js",
    "components",
    "foundations",
    "images",         # static SVGs/diagrams referenced by paper pages
    "AutoGenerated",  # ships static images bundled under AutoGenerated/images/;
                      # generators write their JSON outputs into the same dir
                      # at build time (overlay, not replace).
)


def copy_static(out_dir: Path | str) -> None:
    """Copy every bundled static file into *out_dir*, preserving layout.

    Existing files at the destination are overwritten. Missing
    intermediate directories are created.
    """
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in _BUNDLED:
        src = _HERE / name
        if not src.exists():
            continue
        dst = out_dir / name
        if src.is_file():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        else:
            shutil.copytree(src, dst, dirs_exist_ok=True)


def bundled_root() -> Path:
    """Return the on-disk root of the bundled static templates."""
    return _HERE


__all__ = ["copy_static", "bundled_root"]
