#!/usr/bin/env bash
# Pre-commit hook for the PrincipiaMetaphysica output repository.
#
# The output repo's working tree is regenerated on every
# `metaphysica.build(out_dir='.')` call. Edits to OUTPUT_PATHS are lost on
# the next build, so this hook refuses commits that touch OUTPUT files
# unless `--no-verify` is passed (a documented escape hatch).
#
# Install (from PrincipiaMetaphysica repo root):
#     cp $(python -c "import metaphysica.scripts; print(metaphysica.scripts.__path__[0])")/pre-commit-output-repo.sh .git/hooks/pre-commit
#     chmod +x .git/hooks/pre-commit
#
# Or, more robustly, drop this file at .git/hooks/pre-commit and adjust
# OUTPUT paths below if needed.

set -euo pipefail

# SOURCE paths — always allowed.
SOURCE_REGEX='^(README\.md|LICENSE|CNAME|_redirects|\.gitignore|\.gitattributes|CLAUDE\.md|build\.bat|build\.py|\.github/)'

# OUTPUT paths — refused unless --no-verify.
OUTPUT_REGEX='^(index\.html|Pages/|css/|js/|components/|foundations/|images/|AutoGenerated/)'

# Discover staged files (added, modified, copied, renamed).
staged=$(git diff --cached --name-only --diff-filter=ACMR || true)

if [[ -z "${staged}" ]]; then
    exit 0
fi

bad=()
while IFS= read -r path; do
    # Source files are fine.
    if [[ "${path}" =~ ${SOURCE_REGEX} ]]; then
        continue
    fi
    # Output files are not.
    if [[ "${path}" =~ ${OUTPUT_REGEX} ]]; then
        bad+=("${path}")
    fi
done <<< "${staged}"

if [[ ${#bad[@]} -gt 0 ]]; then
    echo "ERROR: refusing commit — these paths are regenerated by"
    echo "       \`metaphysica.build()\` and your edits will be wiped on next build:"
    echo
    for p in "${bad[@]}"; do
        echo "       ${p}"
    done
    echo
    echo "If you really need to commit (e.g. emergency hot-fix the lib will"
    echo "later subsume), pass --no-verify. Otherwise patch the change into"
    echo "the metaphysica lib instead."
    exit 1
fi

exit 0
