def _parse_args(argv: Optional[List[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Compare a fresh metaphysica.build() output directory against the "
            "pre-refactor-v24.2 baseline of PrincipiaMetaphysica. Writes a JSON "
            "report and exits 0/1/2 for CI."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Exit codes:\n"
            "  0 = clean (no critical regression)\n"
            "  1 = critical regression (missing files, plots, pages,\n"
            "      or undersized paper PDF)\n"
            "  2 = setup error (bad CLI args, git archive failed, etc.)\n"
        ),
    )
    parser.add_argument(
        "--baseline-tag",
        required=True,
        help="git tag to extract from the baseline repo (e.g. pre-refactor-v24.2)",
    )
    parser.add_argument(
        "--baseline-repo",
        required=True,
        type=Path,
        help="path to the legacy PrincipiaMetaphysica git repo",
    )
    parser.add_argument(
        "--candidate",
        required=True,
        type=Path,
        help="path to a freshly-built metaphysica output directory",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=Path(__file__).with_name(DEFAULT_REPORT_NAME),
        help=(
            "where to write the machine-readable JSON report "
            "(default: scripts/_audit_output_parity.json)"
        ),
    )
    parser.add_argument(
        "--keep-baseline",
        action="store_true",
        help="do not delete the extracted baseline tempdir (for debugging)",
    )
    return parser.parse_args(argv)


def main(argv: Optional[List[str]] = None) -> int:
    try:
        args = _parse_args(argv)
    except SystemExit as exc:
        # argparse already printed the message; treat parse errors as setup.
        return 2 if exc.code not in (0, None) else int(exc.code or 0)

    candidate_root: Path = args.candidate.resolve()
    if not candidate_root.exists():
        _err(f"candidate directory does not exist: {candidate_root}")
        return 2

    # 1) Materialize baseline into a tempdir.
    tmp = tempfile.mkdtemp(prefix="audit_parity_")
    baseline_root = Path(tmp)
    _info(f"extracting baseline '{args.baseline_tag}' from {args.baseline_repo}")
    _info(f"  -> {baseline_root}")
    try:
        materialize_baseline(args.baseline_repo.resolve(), args.baseline_tag, baseline_root)
    except Exception as exc:
        _err(str(exc))
        return 2

    # 2) Run all checks.
    b_files = _filter_interesting(_walk_relative(baseline_root))
    c_files = _filter_interesting(_walk_relative(candidate_root))
    missing_files, extra_files = diff_file_existence(b_files, c_files)
    shared = b_files & c_files

    json_findings = diff_json_files(baseline_root, candidate_root, shared)
    pdf_finding = diff_paper_pdf(baseline_root, candidate_root)
    missing_plots, extra_plots = diff_plots(baseline_root, candidate_root)
    missing_pages = diff_pages(baseline_root, candidate_root)

    # 3) Decide exit code.
    critical_sections: List[str] = []
    if missing_files:
        critical_sections.append("missing_files")
    if pdf_finding.get("flag"):
        critical_sections.append("pdf")
    if missing_plots:
        critical_sections.append("missing_plots")
    if missing_pages:
        critical_sections.append("missing_pages")

    exit_code = 1 if critical_sections else 0
    verdict = (
        "CRITICAL REGRESSION ({} section(s))".format(len(critical_sections))
        if critical_sections
        else "CLEAN"
    )

    report: Dict[str, object] = {
        "baseline_tag": args.baseline_tag,
        "baseline_repo": str(args.baseline_repo.resolve()),
        "candidate": str(candidate_root),
        "baseline_extracted_to": str(baseline_root),
        "missing_files": missing_files,
        "extra_files": extra_files,
        "json_findings": json_findings,
        "pdf": pdf_finding,
        "missing_plots": missing_plots,
        "extra_plots": extra_plots,
        "missing_pages": missing_pages,
        "critical_sections": critical_sections,
        "verdict": verdict,
        "exit_code": exit_code,
    }

    # 4) Write JSON report.
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(
        json.dumps(report, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    _info(f"wrote machine-readable report -> {args.report}")

    # 5) Print summary and (optionally) clean up.
    _print_summary(report)

    if not args.keep_baseline:
        # Best-effort cleanup; do not fail the audit on tempdir issues.
        try:
            import shutil
            shutil.rmtree(baseline_root, ignore_errors=True)
        except Exception:
            pass

    return exit_code


if __name__ == "__main__":
    raise SystemExit(main())
