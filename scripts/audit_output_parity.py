def _print_summary(report: Dict[str, object]) -> None:
    """Pretty-print the human-readable summary; ASCII only."""
    print("=" * 72)
    print(" metaphysica output-parity audit")
    print("=" * 72)
    print(f" baseline tag    : {report['baseline_tag']}")
    print(f" baseline repo   : {report['baseline_repo']}")
    print(f" candidate root  : {report['candidate']}")
    print()

    def _safe(s: object) -> str:
        # Lossy ASCII coercion for non-ASCII paths so Windows cp1252 stdout
        # never crashes the audit. Replacement happens only at print time;
        # the JSON report retains full Unicode.
        return str(s).encode("ascii", errors="replace").decode("ascii")

    # 1. File existence
    missing = report["missing_files"]  # type: ignore[index]
    extra = report["extra_files"]  # type: ignore[index]
    print(f"[1] File-existence diff")
    print(f"    missing from candidate (CRITICAL): {len(missing)}")
    for p in list(missing)[:20]:
        print(f"        - {_safe(p)}")
    if len(missing) > 20:
        print(f"        ... ({len(missing) - 20} more, see JSON report)")
    print(f"    extra in candidate (info)       : {len(extra)}")
    for p in list(extra)[:5]:
        print(f"        + {_safe(p)}")
    if len(extra) > 5:
        print(f"        ... ({len(extra) - 5} more)")
    print()

    # 2. JSON diff
    json_findings = report["json_findings"]  # type: ignore[index]
    flagged_json = [f for f in json_findings if f.get("flag")]
    print(f"[2] JSON byte/key diff")
    print(f"    shared JSONs with notable changes: {len(json_findings)}")
    print(f"    flagged (size drop >5% or missing keys): {len(flagged_json)}")
    for f in flagged_json[:10]:
        dp = f.get("delta_pct")
        missing_keys = f.get("missing_top_level_keys") or []
        bits = []
        if dp is not None:
            bits.append(f"delta={dp}%")
        if missing_keys:
            bits.append(f"missing_keys={missing_keys[:3]}")
        print(f"        ! {f['file']}  ({', '.join(bits) or 'see report'})")
    if len(flagged_json) > 10:
        print(f"        ... ({len(flagged_json) - 10} more, see JSON report)")
    print()

    # 3. PDF
    pdf = report["pdf"]  # type: ignore[index]
    print(f"[3] PDF page-count diff")
    if pdf.get("baseline_pages") is not None:
        print(
            f"    baseline pages : {pdf['baseline_pages']} "
            f"({pdf.get('baseline_path')})"
        )
    if pdf.get("candidate_pages") is not None:
        print(
            f"    candidate pages: {pdf['candidate_pages']} "
            f"({pdf.get('candidate_path')})"
        )
    if pdf.get("delta_pages") is not None:
        print(f"    delta_pages    : {pdf['delta_pages']}")
    if pdf.get("note"):
        print(f"    note           : {pdf['note']}")
    print(f"    flag           : {pdf.get('flag')}")
    print()

    # 4. Plots
    missing_plots = report["missing_plots"]  # type: ignore[index]
    extra_plots = report["extra_plots"]  # type: ignore[index]
    print(f"[4] Plots diff (AutoGenerated/plots/)")
    print(f"    missing from candidate: {len(missing_plots)}")
    for p in list(missing_plots)[:10]:
        print(f"        - {p}")
    if len(missing_plots) > 10:
        print(f"        ... ({len(missing_plots) - 10} more)")
    print(f"    extra in candidate    : {len(extra_plots)}")
    print()

    # 5. Pages
    missing_pages = report["missing_pages"]  # type: ignore[index]
    print(f"[5] Page diff (Pages/*.html)")
    print(f"    missing from candidate: {len(missing_pages)}")
    for p in missing_pages:
        print(f"        - {p}")
    print()

    # Verdict
    print("-" * 72)
    print(f" verdict   : {report['verdict']}")
    print(f" exit code : {report['exit_code']}")
    print("=" * 72)


