#!/usr/bin/env python3
"""Audit output parity between a fresh ``metaphysica.build()`` directory and a
git-archived baseline of the legacy PrincipiaMetaphysica static site.

Used by Sprint 1 of the metaphysica refactor (see
``C:/Users/Andrew/.claude/plans/ensure-all-simulation-and-greedy-nygaard.md``)
and by CI to detect regressions in the public-facing build output.

CLI
---
    python scripts/audit_output_parity.py \
        --baseline-tag pre-refactor-v24.2 \
        --baseline-repo h:/Github/PrincipiaMetaphysica \
        --candidate /tmp/final_e2e

What it checks
--------------
1. **File-existence diff** - files in baseline missing from candidate (CRITICAL)
   and files in candidate not in baseline (informational).
2. **JSON byte/key diff** - for every ``*.json`` file shared between both,
   compare sizes and top-level key sets. Flag any byte-size drop > 5%.
3. **PDF page-count diff** - ``Principia_Metaphysica_v24.1_Paper.pdf`` (baseline)
   vs ``Principia_Metaphysica_Paper.pdf`` (candidate). Flag if candidate has
   fewer than 200 pages.
4. **Plots diff** - list missing PNG/PDF files under ``AutoGenerated/plots/``.
5. **Page diff** - every ``Pages/*.html`` should exist in both.

Exit codes
----------
* 0 - clean (no critical regressions)
* 1 - critical regression (anything from sections 1, 3, 4, 5; section 2 is
      informational unless the file is missing, which lands in section 1)
* 2 - setup error (bad CLI args, missing baseline tag, broken tar stream, etc.)

The full report is written to ``scripts/_audit_output_parity.json`` for CI
consumption; a pretty human summary is printed to stdout. All output is
Unicode-free so it survives cp1252 Windows consoles.
"""
from __future__ import annotations

import argparse
import io
import json
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path
from typing import Dict, List, Optional, Set, Tuple

# ----------------------------------------------------------------------------
# Constants
# ----------------------------------------------------------------------------

#: Drop in raw byte size that we consider a regression for JSON files.
JSON_SIZE_DROP_THRESHOLD = 0.05  # 5%

#: Minimum acceptable page count for the candidate paper PDF.
MIN_PAPER_PAGES = 200

#: Baseline vs candidate paper filenames.
BASELINE_PAPER = "Principia_Metaphysica_v24.1_Paper.pdf"
CANDIDATE_PAPER_LOCATIONS = (
    "Principia_Metaphysica_Paper.pdf",
    "AutoGenerated/Principia_Metaphysica_Paper.pdf",
)

#: Path prefixes we care about when comparing.
INTERESTING_PREFIXES = (
    "AutoGenerated/",
    "Pages/",
    "index.html",
    "css/",
    "js/",
    BASELINE_PAPER,
)

#: Where the JSON report is written (relative to this script).
DEFAULT_REPORT_NAME = "_audit_output_parity.json"


# ----------------------------------------------------------------------------
# Setup helpers
# ----------------------------------------------------------------------------


def _err(msg: str) -> None:
    """Write a setup-error message to stderr without using emoji or accents."""
    sys.stderr.write(f"[audit_output_parity] ERROR: {msg}\n")


def _info(msg: str) -> None:
    sys.stdout.write(f"[audit_output_parity] {msg}\n")


def materialize_baseline(repo: Path, tag: str, dest: Path) -> None:
    """Run ``git archive <tag>`` from *repo* and extract the tarball into *dest*.

    Uses ``subprocess`` + Python's ``tarfile`` module so we do not need ``tar``
    on the PATH (Windows shells often do, but we keep the dependency surface
    minimal).
    """
    if not repo.exists():
        raise FileNotFoundError(f"baseline repo not found: {repo}")
    dest.mkdir(parents=True, exist_ok=True)

    cmd = ["git", "-C", str(repo), "archive", "--format=tar", tag]
    try:
        proc = subprocess.run(cmd, capture_output=True, check=True)
    except FileNotFoundError as exc:
        raise RuntimeError("'git' executable not found on PATH") from exc
    except subprocess.CalledProcessError as exc:
        stderr = exc.stderr.decode("utf-8", errors="replace").strip()
        raise RuntimeError(
            f"git archive failed for tag '{tag}' in {repo}: {stderr}"
        ) from exc

    buf = io.BytesIO(proc.stdout)
    with tarfile.open(fileobj=buf, mode="r:") as tar:
        # Python 3.12+ requires an explicit filter; 'data' is the safe one.
        try:
            tar.extractall(dest, filter="data")  # type: ignore[arg-type]
        except TypeError:
            tar.extractall(dest)  # pragma: no cover - old Pythons


# ----------------------------------------------------------------------------
# File walking
# ----------------------------------------------------------------------------


def _walk_relative(root: Path) -> Set[str]:
    """Return every file path under *root* as a POSIX-style relative string."""
    files: Set[str] = set()
    if not root.exists():
        return files
    for p in root.rglob("*"):
        if p.is_file():
            rel = p.relative_to(root).as_posix()
            files.add(rel)
    return files


def _filter_interesting(paths: Set[str]) -> Set[str]:
    """Keep only paths under prefixes we audit (AutoGenerated/, Pages/, ...)."""
    return {p for p in paths if p.startswith(INTERESTING_PREFIXES)}


# ----------------------------------------------------------------------------
# Individual diff checks
# ----------------------------------------------------------------------------


def diff_file_existence(
    baseline: Set[str], candidate: Set[str]
) -> Tuple[List[str], List[str]]:
    """Return (missing_from_candidate, extra_in_candidate) sorted lists."""
    missing = sorted(p for p in baseline if p not in candidate)
    extra = sorted(p for p in candidate if p not in baseline)
    return missing, extra


def diff_json_files(
    baseline_root: Path, candidate_root: Path, shared: Set[str]
) -> List[Dict[str, object]]:
    """For each shared ``*.json`` file, compare byte size and top-level keys.

    Returns a list of finding dicts with raw numbers plus a ``flag`` boolean.
    """
    findings: List[Dict[str, object]] = []
    for rel in sorted(shared):
        if not rel.endswith(".json"):
            continue
        b_path = baseline_root / rel
        c_path = candidate_root / rel
        try:
            b_size = b_path.stat().st_size
            c_size = c_path.stat().st_size
        except OSError as exc:
            findings.append(
                {
                    "file": rel,
                    "error": f"stat failed: {exc}",
                    "flag": True,
                }
            )
            continue

        size_delta = c_size - b_size
        # Avoid div-by-zero on empty baseline files.
        size_pct = (size_delta / b_size) if b_size else 0.0
        flag_size = size_pct < -JSON_SIZE_DROP_THRESHOLD

        b_keys = _safe_top_level_keys(b_path)
        c_keys = _safe_top_level_keys(c_path)

        missing_keys: List[str] = []
        extra_keys: List[str] = []
        if b_keys is not None and c_keys is not None:
            missing_keys = sorted(b_keys - c_keys)
            extra_keys = sorted(c_keys - b_keys)
        flag_keys = bool(missing_keys)

        flag = flag_size or flag_keys
        if not flag and not missing_keys and not extra_keys and size_delta == 0:
            # Identical; skip from the findings list to keep output sane.
            continue

        findings.append(
            {
                "file": rel,
                "baseline_bytes": b_size,
                "candidate_bytes": c_size,
                "delta_bytes": size_delta,
                "delta_pct": round(size_pct * 100, 2),
                "missing_top_level_keys": missing_keys,
                "extra_top_level_keys": extra_keys,
                "flag": flag,
            }
        )
    return findings


def _safe_top_level_keys(path: Path) -> Optional[Set[str]]:
    """Return top-level dict keys, or None if file is not a JSON object."""
    try:
        with path.open("r", encoding="utf-8") as fh:
            data = json.load(fh)
    except (json.JSONDecodeError, OSError, UnicodeDecodeError):
        return None
    if isinstance(data, dict):
        return set(data.keys())
    return set()  # JSON array or scalar -> no top-level keys to diff


def diff_paper_pdf(
    baseline_root: Path, candidate_root: Path
) -> Dict[str, object]:
    """Compare paper PDF page counts.

    Looks for the baseline at its known location and the candidate at either
    of the known candidate locations.
    """
    result: Dict[str, object] = {
        "baseline_path": None,
        "candidate_path": None,
        "baseline_pages": None,
        "candidate_pages": None,
        "delta_pages": None,
        "flag": False,
        "note": "",
    }

    b_pdf = baseline_root / BASELINE_PAPER
    if not b_pdf.exists():
        result["note"] = "baseline paper PDF not found"
        result["flag"] = True
        return result
    result["baseline_path"] = BASELINE_PAPER

    c_pdf: Optional[Path] = None
    for rel in CANDIDATE_PAPER_LOCATIONS:
        candidate_pdf = candidate_root / rel
        if candidate_pdf.exists():
            c_pdf = candidate_pdf
            result["candidate_path"] = rel
            break
    if c_pdf is None:
        result["note"] = (
            "candidate paper PDF not found in any expected location: "
            + ", ".join(CANDIDATE_PAPER_LOCATIONS)
        )
        result["flag"] = True
        return result

    try:
        from pypdf import PdfReader  # type: ignore[import-not-found]
    except ImportError as exc:
        result["note"] = f"pypdf import failed: {exc}"
        result["flag"] = True
        return result

    try:
        b_pages = len(PdfReader(str(b_pdf)).pages)
        c_pages = len(PdfReader(str(c_pdf)).pages)
    except Exception as exc:  # pypdf raises a variety of exceptions
        result["note"] = f"pypdf failed to read a PDF: {exc}"
        result["flag"] = True
        return result

    result["baseline_pages"] = b_pages
    result["candidate_pages"] = c_pages
    result["delta_pages"] = c_pages - b_pages
    if c_pages < MIN_PAPER_PAGES:
        result["flag"] = True
        result["note"] = (
            f"candidate has {c_pages} pages, below the {MIN_PAPER_PAGES}-page floor"
        )
    return result


def diff_plots(
    baseline_root: Path, candidate_root: Path
) -> Tuple[List[str], List[str]]:
    """List missing plot artefacts under ``AutoGenerated/plots/``."""
    def _plots(root: Path) -> Set[str]:
        plot_dir = root / "AutoGenerated" / "plots"
        if not plot_dir.exists():
            return set()
        return {
            p.relative_to(root).as_posix()
            for p in plot_dir.rglob("*")
            if p.is_file() and p.suffix.lower() in {".png", ".pdf"}
        }

    b_plots = _plots(baseline_root)
    c_plots = _plots(candidate_root)
    missing = sorted(b_plots - c_plots)
    extra = sorted(c_plots - b_plots)
    return missing, extra


def diff_pages(
    baseline_root: Path, candidate_root: Path
) -> List[str]:
    """Every ``Pages/*.html`` in the baseline must exist in the candidate."""
    def _pages(root: Path) -> Set[str]:
        pages_dir = root / "Pages"
        if not pages_dir.exists():
            return set()
        return {
            p.relative_to(root).as_posix()
            for p in pages_dir.glob("*.html")
            if p.is_file()
        }

    b_pages = _pages(baseline_root)
    c_pages = _pages(candidate_root)
    return sorted(b_pages - c_pages)


