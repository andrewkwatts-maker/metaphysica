def load_json(path: Path):
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def first_existing(fids, formulas):
    for fid in fids:
        if fid in formulas:
            return fid
    return None


def truncate(s, n=120):
    if s is None:
        return ""
    s = str(s)
    if len(s) <= n:
        return s
    return s[: n - 1] + "…"


def has_arithma(entry):
    """Arithma track present if either compact or LaTeX is non-empty."""
    return bool((entry.get("arithma_latex") or "").strip()
                or (entry.get("arithma_compact") or "") not in ("", None))


def has_eml(entry):
    return bool((entry.get("eml_latex") or "").strip()
                or (entry.get("eml_tree_compact") or "").strip()
                or (entry.get("eml_tree_str") or "").strip())


def get_value(entry):
    """Return numeric value if present and finite, else None."""
    v = entry.get("value", None)
    if v is None:
        return None
    try:
        f = float(v)
        return f
    except (TypeError, ValueError):
        return None


def is_sentinel(entry):
    v = get_value(entry)
    return v is not None and v == 0.0


def is_triple_tracked(entry):
    """Strict: Arithma + EML + non-sentinel numeric value."""
    v = get_value(entry)
    return has_arithma(entry) and has_eml(entry) and v is not None and v != 0.0


def is_eml_value_only(entry):
    """EML + value present, Arithma stub (empty/null)."""
    v = get_value(entry)
    return (not has_arithma(entry)) and has_eml(entry) and v is not None and v != 0.0


def sector_for(fid, audit_pf):
    """Derive sector from audit's module path; fallback 'unknown'."""
    rec = audit_pf.get(fid)
    if not rec:
        return "unknown"
    mod = rec.get("module", "") or ""
    parts = mod.split(".")
    # metaphysica.simulations.PM.<sector>.<file>
    return parts[3] if len(parts) > 3 else "unknown"


def build_per_sector(formulas, audit_pf, chains):
    sectors = {}
    for fid, entry in formulas.items():
        sec = sector_for(fid, audit_pf)
        s = sectors.setdefault(sec, {
            "total": 0, "triple": 0, "eml_value": 0,
            "sentinel": 0, "b3_rooted": 0,
        })
        s["total"] += 1
        if is_triple_tracked(entry):
            s["triple"] += 1
        if is_eml_value_only(entry):
            s["eml_value"] += 1
        if is_sentinel(entry):
            s["sentinel"] += 1
        chain = chains.get(fid)
        if chain and chain.get("b3_rooted"):
            s["b3_rooted"] += 1
    return sectors


def find_param_row(ledger_rows_by_name, name):
    return ledger_rows_by_name.get(name)


def main():
    formulas_doc = load_json(FORMULAS)
    formulas = formulas_doc["formulas"]
    ledger = load_json(LEDGER)
    audit = load_json(AUDIT)
    audit_pf = audit.get("per_formula", {})

    dep_path = DEP_LOCAL if DEP_LOCAL.exists() else DEP_PM
    chains_doc = load_json(dep_path)
    chains = chains_doc.get("chains", {})

    # totals
    total = len(formulas)
    triple_count = sum(1 for e in formulas.values() if is_triple_tracked(e))
    eml_value_count = sum(1 for e in formulas.values() if is_eml_value_only(e))
    sentinel_count = sum(1 for e in formulas.values() if is_sentinel(e))
    has_eml_count = sum(1 for e in formulas.values() if has_eml(e))
    has_arithma_count = sum(1 for e in formulas.values() if has_arithma(e))
    has_value_count = sum(1 for e in formulas.values()
                          if get_value(e) is not None and get_value(e) != 0.0)

    # sector breakdown
    sectors = build_per_sector(formulas, audit_pf, chains)

    # b3 totals from dep chains
    b3_rooted_total = chains_doc.get("b3_rooted_count")
    non_b3_total = chains_doc.get("non_b3_rooted_count")
    ambiguous_total = chains_doc.get("ambiguous_count")

    # marquee
    ledger_rows = {r["parameter"]: r for r in ledger.get("rows", [])}
    marquee_records = []
    for label, candidates, param in MARQUEE_SPEC:
        fid = first_existing(candidates, formulas)
        if fid is None:
            marquee_records.append({
                "marquee": label,
                "fid": None,
                "entry": None,
                "param": param,
                "param_row": ledger_rows.get(param),
                "chain": None,
            })
            continue
        marquee_records.append({
            "marquee": label,
            "fid": fid,
            "entry": formulas[fid],
            "param": param,
            "param_row": ledger_rows.get(param),
            "chain": chains.get(fid),
        })

    today = date.today().isoformat()

    # ---- emit markdown ----
    lines = []
    lines.append("# Triple-Track Inventory")
    lines.append("")
    lines.append(f"**Date**: {today}  ")
    lines.append(f"**Total formulas**: {total}  ")
    lines.append(f"**Triple-tracked (Arithma + EML + non-zero value)**: "
                 f"{triple_count}  ")
    lines.append(f"**EML + value only (Arithma stub)**: {eml_value_count}  ")
    lines.append(f"**Sentinel-valued (value == 0)**: {sentinel_count}  ")
    lines.append("")
    lines.append("## Track coverage")
    lines.append("")
    lines.append("| Track | Count | Coverage |")
    lines.append("|---|---:|---:|")
    lines.append(f"| Arithma (latex or compact) | {has_arithma_count} | "
                 f"{100.0 * has_arithma_count / total:.1f}% |")
    lines.append(f"| EML (any) | {has_eml_count} | "
                 f"{100.0 * has_eml_count / total:.1f}% |")
    lines.append(f"| Non-zero numeric value | {has_value_count} | "
                 f"{100.0 * has_value_count / total:.1f}% |")
    lines.append("")
    lines.append("## b₃-rootedness (from dependency_chains.json)")
    lines.append("")
    lines.append(f"- b₃-rooted: **{b3_rooted_total}** / "
                 f"{chains_doc.get('total_formulas', total)}")
    lines.append(f"- Ambiguous: {ambiguous_total}")
    lines.append(f"- Non-b₃-rooted: {non_b3_total}")
    lines.append(f"- Degraded walks: {chains_doc.get('degraded_walks')}")
    lines.append(f"- Arithma available at walk time: "
                 f"{chains_doc.get('arithma_available')}")
    lines.append("")
    lines.append("## By sector")
    lines.append("")
    lines.append("| Sector | Total | Triple | EML+value | Sentinel | b₃-rooted |")
    lines.append("|---|---:|---:|---:|---:|---:|")
    for sec, s in sorted(sectors.items(), key=lambda x: -x[1]["total"]):
        lines.append(f"| {sec} | {s['total']} | {s['triple']} | "
                     f"{s['eml_value']} | {s['sentinel']} | {s['b3_rooted']} |")
    # totals row
    tot_s = {k: sum(v[k] for v in sectors.values())
             for k in ("total", "triple", "eml_value", "sentinel", "b3_rooted")}
    lines.append(f"| **TOTAL** | **{tot_s['total']}** | **{tot_s['triple']}** | "
                 f"**{tot_s['eml_value']}** | **{tot_s['sentinel']}** | "
                 f"**{tot_s['b3_rooted']}** |")
    lines.append("")
    lines.append("## Marquee formulas (13 b₃-rooted derivations)")
    lines.append("")
    lines.append("For each marquee derivation: the formula ID found in "
                 "`formulas.json`, the Arithma LaTeX (if any), the EML compact "
                 "tree truncated to 120 chars, computed value, observed "
                 "comparison, and b₃-rootedness chain depth.")
    lines.append("")
    for rec in marquee_records:
        mq = rec["marquee"]
        lines.append(f"### {mq}")
        lines.append("")
        if rec["fid"] is None:
            lines.append(f"- **Formula ID**: _no matching formula in "
                         f"`formulas.json`_")
            lines.append(f"- **Parameter target**: `{rec['param']}`")
            pr = rec["param_row"]
            if pr is not None:
                lines.append(f"- **Observed parameter row**: "
                             f"status=`{pr['status']}` value="
                             f"`{pr['value']}` "
                             f"σ=`{pr.get('uncertainty')}`")
            else:
                lines.append(f"- **Observed parameter row**: _not present in "
                             f"ledger_")
            lines.append("")
            continue
        e = rec["entry"]
        lines.append(f"- **ID**: `{rec['fid']}`  (label {e.get('label','—')})")
        lines.append(f"- **Category**: `{e.get('category','—')}` · "
                     f"**triple_status**: "
                     f"`{e.get('triple_status') or '(unset)'}`")
        lines.append(f"- **Source simulation**: "
                     f"`{e.get('source_simulation','—')}`")
        # Arithma
        ar = (e.get("arithma_latex") or "").strip()
        if ar:
            lines.append(f"- **Arithma LaTeX**: `{truncate(ar, 200)}`")
        else:
            ac = e.get("arithma_compact")
            if ac:
                lines.append(f"- **Arithma compact**: `{truncate(ac, 200)}`")
            else:
                lines.append("- **Arithma**: _stub (empty)_")
        # EML compact tree truncated 120
        eml_compact = e.get("eml_tree_compact") or e.get("eml_tree_str") or ""
        if eml_compact:
            lines.append(f"- **EML compact tree (120)**: "
                         f"`{truncate(eml_compact, 120)}`")
        else:
            lines.append("- **EML**: _no tree present_")
        # value
        v = get_value(e)
        if v is None:
            lines.append("- **Computed value**: _none_")
        else:
            lines.append(f"- **Computed value**: `{v}`")
        # observed
        pr = rec["param_row"]
        if pr is not None:
            lines.append(f"- **Observed parameter** "
                         f"(`{rec['param']}`): "
                         f"value=`{pr['value']}` "
                         f"σ=`{pr.get('uncertainty')}` "
                         f"status=`{pr['status']}`")
        else:
            lines.append(f"- **Observed parameter** (`{rec['param']}`): "
                         f"_not in ledger_")
        # chain
        ch = rec["chain"]
        if ch is not None:
            rooted = "yes" if ch.get("b3_rooted") else "no"
            depth = ch.get("depth")
            path = ch.get("path", [])
            via = ch.get("via", [])
            lines.append(f"- **b₃-rooted**: {rooted} · depth={depth} · "
                         f"path: `{' -> '.join(map(str, path))}`"
                         f"{' · via ' + ','.join(map(str, via)) if via else ''}")
        else:
            lines.append("- **b₃-rooted**: _no chain entry_")
        lines.append("")

    # footer / methodology
    lines.append("---")
    lines.append("")
    lines.append("## Definitions used in this inventory")
    lines.append("")
    lines.append("- **Arithma present** ⇔ `arithma_latex` non-empty *or* "
                 "`arithma_compact` non-null.")
    lines.append("- **EML present** ⇔ any of `eml_latex`, `eml_tree_str`, "
                 "`eml_tree_compact` non-empty.")
    lines.append("- **Non-zero numeric value** ⇔ `value` is finite and "
                 "≠ 0 (the sentinel).")
    lines.append("- **Triple-tracked** ⇔ Arithma ∧ EML ∧ non-zero value.")
    lines.append("- **EML + value only** ⇔ ¬Arithma ∧ EML ∧ non-zero value.")
    lines.append("- **Sentinel-valued** ⇔ `value == 0` (placeholder pending "
                 "derivation).")
    lines.append("")
    lines.append("## Source files")
    lines.append("")
    lines.append(f"- Formulas: `{FORMULAS.as_posix()}` "
                 f"(version "
                 f"{formulas_doc.get('version','?')}, "
                 f"count {formulas_doc.get('count','?')})")
    lines.append(f"- Ledger: `{LEDGER.as_posix()}` "
                 f"(rows {len(ledger.get('rows', []))}, "
                 f"sprint {ledger.get('meta', {}).get('sprint','?')})")
    lines.append(f"- Dependency chains: `{dep_path.as_posix()}`")
    lines.append(f"- Audit: `{AUDIT.as_posix()}`")
    lines.append("")

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT}")
    print(f"  lines={len(lines)+1}, "
          f"marquee_records={len(marquee_records)}, "
          f"sectors={len(sectors)}")
    print(f"  totals: total={total} triple={triple_count} "
          f"eml_value={eml_value_count} sentinel={sentinel_count}")


if __name__ == "__main__":
    main()
