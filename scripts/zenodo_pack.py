#!/usr/bin/env python3
"""Bundle a Zenodo-ready release archive of the metaphysica framework.

Produces ``dist/metaphysica-v<VERSION>-zenodo.zip`` containing:

* Compiled wheel + sdist under ``target/wheels/`` (both metaphysica repos)
* The full generated site tree from the paired PrincipiaMetaphysica repo
  (index.html, Pages/, css/, js/, components/, foundations/, images/,
  AutoGenerated/)
* Release documents: README.md, CHANGELOG.md, LICENSE
* Zenodo metadata: .zenodo.json, CITATION.cff

Usage::

    python scripts/zenodo_pack.py                     # bundle current v2.2.0
    python scripts/zenodo_pack.py --out ./dist         # custom output dir
    python scripts/zenodo_pack.py --pm-root PATH       # override PM repo location
    python scripts/zenodo_pack.py --skip-pm            # lib-only bundle

The script is idempotent: rerunning overwrites the target ZIP. No
external services are touched; the actual Zenodo upload is a manual
user step via the Zenodo web UI or ``zenodo-cli``.

Environment variables honoured:

* ``METAPHYSICA_PM_ROOT`` — path to the PrincipiaMetaphysica repo
  (defaults to ``H:/Github/PrincipiaMetaphysica``, i.e. the standard
  sibling layout).

Standing rule: no AI attribution in commit messages or release notes.
"""
from __future__ import annotations

import argparse
import os
import sys
import zipfile
from pathlib import Path
from typing import Iterable, List


REPO_ROOT = Path(__file__).resolve().parents[1]


def _read_version(pyproject_path: Path) -> str:
    """Extract the ``version = "..."`` field from pyproject.toml."""
    for line in pyproject_path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.startswith("version"):
            _, _, rhs = s.partition("=")
            return rhs.strip().strip('"').strip("'")
    raise RuntimeError(f"No version line in {pyproject_path}")


def _default_pm_root() -> Path:
    """Where the sibling PrincipiaMetaphysica repo lives by default."""
    env = os.environ.get("METAPHYSICA_PM_ROOT")
    if env:
        return Path(env)
    # Standard sibling layout on the author's workstation.
    return Path("H:/Github/PrincipiaMetaphysica")


def _add_file(zf: zipfile.ZipFile, src: Path, arcname: str) -> None:
    """Write *src* into the zip at *arcname*, printing progress."""
    if not src.exists():
        print(f"  - SKIP (missing): {arcname}", file=sys.stderr)
        return
    zf.write(src, arcname)


def _add_dir(zf: zipfile.ZipFile, src: Path, arcname_prefix: str, *,
             excludes: Iterable[str] = ()) -> int:
    """Recursively write *src* into the zip; return files-written count.

    Paths matching any entry of *excludes* (glob-style; matched against
    the arcname) are silently skipped so ``.git``, ``.pytest_cache``,
    ``__pycache__``, etc. don't bloat the release bundle.
    """
    if not src.is_dir():
        print(f"  - SKIP (missing dir): {arcname_prefix}", file=sys.stderr)
        return 0
    excludes = tuple(excludes)
    count = 0
    for p in sorted(src.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(src)
        arc = f"{arcname_prefix}/{rel.as_posix()}"
        if any(_matches(arc, pat) for pat in excludes):
            continue
        zf.write(p, arc)
        count += 1
    return count


def _matches(path: str, pattern: str) -> bool:
    """Simple glob match (supports leading ``**/`` prefix)."""
    from fnmatch import fnmatch

    if pattern.startswith("**/"):
        pattern = pattern[3:]
    return (
        fnmatch(path, pattern)
        or fnmatch(path, f"**/{pattern}")
        or fnmatch(path, f"*/{pattern}")
    )


def _find_wheel_artefacts(lib_root: Path) -> List[Path]:
    """Return the newest wheel + sdist under ``target/wheels/``."""
    wheels_dir = lib_root / "target" / "wheels"
    if not wheels_dir.is_dir():
        return []
    return sorted(
        list(wheels_dir.glob("metaphysica-*.whl"))
        + list(wheels_dir.glob("metaphysica-*.tar.gz"))
    )


DEFAULT_EXCLUDES = (
    "**/.git/**", "**/.git/*", "**/.git",
    "**/.pytest_cache/**", "**/__pycache__/**",
    "**/.claude/**", "**/.mypy_cache/**",
    "**/*.pyc", "**/*.pyo",
    "**/AutoGenerated_full_test/**",  # historical scratch dir
    "**/dist/**",
)


def pack(*, out_dir: Path, lib_root: Path, pm_root: Path | None,
         version: str) -> Path:
    """Assemble the Zenodo bundle ZIP. Returns the written path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    zip_path = out_dir / f"metaphysica-v{version}-zenodo.zip"
    if zip_path.exists():
        zip_path.unlink()

    print(f"Building Zenodo bundle: {zip_path}")
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        # ── Metadata + release documents ──────────────────────────────
        for f in ("README.md", "CHANGELOG.md", "LICENSE", "RELEASE.md",
                  ".zenodo.json", "CITATION.cff"):
            src = lib_root / f
            if src.exists():
                _add_file(zf, src, f)

        # ── Wheel + sdist ────────────────────────────────────────────
        wheels = _find_wheel_artefacts(lib_root)
        for w in wheels:
            _add_file(zf, w, f"dist/{w.name}")
        print(f"  + wheel/sdist artefacts: {len(wheels)}")

        # ── PrincipiaMetaphysica generated site tree ────────────────
        if pm_root is not None and pm_root.is_dir():
            # Prefer the PM repo's fresher .zenodo.json + CITATION.cff
            # (they're the ones Zenodo will read).
            for f in (".zenodo.json", "CITATION.cff"):
                src = pm_root / f
                if src.exists():
                    _add_file(zf, src, f"principia_metaphysica/{f}")
            for sub in ("AutoGenerated", "Pages", "css", "js",
                        "components", "foundations", "images"):
                n = _add_dir(zf, pm_root / sub,
                             f"principia_metaphysica/{sub}",
                             excludes=DEFAULT_EXCLUDES)
                if n:
                    print(f"  + {sub}/: {n} files")
            for f in ("index.html", "README.md", "LICENSE", "CNAME",
                      "_redirects", "CHANGELOG.md"):
                src = pm_root / f
                if src.exists():
                    _add_file(zf, src, f"principia_metaphysica/{f}")

    size_mb = zip_path.stat().st_size / (1024 * 1024)
    print(f"\nDone. {zip_path} ({size_mb:.1f} MB)")
    return zip_path


def main(argv: List[str] | None = None) -> int:
    p = argparse.ArgumentParser(
        description="Bundle a Zenodo release ZIP of the metaphysica framework."
    )
    p.add_argument("--out", type=Path, default=REPO_ROOT / "dist",
                   help="Output directory (default: ./dist)")
    p.add_argument("--pm-root", type=Path, default=_default_pm_root(),
                   help="PrincipiaMetaphysica repo location")
    p.add_argument("--skip-pm", action="store_true",
                   help="Skip bundling PrincipiaMetaphysica outputs (lib-only)")
    p.add_argument("--version", type=str, default=None,
                   help="Override version string (default: read from pyproject.toml)")
    args = p.parse_args(argv)

    version = args.version or _read_version(REPO_ROOT / "pyproject.toml")
    pm_root = None if args.skip_pm else args.pm_root

    if pm_root is not None and not pm_root.exists():
        print(f"WARNING: PrincipiaMetaphysica repo not found at {pm_root}; "
              "bundling wheel + metadata only.", file=sys.stderr)
        pm_root = None

    pack(out_dir=args.out, lib_root=REPO_ROOT, pm_root=pm_root,
         version=version)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
