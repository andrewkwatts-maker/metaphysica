"""CI gate: no shadow derivations among observable groups.

A *shadow derivation* is when two or more registered parameters claim to
compute the same physical observable but produce numerically different
values. Sprint T1 surfaced three such conflicts (``n_s``, ``eta_B``,
``H0``); Sprint T4 eliminated them. This test wires the shadow detector
(``scripts/audit_shadow_derivations.py``) into the pytest suite so that
any PR which reintroduces a shadow conflict fails CI immediately.

The test runs against a *fresh* ``AutoGenerated/parameters.json`` —
regenerated by the session-scoped ``fresh_parameters_json`` fixture via
``metaphysica.build(skip_sims=False, fast=True)`` — so we are auditing
what the simulations actually produce in this commit, not a stale copy
of the JSON checked in to the repo.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parent.parent
AUDIT_SCRIPT = REPO_ROOT / "scripts" / "audit_shadow_derivations.py"
PARAMETERS_JSON = REPO_ROOT / "AutoGenerated" / "parameters.json"


@pytest.fixture(scope="session")
def fresh_parameters_json() -> Path:
    """Regenerate AutoGenerated/parameters.json from the live simulations.

    Uses ``metaphysica.build`` with ``fast=True`` so that we skip the
    expensive plot/PDF stages — the shadow auditor only needs
    ``parameters.json``, which is produced by the core sim step.

    If the build fails or the file is still missing afterward, the
    test is *skipped with a clear message* rather than passing silently,
    so an environment that can't actually run the sims (e.g. missing
    optional ``[sims]`` extras) cannot mask a genuine shadow conflict.
    """
    try:
        import metaphysica
    except ImportError as exc:  # pragma: no cover — install-time issue.
        pytest.skip(f"metaphysica package not importable: {exc}")

    try:
        rc = metaphysica.build(out_dir=str(REPO_ROOT), fast=True)
    except Exception as exc:
        pytest.skip(f"metaphysica.build raised: {exc}")

    if rc != 0:
        pytest.skip(
            f"metaphysica.build exited {rc}; cannot audit a stale "
            f"parameters.json. Skipping shadow gate."
        )

    if not PARAMETERS_JSON.is_file():
        pytest.skip(
            f"{PARAMETERS_JSON} missing after build; cannot run shadow audit."
        )

    return PARAMETERS_JSON


def test_shadow_audit_clean(fresh_parameters_json: Path) -> None:
    """The shadow-derivation auditor must exit 0 (no conflicts)."""
    result = subprocess.run(
        [sys.executable, str(AUDIT_SCRIPT)],
        capture_output=True,
        text=True,
        cwd=str(REPO_ROOT),
    )

    # Surface the JSON report on failure so CI logs show *which* group(s)
    # conflicted, not just "exit 1".
    report_path = REPO_ROOT / "scripts" / "_audit_shadow_derivations.json"
    detail = ""
    if report_path.is_file():
        try:
            with open(report_path, "r", encoding="utf-8") as fh:
                report = json.load(fh)
            conflicts = report.get("shadow_conflicts", [])
            if conflicts:
                detail = "\nConflicts:\n" + json.dumps(conflicts, indent=2)
        except (OSError, json.JSONDecodeError):
            pass

    assert result.returncode == 0, (
        f"Shadow audit failed (exit {result.returncode}).\n"
        f"--- stdout ---\n{result.stdout}\n"
        f"--- stderr ---\n{result.stderr}"
        f"{detail}"
    )
