"""The published holonomy gate was a literal PASS over checks that could not fail.

WHAT WAS THERE
==============
`g2_geometry.get_gate_checks()` published, into `theory_output.json`:

    "gate_id": "G_GEOMETRY_HOLONOMY",
    "assertion": "G2 holonomy validated (parallel spinor + Ricci-flat + ...)",
    "result": "PASS",
    "details": {"parallel_spinors": 1, "ricci_scalar": 0.0,
                "torsion_free": True}

It was the ONLY gate in that list whose `result` was a literal rather than a
comparison -- its three siblings all read `"PASS" if <expr> else "FAIL"`. The
three "details" were the same three literals the check itself used.

And the check could not fail. `_validate_g2_holonomy` was `all()` over:

    n_parallel_spinors = 1     then asserted == 1
    ricci_scalar       = 0.0   then asserted < 1e-10
    torsion_norm       = _validate_torsion_free()

and the third is zero by construction too, because
`_exterior_derivative_3form` returns `np.zeros(...)` -- which
`_validate_torsion_free`'s own docstring already admitted.

So a validation that returned True unconditionally published a PASS for a
claim that is FALSE on the adopted branch: phi is a G2-structure for the SPLIT
real form, induced metric signature (4,3), so no Riemannian G2-holonomy
manifold exists behind it.

TWO INDEPENDENT REASONS, AND THEY ARE REPORTED SEPARATELY
=========================================================
The gate is now generated by `geometry_narration`, so a fork switch rewrites
the sentence. On `octonion_derived` the real-form objection disappears and the
sentence changes to the compact form -- and the gate STILL refuses, because the
three conditions are placeholders either way. Collapsing those two reasons into
one verdict would hide whichever got fixed first.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import pytest

from metaphysica.simulations.PM.geometry.g2_geometry import G2GeometryV16


@pytest.fixture(scope="module")
def geometry():
    return G2GeometryV16()


# ------------------------------------------------- the check can now fail

def test_the_holonomy_check_is_false_on_the_adopted_branch(geometry):
    assert geometry._validate_g2_holonomy() is False, (
        "the holonomy check returned True. On the adopted branch phi is the "
        "SPLIT real form and no Riemannian G2 holonomy exists, and every "
        "condition below the check is a placeholder."
    )


def test_no_condition_is_measured_and_the_report_says_so(geometry):
    report = geometry.holonomy_validation_report()
    assert report["n_conditions"] == 3
    assert report["n_measured"] == 0
    assert report["n_placeholder"] == 3
    assert report["any_condition_can_fail"] is False, (
        "a condition has become measurable. That is progress and this test "
        "should be updated to say which -- but the count must never claim a "
        "measurement that is not there."
    )
    for condition in report["conditions"]:
        assert condition["status"] == "PLACEHOLDER"
        assert condition["detail"], "a placeholder must say why it is one"


def test_the_underlying_torsion_check_is_still_identically_zero(geometry):
    """Pinned so that fixing it is visible rather than silent.

    If `_exterior_derivative_3form` ever computes a real derivative this fails,
    and the placeholder bookkeeping above has to be updated with it.
    """
    import numpy as np

    phi = geometry._construct_g2_three_form()
    assert np.all(geometry._exterior_derivative_3form(phi) == 0)
    assert geometry._validate_torsion_free() == 0.0


# ------------------------------------------------------ the published gate

def test_the_gate_no_longer_publishes_a_literal_pass(geometry):
    gate = geometry._holonomy_gate()
    assert gate["gate_id"] == "G_GEOMETRY_HOLONOMY"
    assert gate["result"] == "NOT_ESTABLISHED", (
        "the published gate is claiming %r again" % gate["result"]
    )


def test_the_gate_details_carry_the_branch_not_three_literals(geometry):
    details = geometry._holonomy_gate()["details"]
    assert details["branch"] == "all_plus_one"
    assert details["induced_metric_signature"] == [4, 3]
    assert details["may_claim_g2_holonomy"] is False
    assert details["conditions_placeholder"] == 3
    for gone in ("parallel_spinors", "ricci_scalar", "torsion_free"):
        assert gone not in details, (
            "the literal %r is being published as evidence again" % gone
        )


def test_the_gate_is_in_the_published_list(geometry):
    ids = [g["gate_id"] for g in geometry.get_gate_checks()]
    assert "G_GEOMETRY_HOLONOMY" in ids
    assert len(ids) == len(set(ids)), "a gate id is duplicated"


def test_the_sibling_gates_still_compute_their_results(geometry):
    """The three siblings were always comparisons; they must stay that way."""
    for gate in geometry.get_gate_checks():
        assert gate["result"] in ("PASS", "FAIL", "NOT_ESTABLISHED"), (
            "%s has an unreadable result %r"
            % (gate["gate_id"], gate["result"])
        )


# ------------------------------------------------------- the fork rewrites it

def test_the_sentence_is_generated_from_the_live_fork(monkeypatch):
    """Switching the convention must rewrite the assertion, not contradict it."""
    monkeypatch.setenv("METAPHYSICA_VARIANT_G2_FORM_CONVENTION",
                       "octonion_derived")
    report = G2GeometryV16().holonomy_validation_report()
    assert report["branch"] == "octonion_derived"
    assert report["real_form"] == "compact G2"
    assert report["signature"] == (7, 0)
    assert report["may_claim_g2_holonomy"] is True
    assert "COMPACT" in report["why"]


def test_the_gate_still_refuses_on_the_compact_branch(monkeypatch):
    """The two reasons are independent and must not be collapsed.

    On `octonion_derived` the real-form objection goes away. The placeholder
    objection does not, so the gate must still refuse -- otherwise switching
    the fork would silently restore a PASS built on three literals.
    """
    monkeypatch.setenv("METAPHYSICA_VARIANT_G2_FORM_CONVENTION",
                       "octonion_derived")
    geometry = G2GeometryV16()
    assert geometry.holonomy_validation_report()["may_claim_g2_holonomy"] is True
    assert geometry._holonomy_gate()["result"] == "NOT_ESTABLISHED"
    assert geometry._validate_g2_holonomy() is False


def test_the_assertion_is_not_a_hand_written_sentence(geometry):
    """It must be the narration's own text, or the routing is decorative."""
    from metaphysica.simulations.PM.geometry.geometry_narration import (
        holonomy_claim,
    )

    assert holonomy_claim()["sentence"] in geometry._holonomy_gate()["assertion"]
