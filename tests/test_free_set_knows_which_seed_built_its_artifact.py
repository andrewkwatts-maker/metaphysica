"""The free set reads a BUILD ARTIFACT, and now says which seed built it.

Measured 2026-09-22: with METAPHYSICA_VARIANT_B3_SEED=seed_43_joyce set and no
rebuild, the registered particle.b3 still reads 24 -- _params() reads
AutoGenerated/parameters.json, which fork branches share. Every b_3-arithmetic
removal (fermion.n_generations, cosmology.wa_thawing,
algebra.freudenthal_quartic) verified against the artifact's 24 while the fork
said 43. The removals are internally consistent with the artifact as built;
what was wrong was presenting artifact-truth as fork-truth with nothing in the
output saying which seed it was.

This file pins the guard: build_free_set() carries the provenance, the
consistency verdict responds to the fork, and a mismatch NAMES the removals
that rest on the stale value instead of hiding them in the count.

These tests are written RELATIVE to whatever artifact is on disk -- they pick
the mismatching seed by reading the artifact first -- so they cannot be
defeated by which build last ran.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import pytest

from metaphysica.simulations.core.free_set import (
    _params,
    _value,
    artifact_seed_provenance,
    build_free_set,
)

_SEED_FOR_B3 = {24: "seed_24", 43: "seed_43_joyce"}


def _artifact_b3():
    b3 = _value(_params(), "particle.b3")
    if b3 not in _SEED_FOR_B3:
        pytest.skip("no artifact with a recognised particle.b3 on disk (%r); "
                    "the guard needs a built parameters.json to exercise" % b3)
    return b3


def _matching_and_mismatching_seed():
    b3 = _artifact_b3()
    matching = _SEED_FOR_B3[b3]
    other = {v for k, v in _SEED_FOR_B3.items() if k != b3}.pop()
    return matching, other


# ------------------------------------------------- the provenance record

def test_provenance_reports_both_sides():
    prov = artifact_seed_provenance()
    assert set(prov) >= {"artifact_b3", "live_fork_seed", "live_fork_b3",
                         "consistent", "note"}
    assert "rebuild" in prov["note"]


def test_consistency_is_the_comparison_not_an_opinion():
    """consistent must equal (artifact_b3 == live_fork_b3), always."""
    prov = artifact_seed_provenance()
    if prov["artifact_b3"] is None or prov["live_fork_b3"] is None:
        assert prov["consistent"] is None
    else:
        assert prov["consistent"] == (
            prov["artifact_b3"] == prov["live_fork_b3"])


def test_the_verdict_responds_to_the_fork(monkeypatch):
    """Switching the fork away from the artifact's seed must flip it."""
    matching, mismatching = _matching_and_mismatching_seed()

    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", matching)
    assert artifact_seed_provenance()["consistent"] is True

    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", mismatching)
    prov = artifact_seed_provenance()
    assert prov["consistent"] is False, (
        "the fork moved off the artifact's seed and the provenance did not "
        "notice -- the guard is a constant wearing a comparison"
    )


# ------------------------------------------------- the labelled removals

def test_a_mismatch_names_the_removals_that_rest_on_it(monkeypatch):
    _, mismatching = _matching_and_mismatching_seed()
    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", mismatching)

    from metaphysica.simulations.core.free_set import (
        verify_geometric_identities,
    )

    report = build_free_set()
    assert report["artifact_seed_provenance"]["consistent"] is False
    stale = report["removals_resting_on_stale_b3"]

    # Every named row must actually be a removal that used b_3.
    for name in stale:
        assert name in report["removed"], name

    # n_generations left this set on 2026-09-22 when free_set stopped
    # checking the abandoned b_3/8 route and started checking the RULED
    # n_gen_source route, which does not consume b_3 at all.
    assert "fermion.n_generations" not in stale, (
        "n_generations is resting on b_3 again, which would mean the "
        "geometric-identity check reverted to the abandoned b_3/8 route"
    )

    # The naming is only REQUIRED when a b_3-arithmetic removal actually
    # fires. Right now none does -- the only remaining uses_b3 identity,
    # algebra.freudenthal_quartic, does not reproduce, so it stays in the
    # free set and is never removed. That is a legitimate transient, not a
    # broken guard, and asserting otherwise would be asserting a premise
    # that stopped being true. The mechanism is still checked: if such a
    # removal exists, it MUST be named.
    fired = {name for name, rec in verify_geometric_identities().items()
             if rec.get("uses_b3") and name in report["removed"]}
    if not fired:
        pytest.skip(
            "no b_3-arithmetic removal currently fires (n_generations moved "
            "to the ruled route; freudenthal_quartic does not reproduce), so "
            "there is nothing for the mismatch to name")
    assert fired <= set(stale), (
        "these b_3-arithmetic removals fired but were not named as resting "
        "on the stale b_3: %s" % sorted(fired - set(stale))
    )


def test_a_match_labels_nothing(monkeypatch):
    matching, _ = _matching_and_mismatching_seed()
    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", matching)

    report = build_free_set()
    assert report["artifact_seed_provenance"]["consistent"] is True
    assert report["removals_resting_on_stale_b3"] == []


def test_the_free_count_itself_does_not_move_without_a_rebuild(monkeypatch):
    """The guard LABELS; it does not un-remove.

    The removals are internally consistent with the artifact as built --
    the dependent rows moved together -- so the honest fork-side count
    exists only after a rebuild. Changing the count from the env var alone
    would fake a measurement that was never made.
    """
    matching, mismatching = _matching_and_mismatching_seed()

    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", matching)
    size_matching = build_free_set()["free_set_size"]

    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", mismatching)
    size_mismatching = build_free_set()["free_set_size"]

    assert size_matching == size_mismatching


# ------------------------------------------------- downstream visibility

def test_the_closure_report_carries_the_provenance():
    from metaphysica.simulations.core.closure_ledger import closure_report

    report = closure_report()
    prov = report["free_set_artifact_provenance"]
    assert "artifact_b3" in prov
    assert "consistent" in prov
