"""Formula EML offer policy (lane F4): withheld ids, placeholders, master-action tree."""
import json
from pathlib import Path

import pytest

from metaphysica.generators.eml_render_validity import (
    classify_formula_tree, tree_operator_count)

AUTOGEN = Path("H:/Projects/MathsPhysicsEcosystem/PrincipiaMetaphysica/AutoGenerated")
AST_IDS = ["abstract-framework-overview", "ckm-overlap-integral",
           "yukawa-hierarchy-v18", "yukawa-texture-matrix-v18"]
#: The single configured master-action diagram id (mirrors formulas.html).
MASTER_ACTION_DIAGRAM_ID = "pneuma-master-action-v23"


def test_classify_withholds_each_defect():
    assert classify_formula_tree(["<error>", "?"]) == "parse_error"
    assert classify_formula_tree(["mul", "c", ["Name(id='b2', ctx=Lo", "v"], ["4", "#"]]) == "ast_repr"
    assert classify_formula_tree(["M_GUT", "v"]) == "no_operator"
    assert classify_formula_tree(["mul", "c", ["6", "#"], ["b3_leaf", "c"]]) == "leaf_placeholder"
    assert classify_formula_tree(["div", "c", ["a", "v"], ["b", "v"]]) is None


@pytest.fixture(scope="module")
def artifacts():
    policy, trees = AUTOGEN / "eml_offer_policy.json", AUTOGEN / "eml_trees.json"
    if not (policy.exists() and trees.exists()):
        pytest.skip("generated EML artifacts absent")
    p = json.loads(policy.read_text(encoding="utf-8"))
    if "formulas" not in p:
        pytest.skip("policy not regenerated with the formulas section")
    return p, json.loads(trees.read_text(encoding="utf-8"))["f"]


def test_ast_ids_and_single_leaf_withheld(artifacts):
    policy, trees = artifacts
    withheld = policy["formulas"]["withheld"]
    for fid in AST_IDS:
        assert withheld[fid] == "ast_repr" and fid not in trees
    assert policy["_v"] >= 2
    assert "no_operator" in withheld.values()
    assert any(r == "no_operator" for r in withheld.values())


def test_no_offered_tree_violates_policy(artifacts):
    _, trees = artifacts
    for fid, entry in trees.items():
        assert classify_formula_tree(entry["c"], entry["x"]) is None, fid


def test_configured_master_action_has_a_real_tree(artifacts):
    policy, trees = artifacts
    assert MASTER_ACTION_DIAGRAM_ID not in policy["formulas"]["withheld"]
    assert tree_operator_count(trees[MASTER_ACTION_DIAGRAM_ID]["c"]) >= 8


def test_shared_gate_placeholder_withheld(artifacts):
    policy, _ = artifacts
    assert list(policy["formulas"]["withheld"].values()).count("shared_placeholder") >= 10
