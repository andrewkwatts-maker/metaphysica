def test_eml_deferred_skips_uncertainty_propagation(isolated_autogen) -> None:
    """EML-deferred parameters skip propagation — σ pinned at 0.

    Speculative Orch-OR / Gnosis rows shouldn't move the headline error
    budget. The ``eml_deferred_default`` PRIORS entry is explicitly
    ``None``, which the resolver maps to a skip sentinel, which the
    Bayesian scan honours by leaving σ at 0.0.
    """
    from metaphysica.simulations.PM.analysis.proof_completeness import (
        PRIORS,
        STATUS_EML_DEFERRED,
        STATUS_FULLY_DERIVED,
        ProofLedger,
        resolve_prior,
    )

    # Static lookup contract — the eml_deferred default is None.
    assert PRIORS["eml_deferred_default"] is None

    # Resolver returns the skip sentinel (NOT None — None means "fall
    # through to legacy default").
    sentinel = resolve_prior("consciousness.tau", STATUS_EML_DEFERRED)
    assert sentinel != {"sigma_rel": 0.01, "distribution": "gaussian"}
    # The sentinel must not be a dict — that would be misread as a real
    # prior by the scan loop.
    assert not isinstance(sentinel, dict)

    # End-to-end: 3 deferred entries + 1 fully-derived control. The
    # deferred σ must be exactly 0; the control must be > 0.
    registry = {
        "consciousness.tau_baseline": {
            "value": 0.024,
            "eml_tree": "EML: eml_scalar(0.024)",
            "eml_deferred": True,
            "status": "PREDICTED",
        },
        "consciousness.dice_branches": {
            "value": 256,
            "source": "four_dice_sampling_v22",
            "eml_description": "EML: eml_scalar(256)",
            "status": "PREDICTED",
        },
        "consciousness.coherence_boost": {
            "value": 10.21,
            "metadata": {
                "source_simulation": "gnosis_unlocking_v22_2",
                "eml_description": "EML: eml_scalar(10.21)",
            },
            "status": "PREDICTED",
        },
        # Control: pure derived theory parameter — should propagate.
        "constants.alpha_em": {
            "value": 0.0072973525693,
            "eml_tree": "EML: eml_scalar(0.0073)",
            "status": "DERIVED",
        },
    }
    df, unc = ProofLedger(rng_seed=33).build_ledger(registry)
    by_param = {
        row["Parameter"]: (row["Status"], float(unc[i]))
        for i, (_, row) in enumerate(df.iterrows())
    }

    # All three deferred rows: σ == 0 exactly.
    for p in (
        "consciousness.tau_baseline",
        "consciousness.dice_branches",
        "consciousness.coherence_boost",
    ):
        status, sigma = by_param[p]
        assert status == "eml_deferred", f"{p} should be eml_deferred, got {status}"
        assert sigma == 0.0, f"{p} should skip propagation, got σ={sigma}"

    # Control: fully_derived → non-zero σ from the 1 % Gaussian default.
    status, sigma = by_param["constants.alpha_em"]
    assert status == STATUS_FULLY_DERIVED
    assert sigma > 0.0
