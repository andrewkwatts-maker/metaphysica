# ── Test 1 — classification rules ───────────────────────────────────────────


def test_classification_buckets(isolated_autogen, sample_registry) -> None:
    """Each canonical entry lands in the expected bucket."""
    from metaphysica.simulations.PM.analysis.proof_completeness import (
        STATUS_EXPERIMENTAL_ANCHOR,
        STATUS_FITTED,
        STATUS_FULLY_DERIVED,
        STATUS_NUMERICAL,
        STATUS_OPEN_TENSION,
        ProofLedger,
    )

    df, unc = ProofLedger(rng_seed=42).build_ledger(sample_registry)

    # DataFrame column contract from the task plan.
    assert {"Parameter", "Value", "Status", "EML_Tree", "Uncertainty"} <= set(df.columns)
    assert "Section" in df.columns  # extra column, used for grouping.
    assert len(unc) == len(df)

    by_param = {row["Parameter"]: row["Status"] for _, row in df.iterrows()}

    # Fully derived (EML tree present, no fitted marker, no tension).
    assert by_param["constants.alpha_em"] == STATUS_FULLY_DERIVED
    assert by_param["geometry.b3"] == STATUS_FULLY_DERIVED

    # Numerical agreement (no EML tree).
    assert by_param["cosmology.H0_geometric"] == STATUS_NUMERICAL

    # Experimental anchors — NuFIT / PDG / DESI observational inputs,
    # not theory fits. The anchor classifier wins over the legacy
    # theta_13 / delta_CP fitted-marker pattern.
    assert by_param["nufit.theta_13"] == STATUS_EXPERIMENTAL_ANCHOR
    assert by_param["pdg.m_electron"] == STATUS_EXPERIMENTAL_ANCHOR
    assert by_param["parameters.desi.w0"] == STATUS_EXPERIMENTAL_ANCHOR

    # Fitted (theta_13 / delta_CP markers — outside the anchor namespace
    # OR inside a recognised prefix but lacking the ESTABLISHED: source).
    assert by_param["neutrino.delta_CP_pred"] == STATUS_FITTED
    assert by_param["neutrino.theta_13_legacy"] == STATUS_FITTED
    assert by_param["pdg.theta_13_derived"] == STATUS_FITTED

    # Open tension (validation_status = TENSION with experimental anchor).
    assert by_param["particle.m_axion"] == STATUS_OPEN_TENSION

    # Non-numeric value falls through to numerical_agreement bucket.
    assert by_param["vacuum.note"] == STATUS_NUMERICAL


# ── Test 2 — Bayesian scan semantics ────────────────────────────────────────


def test_bayesian_scan_produces_nonzero_uncertainty(
    isolated_autogen, sample_registry,
) -> None:
    """σ ≈ 1 % of |value| for numeric entries; 0 for non-numeric."""
    from metaphysica.simulations.PM.analysis.proof_completeness import (
        DEFAULT_N_SAMPLES,
        DEFAULT_SIGMA_FRACTION,
        ProofLedger,
    )

    df, unc = ProofLedger(rng_seed=1234).build_ledger(sample_registry)

    by_param_unc = {
        row["Parameter"]: float(unc[i])
        for i, (_, row) in enumerate(df.iterrows())
    }

    # Sanity: numeric entries get a strictly positive posterior σ.
    for p in (
        "constants.alpha_em",
        "geometry.b3",
        "cosmology.H0_geometric",
        "nufit.theta_13",
        "particle.m_axion",
    ):
        assert by_param_unc[p] > 0.0, f"{p} should have non-zero uncertainty"

    # Non-numeric value → σ pinned at 0.
    assert by_param_unc["vacuum.note"] == 0.0

    # Order-of-magnitude check: σ ≈ sigma_fraction * |value| (within ~10 %
    # — finite-sample noise around 1000 draws is ~3 %).
    value_b3 = 24.0
    expected_b3 = DEFAULT_SIGMA_FRACTION * value_b3
    assert 0.85 * expected_b3 < by_param_unc["geometry.b3"] < 1.15 * expected_b3

    # Defaults are 1 % / 1000 — make sure they're what the spec mandates.
    assert DEFAULT_SIGMA_FRACTION == pytest.approx(0.01)
    assert DEFAULT_N_SAMPLES == 1000


# ── Test 3 — derive_proof_ledger payload + EML tree persistence ─────────────


def test_derive_proof_ledger_payload_and_eml_tree(
    isolated_autogen, sample_registry,
) -> None:
    """derive_proof_ledger returns a complete dict + writes ledger_summary."""
    from metaphysica.simulations.PM.analysis.proof_completeness import (
        ProofLedger,
        STATUS_ORDER,
        derive_proof_ledger,
        generate_proof_ledger,
    )
    from metaphysica.simulations.core.eml_tree_adapter import (
        TREES_FILENAME,
        eml_operator_tree,
    )

    payload = derive_proof_ledger(sample_registry)

    # Top-level shape.
    assert set(payload) >= {"rows", "status_counts", "per_section",
                            "uncertainties", "meta"}
    assert payload["meta"]["n_parameters"] == len(sample_registry)
    assert payload["meta"]["sigma_fraction"] == pytest.approx(0.01)
    assert payload["meta"]["n_samples"] == 1000

    # Status histogram covers all four buckets (even when count == 0).
    assert set(payload["status_counts"]) == set(STATUS_ORDER)
    assert sum(payload["status_counts"].values()) == len(sample_registry)

    # Per-section matrix matches the section prefixes of the input.
    sections = {p.split(".", 1)[0] for p in sample_registry}
    assert set(payload["per_section"]) == sections

    # Each row carries the seven canonical fields (six pre-Sprint-T2 +
    # the duplicate_derivations cross-link column added in T2 #6).
    for row in payload["rows"]:
        assert set(row) == {
            "parameter", "value", "status", "eml_tree",
            "section", "uncertainty", "duplicate_derivations",
        }
        # duplicate_derivations is always a list (possibly empty) of
        # canonical parameter ID strings.
        assert isinstance(row["duplicate_derivations"], list)
        for sibling in row["duplicate_derivations"]:
            assert isinstance(sibling, str) and sibling

    # Aliases — both names in the source spec must work.
    payload2 = generate_proof_ledger(sample_registry)
    assert payload2["meta"]["n_parameters"] == payload["meta"]["n_parameters"]

    # EML tree adapter wrote ledger_summary + the four bucket counts into
    # AutoGenerated/eml_trees_v25.json.
    json_path = isolated_autogen / TREES_FILENAME
    assert json_path.exists()
    on_disk = json.loads(json_path.read_text(encoding="utf-8"))
    assert "proof_completeness" in on_disk
    bucket = on_disk["proof_completeness"]
    assert "ledger_summary" in bucket
    assert bucket["ledger_summary"]["value"] == len(sample_registry)
    for status in STATUS_ORDER:
        assert f"status_count_{status}" in bucket

    # Reading back through the adapter recovers the same dict.
    tree = eml_operator_tree("proof_completeness")
    assert tree.get_tree()["ledger_summary"]["value"] == len(sample_registry)


