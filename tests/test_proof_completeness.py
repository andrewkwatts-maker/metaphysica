def test_eml_deferred_excluded_from_fully_derived_denominator(
    isolated_autogen,
) -> None:
    """Tagging a parameter ``eml_deferred=True`` (or routing it through a
    deferred sim) pulls it OUT of the ``fully_derived`` bucket even when an
    EML tree is present — keeps the headline 92 % metric clean per
    TIER_2_3_ROADMAP §T2.2.
    """
    from metaphysica.simulations.PM.analysis.proof_completeness import (
        STATUS_EML_DEFERRED,
        STATUS_FULLY_DERIVED,
        STATUS_ORDER,
        ProofLedger,
        derive_proof_ledger,
    )

    # ``STATUS_EML_DEFERRED`` must appear in the canonical histogram order
    # so the markdown / JSON outputs always carry a slot for it (even when
    # the count is zero).
    assert STATUS_EML_DEFERRED in STATUS_ORDER

    registry = {
        # Pure derived control — must end up fully_derived.
        "constants.alpha_em": {
            "value": 0.00729735,
            "eml_tree": "EML: eml_scalar(0.0073)",
            "status": "DERIVED",
        },
        # Explicit opt-in flag at top level — speculative even though an
        # EML tree is present.
        "consciousness.tau_baseline": {
            "value": 0.024,
            "eml_tree": "EML: eml_scalar(0.024)",
            "eml_deferred": True,
            "status": "PREDICTED",
        },
        # Opt-in flag under metadata — same effect.
        "consciousness.tau_gnosis": {
            "value": 2.45,
            "eml_tree": "EML: eml_scalar(2.45)",
            "metadata": {"eml_deferred": True},
            "status": "PREDICTED",
        },
        # Hardcoded deferred sim — same effect.
        "consciousness.dice_branches": {
            "value": 256,
            "source": "four_dice_sampling_v22",
            "eml_description": "EML: eml_scalar(256)",
            "status": "PREDICTED",
        },
    }

    payload = derive_proof_ledger(registry)
    counts = payload["status_counts"]

    # The histogram always carries the eml_deferred bucket.
    assert STATUS_EML_DEFERRED in counts
    # 3 deferred entries, 1 fully_derived control — none of the deferred
    # parameters leak into fully_derived.
    assert counts[STATUS_EML_DEFERRED] == 3
    assert counts[STATUS_FULLY_DERIVED] == 1
    # Round-trip check via build_ledger — same numbers.
    df, _ = ProofLedger(rng_seed=7).build_ledger(registry)
    statuses = df["Status"].tolist()
    assert statuses.count(STATUS_EML_DEFERRED) == 3
    assert statuses.count(STATUS_FULLY_DERIVED) == 1


