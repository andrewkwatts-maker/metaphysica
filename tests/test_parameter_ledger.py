"""Parameter ledger: synthetic fixtures for every class and flag, and ratchets.

The real-build test reads ``AutoGenerated/parameter_ledger.json`` under
PM_PUBLISHED_ROOT and skips when absent. Its ceilings may only fall.
"""
import json
import os
from pathlib import Path

import pytest

from metaphysica.generators import parameter_ledger as pl


def row(status, value=1.0, source="x", **kw):
    r = {"value": value, "status": status, "source": source}
    r.update(kw)
    return r


def formula(ins, outs):
    return {"input_params": ins, "output_params": outs}


def ledger(params, formulas=None, report=None):
    return pl.build_ledger(params, formulas or {}, {"rows": []}, report or {})["rows"]


def test_every_label_has_a_class_and_unknown_fails():
    for lab in pl.LABEL_CLASS:
        assert pl.label_class(lab)
    with pytest.raises(pl.UnknownLabel):
        pl.label_class("NOT_A_LABEL")
    with pytest.raises(pl.UnknownLabel):
        ledger({"a.b": row("NOT_A_LABEL")})


def test_label_classes_and_measured_needs_a_source():
    rows = ledger({"m.a": row("ESTABLISHED", source="PDG"),
                   "m.b": row("MEASURED", source="unknown"),
                   "c.a": row("CALIBRATED"), "f.a": row("FITTED"),
                   "a.a": row("ANSATZ"), "s.a": row("SYSTEM")})
    assert rows["m.a"]["class"] == pl.MEASURED_INPUT
    assert rows["m.b"]["class"] == pl.UNJUSTIFIED
    assert rows["c.a"]["class"] == pl.CALIBRATED
    assert rows["f.a"]["class"] == pl.FITTED
    assert rows["a.a"]["class"] == pl.ANSATZ
    assert rows["s.a"]["class"] == pl.CONVENTION


def test_geometry_chain_and_anchor_leaf():
    params = {"g.b3": row("GEOMETRIC", 24, source="geometric_anchors"),
              "d.x": row("DERIVED", 12.0)}
    rows = ledger(params, {"f1": formula(["g.b3"], ["d.x"])})
    assert rows["g.b3"]["class"] == pl.GEOMETRY
    assert rows["d.x"]["class"] == pl.GEOMETRY


def test_weak_leaf_demotes_chain():
    params = {"g.b3": row("GEOMETRIC", 24, source="geometric_anchors"),
              "a.k": row("ANSATZ"), "d.x": row("DERIVED")}
    rows = ledger(params, {"f1": formula(["g.b3", "a.k"], ["d.x"])})
    assert rows["d.x"]["class"] == pl.ANSATZ


def test_empty_chain_is_unjustified():
    rows = ledger({"d.x": row("DERIVED", 3.7)})
    assert rows["d.x"]["class"] == pl.UNJUSTIFIED


def test_missing_link_is_unjustified():
    params = {"d.x": row("DERIVED", derivation_formula="no-such-formula")}
    assert ledger(params)["d.x"]["class"] == pl.UNJUSTIFIED
    params = {"d.x": row("DERIVED")}
    rows = ledger(params, {"f1": formula(["ghost.row"], ["d.x"])})
    assert rows["d.x"]["class"] == pl.UNJUSTIFIED
    assert "missing" in rows["d.x"]["evidence"]


def test_loop_is_unjustified_but_self_restatement_is_not():
    params = {"d.a": row("DERIVED"), "d.b": row("DERIVED"),
              "g.b3": row("GEOMETRIC", 24, source="geometric_anchors"),
              "d.c": row("DERIVED")}
    formulas = {"f1": formula(["d.b"], ["d.a"]), "f2": formula(["d.a"], ["d.b"]),
                "f3": formula(["g.b3", "d.c"], ["d.c"])}
    rows = ledger(params, formulas)
    assert rows["d.a"]["class"] == pl.UNJUSTIFIED and "loop" in rows["d.a"]["evidence"]
    assert rows["d.c"]["class"] == pl.GEOMETRY


def test_action_hook(monkeypatch):
    monkeypatch.setattr(pl, "ACTION_SOURCES", frozenset({"ladder:term"}))
    params = {"l.t": row("GEOMETRIC", 2.5, source="ladder:term"), "d.x": row("DERIVED")}
    rows = ledger(params, {"f1": formula(["l.t"], ["d.x"])})
    assert rows["d.x"]["class"] == pl.ACTION


def test_falsifiability_states():
    params = {"t.a": row("PREDICTED", 1.0, experimental_value=1.0,
                         validation_status="PASS", sigma_deviation=0.1),
              "u.a": row("PREDICTED", 5.0),
              "k.a": row("PREDICTED", 3.51),
              "s.a": row("SYSTEM")}
    report = {"detailed_risk_analysis": {"ALP_Principia_Metric": {
        "status": "TESTABLE", "predicted_mass_meV": 3.51}}}
    f = {k: v["falsifiability"]["state"] for k, v in ledger(params, report=report).items()}
    assert f["t.a"] == "TESTED_NOW" and f["u.a"] == "UNFALSIFIABLE"
    assert f["s.a"] == "NOT_OBSERVABLE"
    params["alp.mass_meV"] = row("PREDICTED", 3.51)
    rows = ledger(params, report=report)
    assert rows["alp.mass_meV"]["falsifiability"]["state"] == "TESTABLE"


def test_kill_switch_disagreement_is_reported():
    params = {"alp.mass_meV": row("PREDICTED", 3.51),
              "portals.sterile_mixing_sin2_2theta": row("PREDICTED", 7.9e-5)}
    report = {"detailed_risk_analysis": {
        "ALP_Principia_Metric": {"predicted_mass_meV": 3.51},
        "Sterile_Neutrino": {"predicted_mixing": 0.01},
        "Cross_Pair_Bell": {"status": "SPECULATIVE"}}}
    k = {x["test"]: x for x in pl.link_kill_switches(report, params)}
    assert k["ALP_Principia_Metric"]["agrees"]
    assert not k["Sterile_Neutrino"]["agrees"]
    assert k["Cross_Pair_Bell"]["registry_id"] is None


def test_circular_flags():
    params = {"m.in": row("ESTABLISHED", 0.4082, source="PDG", experimental_source="PDG",
                          experimental_value=0.4082),
              "p.x": row("PREDICTED", 0.41, experimental_value=0.4082,
                         experimental_source="PDG", validation_status="PASS"),
              "f.y": row("FITTED", 2.5, experimental_value=2.5, validation_status="PASS")}
    rows = ledger(params, {"f1": formula(["m.in"], ["p.x"])})
    assert any("own datum" in c for c in rows["p.x"]["circular"])
    assert rows["f.y"]["circular"]
    assert not rows["m.in"]["circular"]


def test_value_conflict_and_readers():
    params = {"a.b3": row("GEOMETRIC", 24, source="geometric_anchors"),
              "t.b3": row("GEOMETRIC", 43, source="geometric_anchors"),
              "u.b3": row("GEOMETRIC", 43, source="geometric_anchors"),
              "d.r": row("DERIVED")}
    out = pl.build_ledger(params, {"f1": formula(["a.b3"], ["d.r"])}, {"rows": []}, {})
    c = [x for x in out["value_conflicts"] if x["group"] == "same_name:b3"][0]
    assert c["off_path"] == ["a.b3"] and c["readers"] == ["d.r"]


def test_free_variable_cross_check_flags_derived_class():
    params = {"g.x": row("GEOMETRIC", 24, source="geometric_anchors")}
    out = pl.build_ledger(params, {}, {"rows": [{"name": "g.x"}]}, {})
    assert out["free_variable_cross_check"]["rows_in_derived_class"] == ["g.x"]


# ---- ratchets on the real build -------------------------------------------
#: Ceilings measured 2026-10-27 on the fresh fast build; they may only fall.
CEILINGS = {"unjustified": 223, "ansatz_plus_fitted": 32,
            "unfalsifiable_predictions": 46, "circular": 6}
FV_DERIVED_CEILING = 2  # geometry.alpha_inverse, cosmology.M_Pl_4D: free-variable row in a derived class
PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT", "H:/claude-scratch/runs_g/active"))
LEDGER = PUBLISHED / "AutoGenerated" / "parameter_ledger.json"


@pytest.mark.skipif(not LEDGER.exists(), reason="no build: %s absent (set PM_PUBLISHED_ROOT)" % LEDGER)
def test_real_build_ratchets_and_label_coverage():
    data = json.loads(LEDGER.read_text(encoding="utf-8"))
    for key, ceiling in CEILINGS.items():
        assert data["counts"][key] <= ceiling, "%s rose above %d" % (key, ceiling)
    params = json.loads((PUBLISHED / "AutoGenerated" / "parameters.json")
                        .read_text(encoding="utf-8"))["parameters"]
    for name, p in params.items():
        pl.label_class(p["status"])
    assert set(data["rows"]) == set(params)
    assert len(data["free_variable_cross_check"]["rows_in_derived_class"]) <= FV_DERIVED_CEILING
