"""Prose lints: long sentences, filler, version tags in headings, duplicate paragraphs.

Each check has a passing and a failing example. The ratchet runs the lints over
the published build (PM_PUBLISHED_ROOT, default H:/claude-scratch/runs_g/active)
and is skipped when the build is absent. Ceilings only go down.
"""
from __future__ import annotations

import os
from pathlib import Path

import pytest

from metaphysica.generators import prose_lint as pl

PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT",
                                "H:/claude-scratch/runs_g/active"))

#: Findings permitted on the published text. Only goes down.
CEILINGS = {"long_sentence": 317, "filler": 5, "version_tag": 14,
            "duplicate_paragraph": 2}


# --- long sentences ---------------------------------------------------------

def test_short_sentence_passes():
    assert pl.long_sentences("x", "<p>The seed is closed. The sweep agrees.</p>") == []


def test_sentence_over_40_words_fails():
    text = "<p>" + " ".join(["word"] * 41) + ".</p>"
    found = pl.long_sentences("x", text)
    assert [f.check for f in found] == ["long_sentence"]


def test_abbreviations_and_decimals_do_not_split_or_inflate():
    text = "See e.g. Fig. 3 for w = 0.97 and i.e. the case " + " ".join(["a"] * 20) + "."
    assert len(pl.sentences(text)) == 1
    assert pl.long_sentences("x", text) == []


def test_markup_and_maths_are_not_words():
    text = "<p>" + "$" + " ".join(["x"] * 60) + "$" + " is small.</p>"
    assert pl.long_sentences("x", text) == []


# --- filler -----------------------------------------------------------------

def test_clean_sentence_has_no_filler():
    assert pl.filler("x", "<p>The seed gives b3 = 43.</p>") == []


@pytest.mark.parametrize("phrase", pl.FILLER)
def test_each_filler_phrase_is_found(phrase):
    found = pl.filler("x", "<p>This is %s here.</p>" % phrase)
    assert [f.text for f in found] == [phrase]


def test_filler_needs_the_whole_word():
    assert pl.filler("x", "<p>Every verification is verifiable.</p>") == []


# --- version tags -----------------------------------------------------------

@pytest.mark.parametrize("title", ["Hubble Engine (v16.2)", "Ledger v22", "Bridge_v19"])
def test_version_tag_in_title_fails(title):
    assert len(pl.version_tags("x", title)) == 1


@pytest.mark.parametrize("title", ["Hubble Engine", "The v-shaped well", "Section 3.2"])
def test_title_without_version_tag_passes(title):
    assert pl.version_tags("x", title) == []


def test_section_items_expose_block_headings():
    secs = {"s": {"id": "s", "title": "T", "contentBlocks": [
        {"type": "text", "content": "<h3>Ledger (v24.2)</h3><p>Body.</p>"}]}}
    found = pl.lint_items(pl.section_items(secs))
    assert [f.check for f in found] == ["version_tag"]


# --- duplicate paragraphs ---------------------------------------------------

PARA = "<p>" + " ".join(["same"] * 15) + ".</p>"


def test_paragraph_in_two_sections_fails():
    found = pl.duplicate_paragraphs([("a", PARA), ("b", PARA)])
    assert [f.check for f in found] == ["duplicate_paragraph"]


def test_paragraph_repeated_inside_one_section_passes():
    assert pl.duplicate_paragraphs([("a", PARA), ("a", PARA)]) == []


def test_short_repeated_paragraph_passes():
    assert pl.duplicate_paragraphs([("a", "<p>Caption.</p>"), ("b", "<p>Caption.</p>")]) == []


# --- ratchet on the published build ----------------------------------------

def test_published_prose_under_ceilings():
    if not (PUBLISHED / "AutoGenerated" / "sections.json").is_file():
        pytest.skip("no published build at %s" % PUBLISHED)
    items = list(pl.section_items(pl.load_sections(PUBLISHED)))
    items += list(pl.page_items(PUBLISHED / "Pages"))
    found = pl.counts(pl.lint_items(items))
    over = {k: (found[k], CEILINGS[k]) for k in CEILINGS if found[k] > CEILINGS[k]}
    assert not over, over
