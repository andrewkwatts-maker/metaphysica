def test_get_quark_as_json_returns_dict():
    """``get('up', fmt='json')`` returns the bundled quark datasheet dict."""
    out = get("up", JSON, kind=KIND_QUARK)
    assert isinstance(out, dict)
    # The datasheet schema (periodica-compatible) uses capitalised keys.
    assert any(out.get(k) for k in ("Name", "Symbol", "name", "canonical_name", "label"))


def test_GetJSON_alias_matches_get():
    """``GetJSON(name)`` and ``get(name, JSON)`` must agree."""
    a = GetJSON("up", kind=KIND_QUARK)
    b = get("up", JSON, kind=KIND_QUARK)
    assert a == b


def test_get_constant_b3_as_json():
    """``get('b3')`` returns the curated b3 datasheet (always bundled)."""
    out = get("b3", JSON, kind=KIND_CONSTANT)
    assert isinstance(out, dict)
    # b3 = 24 by construction of the framework.
    val = out.get("value")
    if val is not None:
        assert float(val) == 24.0


