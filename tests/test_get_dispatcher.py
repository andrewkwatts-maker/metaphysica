def test_iter_kind_yields_entity_refs():
    """Iterators yield EntityRef carriers with payload + source."""
    from metaphysica._catalog import EntityRef as _ER
    yielded = list(iter_kind(KIND_QUARK))
    assert yielded, "Expected at least one quark in the iterator"
    for ref in yielded[:3]:
        assert isinstance(ref, _ER)
        assert ref.kind == KIND_QUARK
        assert isinstance(ref.canonical_id, str)
        assert ref.payload  # payload populated


