def test_out_path_writes_json_file(tmp_path):
    target = tmp_path / "b3.json"
    out = get("b3", JSON, kind=KIND_CONSTANT, out_path=target)
    assert isinstance(out, dict)
    assert target.exists()
    assert target.read_text(encoding="utf-8").strip().startswith("{")


