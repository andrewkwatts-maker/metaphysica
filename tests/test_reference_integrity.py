def test_module_join_attaches_a_modules_own_references():
    """Both sides record source_simulation, so the join invents nothing."""
    from metaphysica.simulations.run_all_simulations import (
        _attach_module_references,
    )

    data = {
        "formulas": {"f1": {"source_simulation": "sim_a"},
                     "f2": {"source_simulation": "sim_b"}},
        "parameters": {"p1": {"source_simulation": "sim_a"}},
        "references": [
            {"id": "r_a", "source_simulation": "sim_a"},
            {"id": "r_b", "source_simulation": "sim_b"},
        ],
    }
    _attach_module_references(data)
    assert data["formulas"]["f1"]["references"] == ["r_a"]
    assert data["formulas"]["f2"]["references"] == ["r_b"]
    assert data["parameters"]["p1"]["references"] == ["r_a"]


def test_explicit_references_are_never_overwritten():
    """A simulation that does the finer-grained work must keep it."""
    from metaphysica.simulations.run_all_simulations import (
        _attach_module_references,
    )

    data = {
        "formulas": {"f1": {"source_simulation": "sim_a",
                            "references": ["hand_picked"]}},
        "references": [{"id": "r_a", "source_simulation": "sim_a"}],
    }
    _attach_module_references(data)
    assert data["formulas"]["f1"]["references"] == ["hand_picked"]
    assert data["formulas"]["f1"]["references_are_module_level"] is False


def test_module_level_attribution_is_flagged_as_such():
    """The weaker claim must be labelled, not passed off as per-claim
    sourcing. 'This formula comes from a module that declared these papers'
    is not 'this paper proves this line'."""
    from metaphysica.simulations.run_all_simulations import (
        _attach_module_references,
    )

    data = {
        "formulas": {"f1": {"source_simulation": "sim_a"}},
        "references": [{"id": "r_a", "source_simulation": "sim_a"}],
    }
    _attach_module_references(data)
    assert data["formulas"]["f1"]["references_are_module_level"] is True


def test_a_module_with_no_references_gets_an_empty_list_not_a_flag():
    from metaphysica.simulations.run_all_simulations import (
        _attach_module_references,
    )

    data = {"formulas": {"f1": {"source_simulation": "lonely"}},
            "references": [{"id": "r_a", "source_simulation": "other"}]}
    _attach_module_references(data)
    assert data["formulas"]["f1"]["references"] == []
    assert data["formulas"]["f1"]["references_are_module_level"] is False


