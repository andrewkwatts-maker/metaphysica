"""Formula lints: measure, Planck exponent, superseded wording.

Each lint has a passing and a failing example. The ratchet runs the lints over
the published build (PM_PUBLISHED_ROOT, default H:/claude-scratch/runs_g/active)
and is skipped when the build is absent. Ceilings only go down.
"""
from __future__ import annotations

import json
import os
import re
from pathlib import Path

import pytest

from metaphysica.generators import formula_lint as fl

ROOT = Path(__file__).resolve().parents[1]
PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT",
                                "H:/claude-scratch/runs_g/active"))
ANCHORS = (ROOT / "src/metaphysica/simulations/PM/geometry/"
           "geometric_anchors_core.py")

#: Findings permitted on the published formulas. Only goes down.
#: superseded: labelled "off-path seed / retired b3 = 24" statements (lane W1).
CEILINGS = {"measure": 0, "planck_exponent": 0, "superseded": 13}


# --- measure ----------------------------------------------------------------

def test_measure_26d_abs_passes():
    assert fl.check_measure("x", r"S = \int d^{26}X \sqrt{|G|} [R]") == []


def test_measure_26d_minus_g_fails():
    found = fl.check_measure("x", r"S = \int d^{26}X \sqrt{-G} [R]")
    assert [f.lint for f in found] == ["measure"] and "two times" in found[0].message


@pytest.mark.parametrize("dim", [4, 6, 11, 13])
def test_measure_one_time_dims_need_minus_g(dim):
    assert fl.check_measure("x", r"\int d^{%d}x \sqrt{-g} R" % dim) == []
    bad = fl.check_measure("x", r"\int d^{%d}x \sqrt{g} R" % dim)
    assert len(bad) == 1 and "one time" in bad[0].message


def test_measure_rows_are_independent():
    latex = r"\int d^{26}X \sqrt{|G|} R \\ \int d^{13}x \sqrt{-g} R"
    assert fl.check_measure("x", latex) == []


def test_measure_vielbein_form_passes_and_flat_integral_is_ignored():
    assert fl.check_measure("x", r"\int d^{26}x\,e\,e_a^\mu R^{a}") == []
    assert fl.check_measure("x", r"\int d^{26}x [\lambda (X\cdot P)]") == []


def test_measure_curvature_without_sqrt_fails():
    assert len(fl.check_measure("x", r"\int d^{4}x R")) == 1


# --- planck exponent --------------------------------------------------------

def test_planck_exponent_d_minus_2_passes():
    assert fl.check_planck_exponent("x", r"\int d^{26}X \sqrt{|G|} \frac{M_*^{24}}{2} R") == []
    assert fl.check_planck_exponent("x", r"\int d^{13}x \sqrt{-g} M_*^{11} R") == []


def test_planck_exponent_wrong_power_fails():
    found = fl.check_planck_exponent("x", r"\int d^{26}X \sqrt{|G|} \frac{M_*^{25}}{2} R")
    assert len(found) == 1 and "expected 24" in found[0].message


def test_planck_exponent_other_row_is_not_judged_by_the_integral():
    latex = r"\int d^{26}X \sqrt{|G|} M_*^{24} R \\ M_*^{11} R_{13}"
    assert fl.check_planck_exponent("x", latex) == []


# --- superseded -------------------------------------------------------------

def test_superseded_clean_text_passes():
    assert fl.check_superseded("x", r"N_1 = b_3 = 43", "N1 = b3 = 43") == []


def test_superseded_retired_value_fails():
    found = fl.check_superseded("x", r"N_1 = b_3 = 24", "N1 = b3 = 24")
    assert {f.message for f in found} == {"superseded wording in latex",
                                           "superseded wording in plain_text"}


# --- the signature table ----------------------------------------------------

def test_signature_table_matches_the_chain_comment():
    comment = next(l for l in ANCHORS.read_text(encoding="utf-8").splitlines()
                   if l.strip().startswith("# Chain:"))
    chain = {int(d): (int(s), int(t))
             for d, s, t in re.findall(r"(\d+)D\((\d+),\s*(\d+)\)", comment)}
    assert set(chain) == {26, 13, 6, 4}
    for dim, sig in chain.items():
        assert fl.DIMENSION_SIGNATURES[dim] == sig


# --- ratchet on the published build ----------------------------------------

def test_published_formulas_under_ceilings():
    path = PUBLISHED / "AutoGenerated" / "formulas.json"
    if not path.is_file():
        pytest.skip("no published formulas at %s" % path)
    formulas = json.loads(path.read_text(encoding="utf-8"))["formulas"]
    counts = {name: 0 for name in CEILINGS}
    for fid, f in formulas.items():
        for hit in fl.lint_formula(fid, f.get("latex") or "", f.get("plain_text") or ""):
            counts[hit.lint] += 1
    over = {k: (counts[k], CEILINGS[k]) for k in CEILINGS if counts[k] > CEILINGS[k]}
    assert not over, over
