def test_variants_json_is_bookkeeping(tmp_path, stub_theory):
    m, v, r = tmp_path / "M", tmp_path / "V", tmp_path / "R"
    files = {"variants.json": {"sel": "a"}, "p.json": {"x": 1}}
    _w(m, files, "t0")
    _w(v, files, "t1")
    _run(r, "f--sw", dict(files, **{"variants.json": {"sel": "b"}}), "t2")
    out = tmp_path / "out"
    index = publish("synth", m, v, r, m, out)
    e = {p["id"]: p for p in index["paths"]}["f--sw"]
    assert e["inert"] is True and e["changed_values"] == 0
    assert e["changed_artifacts"] == []
    patch = json.loads((out / "f--sw" / "patch.json").read_text("utf-8"))
    assert list(patch["files"]) == ["variants.json"]


def _status(runs, pid, steps):
    p = runs / pid / "AutoGenerated" / "build_status.json"
    p.write_text(json.dumps({"schema": "metaphysica.build_status/1",
                             "failed_steps": steps, "keep_going": True}),
                 encoding="utf-8")


def _step(sid, reason):
    return {"id": sid, "title": sid, "exit": 1, "reason": reason}


def test_required_step_failure_is_not_computed_with_its_reason(tree, stub_theory):
    m, v, r, out = tree
    sys.modules["metaphysica.theories.synth.results"].REQUIRED_STEPS = ("sims",)
    _status(r, "f--changed", [_step("sims", "ValueError: incoherent seed")])
    index = publish("synth", m, v, r, m, out)
    reasons = {s["id"]: s["reason"] for s in index["not_computed"]}
    assert reasons["f--changed"] == "ValueError: incoherent seed"
    assert "f--changed" not in {p["id"] for p in index["paths"]}


def test_optional_step_failure_is_listed_but_computed(tree, stub_theory):
    m, v, r, out = tree
    sys.modules["metaphysica.theories.synth.results"].REQUIRED_STEPS = ("sims",)
    _status(r, "f--changed", [_step("audit", None)])
