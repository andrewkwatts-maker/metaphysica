"""publish on a tiny synthetic tree: changed, inert, failed, sha256."""
import hashlib
import json
import sys
import types

import pytest

from metaphysica.testground.results.publish import publish

MAIN = {"a.json": {"ts": "t0", "v": 1, "arr": [1, 2, 3], "k": {"x": 1}},
        "b.json": {"ts": "t0", "w": 5},
        "sub/c.json": {"ts": "t0", "z": [1]}}


def _w(root, files, ts):
    for name, doc in files.items():
        p = root / "AutoGenerated" / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(dict(doc, ts=ts)), encoding="utf-8")


def _run(runs, pid, files, ts, exit_code=0):
    d = runs / pid
    _w(d, files, ts)
    (d / "DONE.json").write_text(json.dumps(
        {"path": pid, "fork": pid.split("--")[0], "option": pid.split("--")[1],
         "exit": exit_code, "secs": 1}), encoding="utf-8")


@pytest.fixture
def stub_theory(monkeypatch):
    mod = types.ModuleType("metaphysica.theories.synth.results")
    mod.main_entry = lambda: {"kind": "main", "label": "Main path",
                              "status": "active", "selection": {}}
    mod.deviation_entry = lambda f, o: {"kind": "deviation", "label": f + o,
                                        "status": "considered"}
    mod.build_summary = lambda pid, m, p, ch, *vol: {"path": pid, "changed": ch}
    monkeypatch.setitem(sys.modules, "metaphysica.theories.synth.results", mod)


@pytest.fixture
def tree(tmp_path):
    m, v, r = tmp_path / "M", tmp_path / "V", tmp_path / "R"
    _w(m, MAIN, "t0")
    _w(v, MAIN, "t1")
    (m / "AutoGenerated" / "paths").mkdir()
    (m / "AutoGenerated" / "paths" / "x.json").write_text("{}")
    changed = json.loads(json.dumps(MAIN))
    changed["a.json"].update(v=2, arr=[1, 2], k={"y": 3})
    changed["sub/c.json"]["z"] = [9]
    _run(r, "f--changed", changed, "t2")
    _run(r, "f--inert", MAIN, "t3")
    _run(r, "f--failed", MAIN, "t4", exit_code=1)
    return m, v, r, tmp_path / "out"


def test_publish_counts_and_patches(tree, stub_theory):
    m, v, r, out = tree
    index = publish("synth", m, v, r, m, out)
    by_id = {p["id"]: p for p in index["paths"]}
    assert set(by_id) == {"main", "f--changed", "f--inert"}
    assert by_id["f--inert"]["inert"] is True
    assert by_id["f--inert"]["changed_values"] == 0
    ch = by_id["f--changed"]
    assert ch["inert"] is False and ch["changed_values"] == 5
    assert ch["changed_artifacts"] == ["a.json", "sub/c.json"]
    assert index["not_computed"] == [
        {"id": "f--failed", "fork": "f", "option": "failed",
         "reason": "build failed (exit 1)"}]
    patch = json.loads((out / "f--changed" / "patch.json").read_text("utf-8"))
    sha = hashlib.sha256(
        (m / "AutoGenerated" / "a.json").read_bytes()).hexdigest()
    assert patch["files"]["a.json"]["base_sha256"] == sha
    assert index["base"]["a.json"] == sha
    assert "a.json:/ts" in patch["excluded_keys"]
    assert (out / "main" / "summary.json").is_file()


def test_unverifiable_against_published_goes_to_unverified(tree, stub_theory,
                                                           tmp_path):
    m, v, r, out = tree
    pub = tmp_path / "P"
    _w(pub, MAIN, "t0")
    drifted = json.loads(json.dumps(MAIN))
    drifted["a.json"]["v"] = 99         # the published value differs from main
    _w(pub, {"a.json": drifted["a.json"]}, "t0")
    index = publish("synth", m, v, r, pub, out)
    ch = {p["id"]: p for p in index["paths"]}["f--changed"]
    assert ch["changed_artifacts"] == ["sub/c.json"]
    summary = json.loads((out / "f--changed" / "summary.json")
                         .read_text("utf-8"))
    assert summary["changed"]["unverified_files"] == ["a.json"]


