def test_a_key_differing_in_any_twin_is_volatile(tmp_path):
    # A full main with a fast twin: build-mode keys must not count as a
    # deviation's result (2026-10-25: de_plane_gate.count differed fast/full).
    from metaphysica.testground.results.publish import Base
    for name, doc in (("main", {"a": 1, "mode": "full", "t": 1}),
                      ("t1", {"a": 1, "mode": "fast", "t": 1}),
                      ("t2", {"a": 1, "mode": "full", "t": 2})):
        (tmp_path / name / "AutoGenerated").mkdir(parents=True)
        (tmp_path / name / "AutoGenerated" / "x.json").write_text(
            json.dumps(doc), encoding="utf-8")
    base = Base(tmp_path / "main", [tmp_path / "t1", tmp_path / "t2"],
                tmp_path / "main")
    assert base.patterns["x.json"] == ["/mode", "/t"]


def test_declared_stochastic_subtree_is_volatile_when_twins_agree(tmp_path):
    # 2026-10-25: the rigor report's Jacobian is a random stub; main and both
    # twins all gave dimensions_for_95_variance 22 while 13 paths gave 21.
    from metaphysica.testground.results.patch import file_ops
    from metaphysica.testground.results.publish import Base
    from metaphysica.theories.pm.results import STOCHASTIC
    name = "statistical_rigor_report.json"
    main = {"jacobian_analysis": {"rank_analysis": {"dims": 22}}, "chi": 1}
    for d in ("main", "t1"):
        (tmp_path / d / "AutoGenerated").mkdir(parents=True)
        (tmp_path / d / "AutoGenerated" / name).write_text(
            json.dumps(main), encoding="utf-8")
    base = Base(tmp_path / "main", [tmp_path / "t1"], tmp_path / "main",
                STOCHASTIC)
    path = {"jacobian_analysis": {"rank_analysis": {"dims": 21}}, "chi": 1}
    assert base.patterns[name] == ["/jacobian_analysis"]
    assert file_ops(base.raw[name], path, base.patterns[name],
                    base.masked[name]) == []


def test_volatile_parameter_values_never_rank_as_moved():
    # A value that differs between two builds of main is not a path result.
    from metaphysica.testground.results.publish import volatile_ids
    from metaphysica.theories.pm.results import _key_values
    base = types.SimpleNamespace(patterns={"parameters.json": [
        "/parameters/noisy/value", "/parameters/*/timestamp",
        "/parameters/a~1b/value"]})
    vol = volatile_ids(base)
    assert vol == frozenset({"noisy", "a/b"})
    main = {"noisy": {"value": 1.0}, "real": {"value": 1.0}}
    run = {"noisy": {"value": 9.0}, "real": {"value": 2.0}}
    ids = [k["id"] for k in _key_values(run, main, vol)]
    assert "real" in ids and "noisy" not in ids
