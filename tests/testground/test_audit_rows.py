"""audit.rows and audit.classes: tolerance, loading, equivalence classes."""
import json

from metaphysica.testground.audit import changed, differs, equivalence_classes, load_rows, no_op_options


def test_differs_tolerance_nan_and_exact():
    assert not differs(1.0, 1.0 + 1e-14)
    assert differs(1.0, 1.0 + 1e-9)
    assert not differs(float("nan"), float("nan"))
    assert differs("a", "b") and not differs("a", "a")
    assert differs(None, 1)


def test_changed_counts_missing_keys():
    assert changed({"x": 1, "y": 2}, {"x": 1, "z": 3}) == frozenset({"y", "z"})


def test_load_rows(tmp_path):
    assert load_rows(tmp_path) is None
    d = tmp_path / "AutoGenerated"
    d.mkdir()
    (d / "parameters.json").write_text(json.dumps({"parameters": {"a": {"value": 1}, "b": {}}}))
    assert load_rows(tmp_path) == {"a": 1, "b": None}


def test_coincidence_is_one_class_in_input_order():
    runs = {"r1": {"x": 1.0}, "r2": {"x": 2.0}, "r3": {"x": 1.0 + 1e-15}, "r4": {"x": 2.0}}
    classes = equivalence_classes(runs)
    assert [(c.representative, c.members) for c in classes] == [
        ("r1", ["r1", "r3"]), ("r2", ["r2", "r4"])]


def test_classes_split_when_any_row_differs():
    runs = {"a": {"x": 1, "y": 1}, "b": {"x": 1, "y": 2}}
    assert len(equivalence_classes(runs)) == 2


def test_no_op_options():
    base = {"x": 1}
    singles = {("f", "b"): {"x": 1}, ("f", "c"): {"x": 2}, ("a", "z"): {"x": 1.0}}
    assert no_op_options(base, singles) == [("a", "z"), ("f", "b")]
