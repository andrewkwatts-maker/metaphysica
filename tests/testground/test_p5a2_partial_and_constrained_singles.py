_PARTIAL = (
    "import json, os, sys\n"
    "os.makedirs('AutoGenerated', exist_ok=True)\n"
    "json.dump({'parameters': {'p': {'value': 1}}},\n"
    "          open('AutoGenerated/parameters.json', 'w'))\n"
    "json.dump({'failed_steps': [{'id': 'late', 'reason': 'boom'}]},\n"
    "          open('AutoGenerated/build_status.json', 'w'))\n"
    "sys.exit(1)\n")


def _wrote(root) -> bool:
    return (root / "AutoGenerated" / "parameters.json").is_file()


def _partial_theory(with_check: bool = True):
    stage = tiny.py_stage("build", _PARTIAL,
                          **({"rows_written": _wrote} if with_check else {}))
    return tiny.make_theory(stages=[stage])


def test_run_with_rows_is_completed_with_failures(tmp_path):
    res = run_configuration(_partial_theory(), tiny.cfg(), tmp_path, "fp")
    assert res.status == COMPLETED_WITH_FAILURES and res.has_rows
    assert not res.completed and "exited 1" in res.reason and res.cacheable


def test_without_the_theorys_check_it_stays_not_runnable(tmp_path):
    res = run_configuration(_partial_theory(False), tiny.cfg(), tmp_path, "fp")
    assert res.status == NOT_RUNNABLE and not res.has_rows


def test_no_rows_no_credit(tmp_path):
    stage = tiny.py_stage("build", "import sys; sys.exit(1)", rows_written=_wrote)
    res = run_configuration(tiny.make_theory(stages=[stage]), tiny.cfg(), tmp_path, "fp")
    assert res.status == NOT_RUNNABLE


def test_audit_compares_partial_run_and_lists_its_failure(tmp_path, capsys):
    args = ["--runs-dir", str(tmp_path / "runs"), "--fingerprint-root", str(tmp_path)]
    theory = _partial_theory()
    assert cli.main(["sweep", "--singles"] + args, theory=theory) == 0
    assert "completed with failed steps" in capsys.readouterr().out
    out = tmp_path / "r.json"
    cli.main(["audit", "--out", str(out)] + args, theory=theory)
    report = json.loads(out.read_text(encoding="utf-8"))
    assert report["runs"] == 4 and report["classes"]
    (key, ids), = report["failures"].items()
    assert key == "failed: late: boom" and len(ids) == 4


def _constrained_theory():
    forks = tiny.forks()
    why = dict(rationale="test", source="test")
    cons = (Excludes("mode", "b", "seed", "low", **why),
            Excludes("mode", "c", "seed", "low", **why),
            Excludes("mode", "c", "seed", "high", **why))

    class Switches(tiny.Switches):
        def constraints(self):
            return cons
    theory = tiny.make_theory(fork_map=forks)
    object.__setattr__(theory, "switches", Switches(forks))
    return theory, cons


def test_refused_single_with_unique_repair_runs_labelled_pair():
    theory, cons = _constrained_theory()
    forks = sweep_forks(theory)
    plan = constrained_singles(forks, single_selections(forks), cons)
    assert {"mode": "b", "seed": "high"} in plan.selections
    assert "mode=b,seed=high" in plan.repaired
    assert "mode=b" in plan.repaired["mode=b,seed=high"]


def test_refused_single_without_repair_is_listed_with_reason():
    theory, cons = _constrained_theory()
    forks = sweep_forks(theory)
    plan = constrained_singles(forks, single_selections(forks), cons)
    (name, why), = plan.refused
    assert name == "mode=c" and "excludes" in why and "no other fork" in why
    assert all(s.get("mode") != "c" for s in plan.selections)


def test_dry_run_prints_repairs_and_refusals(tmp_path, capsys):
    theory, _ = _constrained_theory()
    args = ["--runs-dir", str(tmp_path / "runs"), "--fingerprint-root", str(tmp_path)]
    cli.main(["sweep", "--singles", "--dry-run"] + args, theory=theory)
    out = capsys.readouterr().out
    assert "repaired: mode=b,seed=high" in out and "refused: mode=c" in out


# -- PM: every b3_seed x n_gen_source pair -----------------------------------
def _n_gen(seed: str, source: str) -> float:
    spec = b3_path.PATHS[seed]
    return b3_path._n_gen_value(source, spec["b3"] / 8, spec["b2"] / 4)


def test_pm_constraints_accept_exactly_the_pairs_giving_three():
    cons = list(PmSwitches().constraints())
    for seed in b3_path.PATHS:
        for source in ("b3_over_dim_O", "b2_over_faces", "chi_over_24", "chi_eff_over_48"):
            ok = is_valid({"b3_seed": seed, "n_gen_source": source}, cons)
            assert ok == (_n_gen(seed, source) == 3.0), (seed, source)


def test_pm_known_n_gen_values():
    assert _n_gen("seed_43_joyce", "b3_over_dim_O") == 5.375
    assert _n_gen("seed_7_joyce", "b2_over_faces") == 0.0
    assert _n_gen("seed_24", "b2_over_faces") == 1.0
