"""`testground sweep` and `testground audit` on a tiny theory (no PM build).

The tiny theory's single stage writes AutoGenerated/parameters.json with
p (mode only), q (seed only) and r = mc + sc + 7*mc*sc (a planted interaction).

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

from __future__ import annotations

import json

import pytest

from metaphysica.testground import cli
from metaphysica.testground.sweep.execute import check_jobs, run_selections
from metaphysica.testground.sweep.selections import (label, sampled_selections,
                                                     single_selections, sweep_forks)
from metaphysica.testground.switches.model import Fork
from tests.testground import test_2c_support as tiny

_CODE = (
    "import json, os\n"
    "mc = {'a': 0, 'b': 1, 'c': 2}[os.environ.get('%s', 'a')]\n"
    "sc = {'low': 0, 'high': 1}[os.environ.get('%s', 'low')]\n"
    "os.makedirs('AutoGenerated', exist_ok=True)\n"
    "rows = {'p': mc, 'q': sc, 'r': mc + sc + 7 * mc * sc}\n"
    "json.dump({'parameters': {k: {'value': v} for k, v in rows.items()}},\n"
    "          open('AutoGenerated/parameters.json', 'w'))\n"
) % (tiny.MODE_VAR, tiny.SEED_VAR)


def _theory(gated: bool = False):
    forks = tiny.forks()
    if gated:
        seed = forks["seed"]
        forks["seed"] = Fork(seed.id, seed.question, seed.source, seed.options,
                             status=seed.status, binding=seed.binding,
                             applies_when=(("mode", "b"),))
    return tiny.make_theory(stages=[tiny.py_stage("compute", _CODE)], fork_map=forks)


def _src(tmp_path, text="1"):
    src = tmp_path / "engine_src"
    src.mkdir(exist_ok=True)
    (src / "physics.py").write_text("ALPHA = %s\n" % text, encoding="utf-8")
    return str(src)


def _args(tmp_path, src=None):
    return ["--runs-dir", str(tmp_path / "runs"),
            "--fingerprint-root", src or _src(tmp_path)]


def test_singles_count_is_options_minus_one_per_fork():
    forks = sweep_forks(_theory())
    sels = single_selections(forks)
    assert len(sels) == sum(len(f.options) - 1 for f in forks.values()) == 3
    assert sorted(label(s) for s in sels) == ["mode=b", "mode=c", "seed=high"]


def test_singles_canonical_dedup_and_only_filter():
    forks = sweep_forks(_theory(gated=True))
    assert sorted(label(s) for s in single_selections(forks)) == ["mode=b", "mode=c"]
    assert [label(s) for s in single_selections(sweep_forks(_theory()),
                                                [("mode", "c")])] == ["mode=c"]


def test_dry_run_runs_nothing(tmp_path, capsys):
    rc = cli.main(["sweep", "--singles", "--dry-run"] + _args(tmp_path), theory=_theory())
    out = capsys.readouterr().out
    assert rc == 0 and "4 selections" in out and "mode=b" in out
    assert not (tmp_path / "runs").exists()


def test_sample_is_seeded():
    forks = sweep_forks(_theory())
    a = sampled_selections(forks, 3, 5, lambda s: True)
    assert [label(s) for s in a] == [label(s) for s in sampled_selections(forks, 3, 5, lambda s: True)]
    assert len(a) == 3


def test_jobs_refused_for_shared_state_theory():
    pm_like = type("T", (), {"id": "x", "shared_state": True})()
    with pytest.raises(ValueError, match="shares state"):
        check_jobs(pm_like, 2)
    check_jobs(pm_like, 1)
    check_jobs(_theory(), 4)


def test_shared_state_declared_on_theory():
    from metaphysica.testground.theory import Theory
    from metaphysica.theories.pm import THEORY
    assert Theory.__dataclass_fields__["shared_state"].default is False
    assert THEORY.shared_state is True
    assert _theory().shared_state is False


def test_resume_skips_current_and_reruns_stale(tmp_path):
    theory, calls = _theory(), []

    def runner(*a, **kw):
        calls.append(a[1].digest)
        return run_configuration(*a, **kw)

    from metaphysica.testground.runner.worker import run_configuration
    runs = tmp_path / "runs"
    sels = [{}, {"mode": "b"}]
    res = run_selections(theory, sels, runs, "fpA", runner=runner)
    assert len(calls) == 2 and not any(r.value.cached for r in res)
    res = run_selections(theory, sels, runs, "fpA", runner=runner)
    assert len(calls) == 4 and all(r.value.cached for r in res)   # runner called, cache hit
    res = run_selections(theory, sels, runs, "fpB", runner=runner)
    assert not any(r.value.cached for r in res)                   # stale fingerprint reruns
    assert all((runs / "tiny" / fp).is_dir() for fp in ("fpA", "fpB"))


def test_joint_runs_only_overlapping_sets_and_audit_flags_non_additive(tmp_path, capsys):
    theory, args = _theory(), _args(tmp_path)
    assert cli.main(["sweep", "--singles"] + args, theory=theory) == 0
    capsys.readouterr()
    cli.main(["sweep", "--joint", "2", "--dry-run"] + args, theory=theory)
    ids = capsys.readouterr().out.splitlines()
    assert sorted(ids[1:-1]) == ["mode=b,seed=high", "mode=c,seed=high"]
    assert cli.main(["sweep", "--joint", "2"] + args, theory=theory) == 0
    out = tmp_path / "report.json"
    rc = cli.main(["audit", "--out", str(out), "--md", str(tmp_path / "r.md")] + args,
                  theory=theory)
    report = json.loads(out.read_text(encoding="utf-8"))
    assert rc == 3 and sorted(report["mismatches"]) == ["mode=b,seed=high", "mode=c,seed=high"]
    assert report["mismatches"]["mode=b,seed=high"] == ["r"]
    assert report["schema"] == "metaphysica.path_audit/2" and report["failures"] == {}
    assert "Non-additive rows" in (tmp_path / "r.md").read_text(encoding="utf-8")


def test_audit_clean_on_singles_and_lists_stale(tmp_path, capsys):
    theory = _theory()
    cli.main(["sweep", "--singles"] + _args(tmp_path, _src(tmp_path, "1")), theory=theory)
    new = _args(tmp_path, _src(tmp_path, "2"))
    cli.main(["sweep", "--singles"] + new, theory=theory)
    capsys.readouterr()
    assert cli.main(["audit"] + new, theory=theory) == 0
    assert "skipped stale fingerprints" in capsys.readouterr().out


def test_audit_flags_closed_gate_read(tmp_path):
    theory, args = _theory(gated=True), _args(tmp_path)
    cli.main(["sweep", "--singles"] + args, theory=theory)
    from metaphysica.testground.sweep.loading import load_runs
    from metaphysica.testground.runner.fingerprint import engine_fingerprint
    fp = engine_fingerprint([_src(tmp_path)])
    run = load_runs(tmp_path / "runs", "tiny", fp).runs["mode=c"]
    (run.root / "AutoGenerated" / "fork_reads.json").write_text(
        json.dumps({"reads": {"seed": 3}}), encoding="utf-8")
    out = tmp_path / "rep.json"
    assert cli.main(["audit", "--out", str(out)] + args, theory=theory) == 3
    assert json.loads(out.read_text(encoding="utf-8"))["closed_gate_reads"] == [
        {"fork": "seed", "run": "mode=c"}]
