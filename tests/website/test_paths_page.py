"""Paths page (lane F3): selection, lineage legibility, declared-only list, glow.

Playwright against the preview server; skipped when either is absent.
"""
import json
import urllib.request

import pytest

BASE = "http://127.0.0.1:8000"
URL = BASE + "/Pages/paths.html"
sync_api = pytest.importorskip("playwright.sync_api")


def _server_up() -> bool:
    """True when the preview server answers for the paths page."""
    try:
        return urllib.request.urlopen(URL, timeout=2).status == 200
    except Exception:
        return False


pytestmark = pytest.mark.skipif(not _server_up(), reason="preview server not running")


@pytest.fixture(scope="module")
def browser():
    with sync_api.sync_playwright() as p:
        try:
            b = p.chromium.launch()
        except Exception as exc:  # browser binaries not installed
            pytest.skip("chromium unavailable: %s" % exc)
        yield b
        b.close()


@pytest.fixture()
def page(browser):
    pg = browser.new_page(viewport={"width": 1280, "height": 800})
    pg.errors = []
    pg.on("console", lambda m: pg.errors.append(m.text) if m.type == "error" else None)
    pg.on("pageerror", lambda e: pg.errors.append(str(e)))
    yield pg
    pg.close()


def _open(pg, hash_=""):
    pg.goto(URL + hash_)
    pg.wait_for_selector(".pp-node")


def _view(pg, name):
    pg.click('.pp-toggle button[data-view="%s"]' % name)
    pg.wait_for_selector(".pp-node")


def test_every_node_selects_exactly_one_in_both_views(page):
    _open(page)
    for view in ("lineage", "switches"):
        _view(page, view)
        ids = page.eval_on_selector_all(".pp-node", "e => e.map(x => x.getAttribute('data-id'))")
        assert ids
        for node_id in ids:
            page.evaluate("id => document.querySelector('.pp-node[data-id=\"' + id + '\"]')"
                          ".dispatchEvent(new MouseEvent('click', {bubbles: true}))", node_id)
            assert page.locator(".pp-node.is-selected").count() == 1, node_id
    assert page.errors == []


def test_every_list_item_selects_exactly_one(page):
    _open(page)
    n = page.locator("#pp-list button").count()
    assert n > 70  # 43 paths plus the declared-only options
    for i in range(n):
        page.locator("#pp-list button").nth(i).click()
        assert page.locator("#pp-list button.is-selected").count() == 1
    assert page.errors == []


def test_main_path_highlights_and_survives_view_switch(page):
    _open(page)
    page.click('#pp-list button[data-path="main"]')
    assert page.locator(".pp-node.is-selected").count() >= 1
    _view(page, "switches")
    assert page.locator(".pp-node.is-selected").count() >= 1
    _view(page, "lineage")
    assert page.locator(".pp-node.is-selected").count() >= 1


def test_absent_node_shows_note_and_survives(page):
    _open(page)
    _view(page, "switches")
    page.click(".pp-node[data-id^='option:'] >> nth=0")
    _view(page, "lineage")
    note = page.inner_text("#pp-viewnote")
    assert note == "" or "not drawn in this view" in note
    _view(page, "switches")
    assert page.locator(".pp-node.is-selected").count() == 1


def test_lineage_nodes_are_legible_by_default(page):
    _open(page)
    width = page.evaluate("document.querySelector('.pp-node rect').getBoundingClientRect().width")
    assert width >= 85


def test_declared_only_group_and_hash(page):
    _open(page)
    groups = page.eval_on_selector_all("#pp-list h3", "e => e.map(x => x.textContent)")
    assert "Declared, not computed" in groups
    item = page.locator('#pp-list button[data-path="dark_energy_mechanism--thermal_time"]')
    assert item.count() == 1 and "no path was computed" in item.inner_text()
    _open(page, "#dark_energy_mechanism--thermal_time")
    assert page.locator('#pp-list button.is-selected[data-path="dark_energy_mechanism--thermal_time"]').count() == 1


def test_decision_and_theory_nodes_drawn_with_edges(page):
    _open(page)
    _view(page, "switches")
    assert page.locator(".pp-node[data-id^='decision:']").count() == 9
    assert page.locator(".pp-node[data-id^='theory:']").count() == 1
    assert page.locator(".pp-edge-decided").count() > 0 and page.locator(".pp-edge-excludes").count() > 0


def test_legend_states_rule_when_none_reasonable(page):
    _open(page)
    assert "No alternative currently meets the rule" in page.inner_text("#pp-legend")


def test_glow_and_selection_ring_show_together(page):
    def patch(route):
        data = json.loads(route.fetch().text())
        opt = [n for n in data["nodes"] if n["type"] == "option" and not n["attrs"].get("on_active_path")][0]
        opt["attrs"].update({"reasonable": True, "rank": 2, "delta_chi2": 1.5})
        data["ranking"] = {"reasonable_rule": "fixture rule"}
        route.fulfill(json=data)

    page.route("**/AutoGenerated/path_graph.json", patch)
    _open(page)
    _view(page, "switches")
    node = page.locator(".pp-node.pp-reasonable").first
    assert node.count() == 1
    node.click()
    css = node.locator("rect").evaluate(
        "r => { const s = getComputedStyle(r); return [s.strokeWidth, s.filter, s.stroke]; }")
    assert css[0].startswith("5") and css[1].count("drop-shadow") == 2
    assert page.errors == []
