"""The refresh patches section 7 and the chi^2 formula from the rigor report.

A fresh build renders them before the report exists (NOT AVAILABLE); the
refresh re-renders only those ids, leaving every other key untouched.
"""
import json

import pytest

from metaphysica.generators import refresh_paper_conclusions as R
from tests.test_discussion_section import CHI, _write_build

FORMULA_ID = "discussion-global-alignment"
NA = "NOT AVAILABLE"


def _stale_files(out):
    sections = {"version": "t", "count": 2, "sections": {
        "7": {"id": "7", "title": "Discussion", "contentBlocks": [
            {"type": "paragraph", "content": NA}]},
        "2": {"id": "2", "title": "Untouched", "contentBlocks": []}}}
    formulas = {"version": "t", "count": 1, "formulas": {
        FORMULA_ID: {"id": FORMULA_ID, "plain_text": NA, "latex": NA,
                     "html": NA}}}
    (out / "sections.json").write_text(json.dumps(sections))
    (out / "formulas.json").write_text(json.dumps(formulas))


@pytest.fixture
def build(tmp_path, monkeypatch):
    _write_build(tmp_path)
    out = tmp_path / "AutoGenerated"
    (out / "validation_report.json").write_text(json.dumps(
        {"summary": {"pass": 1, "marginal": 1, "tension": 1, "fail": 1}}))
    _stale_files(out)
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    return out


def test_refresh_replaces_not_available(build):
    R.refresh()
    sections = json.loads((build / "sections.json").read_text(encoding="utf-8"))["sections"]
    formula = json.loads((build / "formulas.json").read_text(encoding="utf-8"))["formulas"][
        FORMULA_ID]
    chi2 = CHI["all_scoring_rows"]["chi_squared"]
    blocks = sections["7"]["contentBlocks"]
    assert not [b for b in blocks if b.get("label") == "fit-unavailable"]
    assert "Fit quality: " + NA not in json.dumps(blocks)
    assert "{:,.2f}".format(chi2) in json.dumps(blocks)
    assert NA not in json.dumps(formula)
    assert "%.2f" % chi2 in formula["plain_text"]
    assert sections["2"] == {"id": "2", "title": "Untouched",
                             "contentBlocks": []}


def test_refresh_fails_early_without_files(build):
    (build / "sections.json").unlink()
    with pytest.raises(SystemExit, match="sections.json"):
        R.refresh()
