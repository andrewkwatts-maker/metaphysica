"""Sprint 6 — ``metaphysica.help`` + the ``metaphysica`` CLI.

Smoke-tests the new help() function and the ``metaphysica get/list/help``
subcommands.
"""
from __future__ import annotations

import io
import sys
from pathlib import Path

import pytest

import metaphysica
from metaphysica._catalog import set_last_build_dir
from metaphysica._help import cli


PM_TREE = Path("H:/Github/PrincipiaMetaphysica")


@pytest.fixture(scope="module", autouse=True)
def _point_catalog_at_pm_build():
    if PM_TREE.is_dir() and (PM_TREE / "AutoGenerated" / "parameters.json").exists():
        set_last_build_dir(PM_TREE)
    yield
    set_last_build_dir(None)


# ---------------------------------------------------------------------------
# help()
# ---------------------------------------------------------------------------


def test_help_overview_no_args(capsys):
    """No-arg help prints the overview banner."""
    metaphysica.help()
    out = capsys.readouterr().out
    assert "metaphysica" in out.lower()
    assert "formats" in out.lower() or "format" in out.lower()
    assert "kinds" in out.lower() or "kind" in out.lower()


def test_help_for_constant(capsys):
    """help('b3') prints kind=constant, value, and example get() calls."""
    metaphysica.help("b3", kind="constant")
    out = capsys.readouterr().out
    assert "b3" in out
    assert "constant" in out.lower()
    # Examples block must mention the typed aliases.
    assert "GetLaTeX" in out or "get(" in out


def test_help_for_unknown_writes_stderr(capsys):
    """help on a bogus name must NOT raise; it writes to stderr."""
    metaphysica.help("not-a-real-entity-zzz")
    err = capsys.readouterr().err
    assert "No metaphysica entity" in err or "not-a-real" in err.lower()


