def test_cli_get_json_for_constant(capsys):
    rc = cli(["get", "b3", "--fmt", "json", "--kind", "constant"])
    assert rc == 0
    out = capsys.readouterr().out
    assert out.strip().startswith("{")
    assert "24" in out


def test_cli_get_latex_for_constant(capsys):
    rc = cli(["get", "b3", "--fmt", "latex", "--kind", "constant"])
    assert rc == 0
    out = capsys.readouterr().out
    assert "b3" in out or "24" in out


def test_cli_list_kind(capsys):
    rc = cli(["list", "constant"])
    assert rc == 0
    out = capsys.readouterr().out
    # At least the b3 entry must appear.
    assert any("b3" in line for line in out.splitlines())


def test_cli_list_all(capsys):
    rc = cli(["list"])
    assert rc == 0
    out = capsys.readouterr().out
    # Output prints a "# kind (count)" banner per kind.
    assert "# constant" in out
    assert "# quark" in out


def test_cli_get_unknown_returns_nonzero(capsys):
    rc = cli(["get", "not-a-thing-xyz", "--fmt", "json"])
    assert rc == 1
    err = capsys.readouterr().err
    assert "No metaphysica entity" in err or "metaphysica get" in err


def test_cli_get_with_out_writes_file(tmp_path, capsys):
    target = tmp_path / "b3.json"
    rc = cli([
        "get", "b3",
        "--fmt", "json",
        "--kind", "constant",
        "--out", str(target),
    ])
    assert rc == 0
    assert target.exists()
    assert target.read_text(encoding="utf-8").strip().startswith("{")
