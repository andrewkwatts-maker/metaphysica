def test_text_follows_the_off_path_seed(tmp_path, monkeypatch):
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    _write_build(tmp_path)
    monkeypatch.setenv("METAPHYSICA_VARIANT_B3_SEED", "seed_24")
    blocks = C.section7_blocks()
    text = _text(blocks)
    assert "seed_24" in text and "not on the adopted path" in text
    assert "DOES NOT HOLD" in text
    assert any(b.label == "artifact-seed-mismatch" for b in blocks)
    monkeypatch.delenv("METAPHYSICA_VARIANT_B3_SEED")
    assert "not on the adopted path" not in _text(C.section7_blocks())


