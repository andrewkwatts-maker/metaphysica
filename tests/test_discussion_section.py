"""Section 7 is generated from live state: statuses, numbers and path follow it.

The artifacts are a synthetic build directory (METAPHYSICA_OUT), so every
expected number below is computed from the fixture or the certificate, never
typed in beside the code under test.
"""

import json
import re
from pathlib import Path

import pytest

from metaphysica.simulations.PM.paper import conclusions as C
from metaphysica.simulations.PM.paper.discussion import DiscussionV16

CHI = {"all_scoring_rows": {"chi_squared": 1234.5, "n": 10, "reduced": 123.45},
       "excluding_falsified": {"chi_squared": 100.25, "n": 8,
                               "reduced": 12.53},
       "withdrawn_rows": [{"path": "a"}, {"path": "b"}]}
COUNTS = {"pass": 11, "marginal": 4, "tension": 3, "fail": 7}


def _row(value, status):
    return {"value": value, "status": status, "source_simulation": "sim_x"}


def _write_build(root: Path, with_fit=True, b3=43):
    out = root / "AutoGenerated"
    out.mkdir(parents=True)
    params = {c.path: _row(1.5, "DERIVED") for c in C.CONCLUSIONS}
    params["alp.mass_meV"] = _row(2.5, "PREDICTED")
    params["cosmology.wa_thawing"] = _row(-0.5, "FITTED")
    params["cosmology.racetrack_Re_T"] = _row(7.0, "CALIBRATED")
    params["algebra.gaugino_cabibbo_derived"] = _row(0.2, "FALSIFIED")
    params["particle.b3"] = _row(b3, "DERIVED")
    (out / "parameters.json").write_text(json.dumps({"parameters": params}))
    if with_fit:
        (out / "statistical_rigor_report.json").write_text(
            json.dumps({"chi_squared_from_rows": CHI}))
        (out / "validation_report.json").write_text(
            json.dumps({"summary": COUNTS}))
    return out


@pytest.fixture
def build(tmp_path, monkeypatch):
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    monkeypatch.delenv("METAPHYSICA_VARIANT_B3_SEED", raising=False)
    return _write_build(tmp_path)


def _text(blocks):
    parts = []
    for b in blocks:
        parts.append(b.content or "")
        parts.extend(b.items or [])
    return "\n".join(parts)


def test_adopted_path_is_stated_and_dead_ends_only_as_superseded(build):
    blocks = C.section7_blocks()
    rest = [b for b in blocks if b.label != "superseded-paths"]
    text = _text(rest)
    assert "seed_43_joyce" in text
    assert "TCS" not in text and "Twisted" not in text
    assert not re.search(r"b(<sub>)?_?3(</sub>)? = 24", text)
    sup = [b for b in blocks if b.label == "superseded-paths"]
    assert len(sup) == 1 and C.PATHS_LINK in sup[0].content


def test_every_conclusion_block_has_a_status_tag(build):
    blocks = [b for b in C.section7_blocks()
              if (b.label or "").startswith("conclusion-")
              and b.label != "conclusion-scope"]
    assert len(blocks) == len(C.CONCLUSIONS)
    for b in blocks:
        m = re.match(r"<strong>\[(\w+)\]</strong>", b.content)
        assert m and m.group(1) in C.STATUS_TAGS, b.label


def test_status_tags_follow_the_registry_row(build):
    tags = {r["spec"].key: r["tag"] for r in C.physics_rows()}
    assert tags["alp"] == "predicted" and tags["wa"] == "fitted"
    assert tags["re_t"] == "calibrated" and tags["cabibbo"] == "open"
    assert tags["n_gen"] == "derived"


def test_unmapped_status_and_missing_row_fail_visibly(build):
    with pytest.raises(ValueError):
        C.status_tag("ESTABLISHED")
    spec = C.Conclusion("x", "Absent", "no.such.row")
    row = C._conclusion_row(spec, {})
    assert row["tag"] == "open" and "NOT AVAILABLE" in row["source"]


def test_fit_numbers_match_the_artifacts(build):
    text = _text(C.fit_blocks(C.load_fit_summary()))
    assert "{:,.2f}".format(CHI["all_scoring_rows"]["chi_squared"]) in text
    assert "n = %d" % CHI["all_scoring_rows"]["n"] in text
    for k, label in (("pass", "PASS"), ("marginal", "MARGINAL"),
                     ("tension", "TENSION"), ("fail", "FAIL")):
        assert "%s %d" % (label, COUNTS[k]) in text
    f = DiscussionV16().get_formulas()[0]
    assert f.value == CHI["all_scoring_rows"]["chi_squared"]
    assert "1{,}234.50" in f.latex and "sigma_bar" not in f.plain_text
    assert "sigma_bar" not in " ".join(f.terms)


def test_geometry_statements_are_the_certificate(build):
    cert = C._certificate_by_label()
    text = _text(C.geometry_blocks(cert))
    for label in C.GEOMETRY_LABELS:
        assert label in text and cert[label]["statement"] in text


