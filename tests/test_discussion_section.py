def test_missing_fit_artifact_is_stated_and_no_number_is_invented(
        tmp_path, monkeypatch):
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    _write_build(tmp_path, with_fit=False)
    fit = C.load_fit_summary()
    if fit["available"]:          # a fallback location supplied a real build
        pytest.skip("another artifact directory supplies the fit files")
    text = _text(C.fit_blocks(fit))
    assert "NOT AVAILABLE" in text and "chi&sup2; =" not in text
    assert DiscussionV16().get_formulas()[0].value is None


