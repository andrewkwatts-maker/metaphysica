"""A parameter stated by several formulas with differing latex is a duplicate statement.

Unit tests cover the grouping and keeper rules. The ratchet counts the groups on
the published build (PM_PUBLISHED_ROOT) and is skipped when it is absent. The
ceiling only goes down.
"""
from __future__ import annotations

import os
from pathlib import Path

import pytest

from metaphysica.generators import duplicate_statements as ds

PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT",
                                "H:/claude-scratch/runs_g/active"))

#: Groups permitted on the published build. Only goes down.
CEILING_GROUPS = 56
CEILING_WITHOUT_KEEPER = 34


def _f(latex, *outs):
    return {"latex": latex, "output_params": list(outs)}


def test_single_statement_is_not_a_group():
    assert ds.duplicate_groups({"a": _f("x=1", "p")}, {}) == []


def test_same_latex_modulo_whitespace_is_not_a_group():
    fs = {"a": _f("x = 1", "p"), "b": _f("x=1", "p")}
    assert ds.duplicate_groups(fs, {}) == []


def test_differing_latex_is_a_group_with_the_named_keeper():
    fs = {"a": _f("x=1", "p"), "b": _f("x=2", "p")}
    ps = {"p": {"metadata": {"derivation_formula": "b"}}}
    (g,) = ds.duplicate_groups(fs, ps)
    assert (g.param, g.formulas, g.keeper) == ("p", ("a", "b"), "b")


def test_keeper_outside_the_group_is_no_keeper():
    fs = {"a": _f("x=1", "p"), "b": _f("x=2", "p")}
    ps = {"p": {"metadata": {"derivation_formula": "zzz"}}}
    assert ds.duplicate_groups(fs, ps)[0].keeper is None


def test_alias_takes_the_targets_derivation_formula():
    ps = {"t": {"metadata": {"derivation_formula": "f"}},
          "q": {"metadata": {"alias_of": "t"}}}
    assert ds.derivation_formula(ps["q"], ps) == "f"


def test_published_duplicate_groups_do_not_grow():
    if not (PUBLISHED / "AutoGenerated" / "formulas.json").is_file():
        pytest.skip("no published build at %s" % PUBLISHED)
    groups = ds.duplicate_groups(*ds.load(PUBLISHED))
    assert len(groups) <= CEILING_GROUPS
    assert sum(g.keeper is None for g in groups) <= CEILING_WITHOUT_KEEPER
