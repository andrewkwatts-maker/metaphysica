"""One artifact search order, shared by every test that reads a build artifact.

WHY THIS EXISTS
---------------
Fifty-three test files each carried their own copy of this candidate list:

    raw = os.environ.get("METAPHYSICA_OUT")
    candidates = []
    if raw:
        candidates.append(Path(raw) / "AutoGenerated")
    candidates += [
        Path("H:/Github/PrincipiaMetaphysica/AutoGenerated"),
        Path(__file__).resolve().parents[1] / "AutoGenerated",
    ]

Three defects rode in that block, and all three were invisible because a
missing artifact SKIPS rather than fails:

1.  ``Path("H:/Github/...")`` is one developer's absolute Windows path. On
    POSIX it is a RELATIVE path -- a directory literally named ``H:`` under
    the current working directory -- so it never resolves, and the sibling
    checkout it was meant to name was unreachable. Measured 2026-09-22 in the
    remote environment: 846 skips, among them the seven validation-report
    tests that debt (h) was raised for, all because the published artifacts
    sat in a sibling directory no candidate pointed at.

2.  The order put that path AHEAD of the repo-local tree. On the author's
    machine H:/Github/PrincipiaMetaphysica IS the published checkout and the
    repo-local ``AutoGenerated`` is build scratch, so the order was right
    there and wrong everywhere else -- and nothing in the block said which
    role either path was playing.

3.  Resolution was per-DIRECTORY: the first candidate that ``is_dir()`` won,
    whatever it contained. A partial build-scratch tree therefore shadowed a
    complete published one. Measured the same day: an incomplete build left
    25 artifacts in the repo-local tree against 67 published, with
    ``formulas.json`` at 761 KB against 1.69 MB, and a ``certificates/``
    directory holding per-category files but none of the per-gate ones --
    which is exactly how ``test_strategy_c_all_pass`` came to fail looking
    for ``G01_integer_root_parity.json`` in a directory that existed and was
    simply the wrong one.

THE ORDER, AND WHY EACH POSITION IS WHERE IT IS
-----------------------------------------------
``METAPHYSICA_OUT``   an explicit instruction from the caller. Always wins.
repo-local            FIRST among the implicit roots, per the standing
                      directive. Safe here only because resolution is
                      per-FILE (below): when the local tree is a partial
                      build it simply does not carry the file, and the
                      search falls through instead of shadowing.
sibling checkout      the PUBLISHED tree, addressed portably as
                      ``../PrincipiaMetaphysica`` rather than by one
                      machine's drive letter.
legacy Windows path   kept last so the author's tree still resolves, and
                      kept at all because deleting it would silently change
                      behaviour on the one machine where it works.

RESOLUTION IS PER-FILE, NOT PER-DIRECTORY
-----------------------------------------
:func:`artifact` returns the first root that actually HOLDS the requested
file. That is the whole reason repo-local can safely go first: "this tree
exists" and "this tree has what you asked for" are different questions, and
conflating them is defect 3 above.

:func:`autogen_dir` is kept for callers that genuinely want a directory, and
it deliberately requires the directory to be non-empty -- an empty
``AutoGenerated/`` is a directory that exists and answers nothing.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import List, Optional, Tuple

__all__ = [
    "search_roots",
    "artifact",
    "autogen_dir",
    "provenance",
    "LEGACY_WINDOWS_ROOT",
]

#: The author's published checkout on their own machine. Kept last in the
#: order; see the module docstring.
LEGACY_WINDOWS_ROOT = Path("H:/Github/PrincipiaMetaphysica")


def _repo_root() -> Path:
    """The `metaphysica` checkout this test file lives in."""
    return Path(__file__).resolve().parents[1]


def search_roots() -> List[Tuple[str, Path]]:
    """(role, root) in search order. The roles are part of the contract."""
    roots: List[Tuple[str, Path]] = []
    raw = os.environ.get("METAPHYSICA_OUT")
    if raw:
        roots.append(("METAPHYSICA_OUT", Path(raw)))
    repo = _repo_root()
    roots.append(("repo-local", repo))
    roots.append(("sibling-checkout", repo.parent / "PrincipiaMetaphysica"))
    roots.append(("legacy-windows", LEGACY_WINDOWS_ROOT))
    return roots


def artifact(name: str) -> Optional[Path]:
    """The first root that actually holds ``AutoGenerated/<name>``.

    ``name`` may contain separators (``certificates/G01_x.json``). Returns
    None when no root carries it, so the caller decides between skipping and
    failing -- this helper never calls ``pytest.skip`` itself, because a
    helper that skips makes every caller's failure mode invisible.
    """
    for _role, root in search_roots():
        candidate = root / "AutoGenerated" / name
        if candidate.exists():
            return candidate
    return None


def autogen_dir() -> Optional[Path]:
    """The first NON-EMPTY ``AutoGenerated`` directory, or None."""
    for _role, root in search_roots():
        path = root / "AutoGenerated"
        if path.is_dir() and any(path.iterdir()):
            return path
    return None


def provenance(name: str) -> Optional[str]:
    """Which role supplied ``name``, for a test that wants to say so."""
    for role, root in search_roots():
        if (root / "AutoGenerated" / name).exists():
            return role
    return None


def repo_file(relative: str) -> Optional[Path]:
    """The first root holding ``<root>/<relative>``, for non-artifact files.

    The register (``docs/OUTSTANDING_ISSUES.md``) and the site tree live
    beside ``AutoGenerated`` rather than inside it, and several tests reached
    them through a bare ``Path("H:/Github/PrincipiaMetaphysica/...")`` with no
    candidate list at all -- a single absolute path that resolved on exactly
    one machine and skipped everywhere else.
    """
    for _role, root in search_roots():
        candidate = root / relative
        if candidate.exists():
            return candidate
    return None


def published_tree() -> Optional[Path]:
    """The first root that looks like a BUILT PrincipiaMetaphysica checkout.

    "Looks like" is defined by carrying ``AutoGenerated/parameters.json``,
    because that is what the callers actually need; a directory that merely
    exists under the right name is the per-directory mistake again.
    """
    for _role, root in search_roots():
        if (root / "AutoGenerated" / "parameters.json").is_file():
            return root
    return None
