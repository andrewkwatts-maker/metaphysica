"""A parameter must be able to name the formula that derives it.

WHY THIS EXISTS
---------------
``Parameter(derivation_formula=...)`` is declared on 315 definitions across
the simulation modules. It reached ZERO exported artifacts: no
``derivation_formula`` or ``derivationFormula`` key appeared anywhere under
``AutoGenerated/``. ``register_outputs`` read every other field off the
parameter definition -- description, theory_uncertainty, eml_description,
the experimental bound -- and passed this one over, so no consumer could
link a parameter to the formula producing it, and ``derivation_chain``
shipped empty for all 715 rows.

It is now carried through metadata the same way ``eml_description`` is, and
surfaced at top level by the exporter. 195 parameters carry one, naming 114
distinct formulas.

The tests check the link both exists AND resolves: a declared formula id
that does not appear in ``formulas.json`` is a dangling reference, which is
the failure this feature would otherwise introduce quietly.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import pytest


def _autogen() -> Path:
    raw = os.environ.get("METAPHYSICA_OUT")
    candidates = []
    if raw:
        candidates.append(Path(raw) / "AutoGenerated")
    candidates += [
        Path("H:/Github/PrincipiaMetaphysica/AutoGenerated"),
        Path(__file__).resolve().parents[1] / "AutoGenerated",
    ]
    for path in candidates:
        if path.is_dir() and (path / "parameters.json").is_file():
            return path
    pytest.skip("no parameters.json; run the build first")


def _load(name, key):
    return json.loads((_autogen() / name).read_text(encoding="utf-8"))[key]


def test_the_link_reaches_the_artifact_at_all():
    """It was declared 315 times and exported zero times."""
    params = _load("parameters.json", "parameters")
    carrying = [k for k, v in params.items() if v.get("derivation_formula")]
    assert carrying, (
        "no parameter carries a derivation_formula. It is declared on "
        "hundreds of Parameter definitions, so a count of zero means the "
        "field is being dropped between definition and export again."
    )
    assert len(carrying) > 100


def test_every_named_formula_resolves():
    """A dangling id is worse than no link -- it looks like provenance."""
    params = _load("parameters.json", "parameters")
    formulas = _load("formulas.json", "formulas")
    dangling = sorted({
        v["derivation_formula"] for v in params.values()
        if v.get("derivation_formula")
    } - set(formulas))
    assert len(dangling) <= 1, (
        f"{len(dangling)} parameters name a formula that does not exist in "
        f"formulas.json: {dangling[:10]}"
    )


def test_the_one_known_dangling_id_is_the_expected_one():
    """Pin it, so a second one cannot appear unnoticed.

    odowd-h0-composite is declared by a parameter but defined by no
    simulation that reaches the formula export. Either the formula should be
    published or the declaration dropped; it is recorded here rather than
    silently tolerated.
    """
    params = _load("parameters.json", "parameters")
    formulas = _load("formulas.json", "formulas")
    dangling = {
        v["derivation_formula"] for v in params.values()
        if v.get("derivation_formula")
    } - set(formulas)
    assert dangling <= {"odowd-h0-composite"}, (
        f"a new dangling derivation_formula appeared: "
        f"{sorted(dangling - {'odowd-h0-composite'})}"
    )


def test_the_link_survives_the_metadata_hop():
    """It travels definition -> metadata -> top level; both hops must work."""
    params = _load("parameters.json", "parameters")
    for entry in params.values():
        top = entry.get("derivation_formula")
        if not top:
            continue
        meta = (entry.get("metadata") or {}).get("derivation_formula")
        assert meta == top, (
            "the top-level value disagrees with the metadata it came from"
        )
        break
    else:
        pytest.skip("no parameter carries the field")
