"""Ratchet per published text surface: retired-pathway prose only goes down.

Companion to test_superseded_geometry_prose.py (sections.json, ceiling 0). The
vocabulary is the retired b3 = 24 / TCS claims plus the claim of every DISABLED
option in variants.FORKS, so disabling a new option widens the scan with no
edit. Published surfaces are read from a finished build (PM_PUBLISHED_ROOT,
default H:/claude-scratch/runs_g/active) and skipped when it is absent. The
website source is scanned in place. Ceilings only go down.
"""
from __future__ import annotations

import os
from pathlib import Path

import pytest

from metaphysica.generators import superseded_scan as scan

PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT",
                                "H:/claude-scratch/runs_g/active"))

#: Active-presenting hits permitted per surface. Only goes down.
CEILINGS = {"autogen": 159, "pages": 0, "website": 0}


def _active(surface: str):
    if surface != "website" and not PUBLISHED.is_dir():
        pytest.skip("no published build at %s" % PUBLISHED)
    return scan.active_hits(scan.scan_surface(surface, PUBLISHED))


@pytest.mark.parametrize("surface", sorted(CEILINGS))
def test_surface_under_ceiling(surface):
    hits = _active(surface)
    files = sorted({h["section"] for h in hits})
    assert len(hits) <= CEILINGS[surface], "%d hits in %s" % (len(hits), files[:8])


def test_website_source_pages_carry_no_active_hit():
    """The hand-written pages and scripts (not generated data copies) are clean."""
    pages = [h["section"] for h in _active("website")
             if not h["section"].startswith("website/AutoGenerated/")]
    assert pages == []


def test_vocabulary_comes_from_disabled_options():
    assert scan.is_hit("so n_s = 1 - 2/b3, as claimed")
    assert scan.is_hit("the seed b<sub>3</sub> = 7, the limit")
    assert scan.is_hit("H0 = H0_planck (1 + sin^2(31 deg)/2)")
    assert not scan.is_hit("the adopted b3 = 43 seed")
    assert not scan.is_hit("b3 = 70 is not a claim")
    assert not scan.is_hit("b_3 = 7 flat invariants + 3 x 12")


def test_text_file_hit_is_labelled_by_nearby_retired_wording(tmp_path):
    f = tmp_path / "a.md"
    pad = "x" * 400
    f.write_text("first b3 = 24 stands alone." + pad + "\nlater, formerly b3 = 24 was used.",
                 encoding="utf-8")
    hits = scan.scan_file(f, "x")
    assert [h["in_callout"] for h in hits] == [False, True]


def test_json_file_scanned_by_string(tmp_path):
    f = tmp_path / "a.json"
    f.write_text('{"k": {"v": "TCS gluing", "w": "fine"}}', encoding="utf-8")
    assert [h["in_callout"] for h in scan.scan_file(f, "j")] == [False]
