def _load(path: Path) -> Optional[Dict[str, Any]]:
    try:
        blob = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    return blob.get("parameters", blob) if isinstance(blob, dict) else None


def _bundled_parameters() -> Dict[str, Any]:
    params = _load(_PKG / "data" / "parameters.json")
    assert params, "the bundled snapshot metaphysica/data/parameters.json is " \
                   "unreadable or empty; it ships in the wheel and Get() " \
                   "resolves through it, so its absence is a packaging break"
    return params


def _export_dir() -> Optional[Path]:
    """The AutoGenerated/ tree of a DELIBERATE build, or None.

    Only two locations count: whatever `METAPHYSICA_OUT` names (which is how
    `metaphysica.build` tells every step where to write) and `<repo>/site/`,
    the target of the documented standard command. A bare `AutoGenerated/`
    under the current directory does NOT count: it is where individual modules
    scribble when run ad hoc -- including the fork-sweep tests in this very
    suite, which leave a `variants.json` behind reporting whichever option the
    sweep was on. Treating that as a published export would make this gate
    report another test's scratch file as a leak.
    """
    candidates = []
    out = os.environ.get("METAPHYSICA_OUT")
    if out:
        candidates.append(Path(out) / "AutoGenerated")
    candidates.append(_PKG.parents[1] / "site" / "AutoGenerated")
    for candidate in candidates:
        if candidate.is_dir():
            return candidate
    return None


def _built_parameters() -> Optional[Dict[str, Any]]:
    """A built `parameters.json`, if there is a build target. Never the wheel's."""
    export = _export_dir()
    if export is None:
        return None
    path = export / "parameters.json"
    if path.resolve() == (_PKG / "data" / "parameters.json").resolve():
        return None                                  # pragma: no cover
    return _load(path) if path.is_file() else None


