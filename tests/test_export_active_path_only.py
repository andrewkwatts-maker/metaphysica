def test_the_gate_is_pointed_at_the_adopted_path():
    """The adopted path is what the pins below were measured against."""
    assert resolve_path() == _ADOPTED, (
        "this file pins an export measured against %r, but the live adopted "
        "path is %r. Re-measure the inventory before touching the pins."
        % (_ADOPTED, resolve_path())
    )
    live = downstream()
    assert live["b3"] == seed_values(_ADOPTED)[0]
    assert live["b2"] == seed_values(_ADOPTED)[1]
    assert abs(live["w0"] - ACTIVE["w0"]) < 1e-12
    # The two columns must actually differ, or every verdict below is vacuous.
    for quantity in ACTIVE:
        assert abs(ACTIVE[quantity] - OFF_PATH[quantity]) > 1e-9, (
            "%s takes the same value on both paths, so it cannot discriminate "
            "and must not be in CHECKED_FIELDS" % quantity
        )


def test_the_off_path_option_is_kept_and_stays_labelled():
    """Purity of the export is not a licence to delete the rival."""
    assert _OFF_PATH in PATHS, (
        "seed_24 was removed. It must stay runnable and labelled; the export "
        "is what has to be pure, not the decision space."
    )
    assert PATHS[_OFF_PATH]["reachable_by_joyce"] is False
    assert PATHS[_ADOPTED]["reachable_by_joyce"] is True


def test_the_verdict_function_separates_the_cases():
    """Cheap and structural: the detector must not put everything in one bin."""
    assert verdict(ACTIVE["b3"], "b3") == "ACTIVE"
    assert verdict(OFF_PATH["b3"], "b3") == "OFF_PATH"
    assert verdict(None, "b3") == "ABSENT"
    assert verdict(ACTIVE["b3"] + 1.0, "b3") == "OTHER"
    assert verdict("BROKEN_ON_ADOPTED_SEED(b3=43)", "b3") == "OTHER"


