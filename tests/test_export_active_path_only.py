#: ABSENT from CHECKED_FIELDS. It is forked as `chi_eff_route` with status OPEN
#: and MUST STAY UNRULED, and `b3_path.downstream()` reads chi as an
#: independent registry row rather than as 6 b_3. Calling it a leak here would
#: be adopting that ruling. It is recorded in docs/EXPORT_PATH_PURITY.md as
#: measurement instead.
_EXCLUDED_BY_OPEN_RULING = ("topology.mephorash_chi", "geometry.chi_eff_total")


def verdict(value: Any, quantity: str) -> str:
    """ACTIVE / OFF_PATH / ABSENT / OTHER for one published value."""
    if value is None:
        return "ABSENT"
    try:
        v = float(value)
    except (TypeError, ValueError):
        return "OTHER"
    for name, table in (("ACTIVE", ACTIVE), ("OFF_PATH", OFF_PATH)):
        want = table[quantity]
        if abs(v - want) <= 1e-6 * max(1.0, abs(want)):
            return name
    return "OTHER"


def _verdict_map(params: Dict[str, Any]) -> Dict[str, str]:
    out = {}
    for key, quantity in CHECKED_FIELDS.items():
        record = params.get(key)
        raw = record.get("value") if isinstance(record, dict) else record
        out[key] = verdict(raw, quantity)
    return out


