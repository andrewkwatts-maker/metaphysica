# ---------------------------------------------------------------------------
# The seed-derived family, computed from the SSoT for both paths.
# ---------------------------------------------------------------------------
def _family(path: str) -> Dict[str, float]:
    """Every quantity this file checks, evaluated at one path's seed.

    Each formula is the one the framework's own writers declare for it, so a
    value that matches the OFF_PATH column is a value produced by the abandoned
    seed -- not merely a number that happens to coincide.
    """
    b3, b2 = seed_values(path)
    return {
        "b3": float(b3),
        "b2": float(b2),
        "w0": -(b3 - 1) / b3,                      # -(b_3 - 1)/b_3
        "k_gimel": b3 / 2.0 + 1.0 / math.pi,       # b_3/2 + 1/pi
        "wa_inv_sqrt": -1.0 / math.sqrt(b3),       # -1/sqrt(b_3)
        "wa_four_over_sqrt": -4.0 / math.sqrt(b3),  # -4/sqrt(b_3)
        "racetrack": 2.0 * math.pi / b3,           # 2 pi / b_3
    }


ACTIVE = _family(_ADOPTED)
OFF_PATH = _family(_OFF_PATH)

