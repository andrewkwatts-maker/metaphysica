def test_a_built_export_carries_the_active_path_as_well_as_the_leak():
    """The other direction, on the same artifact: the 43 path must be THERE.

    Ten of the seventeen checked rows are pinned ACTIVE in a real build. If an
    export ever carries none of them -- because it was produced under the
    off-path override, or because the writers stopped following the seed -- the
    map equality above already fails; this states the requirement in its own
    right so the failure reads as "the active path is missing" rather than as
    a diff.
    """
    params = _built_parameters()
    if params is None:
        pytest.skip("no built AutoGenerated/parameters.json build target")
    measured = _verdict_map(params)
    active = {k for k, v in measured.items() if v == "ACTIVE"}
    expected = {k for k, v in BUILT_VERDICTS.items() if v == "ACTIVE"}
    # Deliberately one-directional: MORE active rows than pinned is a repair,
    # and the map-equality test above is the one that insists a repair updates
    # the inventory. This one only ever says "the 43 path is missing".
    assert not expected - active, (
        "the active path is not published where it must be. Missing: %s. An "
        "export produced under METAPHYSICA_VARIANT_B3_SEED=%s looks exactly "
        "like this, and it is not a publishable export."
        % (sorted(expected - active), _OFF_PATH)
    )


def test_built_sections_prose_names_the_active_seed():
    """sections.json prose: partly generated from the seed, partly frozen.

    `b3_path.narration()` builds its sentences from the live path, so a build
    on the adopted seed puts `42/43` and `b_3 = 43` into the prose; an export
    made under the off-path override contains neither. The frozen abstract
    sentence ("w0 = -23/24 ... from b3=24 topology") is in the SAME artifact,
    which is why both halves are asserted here.
    """
    export = _export_dir()
    sections = export / "sections.json" if export else None
    if sections is None or not sections.is_file():
        pytest.skip("no built AutoGenerated/sections.json build target")
    text = sections.read_text(encoding="utf-8")

    active_marks = {m: text.count(m) for m in ("42/43", "b\u2083 = 43")}
    assert all(count > 0 for count in active_marks.values()), (
        "built sections.json names no active-path w_0 or b_3 (%s). Either it "
        "was produced under the off-path override, or the narration stopped "
        "following the seed." % active_marks
    )
    assert text.count("23/24") > 0, (
        "the frozen abstract sentence is gone from sections.json. If the "
        "abstract now narrates the active path, drop its entries from "
        "FROZEN_WRITER_LITERALS and this assertion in the same change."
    )


def test_the_fork_manifest_is_published_and_reports_the_adopted_seed():
    """The manifest is WANTED -- ids, questions, options, statuses.

    What it must not do is disagree with the export about which option is in
    force, which is how an off-path number becomes readable as the framework's
    result even when every value field is clean.
    """
    export = _export_dir()
    manifest = export / "variants.json" if export else None
    if manifest is None or not manifest.is_file():
        pytest.skip("no built AutoGenerated/variants.json build target")
    blob = json.loads(manifest.read_text(encoding="utf-8"))
    fork = blob.get("forks", {}).get("b3_seed")
    assert fork, "variants.json no longer publishes the b3_seed fork"
    assert fork["selected"] == _ADOPTED
    ids = {option["id"] for option in fork["options"]}
    assert _OFF_PATH in ids, (
        "the manifest stopped listing seed_24. Publishing the option set is "
        "the documentation this project wants; only value fields have to be "
        "pure."
    )
