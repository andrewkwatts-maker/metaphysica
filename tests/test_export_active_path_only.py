"""The published artifacts must describe the ACTIVE path, and only it.

WHAT THIS GATES
===============
`b3_seed = seed_43_joyce` is ADOPTED (author ruling 2026-09-22): (b_2, b_3) =
(12, 43), DERIVED, with `simulations/PM/geometry/b3_path.py` as the SSoT. The
off-path option `seed_24` stays RUNNABLE via `METAPHYSICA_VARIANT_B3_SEED=
seed_24` and stays LABELLED unreachable, and that is deliberate -- nothing here
asks for it to be deleted.

What this file gates is narrower and different: a reader of a PUBLISHED artifact
must never meet an off-path NUMBER sitting in a value field. The fork MANIFEST
(`AutoGenerated/variants.json`: fork id, question, option ids, statuses, which
one is adopted) is documentation of the decision space and is wanted. A value
field is not documentation.

WHY THE VERDICTS ARE PINNED AS EXACT MAPS
=========================================
The leak inventory below was MEASURED (2026-09-26, see
`docs/EXPORT_PATH_PURITY.md` for the seed-diff evidence), and it is pinned as
an exact key -> verdict map rather than a count with a ceiling. Three failure
directions matter and a one-way check catches only one of them:

  * a NEW off-path value appears            -> ACTIVE/ABSENT becomes OFF_PATH
  * a leak is REPAIRED                      -> OFF_PATH becomes ACTIVE, and the
                                               pin below has to be updated with
                                               it, which is the point: the
                                               inventory is a record, not a
                                               tolerance
  * the export produces NEITHER value       -> the key reads ABSENT, which is
                                               not equal to either pinned
                                               verdict, so an empty or
                                               half-written artifact fails
                                               instead of passing quietly

NO PHYSICS VALUE IS RESTATED HERE
=================================
The active and off-path numbers are COMPUTED from `b3_path.seed_values()` for
the two named paths, so this file cannot drift from the SSoT and cannot be used
to smuggle a number in. If the adopted path ever changes,
`test_the_gate_is_pointed_at_the_adopted_path` fails first and says so, rather
than every other assertion failing with a misleading message.

Copyright (c) 2025-2026 Andrew Keith Watts. All rights reserved.
"""

