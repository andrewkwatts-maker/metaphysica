def test_bundled_snapshot_verdicts_are_exactly_the_pinned_inventory():
    """`data/parameters.json` -- the wheel's snapshot, read by Get()."""
    measured = _verdict_map(_bundled_parameters())
    assert measured == BUNDLED_VERDICTS, (
        "the bundled snapshot's path purity changed.\n"
        "  new off-path values: %s\n"
        "  repaired (update BUNDLED_VERDICTS with them): %s\n"
        "  other movement: %s"
        % (
            sorted(k for k, v in measured.items()
                   if v == "OFF_PATH" and BUNDLED_VERDICTS.get(k) != "OFF_PATH"),
            sorted(k for k, v in measured.items()
                   if v == "ACTIVE" and BUNDLED_VERDICTS.get(k) != "ACTIVE"),
            sorted(k for k, v in measured.items()
                   if v != BUNDLED_VERDICTS.get(k)
                   and v not in ("OFF_PATH", "ACTIVE")),
        )
    )


def test_bundled_snapshot_off_path_count_cannot_grow():
    """Stated as a number too, so the failure message names the size."""
    measured = _verdict_map(_bundled_parameters())
    n = sum(1 for v in measured.values() if v == "OFF_PATH")
    pinned = sum(1 for v in BUNDLED_VERDICTS.values() if v == "OFF_PATH")
    assert n == pinned, (
        "off-path values in the bundled snapshot moved from %d to %d over the "
        "%d checked fields" % (pinned, n, len(CHECKED_FIELDS))
    )


def test_bundled_constant_datasheets_leak_set_is_exactly_pinned():
    """`Get('b3')`, `Get('w0')`, `Get('k_gimel')` are the public surface."""
    directory = _PKG / "data" / "constants"
    sheets = sorted(directory.glob("*.json"))
    assert sheets, "no bundled constant datasheets: Get() cannot work"

    measured: Dict[str, str] = {}
    for sheet in sheets:
        try:
            blob = json.loads(sheet.read_text(encoding="utf-8"))
        except ValueError:                           # pragma: no cover
            continue
        canonical = blob.get("canonical_path")
        quantity = CHECKED_FIELDS.get(canonical)
        if quantity is None:
            continue
        if verdict(blob.get("value"), quantity) == "OFF_PATH":
            measured[sheet.stem] = canonical

    assert measured == BUNDLED_DATASHEET_LEAKS, (
        "the set of bundled datasheets serving an off-path value changed "
        "(measured %s, pinned %s). A repair must update "
        "BUNDLED_DATASHEET_LEAKS -- and note that regenerating the sheets does "
        "not repair them: datasheets/constant.py reads the bundled snapshot "
        "before a built one."
        % (sorted(measured), sorted(BUNDLED_DATASHEET_LEAKS))
    )


def test_frozen_writer_literals_are_exactly_the_pinned_inventory():
    """Leaks no rebuild can reach, because the number is in the writer."""
    present, missing = [], []
    for relpath, fragment, _publishes in FROZEN_WRITER_LITERALS:
        source = _PKG / relpath
        assert source.is_file(), "writer disappeared: %s" % relpath
        text = source.read_text(encoding="utf-8")
        (present if fragment in text else missing).append((relpath, fragment))

    assert not missing, (
        "a frozen off-path literal is gone from %s. If it was repaired, remove "
        "the entry from FROZEN_WRITER_LITERALS in the same change -- the "
        "inventory is a record of what leaks, so it must shrink when the leak "
        "does." % missing
    )
    assert len(present) == len(FROZEN_WRITER_LITERALS)


def test_the_js_constants_step_still_cannot_repair_the_js_artifact():
    """Why the frozen JS literals survive a build, pinned as the mechanism.

    `generate_js_constants` is a DRY RUN unless `--write` is passed, and
    `build.py` invokes it without one -- so the step reports the drift it found
    and changes nothing. Pinned here because a repair that adds `--write` must
    also revisit the JS entries in FROZEN_WRITER_LITERALS.
    """
    from metaphysica.build import STEPS

    steps = [argv for label, argv, _extra in STEPS
             if "generate_js_constants" in " ".join(argv)]
    assert len(steps) == 1, (
        "expected exactly one JS-constants step in build.STEPS, found %d"
        % len(steps)
    )
    assert "--write" not in steps[0], (
        "build.py now passes --write to generate_js_constants, so the step can "
        "rewrite js/theory-constants.js. Re-measure its entries in "
        "FROZEN_WRITER_LITERALS."
    )


