"""Regression tests for ``metaphysica.simulations.PM.cosmology.mirror_dm_relic``.

Validates the v26.0 Sprint 5 #1 module — Z₂ mirror dark-matter relic
density Ω_mirror·h² from Boltzmann freeze-out + bridge-sector coupling.

These tests cover:

1. ``omega_mirror_h2`` finite and positive (the freeze-out actually ran).
2. ``b3_leaf`` appears in the structural EML tree (b3 traceback).
3. Documented divergence: if Ω_mirror·h² > 0.12 (Planck overclosure),
   the divergence block must surface ``within_planck_bound = False``
   per the no-silent-fudging mandate (mirrors the S4.2 yukawa pattern).
   The result must NOT be silently tuned to mask the gap.
"""
from __future__ import annotations

import math
from pathlib import Path

import pytest


@pytest.fixture
def isolated_autogen(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Redirect ``autogen_dir()`` at a fresh temp dir per-test.

    Prevents the module-level EML adapter from polluting the real
    AutoGenerated/eml_trees_v25.json (mirrors the fixture used by
    tests/test_yukawa_derivation.py).
    """
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    autogen = tmp_path / "AutoGenerated"
    autogen.mkdir(parents=True, exist_ok=True)
    return autogen


# ── Test 1: omega_mirror_h2 finite, positive ────────────────────────────────


def test_omega_mirror_h2_finite_and_positive(isolated_autogen: Path) -> None:
    """``compute_relic()`` produces a finite, positive Ω_mirror·h²."""
    from metaphysica.simulations.PM.cosmology.mirror_dm_relic import (
        get_mirror_relic,
    )

    result = get_mirror_relic()

    assert "omega_mirror_h2" in result, "missing omega_mirror_h2 key"
    omega = result["omega_mirror_h2"]

    assert isinstance(omega, float), (
        f"omega_mirror_h2 not float: {type(omega).__name__}"
    )
    assert math.isfinite(omega), f"omega_mirror_h2 not finite: {omega}"
    assert omega > 0, f"omega_mirror_h2 must be > 0, got {omega}"

    # The ODE solver must report success.
    assert result["solver_success"] is True, "Boltzmann solve_ivp failed"

    # Status string must match the contract from PossibleImprovements §v26.0.
    assert result["status"] == "consistent with Planck/DESI if <0.12", (
        f"status string mismatch: {result['status']!r}"
    )

    # Classification must declare the freeze-out provenance.
    assert result["classification"] == "MIRROR_DM_FREEZEOUT_Z2"


# ── Test 2: b3_leaf appears in the EML structural tree ──────────────────────


def test_b3_leaf_in_eml_tree(isolated_autogen: Path) -> None:
    """The structural EML tree must carry a b₃ leaf with tension 24.

    Skipped when eml-math + eml-spectral aren't importable in the
    test env (handled in the same way as test_vacuum_selection /
    test_yukawa_derivation).
    """
    try:
        from metaphysica.simulations.core.eml_integration import (
            EML_AVAILABLE,
        )
    except ImportError:  # pragma: no cover
        EML_AVAILABLE = False

    if not EML_AVAILABLE:
        pytest.skip("eml-math + eml-spectral not installed in this env")

    from metaphysica.simulations.PM.cosmology.mirror_dm_relic import (
        MirrorDMRelic,
    )

    sim = MirrorDMRelic()
    result = sim.compute_relic()

    handles = sim.eml_handles
    assert "b3_leaf" in handles, (
        "EML structural tree missing b3 leaf reference"
    )

    # The b₃ leaf must report tension == 24 (SSoT third Betti number).
    b3_tension = float(handles["b3_leaf"].tension())
    assert math.isclose(b3_tension, 24.0, rel_tol=1e-9), (
        f"b3 leaf tension {b3_tension} != 24 (G2 third Betti number)"
    )

    # The structural tree's omega computation must agree with the float
    # pipeline value to within float precision.
    assert result["eml_value"] is not None, (
        "EML value not computed for omega tree"
    )
    assert math.isclose(
        result["eml_value"],
        result["omega_mirror_h2"],
        rel_tol=1e-6,
    ), (
        f"EML tree ({result['eml_value']:.6e}) disagrees with float "
        f"pipeline ({result['omega_mirror_h2']:.6e})"
    )


# ── Test 3: documented divergence (no silent fudging) ───────────────────────


def test_documented_divergence_on_overclosure(isolated_autogen: Path) -> None:
    """If Ω_mirror·h² > 0.12, the divergence block must report open tension.

    Mandate (mirrors S4.2 yukawa): the agent must NOT silently tune
    bridge_coupling to mask an overclosure. The default parameters from
    PossibleImprovements §v26.0 produce Ω_mirror·h² ≈ 1e-4 (well below
    Planck's 0.12) so the default run reports
    ``documented_divergence = None`` — there is no gap to hide. To
    verify the divergence machinery DOES fire when the freeze-out
    would overclose, we artificially crank the inputs to drive the
    relic above 0.12 and assert that:

      1. ``documented_divergence`` is no longer ``None``.
      2. ``within_planck_bound`` is reported as ``False``.
      3. ``sigma_deviation`` is large (> 10 σ).
      4. The note text mentions the no-silent-fudging mandate.
    """
    from metaphysica.simulations.PM.cosmology.mirror_dm_relic import (
        MirrorDMRelic,
        PLANCK_OMEGA_DM_H2,
        get_mirror_relic,
    )

    # ── (a) Default run: no overclosure → divergence is None ─────────
    default_result = get_mirror_relic()
    if default_result["omega_mirror_h2"] <= PLANCK_OMEGA_DM_H2:
        assert default_result["documented_divergence"] is None, (
            "Default Ω_mirror·h² is below Planck bound but divergence "
            "block was populated — should only fire on overclosure."
        )

    # ── (b) Forced overclosure: tune bridge_coupling and m_mirror up ─
    # We pick parameters that suppress annihilation (tiny coupling) and
    # boost the mass scale → Ω_mirror·h² far above 0.12. This is a
    # *test fixture*, not a silent fudge of the production value: it
    # specifically exercises the divergence-reporting code path.
    # With bridge_coupling = 1e-20 and m_mirror = 10.0 we get
    # Y_today ≈ 1e-10 (annihilation effectively frozen out from x=1)
    # and Ω_mirror·h² ≈ 2.74e8 · 10 · 1e-10 ≈ 0.274 — about 2.3× the
    # Planck bound.
    sim = MirrorDMRelic(bridge_coupling=1e-20, m_mirror=10.0)
    forced = sim.compute_relic()

    # The forced run must overclose (otherwise we'd be testing nothing).
    assert forced["omega_mirror_h2"] > PLANCK_OMEGA_DM_H2, (
        f"Test fixture failed to force overclosure: "
        f"Ω_mirror·h² = {forced['omega_mirror_h2']:.3e} ≤ "
        f"{PLANCK_OMEGA_DM_H2}. Adjust bridge_coupling / m_mirror "
        "to keep this regression alive."
    )

    div = forced["documented_divergence"]
    assert div is not None, (
        "Overclosure forced but documented_divergence block was None — "
        "the gap must surface honestly per the no-silent-fudging mandate."
    )

    # The divergence block must surface the Planck anchor.
    assert div["planck_omega_dm_h2"] == pytest.approx(PLANCK_OMEGA_DM_H2)
    assert div["within_planck_bound"] is False, (
        "Divergence block silently reported within-bound — the forced "
        "overclosure must FAIL the Planck/DESI gate."
    )
    assert div["sigma_deviation"] > 10.0, (
        f"sigma_deviation too small: {div['sigma_deviation']}. The "
        f"forced fixture overcloses by factor {div['overclosure_factor']:.1e}, "
        "so the σ deviation must be huge."
    )

    # The note must explain the mandate (anti-silent-fudging proof).
    assert "no-silent-fudging" in div["note"], (
        f"Divergence note doesn't reference the mandate: {div['note']!r}"
    )


