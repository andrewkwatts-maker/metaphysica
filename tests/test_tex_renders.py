"""Render gate: every published math string parses under the site's own MathJax.

tools/texcheck/check.js (mathjax-full 3.2.2, the site's shared
website/js/mathjax-config.js) reads formulas.json, sections.json and HTML
delimited math. Skipped, with the reason, when node or
tools/texcheck/node_modules is absent. The published build is read from
PM_PUBLISHED_ROOT (default H:/claude-scratch/runs_g/active), as in
test_superseded_surfaces.py. Ceilings only go down.
"""
from __future__ import annotations

import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
TEXCHECK = ROOT / "tools" / "texcheck"
WEBSITE = ROOT / "src" / "metaphysica" / "website"
PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT",
                                "H:/claude-scratch/runs_g/active"))

#: Render errors permitted per surface. Only goes down.
CEILING = 0

NODE = shutil.which("node")


@pytest.fixture(scope="module", autouse=True)
def _need_checker():
    if NODE is None:
        pytest.skip("node is not installed; the render gate needs it")
    if not (TEXCHECK / "node_modules" / "mathjax-full").is_dir():
        pytest.skip("run `npm ci` in tools/texcheck to install mathjax-full")


def _check(*inputs):
    proc = subprocess.run([NODE, str(TEXCHECK / "check.js"), *map(str, inputs)],
                          capture_output=True, text=True, encoding="utf-8",
                          cwd=str(TEXCHECK), timeout=600)
    assert proc.returncode in (0, 1), proc.stderr[-400:]
    return json.loads(proc.stdout)


def _html(tmp_path, body):
    page = tmp_path / "fixture.html"
    page.write_text("<html><body>%s</body></html>" % body, encoding="utf-8")
    return _check(page)


# --- the checker catches each error kind ------------------------------------

def test_fixture_undefined_macro_is_caught(tmp_path):
    res = _html(tmp_path, r"<p>$$\notamacro{x}$$</p>")
    assert [e["error"].split()[0] for e in res["errors"]] == ["undefined"]


def test_fixture_thrown_tex_error_is_caught(tmp_path):
    res = _html(tmp_path, r"<p>$$\frac{1$$</p>")
    assert len(res["errors"]) == 1 and "undefined" not in res["errors"][0]["error"]


def test_fixture_script_inside_text_is_caught(tmp_path):
    res = _html(tmp_path, r"<p>$$\text{a_b}$$</p>")
    assert res["errors"][0]["error"].startswith("script character inside text")


def test_fixture_site_macro_slashed_renders(tmp_path):
    assert _html(tmp_path, r"<p>$$\slashed{D}\psi$$</p>")["errors"] == []


def test_fixture_html_entities_are_decoded(tmp_path):
    assert _html(tmp_path, r"<p>\(a &lt; b\)</p>")["errors"] == []


def test_fixture_clean_formula_passes(tmp_path):
    res = _html(tmp_path, r"<p>$$\int d^{4}x\,\sqrt{-g}\,R$$</p>")
    assert res["checked"] == 1 and res["errors"] == []


# --- the surfaces ----------------------------------------------------------

def _published(*parts):
    if not PUBLISHED.is_dir():
        pytest.skip("no published build at %s" % PUBLISHED)
    return [PUBLISHED / p for p in parts]


@pytest.mark.parametrize("surface,parts", [
    ("formulas", ("AutoGenerated/formulas.json",)),
    ("sections", ("AutoGenerated/sections.json",)),
    ("pages", ("Pages",)),
])
def test_published_surface_renders(surface, parts):
    res = _check(*_published(*parts))
    assert res["checked"] > 0
    assert len(res["errors"]) <= CEILING, [
        (e["where"], e["error"]) for e in res["errors"][:8]]


def test_website_source_renders():
    res = _check(WEBSITE)
    assert res["checked"] > 0
    assert len(res["errors"]) <= CEILING, [
        (e["where"], e["error"]) for e in res["errors"][:8]]
