"""L6 algebra-portals-viz: figures read rows, carry no typed b3 or invented error."""
import inspect

from metaphysica.simulations.visualizations import (
    brane_diagrams, certificate_dashboard as cd, figure1_m27_decomposition as f1,
    figure2_convergence_scatter as f2)


def test_figure2_does_not_invent_uncertainty(tmp_path, monkeypatch, capsys):
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    rows = {
        "a": {"value": 2.0, "experimental_value": 1.0, "experimental_uncertainty": 0.5,
              "sigma_deviation": 2.0, "validation_status": "FAIL"},
        "b": {"value": 3.0, "experimental_value": 1.0, "experimental_uncertainty": 0,
              "sigma_deviation": 5.0, "validation_status": "FAIL"},
    }
    f2.generate_figure2_convergence_scatter({"parameters": rows})
    assert "Found 1 testable parameters; 1 left out" in capsys.readouterr().out
    assert "1% default" not in inspect.getsource(f2)


def test_dashboard_seal_comes_from_gate_registry(tmp_path, monkeypatch):
    import json
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    (tmp_path / "AutoGenerated").mkdir(exist_ok=True)
    certs = [{"gate_id": f"G{i}", "evaluation": "COMPUTED_PASS", "status": "LOCKED"}
             for i in range(3)]
    for d in (tmp_path / "AutoGenerated", tmp_path):
        (d / "GATES_CERTIFICATES.json").write_text(
            json.dumps({"certificates": certs}), encoding="utf-8")
    label = cd.seal_label()
    assert "42/42" not in label and "gates locked" in label
    assert "42/42" not in inspect.getsource(cd)
    assert '"288 Roots"' not in inspect.getsource(cd)


def test_figure_text_has_no_typed_b3_or_retired_dimension():
    assert "b_3 = 24" not in inspect.getsource(f1)
    assert "25D_{(24,2)}" not in inspect.getsource(brane_diagrams)
