"""XB-01: CANON builds on an empty output directory.

H0 is computed at access by FormulasRegistry.calculate_h0_local; tau_p is
read from the parameter artifact in the output directory, NOT_EVALUABLE
when there is none, and raises when the artifact lacks its rows.
"""
import json

import pytest

from metaphysica.simulations.core import canonical_values as cv
from metaphysica.simulations.core.FormulasRegistry import FormulasRegistry
from metaphysica.simulations.PM.geometry.b3_path import resolve_path, seed_values


@pytest.fixture
def empty_out(tmp_path, monkeypatch):
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    return tmp_path


def _write_artifact(out, rows):
    autogen = out / "AutoGenerated"
    autogen.mkdir(parents=True, exist_ok=True)
    payload = {"parameters": {k: {"value": v} for k, v in rows.items()}}
    (autogen / "parameters.json").write_text(json.dumps(payload), encoding="utf-8")


def _seed_rows():
    b3, b2 = seed_values(resolve_path())
    return {"topology.elder_kads": b3, "topology.b2": b2}


def test_canon_returns_on_an_empty_output_directory(empty_out):
    table = cv.canon()
    assert table["H0_km_s_Mpc"]["value"] == FormulasRegistry().h0_local
    assert table["H0_km_s_Mpc"]["status"] == "FITTED_COMPOSITE"
    tau = table["tau_p_years"]
    assert tau["value"] is None and tau["status"] == "NOT_EVALUABLE"
    assert tau["note"] == "no parameter artifact in the output directory"
    assert not (empty_out / "AutoGenerated").exists()


def test_h0_form_is_built_from_the_registry(empty_out):
    reg = FormulasRegistry()
    form = cv.get("H0_km_s_Mpc")["form"]
    assert "%d/4" % reg.roots_total in form
    assert "b3 = %d" % seed_values(resolve_path())[0] in form


def test_h0_off_the_path_in_force_is_not_evaluable(empty_out):
    entry = cv.canon("seed_24")["H0_km_s_Mpc"]
    assert entry["value"] is None and entry["status"] == "NOT_EVALUABLE"
    assert "path in force" in entry["note"] and "'seed_24'" in entry["note"]


def test_tau_p_missing_row_raises(empty_out):
    _write_artifact(empty_out, _seed_rows())
    with pytest.raises(KeyError, match="proton_decay.tau_p_years"):
        cv.canon()


def test_tau_p_missing_seed_rows_raise(empty_out):
    _write_artifact(empty_out, {"proton_decay.tau_p_years": 1.0e35})
    with pytest.raises(KeyError, match="topology.elder_kads"):
        cv.get("tau_p_years")


def test_tau_p_read_from_the_output_artifact(empty_out):
    _write_artifact(empty_out, dict(_seed_rows(), **{"proton_decay.tau_p_years": 3.0e35}))
    assert cv.get("tau_p_years")["value"] == 3.0e35


def test_get_builds_one_symbol_only(empty_out, monkeypatch):
    def boom(topo):
        raise AssertionError("tau_p built for get('w0')")

    monkeypatch.setitem(cv._PATH_ENTRIES, "tau_p_years", boom)
    assert cv.get("w0")["value"] is not None
    with pytest.raises(KeyError):
        cv.get("not_a_symbol")
