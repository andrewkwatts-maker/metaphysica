ROWS = {
    KILL_SWITCH_ROWS["ALP_Principia_Metric"]: 3.51,
    ALP_COUPLING_ROW: 1.23e-6,
    KILL_SWITCH_ROWS["Fifth_Force"]: 1.77e-9,
    KILL_SWITCH_ROWS["Proton_Decay"]: 1.0e36,
    KILL_SWITCH_ROWS["Sterile_Neutrino"]: 1.0e-3,
    KILL_SWITCH_ROWS["KK_Gravitons"]: 5.0,
}


@pytest.fixture()
def report(tmp_path, monkeypatch):
    out = tmp_path / "AutoGenerated"
    out.mkdir()
    (out / "parameters.json").write_text(
        json.dumps({"parameters": {k: {"value": v} for k, v in ROWS.items()}}))
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    return fo.FalsificationOracle().generate_falsification_report()


def test_framework_label_from_registry(report):
    assert report["framework"] == fo.FRAMEWORK_LABEL
    assert "v24.1" not in json.dumps(report)


def test_alp_prose_quotes_the_row_coupling(report):
    text = report["peer_review_response"]["principia_metric_statement"]
    assert "1.23e-06" in text or "1.23e-6" in text
    assert "10⁻¹¹" not in text and "FALSIFIED" not in json.dumps(
        report["detailed_risk_analysis"]["ALP_Principia_Metric"])


def test_alp_flags_current_helioscope_limit(report):
    alp = report["detailed_risk_analysis"]["ALP_Principia_Metric"]
    assert alp["exceeds_current_helioscope_limit"] is True
    assert "current_limit_note" in alp


def test_fifth_force_verdict_in_nm_with_units(report):
    ff = report["detailed_risk_analysis"]["Fifth_Force"]
    assert "0.0 microns" not in ff["verdict"] and "nm" in ff["verdict"]
    assert ff["predicted_value_unit"] == "m" and ff["experimental_limit_unit"] == "m"


def test_kk_verdict_says_benchmark(report):
    assert "Benchmark" in report["detailed_risk_analysis"]["KK_Gravitons"]["verdict"]


def test_beacon_has_no_b3():
    assert "b3" not in inspect.getsource(cb.beacon_two_time_bulk_accounting).replace("no b3", "")
    assert cb.beacon_two_time_bulk_accounting().value == 0.0


def _chi_gate(chi):
    v = PrincipiaValidator.__new__(PrincipiaValidator)
    v.reg, v.results = {"topology.mephorash_chi": {"value": chi}}, {}
    v.cert_c003_chi_effective()
    return v.results["C003-CHI"]


def test_c003_follows_b2_not_b3(monkeypatch):
    _, b2 = seed_values(resolve_path())
    assert _chi_gate(48 * (b2 // 4))["status"] == "LOCKED"
    assert _chi_gate(6 * seed_values(resolve_path())[0])["status"] == "FAILED"


def test_pipeline_has_no_b3_24_observables():
    assert not hasattr(gp.GeometricPipeline, "_derive_observables")


def test_adversarial_b3_from_active_path():
    assert "self.b3 = 24" not in inspect.getsource(aat)


def test_distiller_does_not_claim_derived():
    src = inspect.getsource(ibd)
    assert "is DERIVED from G₂ topology, not arbitrary" not in src
    assert "derived from topology, not arbitrary fitting" not in src


def test_registry_load_raises_when_missing(tmp_path, monkeypatch):
    monkeypatch.setattr(g72, "_REGISTRY_MEMO", None)
    monkeypatch.setattr(g72, "_autogen_dir", lambda: tmp_path)
    with pytest.raises(FileNotFoundError):
        g72._load_registry_params()


def test_alp_status_follows_the_current_bound_not_the_projection(report):
    alp = report["detailed_risk_analysis"]["ALP_Principia_Metric"]
    assert alp["exceeds_current_helioscope_limit"] is True
    assert alp["status"] == "EXCLUDED_BY_CURRENT_BOUND"
    assert alp["status"] not in ("IMMINENT_TEST", "TESTABLE")
