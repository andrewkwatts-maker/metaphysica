"""The test session's staging copy of the artifacts is removed, not left behind.

On 2026-11-11 the copies filled the system drive: every pytest start made a
new 41 MB folder in the temporary directory and nothing removed it.
"""
from __future__ import annotations

import os
import subprocess
import sys
import time
from pathlib import Path

from tests import _artifact_staging as staging

ROOT = Path(__file__).resolve().parents[2]


def _source(tmp_path: Path) -> Path:
    source = tmp_path / "published"
    (source / "AutoGenerated").mkdir(parents=True)
    (source / "AutoGenerated" / "parameters.json").write_text("{}", encoding="utf-8")
    return source


def _dead_pid() -> int:
    proc = subprocess.Popen([sys.executable, "-c", "pass"])
    proc.wait()
    return proc.pid


def test_stage_copy_names_its_owner_and_copies_the_artifacts(tmp_path):
    base = tmp_path / "base"
    base.mkdir()
    staged = staging.stage_copy(_source(tmp_path), base)
    assert staged.parent == base
    assert staging.owner_pid(staged) == os.getpid()
    assert (staged / "AutoGenerated" / "parameters.json").is_file()


def test_staging_folder_is_removed_when_the_process_exits(tmp_path):
    base = tmp_path / "base"
    base.mkdir()
    code = (
        "import sys; from pathlib import Path; "
        "from tests import _artifact_staging as s; "
        "print(s.stage_copy(Path(sys.argv[1]), Path(sys.argv[2])))"
    )
    done = subprocess.run(
        [sys.executable, "-c", code, str(_source(tmp_path)), str(base)],
        cwd=ROOT, capture_output=True, text=True, check=True,
    )
    staged = Path(done.stdout.strip())
    assert staged.name.startswith(staging.PREFIX)
    assert not staged.exists()
    assert list(base.iterdir()) == []


def test_sweep_removes_the_folder_of_a_dead_process_and_keeps_a_live_one(tmp_path):
    dead = tmp_path / f"{staging.PREFIX}p{_dead_pid()}-aaaa"
    live = tmp_path / f"{staging.PREFIX}p{os.getpid()}-bbbb"
    other = tmp_path / "something-else"
    for folder in (dead, live, other):
        (folder / "AutoGenerated").mkdir(parents=True)
    assert staging.sweep_orphans(tmp_path) == [dead]
    assert live.is_dir()
    assert other.is_dir()
    assert not dead.exists()


def test_sweep_removes_a_folder_with_the_older_name_only_when_it_is_old(tmp_path):
    old = tmp_path / f"{staging.PREFIX}old00000"
    young = tmp_path / f"{staging.PREFIX}young000"
    for folder in (old, young):
        folder.mkdir()
    past = time.time() - staging.UNOWNED_MAX_AGE_S - 60
    os.utime(old, (past, past))
    assert staging.owner_pid(old) is None
    assert staging.sweep_orphans(tmp_path) == [old]
    assert young.is_dir()


def test_stage_base_follows_the_override(tmp_path, monkeypatch):
    monkeypatch.setenv(staging.BASE_ENV, str(tmp_path / "chosen"))
    assert staging.stage_base() == tmp_path / "chosen"
    assert (tmp_path / "chosen").is_dir()


def test_conftest_stages_through_the_cleaning_helper():
    text = (ROOT / "tests" / "conftest.py").read_text(encoding="utf-8")
    assert "stage_copy(" in text
    assert "mkdtemp" not in text
