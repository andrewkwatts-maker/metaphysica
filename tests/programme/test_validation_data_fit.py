"""L7 validation-data: one scored row per observable, predictions only.

Synthetic rows keep these tests independent of the build artifacts; one test
also checks the live report when it is present.
"""
import json
from pathlib import Path

import pytest

from metaphysica.simulations.PM.validation import observables
from metaphysica.simulations.validation import fit_partition as fp

SCORING = {"PASS", "MARGINAL", "TENSION", "FAIL"}


def row(path, pred, exp, unc, reg="DERIVED", verdict="FAIL", **kw):
    sigma = abs(pred - exp) / unc
    return {"path": path, "status": verdict, "registry_status": reg,
            "predicted_value": pred, "experimental_value": exp,
            "uncertainty": unc, "sigma": sigma, "comparable": True, **kw}


def part(rows):
    return observables.partition_rows(rows, SCORING)


def test_alias_rows_are_scored_once_and_listed_as_duplicates():
    rows = [row("electromagnetic.alpha_inv", 137.0367, 137.036, 1e-5),
            row("geometry.alpha_inverse", 137.0367, 137.036, 1e-5)]
    p = part(rows)
    assert [r["path"] for r in p["scored"]] == ["electromagnetic.alpha_inv"]
    assert p["duplicates"][0]["path"] == "geometry.alpha_inverse"
    assert p["duplicates"][0]["duplicate_of"] == "electromagnetic.alpha_inv"
    assert p["duplicates"][0]["sigma"] is not None
    assert fp.chi_squared(p["scored"])["n"] == 1


def test_primary_is_first_present_prediction_in_group_order():
    rows = [row("geometry.alpha_inverse", 137.0367, 137.036, 1e-5),
            row("x.other", 1.0, 2.0, 1.0)]
    assert [r["path"] for r in part(rows)["scored"]] == [
        "geometry.alpha_inverse", "x.other"]


@pytest.mark.parametrize("reg,verdict,kind", [
    ("FITTED", "PASS", "fitted"), ("CALIBRATED", "FAIL", "calibrated"),
    ("DERIVED", "CIRCULAR", "circular"), ("DERIVED", "IDENTITY", "identity"),
    ("DERIVED", "UNIT_CHECK", "unit_check"), ("DERIVED", "INPUT", "input")])
def test_non_predictions_are_reported_not_scored(reg, verdict, kind):
    p = part([row("a.b", 1.0, 1.1, 0.1, reg=reg, verdict=verdict)])
    assert p["scored"] == []
    assert p["non_predictions"][0]["kind"] == kind
    assert "sigma" not in p["non_predictions"][0]


def test_undeclared_duplicates_are_detected():
    rows = [row("a.one", 1.0, 2.0, 0.5), row("b.two", 1.2, 2.0, 0.5)]
    assert part(rows)["undeclared_duplicates"] == [["a.one", "b.two"]]


def test_a_path_in_two_groups_is_refused():
    with pytest.raises(ValueError):
        fp.dedupe_by_group([], {"g1": ["p"], "g2": ["p"]})


def test_fit_summary_numbers_are_computed_from_rows():
    rows = [row("a.x", 3.0, 1.0, 1.0), row("b.y", 1.0, 1.0, 1.0),
            row("c.z", 4.0, 1.0, 1.0, reg="FALSIFIED")]
    s = fp.fit_summary(rows)
    assert (s["all_scoring_rows"]["chi_squared"], s["all_scoring_rows"]["n"]) == (13.0, 3)
    assert (s["excluding_falsified"]["chi_squared"], s["excluding_falsified"]["n"]) == (4.0, 2)
    top = s["top_contributors"][0]
    assert top["path"] == "c.z" and top["share"] == pytest.approx(9 / 13)
    assert [w["path"] for w in s["withdrawn_rows"]] == ["c.z"]
    assert [r["sigma"] for r in s["scored_rows"]] == [2.0, 0.0, 3.0]


def test_zero_uncertainty_row_fails_early():
    with pytest.raises(ValueError):
        fp.chi_squared([row("a.x", 1.0, 2.0, 1.0) | {"uncertainty": 0.0}])


def _live_report():
    for base in (Path(__file__).resolve().parents[2],):
        f = base / "AutoGenerated" / "validation_report.json"
        if f.is_file():
            data = json.loads(f.read_text(encoding="utf-8"))
            if data.get("validations"):
                return f
    pytest.skip("no validation_report.json with rows")


def test_live_report_has_no_undeclared_duplicates_and_one_row_per_group():
    from metaphysica.simulations.PM.validation.statistical_rigor_validator import (
        StatisticalRigorValidator)
    v = StatisticalRigorValidator(str(_live_report()))
    # Falsified candidates stay scored beside the live row (Rule 5), so they
    # may share its reference; two live rows may not.
    reg = {r["path"]: str(r.get("registry_status") or "").upper()
           for r in v.validation_results}
    for group in v.partition["undeclared_duplicates"]:
        assert sum(reg[p] != "FALSIFIED" for p in group) <= 1, group
    scored = [r["path"] for r in v.validation_results]
    for members in observables.OBSERVABLE_GROUPS.values():
        assert sum(p in scored for p in members) <= 1
    assert not {r["path"] for r in v.partition["non_predictions"]} & set(scored)
