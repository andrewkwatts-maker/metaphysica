"""XB-12: the H0 entry of CANON states the h0_route in force.

``FormulasRegistry.calculate_h0_local`` returns another route's value when
the ``h0_route`` fork is not on ``odowd_composite``; the entry used to print
the O'Dowd form and FITTED_COMPOSITE for every route, print eta_S from the
sterile sector (the code divides ``BULK_PRESSURE``), build two registries,
and let an unparsable parameter artifact raise without its path.

No number is pinned here: every expected value is computed in the test from
the registry, the route modules or the fork in force.
"""
import pytest

from metaphysica.simulations.core import canonical_values as cv
from metaphysica.simulations.core.FormulasRegistry import FormulasRegistry
from metaphysica.simulations.core.variants.selection import forced
from metaphysica.simulations.PM.cosmology import late_time_routes as ltr
from metaphysica.simulations.PM.geometry.b3_path import resolve_path, seed_values

SYMBOL = "H0_km_s_Mpc"
ODOWD_STATUS = "FITTED_COMPOSITE"


def _entry_on(route):
    """(entry, registry H0) with the h0_route fork forced to *route*."""
    with forced({"h0_route": route}):
        return cv.get(SYMBOL), FormulasRegistry().h0_local


def test_ricci_flow_route_states_its_own_form_and_status():
    from metaphysica.simulations.PM.cosmology.ricci_flow_h0 import (
        THETA_MIXING_13D_26D_DEG,
    )

    entry, h0 = _entry_on("ricci_flow")
    adopted, _ = _entry_on(ltr.ADOPTED_H0_ROUTE)
    assert entry["value"] == h0 != adopted["value"]
    assert entry["status"] == "RETRODICTED_VARIANT" != ODOWD_STATUS
    assert entry["spare_vars"] == 2
    form = entry["form"]
    assert "O'Dowd" not in form and "eta_S" not in form
    assert "theta = %g deg" % THETA_MIXING_13D_26D_DEG in form
    assert "H0_planck = %g" % FormulasRegistry().h0_early in form
    assert form.endswith("h0_route = ricci_flow")
    assert entry["source"].endswith("h0_route = ricci_flow")


def test_kk_bridge_route_is_falsified_not_a_fitted_composite():
    from metaphysica.simulations.PM.cosmology import hubble_tension as ht

    entry, h0 = _entry_on("kk_bridge")
    assert entry["value"] == h0
    assert entry["status"] == "FALSIFIED" != ODOWD_STATUS
    assert entry["spare_vars"] is None
    form = entry["form"]
    assert "O'Dowd" not in form and "eta_S" not in form
    assert "b3 = %d" % seed_values(resolve_path())[0] in form
    assert "H0_planck = %g" % ht.H0_PLANCK in form
    assert form.endswith("h0_route = kk_bridge")
    shift = "%.1e" % abs(h0 / ht.H0_PLANCK - 1.0)
    assert "relative shift from the Planck input is %s" % shift in entry["note"]


@pytest.mark.parametrize("route", ["ricci_flow", "kk_bridge"])
def test_note_of_another_route_names_it_and_scores_its_own_value(route):
    entry, h0 = _entry_on(route)
    note = entry["note"]
    assert "resolves to %r, not the adopted route %r" % (
        route, ltr.ADOPTED_H0_ROUTE) in note
    assert "NOT the canonical DISPLAY value" in note
    sigmas = (cv._sigma(h0, *cv._H0_SHOES), cv._sigma(h0, *cv._H0_PLANCK))
    assert "%.2f sigma SH0ES / %.1f Planck" % sigmas in note
    assert "is the canonical DISPLAY value" not in note


def test_eta_s_is_printed_from_bulk_pressure(monkeypatch):
    """The form prints the constant the registry divides, not sterile_sector."""
    sentinel = FormulasRegistry.BULK_PRESSURE + 836
    monkeypatch.setattr(
        FormulasRegistry, "sterile_sector", property(lambda self: sentinel))
    entry, h0 = _entry_on(ltr.ADOPTED_H0_ROUTE)
    assert entry["value"] == h0 and entry["status"] == ODOWD_STATUS
    assert entry["spare_vars"] == 3
    form = entry["form"]
    assert form.startswith("O'Dowd composite: ")
    assert "eta_S = %d/(10 b3 - 1)" % FormulasRegistry.BULK_PRESSURE in form
    assert str(sentinel) not in form
    assert "h0_route" not in entry["source"]


@pytest.mark.parametrize("route", ["odowd_composite", "ricci_flow", "kk_bridge"])
def test_one_registry_instance_per_entry(monkeypatch, route):
    built = []
    init = FormulasRegistry.__init__

    def counting(self, *args, **kwargs):
        built.append(1)
        init(self, *args, **kwargs)

    monkeypatch.setattr(FormulasRegistry, "__init__", counting)
    with forced({"h0_route": route}):
        cv.get(SYMBOL)
    assert len(built) == 1


def test_route_without_a_builder_raises(monkeypatch):
    monkeypatch.delitem(cv._H0_ROUTES, "ricci_flow")
    with forced({"h0_route": "ricci_flow"}):
        with pytest.raises(ValueError, match="h0_route 'ricci_flow'"):
            cv.get(SYMBOL)


def test_unparsable_artifact_names_its_path(tmp_path, monkeypatch):
    from metaphysica.generators._common import out_dir

    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    path = out_dir() / "AutoGenerated" / "parameters.json"
    path.parent.mkdir(parents=True)
    path.write_text('{"parameters": {', encoding="utf-8")
    with pytest.raises(ValueError) as caught:
        cv._output_artifact()
    assert str(path) in str(caught.value)
    assert "is not valid JSON" in str(caught.value)
