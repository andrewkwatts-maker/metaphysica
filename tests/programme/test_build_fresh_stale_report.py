"""XB-10: a rigor-validator run that raises leaves no report behind.

Before the fix, under ``build --keep-going`` a failed run left the previous
build's ``statistical_rigor_report.json`` in the output directory, and the
statistics refresh read it as this build's.
"""
import json

import pytest

from metaphysica.simulations.PM.validation import statistical_rigor_validator as srv


def _stale_report(tmp_path, monkeypatch):
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    path = tmp_path / "AutoGenerated" / "statistical_rigor_report.json"
    path.parent.mkdir(parents=True)
    path.write_text(json.dumps({"stale": True}), encoding="utf-8")
    return path


def test_run_without_validation_report_leaves_no_report(tmp_path, monkeypatch):
    stale = _stale_report(tmp_path, monkeypatch)
    with pytest.raises(FileNotFoundError, match="validation_report.json"):
        srv.main()
    assert not stale.exists()


def test_run_without_scored_rows_leaves_no_report(tmp_path, monkeypatch):
    stale = _stale_report(tmp_path, monkeypatch)
    rows = tmp_path / "AutoGenerated" / "validation_report.json"
    rows.write_text(json.dumps({"validations": []}), encoding="utf-8")
    with pytest.raises(ValueError, match="no scored prediction rows"):
        srv.main()
    assert not stale.exists()
