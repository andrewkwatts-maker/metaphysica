"""PT-13 to PT-18: one resolver of the published root for every build-reading test.

Before this fix each build-reading test carried its own default root, a snapshot
outside the repository built on 2026-10-26. A run with PM_PUBLISHED_ROOT unset
scored that tree and never the build under test. The resolver in
tests/conftest.py answers PM_PUBLISHED_ROOT when it is set, otherwise the output
directory of the engine. With no build there a test skips with the reason, and
fails when CI is set.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from metaphysica.generators._common import out_dir
from tests import conftest as shared

TESTS = Path(__file__).resolve().parents[1]
#: The folder of the retired default, spelled in two parts so this file does not carry it.
SNAPSHOT = "claude" + "-scratch"
#: A private default of the variable, as each consumer had before the fix.
PRIVATE_DEFAULT = 'os.environ.get("PM_PUBLISHED_ROOT"'
CONSUMERS = (
    "test_derivation_chains.py",
    "test_duplicate_statements.py",
    "test_every_fork_accounted.py",
    "test_formula_lint.py",
    "test_master_ladder.py",
    "test_parameter_ledger.py",
    "test_prose_lint.py",
    "test_superseded_surfaces.py",
    "test_tex_renders.py",
)


def _build(root: Path) -> Path:
    """A minimal build under root; returns its formulas.json."""
    formulas = root / "AutoGenerated" / "formulas.json"
    formulas.parent.mkdir(parents=True)
    formulas.write_text('{"formulas": {}}', encoding="utf-8")
    return formulas


def test_variable_set_is_the_root(tmp_path, monkeypatch):
    chosen, engine = tmp_path / "chosen", tmp_path / "engine"
    _build(engine)
    monkeypatch.setenv("PM_PUBLISHED_ROOT", str(chosen))
    monkeypatch.setenv("METAPHYSICA_OUT", str(engine))
    assert shared.published_root() == chosen


def test_variable_unset_with_a_build_reads_the_engine_output(tmp_path, monkeypatch):
    formulas = _build(tmp_path)
    monkeypatch.delenv("PM_PUBLISHED_ROOT", raising=False)
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    root = shared.published_root()
    assert root == out_dir() == tmp_path.resolve()
    assert SNAPSHOT not in root.as_posix()
    assert shared.require_build(root / "AutoGenerated" / "formulas.json") == formulas.resolve()


def test_variable_unset_and_no_engine_target_reads_the_working_directory(tmp_path, monkeypatch):
    monkeypatch.delenv("PM_PUBLISHED_ROOT", raising=False)
    monkeypatch.delenv("METAPHYSICA_OUT", raising=False)
    monkeypatch.chdir(tmp_path)
    assert shared.published_root() == out_dir() == tmp_path.resolve()


def test_empty_variable_counts_as_unset(tmp_path, monkeypatch):
    monkeypatch.setenv("PM_PUBLISHED_ROOT", "")
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    assert shared.published_root() == tmp_path.resolve()


def test_no_build_skips_with_the_reason(tmp_path, monkeypatch):
    monkeypatch.delenv("CI", raising=False)
    missing = tmp_path / "AutoGenerated" / "formulas.json"
    with pytest.raises(pytest.skip.Exception) as caught:
        shared.require_build(missing)
    reason = str(caught.value)
    assert str(missing) in reason and "PM_PUBLISHED_ROOT" in reason


def test_no_build_under_ci_fails_with_the_reason(tmp_path, monkeypatch):
    monkeypatch.setenv("CI", "true")
    missing = tmp_path / "AutoGenerated" / "formulas.json"
    with pytest.raises(pytest.fail.Exception) as caught:
        shared.require_build(missing)
    reason = str(caught.value)
    assert str(missing) in reason and "PM_PUBLISHED_ROOT" in reason


def test_a_build_under_ci_is_returned(tmp_path, monkeypatch):
    monkeypatch.setenv("CI", "true")
    formulas = _build(tmp_path)
    assert shared.require_build(formulas) == formulas


@pytest.mark.parametrize("name", CONSUMERS)
def test_consumer_reads_the_shared_resolver(name):
    text = (TESTS / name).read_text(encoding="utf-8")
    assert "published_root" in text, "%s does not use tests/conftest.py published_root" % name
    assert SNAPSHOT not in text, "%s still names the retired snapshot" % name
    assert PRIVATE_DEFAULT not in text, "%s reads the variable with its own default" % name
