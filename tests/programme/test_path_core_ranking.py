"""L1 path-core: the ranking measures output effect and names no false winner.

core-paths-02: path_ranking.json ranked 40 paths that were all inconsistent,
put a validator-policy flip at rank 1 and declared a winner.
core-paths-03: 30 of 40 options changed nothing scored yet sat in the
ranking as searched paths, with no flag saying so.
Stubbed runs only; the artifact is regenerated by L9.
"""
from __future__ import annotations

import pytest

from metaphysica.testground.rank import (NO_CONSISTENT_PATH, RankEntry,
                                         rank_entries, validate_ranking)
from metaphysica.testground.rank_effects import EFFECTS
from metaphysica.testground.switches.model import ACTIVE, CONSIDERED, Fork, VariantOption
from metaphysica.testground.theory import RunReading


def _fork(fid, options, kind="physics"):
    opts = [VariantOption(id=o, summary=o, consequence=o,
                          status=ACTIVE if i == 0 else CONSIDERED,
                          adopted=i == 0)
            for i, o in enumerate(options)]
    return Fork(id=fid, question=fid, source="stub", options=opts,
                status="OPEN", kind=kind)


FORKS = {
    "seed": _fork("seed", ["a", "b", "c", "never_run"]),
    "policy": _fork("policy", ["strict", "always"], kind="policy"),
}


def _e(pid, selection, **kw):
    base = dict(consistent=False, ladder_failed=3, ladder_total=10,
                gates_failed=0, gates_applicable=2, chi2=100.0, dof=5)
    base.update(kw)
    return RankEntry(pid, selection, RunReading(**base))


def _entries():
    return [_e("default", {}),
            _e("seed_b", {"seed": "b"}, chi2=50.0),          # scored
            _e("seed_c", {"seed": "c"}, ladder_failed=4),    # unscored
            _e("policy_always", {"policy": "always"}, chi2=1.0)]


def test_every_option_of_every_fork_has_a_measured_effect():
    doc = rank_entries(_entries(), "default", forks=FORKS)
    eff = {f: {o: c["output_effect"] for o, c in row.items()}
           for f, row in doc["option_effects"].items()}
    assert eff["seed"] == {"a": "none", "b": "scored", "c": "unscored",
                           "never_run": "not_evaluable"}
    assert eff["policy"]["always"] == "scored"
    assert doc["option_effects"]["seed"]["a"]["baseline"] is True
    for fid, fork in FORKS.items():
        assert set(doc["option_effects"][fid]) == set(fork.option_ids())
        assert {c["output_effect"] for c in doc["option_effects"][fid].values()} <= set(EFFECTS)


def test_policy_forks_do_not_rank_even_when_they_fit_best():
    doc = rank_entries(_entries(), "default", forks=FORKS)
    ranked = [r["path_id"] for r in doc["rows"]]
    assert "policy_always" not in ranked
    assert doc["rows"][0]["path_id"] == "seed_b"
    assert [u["path_id"] for u in doc["unranked"]] == ["policy_always"]
    assert "policy" in doc["unranked"][0]["reason"]
    assert doc["searched"] == 3
    assert validate_ranking(doc) == []


def test_no_consistent_row_says_no_consistent_path():
    doc = rank_entries(_entries(), "default", forks=FORKS)
    assert doc["verdict"] == NO_CONSISTENT_PATH
    entries = _entries() + [_e("seed_ok", {"seed": "never_run"},
                               consistent=True)]
    doc = rank_entries(entries, "default", forks=FORKS)
    assert doc["verdict"] == "1 consistent path(s)"


def test_ties_share_a_rank():
    entries = [_e("default", {}), _e("seed_b", {"seed": "b"}),
               _e("seed_c", {"seed": "c"})]
    doc = rank_entries(entries, "default", forks=FORKS)
    assert {r["rank"] for r in doc["rows"]} == {1}
    assert {c["output_effect"] for o, c in doc["option_effects"]["seed"].items()
            if o in ("b", "c")} == {"none"}


def test_validation_refuses_a_ranking_without_verdict_or_effects():
    doc = rank_entries(_entries(), "default", forks=FORKS)
    for key in ("verdict", "option_effects", "unranked"):
        broken = {k: v for k, v in doc.items() if k != key}
        assert validate_ranking(broken), key
    broken = dict(doc, option_effects={"seed": {"a": {"output_effect": "?"}}})
    assert validate_ranking(broken)


def test_an_undeclared_fork_in_a_run_fails_early():
    with pytest.raises(ValueError, match="undeclared forks"):
        rank_entries([_e("default", {}), _e("x", {"ghost": "y"})], "default",
                     forks=FORKS)


def test_the_pm_policy_forks_are_declared_policy():
    from metaphysica.simulations.core.variants import FORKS as PM

    assert PM["render_policy"].kind == "policy"
    assert PM["theory_uncertainty_policy"].kind == "policy"
    assert all(f.kind == "physics" for k, f in PM.items()
               if k not in ("render_policy", "theory_uncertainty_policy"))
