"""D-026 option assessment generator: synthetic fixtures plus a read-only smoke test."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from metaphysica.generators import generate_option_assessment as g

ROOT = Path(__file__).resolve().parents[2]
PUBLISHED = ROOT / "PrincipiaMetaphysica" / "AutoGenerated"

PARAMS = {
    "a": {"status": "GEOMETRIC"},
    "b": {"status": "CALIBRATED"},
    "c": {"status": "DERIVED"},
}
VALIDATIONS = [{"path": "row.x", "verdict": "FAIL"}, {"path": "row.y", "verdict": "FAIL"}]


def _summary(pass_n, fail_n, chi2=100.0):
    return {"scoreboard": {"PASS": pass_n, "FAIL": fail_n}, "chi2": {"value": chi2}}


def _patch(param_ops=(), row_ops=()):
    files = {}
    if param_ops:
        files["parameters.json"] = {"ops": list(param_ops)}
    if row_ops:
        files["validation_report.json"] = {"ops": list(row_ops)}
    return {"files": files}


def _status_op(name, status):
    return {"op": "replace", "path": f"/parameters/{name}/status", "value": status}


def _verdict_op(i, verdict="PASS"):
    return {"op": "replace", "path": f"/validations/{i}/verdict", "value": verdict}


def _world(tmp_path, options, refused=(), audit=None, validations=VALIDATIONS):
    """options: {opt: (inert, summary, patch)}; returns the assess() result."""
    paths = tmp_path / "paths"
    entries = [{"id": "main", "selection": {"f": "base"}, "inert": False}]
    (paths / "main").mkdir(parents=True)
    (paths / "main" / "summary.json").write_text(json.dumps(_summary(10, 5)))
    for opt, (inert, summ, patch) in options.items():
        pid = f"f--{opt}"
        entries.append({"id": pid, "inert": inert})
        (paths / pid).mkdir()
        (paths / pid / "summary.json").write_text(json.dumps(summ))
        (paths / pid / "patch.json").write_text(json.dumps(patch))
    index = {"paths": entries,
             "not_computed": [{"id": f"f--{o}", "reason": r} for o, r in refused]}
    forks = {"f": {"active": "base",
                   "options": {o: "considered" for o in
                               list(options) + [o for o, _ in refused] + ["base"]}}}
    return g.assess(index, forks, paths, PARAMS, validations, audit)["forks"]["f"]


def _opt(fork, name):
    return next(a for a in fork["alternatives"] if a["option"] == name)


def test_invalid_from_not_computed(tmp_path):
    fork = _world(tmp_path, {}, refused=[("bad", "ValueError: n_gen is not three")])
    a = _opt(fork, "bad")
    assert a["P"]["state"] == "INVALID" and "n_gen" in a["P"]["reason"]
    assert a["candidate"] is False


def test_inert(tmp_path):
    fork = _world(tmp_path, {"same": (True, _summary(10, 5), _patch())})
    a = _opt(fork, "same")
    assert a["P"]["state"] == "INERT" and a["candidate"] is False


def test_better_p_without_guard_is_candidate(tmp_path):
    opts = {"win": (False, _summary(12, 4), _patch(row_ops=[_verdict_op(0)]))}
    fork = _world(tmp_path, opts, audit=[{"path": "row.x", "class": "G"}])
    a = _opt(fork, "win")
    assert a["guard"]["state"] == "CLEAR" and a["candidate"] is True


def test_c24_gain_is_fit_at_24_not_candidate(tmp_path):
    opts = {"fit": (False, _summary(11, 4), _patch(row_ops=[_verdict_op(0)]))}
    fork = _world(tmp_path, opts, audit=[{"path": "row.x", "class": "C24"}])
    a = _opt(fork, "fit")
    assert a["guard"]["state"] == "FIT_AT_24" and a["candidate"] is False
    assert any("fit at 24" in r and "row.x" in r for r in a["reasons"])


def test_worse_on_r_is_not_candidate(tmp_path):
    ops = _patch(param_ops=[_status_op("a", "FITTED")], row_ops=[_verdict_op(0)])
    fork = _world(tmp_path, {"worse": (False, _summary(12, 4), ops)},
                  audit=[{"path": "row.x", "class": "G"}])
    a = _opt(fork, "worse")
    assert a["R"]["d_share"] < 0 and a["candidate"] is False
    assert any("worse on" in r and "R" in r for r in a["reasons"])


def test_tightening_flag(tmp_path):
    ops = _patch(param_ops=[_status_op("b", "DERIVED")])
    fork = _world(tmp_path, {"tight": (False, _summary(10, 5), ops)}, audit=[])
    a = _opt(fork, "tight")
    assert a["T"] is True and a["E"]["d_free"] == -1 and a["candidate"] is True


def test_absent_audit_is_open(tmp_path):
    opts = {"win": (False, _summary(12, 4), _patch(row_ops=[_verdict_op(0)]))}
    fork = _world(tmp_path, opts, audit=None)
    a = _opt(fork, "win")
    assert a["guard"]["state"] == "OPEN" and a["E"]["literals"] == "OPEN"
    assert a["candidate"] is False and a["provisional"] is True


def test_dominance_tie_is_not_candidate(tmp_path):
    fork = _world(tmp_path, {"tie": (False, _summary(10, 5), _patch())}, audit=[])
    a = _opt(fork, "tie")
    assert a["candidate"] is False
    assert any("tie" in r for r in a["reasons"])


def test_missing_index_fails_early(tmp_path, capsys):
    rc = g.main(["--paths", str(tmp_path), "--parameters", "p.json",
                 "--out", str(tmp_path / "o.json")])
    assert rc == 2 and "index.json" in capsys.readouterr().err


def test_functions_are_short():
    import inspect
    for name, fn in inspect.getmembers(g, inspect.isfunction):
        if fn.__module__ == g.__name__:
            assert len(inspect.getsourcelines(fn)[0]) <= 60, name


def test_smoke_on_published_paths(tmp_path):
    if not (PUBLISHED / "paths" / "index.json").is_file():
        pytest.skip("published paths not available")
    from metaphysica.simulations.core.variants import FORKS
    out = tmp_path / "option_assessment.json"
    rc = g.main(["--paths", str(PUBLISHED / "paths"),
                 "--parameters", str(PUBLISHED / "parameters.json"), "--out", str(out)])
    doc = json.loads(out.read_text(encoding="utf-8"))
    assert rc == 0 and set(FORKS) <= set(doc["forks"])
    assert doc["audit"] in ("OPEN", "present")
