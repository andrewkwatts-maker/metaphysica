from __future__ import annotations

from tests.conftest import _artifact_root


def _tree(root):
    (root / "AutoGenerated").mkdir(parents=True)
    (root / "AutoGenerated" / "parameters.json").write_text("{}")
    return root


def test_published_tree_wins_over_stale_scratch(tmp_path):
    """A stale repo-local sections.json failed the prose ratchet in a full run."""
    published = _tree(tmp_path / "published")
    scratch = _tree(tmp_path / "scratch")
    assert _artifact_root((published, scratch)) == published


def test_scratch_is_the_fallback(tmp_path):
    scratch = _tree(tmp_path / "scratch")
    assert _artifact_root((tmp_path / "absent", scratch)) == scratch
    assert _artifact_root((tmp_path / "absent",)) is None
