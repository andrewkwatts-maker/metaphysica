"""Ratchet: prose may not present the retired b3 = 24 / TCS geometry as active.

D-025 ruling 3. The scanner reads AutoGenerated/sections.json and flags blocks
that present b3 = 24, "twisted connected sum", TCS or fano_tcs as the live
geometry, unless the string sits inside a "Superseded path" callout or says in
its own words that the path is retired. The ceiling only goes down: lower it
when a fix lands, never raise it.
"""
from __future__ import annotations

import pytest

from metaphysica.generators import superseded_scan as scan
from metaphysica.simulations.PM.paper import superseded

#: Active-presenting hits permitted outside a superseded callout. Only goes down.
CEILING = 0


def test_active_hits_under_ceiling():
    hits = scan.active_hits(scan.load_hits())
    where = sorted({h["section"] for h in hits})
    assert len(hits) <= CEILING, "%d active hits in %s" % (len(hits), where)


def test_scanner_flags_active_and_spares_callout():
    active = "The manifold has b_3 = 24 and is a TCS."
    assert scan.is_hit(active)
    secs = {"x": {"contentBlocks": [{"content": active},
                                    {"content": superseded.superseded(active)}]}}
    found = scan.scan_sections(secs)
    assert [h["in_callout"] for h in found] == [False, True]


def test_scanner_ignores_bulk_and_fano_plane():
    for text in ("signature (24,2) bulk", "the Leech lattice in 24 dimensions",
                 "the Fano plane gives the octonion table"):
        assert not scan.is_hit(text)


def test_callout_has_link_and_live_numbers_or_open():
    text = superseded.superseded_text()
    assert superseded.LINK in text and "seed_43_joyce" in text
    assert "Joyce 11.6.1" in text and "no closure theorem" in text
    assert "chi-squared" in text or "OPEN" in text


def test_callout_prints_open_when_summaries_missing(monkeypatch):
    monkeypatch.setattr(superseded, "_path_summary", lambda name: None)
    text = superseded.superseded_text()
    assert "OPEN" in text and "chi-squared" not in text


def test_wrapper_keeps_old_text_and_rejects_empty():
    assert "old words" in superseded.superseded("old words")
    with pytest.raises(ValueError):
        superseded.superseded("")


def test_refresh_modules_flag_rejects_module_without_simulation():
    from metaphysica.generators import refresh_paper_conclusions as r
    with pytest.raises(SystemExit):
        r._module_sims(["metaphysica.generators.superseded_scan"])
