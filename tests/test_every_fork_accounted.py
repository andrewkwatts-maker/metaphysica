"""Every fork is read by a build, gated, or explained.

A fork `--fast` never reads cannot change any output of that build, whatever
the selection. So each fork in `fork_reads.json` must be read, carry an
`applies_when` gate, or sit in `UNREAD_OK` with the reason. `UNREAD_OK` may
only shrink: wire or gate a fork, then delete its entry and lower the pin.

Reads `AutoGenerated/fork_reads.json` under PM_PUBLISHED_ROOT; skips when
there is no build.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

from metaphysica.simulations.core.variants import FORKS

PUBLISHED = Path(os.environ.get("PM_PUBLISHED_ROOT", "H:/claude-scratch/runs_g/active"))
READS = PUBLISHED / "AutoGenerated" / "fork_reads.json"

#: fork id -> why a default `--fast` build never reads it.
UNREAD_OK = {
    "b3_origin": "read only by switch_search consistency checks, which no "
                 "build step runs",
    "n_gen_source": "b3_path.n_gen_report resolves it only when is_explicit; "
                    "by default the seed path's own declaration is used",
    "metric_construction": "read by G2DifferentialGeometry.metric_by_convention, "
                           "which no build step calls",
    "twisted_norm_convention": "read by metric_pairing, reached only through "
                               "flux_quantization, which no build step runs",
    "bulk_signature": "DEAD: no resolve; CANON['bulk'] states the signature "
                      "and the fork's read_adopted only checks it",
    "face_genericity": "DEAD: no resolve; face_assignment_candidates "
                       "computes both orbits and always returns the generic one",
    "moduli_indexing": "DEAD: nothing reads it (OPEN fork, no consumer)",
}
UNREAD_OK_PINNED_SIZE = 7


def test_unread_ok_may_only_shrink():
    assert len(UNREAD_OK) <= UNREAD_OK_PINNED_SIZE
    assert all(UNREAD_OK.values()), "every entry needs a reason"
    assert set(UNREAD_OK) <= set(FORKS), "UNREAD_OK names an unknown fork"


@pytest.mark.skipif(not READS.is_file(),
                    reason="no build: %s is absent (set PM_PUBLISHED_ROOT)" % READS)
def test_every_fork_is_read_gated_or_explained():
    data = json.loads(READS.read_text(encoding="utf-8"))
    seen = set(data.get("reads", {})) | set(data.get("closed_gate_reads", {}))
    loose = sorted(fid for fid, fork in FORKS.items()
                   if fid not in seen and not fork.applies_when
                   and fid not in UNREAD_OK)
    assert not loose, "forks neither read, gated nor in UNREAD_OK: %s" % loose
    stale = sorted(fid for fid in UNREAD_OK
                   if fid in seen or FORKS[fid].applies_when)
    assert not stale, "UNREAD_OK entries now read or gated; delete: %s" % stale
