"""build --keep-going records failed steps; no real build runs here."""
import json
import sys

import pytest

import metaphysica.build as b


def _steps(monkeypatch, steps):
    monkeypatch.setattr(b, "STEPS", steps)
    monkeypatch.setattr(b, "_optional_deps_available", lambda m: True)


def _py(code):
    return [sys.executable, "-c", code]


FAIL = "import sys; print('ValueError: nope'); sys.exit(3)"
OK = "print('fine')"


def _status(out):
    return json.loads((out / "AutoGenerated" / "build_status.json")
                      .read_text("utf-8"))


def test_module_imports_and_exposes_flag():
    assert callable(b.build) and callable(b.main)


def test_keep_going_continues_and_records(tmp_path, monkeypatch):
    _steps(monkeypatch, [("Bad step", _py(FAIL), False),
                         ("Good step", _py(OK), False)])
    code = b.build(out_dir=tmp_path, keep_going=True)
    doc = _status(tmp_path)
    assert code == 3 and doc["keep_going"] is True
    assert doc["schema"] == "metaphysica.build_status/1"
    assert doc["failed_steps"] == [{"id": "bad_step", "title": "Bad step",
                                    "exit": 3, "reason": "ValueError: nope"}]


def test_default_halts_at_first_failure(tmp_path, monkeypatch, capsys):
    _steps(monkeypatch, [("Bad step", _py(FAIL), False),
                         ("Good step", _py(OK), False)])
    assert b.build(out_dir=tmp_path) == 3
    assert "fine" not in capsys.readouterr().out
    assert _status(tmp_path)["keep_going"] is False


def test_success_writes_empty_list(tmp_path, monkeypatch):
    _steps(monkeypatch, [("Good step", _py(OK), False)])
    assert b.build(out_dir=tmp_path, keep_going=True) == 0
    assert _status(tmp_path)["failed_steps"] == []


def test_reason_is_null_without_an_exception_line(tmp_path, monkeypatch):
    _steps(monkeypatch, [("Bad step", _py("import sys; sys.exit(2)"), False)])
    b.build(out_dir=tmp_path, keep_going=True)
    assert _status(tmp_path)["failed_steps"][0]["reason"] is None


@pytest.mark.parametrize("label,sid", [("Run all simulations",
                                        "run_all_simulations")])
def test_step_id_is_a_slug(label, sid):
    assert b._step_id(label) == sid
