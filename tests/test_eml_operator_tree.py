"""Tests for ``metaphysica.simulations.core.eml_math.eml_operator_tree``.

The adapter persists v25.0 physics-module derivations into
``AutoGenerated/eml_trees_v25.json`` overlay-safe and cross-links each
formula to ``b3_leaf()`` whenever the text mentions b3 / b_3 / 24.

These three tests cover:

1. Construction (name validation, get_tree() empty after init).
2. register_derivation (entry shape, b3_traceback flag, both positive
   and negative).
3. Persistence round-trip — write twice across two ``eml_operator_tree``
   instances (one per tree name, then a second registration under the
   first name) and confirm the JSON file holds the union.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest


# ── Test plumbing ----------------------------------------------------------


@pytest.fixture
def isolated_autogen(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Point the build's ``autogen_dir()`` at a fresh temp dir.

    The adapter resolves ``AutoGenerated/`` via
    ``metaphysica.generators._common.autogen_dir`` which honours the
    ``METAPHYSICA_OUT`` env var, so we just set that env var to a clean
    location for the duration of the test.
    """
    monkeypatch.setenv("METAPHYSICA_OUT", str(tmp_path))
    autogen = tmp_path / "AutoGenerated"
    autogen.mkdir(parents=True, exist_ok=True)
    return autogen


# ── Test 1 — construction ---------------------------------------------------


def test_construction(isolated_autogen: Path) -> None:
    """``eml_operator_tree(name)`` succeeds and is empty before any registration."""
    from metaphysica.simulations.core.eml_tree_adapter import eml_operator_tree

    tree = eml_operator_tree("yukawa_derivation")
    assert tree.name == "yukawa_derivation"
    assert tree.get_tree() == {}

    # Bad names rejected.
    with pytest.raises(ValueError):
        eml_operator_tree("")
    with pytest.raises(ValueError):
        eml_operator_tree(None)  # type: ignore[arg-type]


# ── Test 2 — register_derivation -------------------------------------------


def test_register_derivation_shape_and_b3_flag(isolated_autogen: Path) -> None:
    """register_derivation stores formula+value and sets b3_traceback correctly."""
    from metaphysica.simulations.core.eml_tree_adapter import eml_operator_tree

    tree = eml_operator_tree("re_t_sector")

    # Formula that mentions b3 → flag should be True.
    entry_yes = tree.register_derivation(
        param="ReT_VEV",
        formula="b3 * exp(-S_inst) / (2*pi)",
        value=10.86,
    )
    assert entry_yes["formula"] == "b3 * exp(-S_inst) / (2*pi)"
    assert entry_yes["value"] == pytest.approx(10.86)
    assert entry_yes["b3_traceback"] is True

    # Formula with literal 24 → flag also True (b3=24 is the same seed).
    entry_24 = tree.register_derivation(
        param="some_param",
        formula="exp(-2*pi*ReT/24)",
        value=0.5,
    )
    assert entry_24["b3_traceback"] is True

    # Formula without b3 / b_3 / 24 → flag False.
    entry_no = tree.register_derivation(
        param="unrelated",
        formula="sin(pi/3) + cos(pi/4)",
        value=1.573,
    )
    assert entry_no["b3_traceback"] is False

    # get_tree returns all three entries under this adapter's name.
    bucket = tree.get_tree()
    assert set(bucket) == {"ReT_VEV", "some_param", "unrelated"}
    assert bucket["ReT_VEV"]["b3_traceback"] is True

    # Input validation.
    with pytest.raises(ValueError):
        tree.register_derivation(param="", formula="x", value=0.0)
    with pytest.raises(TypeError):
        tree.register_derivation(param="x", formula=None, value=0.0)  # type: ignore[arg-type]


# ── Test 3 — persistence round-trip ----------------------------------------


def test_persistence_round_trip(isolated_autogen: Path) -> None:
    """Two adapters writing different names produce a union on disk;
    a second adapter under the first name preserves the second tree."""
    from metaphysica.simulations.core.eml_tree_adapter import (
        TREES_FILENAME,
        eml_operator_tree,
    )

    tree_a = eml_operator_tree("yukawa_derivation")
    tree_a.register_derivation(
        param="theta_13_rad",
        formula="arcsin(sqrt(2)/3) - delta_b3",
        value=0.1485,
    )

    tree_b = eml_operator_tree("strong_cp_axion")
    tree_b.register_derivation(
        param="theta_QCD",
        formula="exp(-S_inst) * sin(b3 * alpha)",
        value=1e-12,
    )

    # On-disk file exists in the right place.
    json_path = isolated_autogen / TREES_FILENAME
    assert json_path.exists(), f"expected {json_path} to be written"

    # Both top-level trees are present and overlay-safe.
    with json_path.open("r", encoding="utf-8") as fh:
        on_disk = json.load(fh)
    assert set(on_disk) == {"yukawa_derivation", "strong_cp_axion"}
    assert on_disk["yukawa_derivation"]["theta_13_rad"]["value"] == pytest.approx(0.1485)
    assert on_disk["strong_cp_axion"]["theta_QCD"]["b3_traceback"] is True

    # A fresh adapter under the *first* name preserves tree_b's data.
    tree_a2 = eml_operator_tree("yukawa_derivation")
    tree_a2.register_derivation(
        param="delta_CP",
        formula="2*pi - phi_golden",  # no b3 / 24
        value=3.77,
    )

    with json_path.open("r", encoding="utf-8") as fh:
        on_disk2 = json.load(fh)

    # strong_cp_axion entry is still there (overlay-safe).
    assert "strong_cp_axion" in on_disk2
    assert on_disk2["strong_cp_axion"]["theta_QCD"]["value"] == pytest.approx(1e-12)

    # yukawa_derivation now has both entries.
    assert set(on_disk2["yukawa_derivation"]) == {"theta_13_rad", "delta_CP"}
    assert on_disk2["yukawa_derivation"]["delta_CP"]["b3_traceback"] is False

    # Round-trip via the read API matches the on-disk JSON.
    assert tree_a2.get_tree() == on_disk2["yukawa_derivation"]
    assert eml_operator_tree("strong_cp_axion").get_tree() == on_disk2["strong_cp_axion"]
