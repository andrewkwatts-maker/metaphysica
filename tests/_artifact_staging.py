"""Per-process staging copy of the published artifacts for a test session.

Each pytest process reads build artifacts from its own copy, so a test that
writes never touches the published tree and never disturbs another run. The
copy is removed when the process exits. A copy whose process was killed is
removed by the next session that starts.

The folder name carries the owning process id: ``metaphysica-artifacts-p<pid>-<random>``.
Folders with the older name (no process id) are removed once they are old.
"""
from __future__ import annotations

import atexit
import os
import re
import shutil
import sys
import tempfile
import time
from pathlib import Path

PREFIX = "metaphysica-artifacts-"
BASE_ENV = "METAPHYSICA_TEST_STAGE_DIR"
UNOWNED_MAX_AGE_S = 6 * 3600.0
OWNED_MAX_AGE_S = 24 * 3600.0

_OWNED = re.compile(r"^" + re.escape(PREFIX) + r"p(\d+)-")
_QUERY_LIMITED_INFORMATION = 0x1000
_ACCESS_DENIED = 5
_STILL_ACTIVE = 259


def stage_base() -> Path:
    """Directory that holds the staging copies: the override, else system temp."""
    chosen = os.environ.get(BASE_ENV)
    base = Path(chosen) if chosen else Path(tempfile.gettempdir())
    base.mkdir(parents=True, exist_ok=True)
    return base


def owner_pid(folder: Path) -> int | None:
    """The process id written in a staging folder name; None for the older name."""
    match = _OWNED.match(folder.name)
    return int(match.group(1)) if match else None


def _windows_process_alive(pid: int) -> bool:
    import ctypes
    from ctypes import wintypes

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    kernel32.OpenProcess.restype = wintypes.HANDLE
    kernel32.OpenProcess.argtypes = (wintypes.DWORD, wintypes.BOOL, wintypes.DWORD)
    kernel32.GetExitCodeProcess.argtypes = (wintypes.HANDLE, ctypes.POINTER(wintypes.DWORD))
    kernel32.CloseHandle.argtypes = (wintypes.HANDLE,)
    handle = kernel32.OpenProcess(_QUERY_LIMITED_INFORMATION, False, pid)
    if not handle:
        # Access denied means the process exists and belongs to someone else.
        return ctypes.get_last_error() == _ACCESS_DENIED
    try:
        code = wintypes.DWORD()
        answered = kernel32.GetExitCodeProcess(handle, ctypes.byref(code))
        return bool(answered) and code.value == _STILL_ACTIVE
    finally:
        kernel32.CloseHandle(handle)


def process_alive(pid: int) -> bool:
    """True when a process with this id is running."""
    if pid <= 0:
        return False
    if sys.platform == "win32":
        # os.kill(pid, 0) ends the process on Windows, so it is never used here.
        return _windows_process_alive(pid)
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def is_orphan(folder: Path, now: float) -> bool:
    """True when no running session owns this staging folder."""
    try:
        age = now - folder.stat().st_mtime
    except OSError:
        return False
    pid = owner_pid(folder)
    if pid is None:
        return age > UNOWNED_MAX_AGE_S
    return age > OWNED_MAX_AGE_S or not process_alive(pid)


def sweep_orphans(base: Path) -> list[Path]:
    """Remove the staging folders under base that no running session owns."""
    removed = []
    now = time.time()
    for folder in sorted(base.glob(PREFIX + "*")):
        if folder.is_dir() and is_orphan(folder, now):
            shutil.rmtree(folder, ignore_errors=True)
            if not folder.exists():
                removed.append(folder)
    return removed


def stage_copy(source: Path, base: Path | None = None) -> Path:
    """Copy source/AutoGenerated into a folder of this process, removed at exit."""
    base = stage_base() if base is None else base
    sweep_orphans(base)
    staged = Path(tempfile.mkdtemp(prefix=f"{PREFIX}p{os.getpid()}-", dir=base))
    atexit.register(shutil.rmtree, staged, ignore_errors=True)
    shutil.copytree(source / "AutoGenerated", staged / "AutoGenerated")
    return staged
