"""Derivation chains recorded at export, calibration checks, kill switches that match.

Fixtures test the rules; the real-build tests read PM_PUBLISHED_ROOT and skip when
it holds no build. Ceilings may only fall.
"""
import json
import os
from pathlib import Path

import pytest

from metaphysica.generators import derivation_chain as dc
from metaphysica.generators import parameter_ledger as pl
from metaphysica.generators.kill_switch_rows import (
    KILL_SWITCH_REPORT_KEYS, KILL_SWITCH_ROWS, NO_REGISTRY_ROW)

AUTO = Path(os.environ.get("PM_PUBLISHED_ROOT", "H:/claude-scratch/runs_g/active")) / "AutoGenerated"
BUILT = (AUTO / "parameters.json").exists()
needs_build = pytest.mark.skipif(not BUILT, reason="no build under PM_PUBLISHED_ROOT")

#: Declared-formula errors on the fresh build (unknown id or output not listed). May only fall.
DECLARED_FORMULA_ERROR_CEILING = 77  # measured on the fresh fast build, 2026-10-27


def _load(name, key=None):
    data = json.loads((AUTO / name).read_text(encoding="utf-8"))
    return data[key] if key else data


F = {"f1": {"input_params": ["a.x", "a.y", "a.x", "b.z"], "output_params": ["b.z"]},
     "f2": {"input_params": ["a.x"], "output_params": ["c.w"]}}


def test_formula_inputs_drop_self_and_repeats():
    assert dc.formula_inputs("b.z", F["f1"]) == ["a.x", "a.y"]


def test_declared_chain_unknown_or_missing_formula_is_empty():
    assert dc.declared_chain("b.z", "f1", F) == ["a.x", "a.y"]
    assert dc.declared_chain("b.z", "nope", F) == []
    assert dc.declared_chain("b.z", None, F) == []


def test_declared_formula_errors_fail_early():
    params = {"b.z": {"derivation_formula": "f1"},      # fine
              "c.q": {"derivation_formula": "f2"},      # output not listed
              "d.r": {"derivation_formula": "ghost"},   # unknown
              "e.s": {}}                                # no declaration
    errs = dc.declared_formula_errors(params, F)
    assert len(errs) == 2
    assert any("c.q" in e and "output_params" in e for e in errs)
    assert any("d.r" in e and "unknown" in e for e in errs)


def test_ledger_uses_the_shared_rule():
    ins, _ = pl.parents("b.z", {"b.z": ["f1"]}, F, {"a.x": {}, "a.y": {}, "b.z": {}})
    assert ins == dc.declared_chain("b.z", "f1", F)


def _prow(status, val, exp=1.0, **kw):
    r = {"value": 1.0, "status": status, "source": "s", "validation_status": val,
         "experimental_value": exp}
    r.update(kw)
    return r


def test_calibration_check_rule_is_generic():
    params = {"c.a": _prow("CALIBRATED", "PASS"), "f.a": _prow("FITTED", "PASS"),
              "c.b": _prow("CALIBRATED", "FAIL"),        # failed: stays a FAIL
              "d.a": _prow("DERIVED", "PASS"),           # no calibrated leaf: a real pass
              "c.c": _prow("CALIBRATED", "PASS", exp=None)}
    assert sorted(pl.calibration_check_names(params, {})) == ["c.a", "f.a"]


def test_calibration_check_is_not_circular_or_a_pass():
    done = _prow("CALIBRATED", pl.CALIBRATION_CHECK)
    rows = pl.build_ledger({"c.a": done}, {}, {"rows": []}, {})["rows"]
    assert not rows["c.a"]["circular"]
    assert rows["c.a"]["falsifiability"]["state"] == pl.CALIBRATION_CHECK
    todo = pl.build_ledger({"c.a": _prow("CALIBRATED", "PASS")}, {}, {"rows": []}, {})["rows"]
    assert todo["c.a"]["circular"]


@needs_build
def test_real_chains_match_declared_formulas():
    params = _load("parameters.json", "parameters")
    formulas = _load("formulas.json", "formulas")
    with_formula = [n for n, r in params.items() if r.get("derivation_formula") in formulas]
    assert with_formula
    for n in with_formula:
        assert params[n]["derivation_chain"] == dc.declared_chain(
            n, params[n]["derivation_formula"], formulas), n


@needs_build
def test_real_declared_formula_errors_under_ceiling():
    errs = dc.declared_formula_errors(_load("parameters.json", "parameters"),
                                      _load("formulas.json", "formulas"))
    assert len(errs) <= DECLARED_FORMULA_ERROR_CEILING, errs[:10]


@needs_build
def test_real_no_calibrated_row_scores_pass():
    params = _load("parameters.json", "parameters")
    formulas = _load("formulas.json", "formulas")
    assert pl.calibration_check_names(params, formulas) == []


@needs_build
def test_each_kill_switch_equals_its_registry_row():
    report = _load("falsification_report.json")["detailed_risk_analysis"]
    params = _load("parameters.json", "parameters")
    for test, rid in KILL_SWITCH_ROWS.items():
        got = report[test][KILL_SWITCH_REPORT_KEYS[test]]
        assert got == pytest.approx(params[rid]["value"], rel=1e-9), test
    for test in NO_REGISTRY_ROW:
        assert test in report
        assert test not in KILL_SWITCH_ROWS
