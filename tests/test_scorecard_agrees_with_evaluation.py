"""Published gate tallies must not contradict each other.

WHY THIS EXISTS
---------------
Three artifacts in the same build directory published three different gate
counts at once:

* ``improvement_scorecard.json`` — "42/42 testable gates LOCKED (100.0%
  complete)", ``open_gate_ids: []``, with G12 among the locked ids.
* ``GATES_CERTIFICATES.json.evaluation_summary`` — G12 COMPUTED_FAIL at
  17.1 sigma, and the G72 seal failing because of it.
* ``GATES_CERTIFICATES.json.summary`` — "verified: 40, pending_lock: 0",
  a third number again.

The cause was that the scorecard generator read ``verification_status``,
the DECLARATIVE field recording what a certificate asserts about itself,
and never looked at ``evaluation_status``, which records what happened when
the gate was actually executed. A gate could therefore be VERIFIED and
COMPUTED_FAIL simultaneously, and the cheerful number was the one on the
dashboard.

The ``summary`` block is a legitimate declarative tally; the fault was that
nothing said so, and that a consumer was reading it as though it were an
execution result. It is now labelled, and the scorecard reads the
evaluation layer.

These tests check agreement rather than specific values, so a genuine
change in gate status moves all three together instead of failing here.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import pytest


def _autogen() -> Path:
    raw = os.environ.get("METAPHYSICA_OUT")
    candidates = []
    if raw:
        candidates.append(Path(raw) / "AutoGenerated")
    candidates += [
        Path(__file__).resolve().parents[1] / "AutoGenerated",
        Path(__file__).resolve().parents[2] / "PrincipiaMetaphysica" / "AutoGenerated",
        Path("H:/Github/PrincipiaMetaphysica/AutoGenerated"),
    ]
    for path in candidates:
        if path.is_dir() and (path / "GATES_CERTIFICATES.json").is_file():
            return path
    pytest.skip("no GATES_CERTIFICATES.json found; run the build first")


def _load(name: str) -> dict:
    path = _autogen() / name
    if not path.is_file():
        pytest.skip(f"{name} not present; run the build first")
    return json.loads(path.read_text(encoding="utf-8"))


def test_every_computed_failure_appears_open_in_the_scorecard():
    """The central contradiction: a failing gate counted as locked."""
    certs = _load("GATES_CERTIFICATES.json")["certificates"]
    scorecard = _load("improvement_scorecard.json")

    failing = {str(c["gate_id"]) for c in certs
               if c.get("evaluation_status") == "COMPUTED_FAIL"}
    locked = set(scorecard.get("locked_gate_ids", []))
    open_ids = set(scorecard.get("open_gate_ids", []))

    assert not (failing & locked), (
        f"gates {sorted(failing & locked)} are COMPUTED_FAIL but the "
        f"scorecard lists them as LOCKED"
    )
    assert failing <= open_ids, (
        f"gates {sorted(failing - open_ids)} are COMPUTED_FAIL but appear "
        f"in neither open_gate_ids nor anywhere the reader would look"
    )


def test_scorecard_cannot_claim_completion_while_a_gate_fails():
    certs = _load("GATES_CERTIFICATES.json")["certificates"]
    scorecard = _load("improvement_scorecard.json")
    any_failing = any(c.get("evaluation_status") == "COMPUTED_FAIL"
                      for c in certs)
    if not any_failing:
        pytest.skip("no gate is currently failing")
    assert scorecard["totals"]["completion_percent"] < 100.0, (
        "a gate is COMPUTED_FAIL but the scorecard reports 100% complete"
    )
    assert scorecard["totals"]["open"] > 0


def test_computed_passes_are_not_reported_open():
    """The converse, so the fix cannot overshoot into pessimism."""
    certs = _load("GATES_CERTIFICATES.json")["certificates"]
    scorecard = _load("improvement_scorecard.json")
    passing = {str(c["gate_id"]) for c in certs
               if c.get("evaluation_status") == "COMPUTED_PASS"}
    open_ids = set(scorecard.get("open_gate_ids", []))
    assert not (passing & open_ids), (
        f"gates {sorted(passing & open_ids)} passed but are listed open"
    )


def test_the_declarative_tally_says_it_is_declarative():
    """It is a legitimate count; it must not read as an execution result."""
    summary = _load("GATES_CERTIFICATES.json")["summary"]
    assert summary.get("tally_type") == (
        "declarative_assertions_not_execution_results"), (
        "the summary block has lost the label distinguishing it from the "
        "evaluation layer -- this is how a consumer came to read it as one"
    )
    assert "evaluation_summary" in str(summary.get("authoritative_counts", ""))


def _status(cert: dict) -> str:
    return str(cert.get("evaluation_status") or "").upper()


def _applicable_tally(certs: list) -> tuple:
    """(gates the selected path carries, of those the ones never run).

    A NOT_APPLICABLE gate has a premise the selected path does not carry
    (generate_72_certificates._apply_path_applicability). It is neither run
    nor a declarative gate of this path, so the scorecard leaves it out
    before it counts anything, as headline_stats.tally_gates does.
    """
    applicable = [c for c in certs if _status(c) != "NOT_APPLICABLE"]
    never_run = sum(1 for c in applicable
                    if not _status(c).startswith("COMPUTED"))
    return len(applicable), never_run


def _assert_totals_match_the_certificates(totals: dict, certs: list) -> None:
    applicable, never_run = _applicable_tally(certs)
    assert totals["total_gates"] == applicable, (
        f"the scorecard counts {totals['total_gates']} gates; the selected "
        f"path carries {applicable} of the {len(certs)} certificates"
    )
    assert totals["declarative_no_executable_form"] == never_run, (
        f"the scorecard reports {totals['declarative_no_executable_form']} "
        f"gates never run; {never_run} applicable certificates have no "
        f"COMPUTED status"
    )


def test_declarative_gates_are_counted_separately():
    """Completion over gates that were never run is not a completion rate.

    Measured 2026-11-11 on the fresh build of 249f362: 72 certificates, G31
    NOT_APPLICABLE, 71 applicable, 38 of them never run (31 with no status
    and 7 DECLARATIVE). The numbers are not pinned here: the test checks
    that the scorecard agrees with the certificates.
    """
    scorecard = _load("improvement_scorecard.json")
    certs = _load("GATES_CERTIFICATES.json")["certificates"]
    _assert_totals_match_the_certificates(scorecard["totals"], certs)


_CONTROL_CERTS = [
    {"gate_id": 1, "evaluation_status": "COMPUTED_PASS"},
    {"gate_id": 2, "evaluation_status": "COMPUTED_FAIL"},
    {"gate_id": 3, "evaluation_status": "DECLARATIVE"},
    {"gate_id": 4},
    {"gate_id": 5, "evaluation_status": "NOT_APPLICABLE"},
]


@pytest.mark.parametrize("total_gates, never_run", [(5, 3), (4, 3), (5, 2)])
def test_a_scorecard_that_counts_a_not_applicable_gate_fails(
        total_gates, never_run):
    """Control: the exclusion is pinned on both totals, not tolerated."""
    _assert_totals_match_the_certificates(
        {"total_gates": 4, "declarative_no_executable_form": 2},
        _CONTROL_CERTS)
    with pytest.raises(AssertionError):
        _assert_totals_match_the_certificates(
            {"total_gates": total_gates,
             "declarative_no_executable_form": never_run},
            _CONTROL_CERTS)


def test_the_built_scorecard_fails_if_it_counts_the_not_applicable_gates():
    """Control on the build: the old count (G31 as never run) is rejected."""
    totals = _load("improvement_scorecard.json")["totals"]
    certs = _load("GATES_CERTIFICATES.json")["certificates"]
    not_applicable = len(certs) - _applicable_tally(certs)[0]
    if not_applicable == 0:
        pytest.skip("the selected path marks no gate NOT_APPLICABLE")
    for key in ("total_gates", "declarative_no_executable_form"):
        counted = dict(totals, **{key: totals[key] + not_applicable})
        with pytest.raises(AssertionError):
            _assert_totals_match_the_certificates(counted, certs)


def test_the_seal_accounting_is_explicit():
    """computed_fail exceeding len(failed_gate_ids) must be explained."""
    evaluation = _load("GATES_CERTIFICATES.json")["evaluation_summary"]
    ids = evaluation.get("failed_gate_ids", [])
    if evaluation.get("computed_fail", 0) == len(ids):
        return
    assert evaluation.get("failed_gate_ids_excludes_seal") is True, (
        "computed_fail does not match failed_gate_ids and nothing says why; "
        "this reads as an arithmetic error"
    )
    assert evaluation.get("seal_gate_id") == 72
