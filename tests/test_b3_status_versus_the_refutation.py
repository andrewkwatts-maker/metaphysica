"""b_3 = 24 is published as DERIVED while no derivation of it is on the books.

HISTORY, which this file must not lose. A parity refutation of b_3 = 24 briefly
stood here and was WITHDRAWN on review: its enumeration covered 1/32 of the
half-shift moduli space, its additivity premise failed on the stratum it did
cover, and its component action carried a labelling defect. So the status of
b_3 = 24 for the Joyce (Z/2)^3 construction is UNDETERMINED — not refuted, and
not derived.

The contradiction of record is therefore narrower but still real:

  * particle.b3 and cosmology.b3 ship with status DERIVED;
  * neither declared construction supplies the derivation — Joyce (Z/2)^3 is
    UNDETERMINED pending the corrected enumeration and the cited contribution
    table, and fano_tcs was separately recorded as placing b_3 = 24 far below
    its exhibited 71-155 range.

Relabelling is a physics ruling and is not taken here. This file is GREEN while
the disagreement stands and FAILS when b_3's published status changes, at which
point the register must record the ruling.
"""

from __future__ import annotations

import json
import os
from pathlib import Path

import pytest

_RECORDED_STATUS = {
    "particle.b3": "DERIVED",
    "cosmology.b3": "DERIVED",
}


def _load_params():
    candidates = []
    raw = os.environ.get("PM_SITE_ROOT")
    if raw:
        candidates.append(Path(raw) / "AutoGenerated" / "parameters.json")
    candidates += [
        Path(__file__).resolve().parents[1] / "AutoGenerated" / "parameters.json",
        Path("H:/Github/PrincipiaMetaphysica/AutoGenerated/parameters.json"),
    ]
    for path in candidates:
        if path.is_file():
            return json.loads(path.read_text(encoding="utf-8"))["parameters"]
    pytest.skip("parameters.json not available; run the build first")


@pytest.fixture(scope="module")
def params():
    return _load_params()


def test_the_seed_ruling_was_executed(params):
    """2026-09-14: topology.elder_kads is INPUT, not GEOMETRIC.

    The ruling removed b_3 = 24's derived status at the SEED. This fails if it
    is ever quietly restored without a derivation landing.
    """
    seed = params.get("topology.elder_kads")
    assert seed is not None
    assert seed.get("status") == "INPUT", (
        "the seed's status is %s; the 2026-09-14 ruling set it to INPUT and "
        "nothing on the books derives b_3 = 24" % seed.get("status")
    )
    ruling = (seed.get("metadata") or {}).get("ruling", "")
    assert "2026-09-14" in ruling
    assert seed.get("value") == 24


def test_the_echo_rows_still_claim_derived_and_that_is_recorded(params):
    """RESIDUAL INCONSISTENCY, pinned rather than hidden.

    The seed is INPUT but particle.b3 and cosmology.b3 -- downstream echoes of
    the same integer, emitted through result dicts where set_param's status
    defaults to DERIVED -- still ship DERIVED. They are derived from nothing;
    they restate the input. Fixing them means threading an explicit status
    through those two registration paths, which touches published rows and is
    therefore staged rather than done here.
    """
    for path in _RECORDED_STATUS:
        assert params[path].get("status") == "DERIVED", (
            "%s changed status; if the echoes now follow the seed, update this "
            "file and record the fix in the register" % path
        )
    seed_status = params["topology.elder_kads"].get("status")
    assert seed_status != "DERIVED", (
        "seed and echoes agree again -- re-examine whether a derivation landed"
    )


def test_the_question_is_open_not_refuted():
    """The withdrawal must hold: no refutation may be quietly reinstated."""
    from metaphysica.simulations.PM.geometry.half_shift_enumeration import (
        status_report,
    )

    report = status_report()
    assert report["b3_24_status"] == "UNDETERMINED"


def test_b3_is_still_published_as_derived(params):
    """The contradiction of record: DERIVED with no derivation on the books.

    Fails when the status changes — which is the point. A change means the
    author has ruled, and the register must say so.
    """
    for path, recorded in _RECORDED_STATUS.items():
        assert path in params, "%s is no longer published" % path
        actual = params[path].get("status")
        assert actual == recorded, (
            "%s status moved from %s to %s. Record the ruling in "
            "docs/OUTSTANDING_ISSUES.md and update this file; the "
            "free-variable count moves with it." % (path, recorded, actual)
        )


def test_the_value_is_still_24(params):
    for path in _RECORDED_STATUS:
        assert params[path].get("value") == 24


def test_b3_is_consumed_so_it_cannot_be_comparison_only(params):
    """It feeds published outputs, so as an input it would be load-bearing."""
    consumers = [k for k, v in params.items()
                 if "b3" in json.dumps(v).lower() and k not in _RECORDED_STATUS]
    assert len(consumers) >= 5, (
        "expected b_3 to feed several published rows; found %d" % len(consumers)
    )


def test_the_withdrawal_is_recorded_in_the_register():
    """Both the refutation and its withdrawal must be on the books."""
    reg = Path("H:/Github/PrincipiaMetaphysica/docs/OUTSTANDING_ISSUES.md")
    if not reg.is_file():
        pytest.skip("register not available")
    text = reg.read_text(encoding="utf-8", errors="replace")
    assert "REFUTED" in text            # the history stays visible
    assert "WITHDRAWN" in text          # and so does the correction
