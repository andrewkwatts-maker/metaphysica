from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REMOVED = re.compile(r"\bast\.(Num|Str|Bytes|NameConstant|Ellipsis)\b")


def test_no_removed_ast_node_names():
    """visit_Num(node: ast.Num) fails at import on 3.14, and since 3.8
    NodeVisitor sends literals to visit_Constant, so it was dead anyway."""
    hits = []
    for sub in ("src", "tests"):
        for path in (ROOT / sub).rglob("*.py"):
            if "AutoGenerated" in path.parts or path.name == Path(__file__).name:
                continue
            for n, line in enumerate(path.read_text(encoding="utf-8",
                                                    errors="replace").splitlines(), 1):
                if REMOVED.search(line):
                    hits.append(f"{path.relative_to(ROOT)}:{n}")
    assert not hits, hits
