"""Every declared falsifier must describe something that can actually happen.

WHY THIS EXISTS
---------------
``AutoGenerated/topological_flux.json`` shipped this kill condition:

    if the bridge-to-channel assignment places the physical bridges only on
    complementary NON-associative 4-sets, every physical channel is
    forbidden by the selection rule and this route is dead

Enumeration over all C(21,12) = 293,930 placements later showed the live
coupling count runs 5..12 and is **never zero**. The condition described an
impossible event. It was written in good faith, it read as rigorous, and it
made a result look falsifiable when nothing could have falsified it.

That is the same disease as a gate that cannot fail, wearing different
clothes — and this repo has now caught it in three forms: tests that
returned instead of asserting, allowlists containing only agreeing members,
and a kill condition for an impossible outcome. A stated falsifier is a
claim about the world, and like any claim it can be wrong.

These tests check the falsifiers this repo currently publishes. They are
necessarily specific: whether a condition is reachable depends on the
physics behind it, so there is no generic scan that could replace them.
What CAN be generic is the requirement that one exist and be non-empty,
which the first test enforces across every report that declares one.
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import pytest


def _autogen() -> Path:
    raw = os.environ.get("METAPHYSICA_OUT")
    candidates = []
    if raw:
        candidates.append(Path(raw) / "AutoGenerated")
    candidates += [
        Path("H:/Github/PrincipiaMetaphysica/AutoGenerated"),
        Path(__file__).resolve().parents[1] / "AutoGenerated",
    ]
    for path in candidates:
        if path.is_dir():
            return path
    pytest.skip("no AutoGenerated directory found; run the build first")


def _reports_with_kill_conditions():
    out = []
    for path in sorted(_autogen().glob("*.json")):
        try:
            payload = json.loads(path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, UnicodeDecodeError):
            continue
        if isinstance(payload, dict) and payload.get("kill_condition"):
            out.append((path.name, payload))
    return out


# ── generic: a declared falsifier must be substantive ───────────────────────


def test_every_declared_kill_condition_is_substantive():
    """A one-word or placeholder falsifier is not a falsifier.

    The property that matters is that the condition names a THRESHOLD --
    some quantity a future measurement could land either side of. An earlier
    version of this test looked for the words "if"/"when"/"unless" instead
    and flagged de_plane_gate, whose condition reads "w0 < -0.99 in a future
    tightened fit ... kills w0 = -23/24 outright". That states a triggering
    circumstance perfectly well; the test was wrong, not the artifact.
    Requiring a numeric threshold is a check on substance rather than on
    phrasing.
    """
    import re

    reports = _reports_with_kill_conditions()
    if not reports:
        pytest.skip("no report declares a kill condition")
    for name, payload in reports:
        condition = payload["kill_condition"]
        assert len(condition) > 60, f"{name}: kill condition is a stub"
        assert re.search(r"\d", condition), (
            f"{name}: kill condition names no quantity, so nothing could be "
            f"measured to trigger it"
        )


def test_retired_kill_conditions_say_why_they_were_retired():
    """Retire loudly, not by deletion.

    A falsifier that quietly vanishes leaves the reader believing the claim
    was never guarded, or worse, that it still is.
    """
    for name, payload in _reports_with_kill_conditions():
        retired = payload.get("kill_condition_retired")
        if not retired:
            continue
        assert len(retired) > 60, f"{name}: retirement note is a stub"
        assert any(w in retired for w in ("SUPERSEDED", "CANNOT", "retired")), (
            f"{name}: does not explain why the condition was retired"
        )


# ── the specific one this repo got wrong ────────────────────────────────────


def test_the_retired_condition_really_was_unfireable():
    """Pin the reason for the retirement, so it cannot be reinstated.

    If a future change made 'all channels forbidden' reachable, this fails
    and the retirement should be revisited -- which is the correct outcome,
    not a nuisance.
    """
    from metaphysica.simulations.PM.gauge.topological_terms import (
        bridge_placement_spectrum,
    )

    spectrum = bridge_placement_spectrum()
    assert spectrum["all_channels_forbidden_is_possible"] is False
    assert spectrum["minimum"] > 0


def test_the_replacement_condition_is_fireable():
    """The face-triangle falsifier must be able to come out false.

    Only 35 of 293,930 placements give four complete triangles, so the vast
    majority of conceivable groupings refute it. A condition satisfied by
    everything would be no better than the one it replaced.
    """
    from metaphysica.simulations.PM.gauge.topological_terms import (
        bridge_placement_spectrum,
    )

    spectrum = bridge_placement_spectrum()
    qualifying = spectrum["n_maximal_placements"]
    total = spectrum["n_placements"]
    assert 0 < qualifying < total, "the falsifier admits everything or nothing"
    assert qualifying / total < 0.001, (
        "the surviving set is too large for the condition to discriminate"
    )


def test_the_de_plane_kill_condition_is_reachable():
    """w0 < -0.99 is a value future data can actually report.

    The framework predicts -23/24 = -0.958, so the condition names a region
    on the far side of the prediction rather than one it already occupies.
    """
    from metaphysica.simulations.PM.validation.de_plane_gate import framework_point

    w0 = framework_point()["w0"]
    assert w0 > -0.99, (
        "the stated kill condition (w0 < -0.99) is already satisfied by the "
        "framework's own point, so it cannot discriminate"
    )


# ── the gates themselves ────────────────────────────────────────────────────


def test_no_gate_passes_by_asserting_its_own_conclusion():
    """Semantic gates must compare against a value they do not set.

    Each evaluator reads the registry and compares to a constant stated in
    the gate's claim. The mutation tests in test_declarative_strategy_a
    prove each can FAIL; this checks the weaker but broader property that
    none of them reports a measured value identical to a hardcoded expected
    by construction alone.
    """
    from metaphysica.simulations.PM.validation.declarative_strategies\
        .strategy_a_semantic import run_all

    results = run_all()
    assert results, "no semantic gates registered"
    for r in results:
        assert r.numbers_invented == 0, f"G{r.gate_id} invented a threshold"
        assert r.expected is not None, f"G{r.gate_id} has no expected value"


# ── a check that used to be arithmetic true-by-definition ───────────────────


def _or_reduction():
    import metaphysica.simulations.PM.gauge.master_action as ma

    cls = [
        v for v in vars(ma).values()
        if isinstance(v, type) and hasattr(v, "compute_distributed_or_reduction")
    ]
    if not cls:
        pytest.skip("master action simulation class not found")
    return cls[0]()


def test_spinor_match_is_computed_from_the_signature_not_a_literal():
    """`2 ** n_pairs == 4096` never consulted the Clifford algebra.

    With n_pairs = 12 that is 2**12 == 4096 -- true by definition. It read
    as a spinor cross-check while really asking "is n_pairs 12", so it could
    not fail for the reason it claimed to test.
    """
    d = _or_reduction().compute_distributed_or_reduction()
    assert d["bulk_weyl_dimension"] == 4096, (
        "Weyl dimension should be computed from the registry signature "
        "(24 + 2 = 26 -> 2^12)"
    )
    assert d["total_rank"] == 4096
    assert d["matches_pneuma_spinor"] is True


def test_the_spinor_check_fails_when_the_two_routes_disagree(monkeypatch):
    """Mutation: move the signature and the agreement must break.

    Under the OPEN signature ruling (CANON["bulk"]) at (26,2), D = 28 gives
    Weyl = 2^13 = 8192 while the OR rank stays 2^12 = 4096. The check must
    then report False -- which is informative, not a regression: it says
    4096 has become the shadow-pair spinor rather than the bulk Weyl one.
    """
    from metaphysica.simulations.core.FormulasRegistry import FormulasRegistry

    monkeypatch.setattr(FormulasRegistry, "D_ancestral_space", 26,
                        raising=False)
    d = _or_reduction().compute_distributed_or_reduction()
    assert d["bulk_weyl_dimension"] == 8192, d
    assert d["matches_pneuma_spinor"] is False, (
        "the spinor check passed under a signature where the OR rank and "
        "the bulk Weyl dimension differ -- it is not testing what it claims"
    )


def test_odd_dimension_reports_no_weyl_spinor(monkeypatch):
    """There is no chirality in odd D, so the comparison must abstain.

    This is the retired Cl(24,1) situation the framework's own notes record;
    reporting a match there would be meaningless.
    """
    from metaphysica.simulations.core.FormulasRegistry import FormulasRegistry

    monkeypatch.setattr(FormulasRegistry, "D_ancestral_time", 1, raising=False)
    d = _or_reduction().compute_distributed_or_reduction()
    assert d["bulk_weyl_dimension"] is None
    assert d["matches_pneuma_spinor"] is False
