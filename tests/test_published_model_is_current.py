def _roots():
    from pathlib import Path

    seen, out = set(), []
    for root in (autogen_dir(),
                 Path("H:/Github/PrincipiaMetaphysica/AutoGenerated")):
        try:
            key = root.resolve()
        except OSError:
            continue
        if key in seen or not root.is_dir():
            continue
        seen.add(key)
        out.append(root)
    return out


def _corpus():
    """Every shipped artifact root, because every one of them is read."""
    blobs = {}
    for root in _roots():
        for name in _ARTIFACTS:
            path = root / name
            if path.is_file():
                blobs["%s::%s" % (root.name, name)] = path.read_text(
                    encoding="utf-8", errors="replace")
    if not blobs:
        pytest.skip("no built artifacts to audit")
    return blobs


#: Words that mark a stale claim as being NAMED in order to refute, label or
#: relocate it. A sentence carrying one of these is doing the right thing --
#: "8 divides no odd number, so b_3/8 yields an integer nowhere", "n_gen =
#: b_2/4 = 12/4, since b_3/8 fails" -- and counting it as a violation made
#: the ratchet punish honest labelling, so it rose every time the corpus got
#: MORE correct. Measured 2026-09-27: 142 raw b3_over_8 occurrences, of
#: which the majority sit in refutation context.
_REFUTATION_MARKERS = (
    "abandon", "aband", "no longer", "not integral", "non-integral",
    "yields an integer nowhere", "divides no", "fails", "failed", "refut",
    "relocat", "superseded", "retired", "off-path", "off the family",
    "was the", "used to", "previously", "formerly", "conjecture",
    "unruled", "awaiting", "instead", "rather than", "not a live",
    "withdrawn", "deprecated", "stale", "b_2/4", "b₂/4",
)

#: How much context around a hit to inspect for a marker. A JSON artifact has
#: no line breaks to rely on, so a fixed window is used and stated.
_CONTEXT = 240


def _asserting_hits(pattern, text):
    """Occurrences NOT sitting in a refutation/labelling context.

    The ratchet's job is to catch prose that still ASSERTS a superseded
    claim, not prose that names it in order to bury it. Without this split
    the count grew whenever the corpus was corrected, which is the opposite
    of what a ratchet is for.
    """
    rx = re.compile(pattern, re.I)
    hits = 0
    for m in rx.finditer(text):
        lo = max(0, m.start() - _CONTEXT)
        window = text[lo:m.end() + _CONTEXT].lower()
        if not any(mark in window for mark in _REFUTATION_MARKERS):
            hits += 1
    return hits


def _worst_root(pattern):
    """The highest ASSERTING count any single root carries."""
    worst = 0
    for root in _roots():
        total = 0
        for name in _ARTIFACTS:
            path = root / name
            if path.is_file():
                total += _asserting_hits(
                    pattern, path.read_text(encoding="utf-8",
                                            errors="replace"))
        worst = max(worst, total)
    return worst


def _count(pattern, blobs):
    rx = re.compile(pattern, re.I)
    return sum(len(rx.findall(text)) for text in blobs.values())


@pytest.mark.parametrize("claim", sorted(_CLAIMS))
def test_a_stale_model_claim_never_rises(claim):
    _corpus()                      # skips cleanly when nothing is built
    found = _worst_root(_CLAIMS[claim])
    assert found <= _CEILINGS[claim], (
        "published occurrences of the stale claim %r rose to %d, above the "
        "measured ceiling of %d. The engine runs (b_2, b_3) = (12, 43) with "
        "n_gen = b_2/4; prose asserting otherwise contradicts the values "
        "printed beside it. New wording must be generated from the live "
        "seed, not typed." % (claim, found, _CEILINGS[claim])
    )


def test_the_audit_actually_reads_the_artifacts():
    """A ratchet over an empty corpus would pass forever."""
    blobs = _corpus()
    assert sum(len(t) for t in blobs.values()) > 100_000, (
        "the artifacts are too small to be real; this audit is measuring "
        "nothing"
    )


def test_the_adopted_values_are_present_at_all():
    """The other side: the CURRENT model must appear, not merely the old
    one be absent. A build that published neither would pass every ceiling.
    """
    blobs = _corpus()
    assert _count(r"b_?3\s*=\s*43|b₃\s*=\s*43", blobs) > 0, (
        "no artifact states b_3 = 43; the adopted seed does not reach the "
        "published prose at all"
    )
    assert _count(r"b_?2\s*/\s*4|b₂/4", blobs) > 0, (
        "no artifact states the ruled generation route n_gen = b_2/4"
    )


def test_the_ceilings_are_documented_as_a_debt_not_a_target():
    """The count is not supposed to be zero, and the reason is on file."""
    assert __doc__ is not None
    assert "may only fall" in __doc__
    assert "label it" in __doc__ or "LABEL it" in __doc__


def test_a_retired_claim_names_the_decision_that_made_it_live():
    """Retiring a pattern must not be a quiet way to lower the bar."""
    for name, entry in _RETIRED_CLAIMS.items():
        assert name not in _CLAIMS, "%s is both retired and audited" % name
        assert re.search(r"D-\d{3}", entry["why"]), (
            "retired claim %r cites no decision" % name)


def test_every_audited_claim_has_a_ceiling():
    assert set(_CLAIMS) == set(_CEILINGS)
